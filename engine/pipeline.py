#: Приставка третьего вида привязки: строка печатается **вместо** строки
#: действия — тогда и только тогда, когда заявки с этим именем среди принятых
#: нет. Двух видов не хватило, и это стоило целой причины в журнале:
#: цепочка выхода — это снятие и закрытие, строка «Выход из лонга по обратному
#: сигналу» привязана к закрытию, и определённый отказ именно в закрытии
#: выбрасывал её вовсе. В журнале свечи оставался один отказ, а **зачем** робот
#: выходил, не было сказано нигде — и так каждую свечу до самой остановки.
#:
#: ⚠️ Работает только для строк разбора свечи (`Outcome`). У `FillOutcome`
#: безусловная часть публикуется ДО подачи заявок (`Engine.on_fill`), и строка
#: «вместо» ушла бы в журнал раньше, чем стал известен ответ исполнителя.
_UNLESS = "!"


def _unless(order_id: str) -> str:
    """Имя привязки «пока заявку с этим именем не приняли»."""
    return f"{_UNLESS}{order_id}"


def _visible(
    written: tuple[tuple[str, JournalEntry], ...], names: set[str]
) -> tuple[JournalEntry, ...]:
    """Строки, видимые при таком наборе принятых заявок. Три вида привязки.

    * пустое имя — строка безусловная: объяснения молчания и всё, что
      не зависит от исполнителя;
    * имя заявки — строка появляется вместе с её приёмом;
    * `!имя` — строка появляется, только если заявку **не** приняли.
    """
    shown: list[JournalEntry] = []
    for key, entry in written:
        if not key:
            shown.append(entry)
        elif key.startswith(_UNLESS):
            if key[len(_UNLESS):] not in names:
                shown.append(entry)
        elif key in names:
            shown.append(entry)
    return tuple(shown)


@dataclass(frozen=True, slots=True)
class Outcome:
    """Что движок решил на этой свече.

    `steps` — какие шаги порядка обработки были пройдены, по номерам
    PROTOTYPE.md §2. Возвращается наружу затем, чтобы порядок проверялся
    тестом, а не вычитывался глазами: перестановка шагов не роняет ничего,
    она просто даёт другие сделки.

    `snapshot` — снимок позиции, взятый на шаге 3, **до** подачи заявок
    на закрытие. Именно он, а не текущее состояние, отвечает на вопрос
    «пуст ли рынок» на шаге 10.

    `skipped` не пуст — свеча вообще не дошла до разбора: её отсеял приём
    (незакрытая, повторная или, по настройке, неполная). Тогда `steps` пуст:
    ни одного шага не выполнялось.

    Два состояния вместо одного
    ---------------------------
    `state` — состояние, **если исполнитель принял все заявки**.
    `state_if_refused` — если не принял ни одной.

    Разбор не знает, чем кончится подача: он чистая функция, а подаёт заявки
    адаптер. Записать «позиция закрывается» до ответа исполнителя — значит
    при отказе брокера получить позицию, закрытую в журнале и открытую
    на счёте, и робота, который её больше не трогает. Поэтому фиксируется
    одно из двух, и решает это тот, кто заявки подавал, — `state_after()`.

    `written` — строки журнала, каждая с именем заявки, от которой она
    зависит (пустое имя — строка безусловная). Публикуются они по числу
    **принятых** заявок, `lines()`.

    ⚠️ Так закрывается целый класс неправды в журнале решений: «Выход
    из лонга по обратному сигналу» уровня TRADE рядом с «Заявка отклонена
    исполнителем», «Сначала снимаем тейк 211 050» при нуле поданных заявок,
    «Тейк-профит выставлен» при уровне, которого у брокера нет.

    `halt` не пуст — разбор требует **остановить робота**. Сегодня причина
    одна: заявка на выход не стала сделкой за отведённое число свечей. Тейк
    к этому моменту снят, шаг 5 закрывающуюся позицию не вооружает, повторно
    подать выход нельзя — вторая рыночная заявка после исполнения первой
    открывает позицию в обратную сторону. Ждать молча тоже нельзя: позиция
    стоит без уровня. Остаётся человек.
    """

    state: EngineState
    orders: tuple[OrderRequest, ...] = ()
    written: tuple[tuple[str, JournalEntry], ...] = ()
    steps: tuple[Step, ...] = ()
    snapshot: Position | None = None
    closes_at: datetime | None = None
    in_window: bool | None = None
    trading_day: bool | None = None
    skipped: str = ""
    state_if_refused: EngineState | None = None
    halt: str = ""

    @property
    def last_step(self) -> Step | None:
        """На каком шаге разбор закончился."""
        return self.steps[-1] if self.steps else None

    @property
    def journal(self) -> tuple[JournalEntry, ...]:
        """Все строки, как если бы исполнитель принял всё. Для разбора и тестов.

        Строки «вместо» (`_UNLESS`) сюда не попадают по определению: они
        печатаются ровно тогда, когда заявку **не** приняли.
        """
        return tuple(
            entry for key, entry in self.written if not key.startswith(_UNLESS)
        )

    def lines(self, accepted: int | None = None) -> tuple[JournalEntry, ...]:
        """Строки журнала этой свечи при таком ответе исполнителя.

        Порядок — тот, в котором их написали шаги обработки. Строки,
        привязанные к непринятым заявкам, отброшены; вместо строки действия
        встаёт её сниженная замена, если такая написана (`_UNLESS`).
        """
        count = len(self.orders) if accepted is None else accepted
        return _visible(
            self.written, {order.order_id for order in self.orders[:count]}
        )

    def state_after(self, accepted: int) -> EngineState:
        """Состояние, если исполнитель принял первые `accepted` заявок.

        `accepted == len(orders)` — принято всё, это `state`. Ноль — не принято
        ничего. Промежуточные значения появляются, когда исполнитель отказал
        на второй заявке из двух: первая уже у брокера, и забыть про неё нельзя.

        :raises ValueError: принято больше заявок, чем подано.
        """
        if not 0 <= accepted <= len(self.orders):
            raise ValueError(
                f"принято {accepted} заявок из поданных {len(self.orders)} — "
                "такого ответа исполнителя не бывает"
            )
        if accepted == len(self.orders):
            return self.state
        state = self.state if self.state_if_refused is None else self.state_if_refused
        for order in self.orders[:accepted]:
            state = after_submit(state, order)
        return state


@dataclass(frozen=True, slots=True)
class FillOutcome:
    """Что изменилось от сообщения исполнителя о сделке.

    `orders` — заявки, **рождённые сделкой**. Сегодня это ровно одно:
    вооружение тейка сразу при открытии позиции. Уровень считается от цены
    входа, а цену входа назначает исполнитель — значит раньше сделки его
    не знает никто.

    `halt` не пуст — движок обязан **остановиться до подачи любой следующей
    заявки**. Сегодня причина одна: сделка, не сопоставившаяся ни с одной
    заявкой в полёте. Пока она не разобрана человеком, движок не знает, что
    на счёте, — и любая следующая заявка может удвоить объём.

    ⚠️ Заявка вооружения обязана дойти до исполнителя **до того**, как он закончит
    разбирать тот же бар: `high`/`low` той же свечи уже сторожат уровень,
    и у прототипа есть три сделки из 127, открывшиеся и закрывшиеся внутри
    одной свечи. Поэтому обмен внутри свечи идёт по кругу, пока порт
    не ответит пустотой (`engine/ports.py`).
    """

    state: EngineState
    written: tuple[tuple[str, JournalEntry], ...] = ()
    orders: tuple[OrderRequest, ...] = ()
    halt: str = ""

    @property
    def journal(self) -> tuple[JournalEntry, ...]:
        return tuple(entry for _, entry in self.written)

    def lines(self, accepted: int = 0) -> tuple[JournalEntry, ...]:
        """Строки при таком ответе исполнителя на рождённые сделкой заявки."""
        names = {order.order_id for order in self.orders[:accepted]}
        return tuple(
            entry for key, entry in self.written if not key or key in names
        )

    def tied(self, accepted: int) -> tuple[JournalEntry, ...]:
        """Только строки, ставшие видимыми от приёма заявок. Дельта к `lines(0)`."""
        names = {order.order_id for order in self.orders[:accepted]}
        return tuple(entry for key, entry in self.written if key and key in names)


def exit_signal(side: Side, intent: Intent) -> bool:
    """Средняя велит выйти из позиции этой стороны.

    Четыре строки правила прототипа — это два условия::

        выход из лонга: close < средняя   ⇔ намерение «шорт»
        выход из шорта: close > средняя   ⇔ намерение «лонг»

    `Intent.NONE` выходом **не** является: при закрытии ровно на средней
    у прототипа нет ни входа, ни выхода — позиция держится (PROTOTYPE.md §3).
    """
    if side is Side.LONG:
        return intent is Intent.SHORT
    return intent is Intent.LONG


def after_submit(state: EngineState, order: OrderRequest) -> EngineState:
    """Исполнитель принял заявку — что движок об этом запоминает.

    Две вещи, и обе не пускают вторую заявку по тому же поводу:

    * заявка на выход переводит позицию в «закрывается». Из снимка она
      не исчезает, поэтому вход в обратную сторону подаётся только
      на следующей свече — это «переворот через свечу» (PROTOTYPE.md §2);
    * заявка запоминается как неподтверждённая. Пока по ней не пришла сделка,
      шаг 10 второй заявки на вход не подаёт: иначе потерянное подтверждение
      входа даёт двойной объём на счёте.

    Функция вызывается **дважды и в двух местах**, и это намеренно: разбор
    свечи строит ею `Outcome.state` (как будто принято всё), а адаптер —
    настоящее состояние по числу принятых заявок. Общий код здесь обязателен:
    две копии этого правила разъедутся молча.

    Две заявки про сторожимый уровень ведут себя иначе:

    * **вооружение** кладётся в полёт, но не вторым экземпляром: заявка с тем
      же именем **заменяется**. «Вооружить» — это состояние «у позиции
      сторожится ровно один уровень», а не «подать ещё одну стоп-заявку»;
    * **снятие** само в полёте не остаётся — оно убирает названную заявку
      и гасит уровень у позиции. Принятое снятие означает, что сторожа больше
      нет, и позиция стоит без уровня до следующего вооружения.
    """
    if order.action is OrderAction.CLOSE:
        state = _mark_closing(state)
        state = replace(state, exit_blocked_bars=0)
    elif order.action is OrderAction.CANCEL_TAKE_PROFIT:
        return _after_cancel(state, order)
    elif order.action is OrderAction.ARM_TAKE_PROFIT:
        state = _after_arm(state, order)
    return replace(state, pending=_with_order(state.pending, order))


def _after_arm(state: EngineState, order: OrderRequest) -> EngineState:
    """Вооружение принято: у позиции появился сторожимый уровень.

    ⚠️ Уровень ставится **здесь**, а не на шаге 5, и это не мелочь. Шаг 5 его
    только считает; сторожимым он становится, когда заявку приняли. Иначе
    движок считал бы позицию защищённой уровнем, которого у брокера нет,
    и рисовал бы на графике линию, за которой ничего не стоит.

    Есть и вторая, техническая сторона: `Outcome` обещает, что состояние
    «принято всё» равно состоянию «принято ноль» плюс применённые заявки.
    Уровень, поставленный мимо заявки, это обещание ломает — молча
    и в единственном месте, где движок и брокер расходятся во мнении.
    """
    position = state.position
    if position is None or take_order_id(position) != order.order_id:
        return state
    return replace(
        state, position=replace(position, take=replace(position.take, level=order.price))
    )


def _with_order(
    pending: tuple[OrderRequest, ...], order: OrderRequest
) -> tuple[OrderRequest, ...]:
    """Заявка в полёте: заменить одноимённую или добавить новую."""
    for index, waiting in enumerate(pending):
        if waiting.order_id == order.order_id:
            return pending[:index] + (order,) + pending[index + 1:]
    return pending + (order,)


def _without_order(
    pending: tuple[OrderRequest, ...], order_id: str
) -> tuple[OrderRequest, ...]:
    return tuple(order for order in pending if order.order_id != order_id)


def after_refused_cancel(
    state: EngineState, order: OrderRequest, reason: Refusal
) -> EngineState:
    """Исполнитель **отказал** в снятии тейка. Что движок об этом запоминает.

    ⚠️ **Два отказа — два разных события, и действия на них противоположны.**
    Разобрать их одним действием нельзя: любой выбор одного ломает другой,
    и оба достижимы каждый торговый день.

    **«Нет такой заявки»** (`Refusal.NO_SUCH_ORDER`) — сторож у брокера исчез
    не по нашей команде: истёк срок, снятие на клиринге, переподключение. Это
    ровно те три случая, ради которых написана перестановка тейка каждую
    свечу. Уровень гасится, заявка вооружения убирается из полёта — и на
    следующей свече шаг 5 вооружает заново, а `_settle` видит невооружённый
    снимок и заявку на выход больше не блокирует.

    **«Уровень уже задет»** (`ALREADY_TRIGGERED`, и то же при `UNKNOWN`) —
    сторож **жив** и вот-вот станет сделкой. Здесь всё наоборот:

    * **уровень остаётся.** Погасив его, движок на следующей свече увидел бы
      невооружённый снимок и подал **голый рыночный выход поверх живого
      сторожа**. Рыночная закрывает лонг, сторож при следующем касании
      продаёт ещё раз — шорт на полный объём, без сигнала и без строки;
    * **заявка вооружения остаётся в полёте.** Убрав её, движок получил бы
      сделку «без своей заявки» — и остановился бы на штатной гонке, потеряв
      настоящий выход по тейку из журнала сделок и оставшись с фантомной
      позицией;
    * **выход не подаётся**, движок ждёт сделку. Если она не приходит, дальше
      работает счётчик.

    ⚠️ `UNKNOWN` разбирается как `ALREADY_TRIGGERED` намеренно: не знать
    и считать, что сторожа нет, — самая дорогая из двух ошибок.

    Счётчик `exit_blocked_bars` растёт в обоих случаях: заявка на выход
    не подана, а значит позиция осталась в рынке не по своей воле. Сбрасывает
    его успешно поданный выход и смена позиции.
    """
    state = replace(state, exit_blocked_bars=state.exit_blocked_bars + 1)
    if reason.order_is_alive:
        return state
    return _after_cancel(state, order)


def after_refused_exit(state: EngineState, order: OrderRequest) -> EngineState:
    """Исполнитель отказал в заявке на **закрытие**. Третья дорога к той же беде.

    Аукцион, инструмент недоступен, лимит риск-менеджера — заявка на выход
    отклонена определённо. Снятие при этом уже прошло: сторожа нет, уровень
    погашен, а позиция осталась открытой. Шаг 5 на следующей свече вооружает
    заново, шаг 6 подаёт выход, `_settle` вооружение выбрасывает — и так
    каждую свечу.

    ⚠️ Без счётчика **позиция ночует и проводит выходные без сторожимого
    уровня**, робот считает себя работающим, а окну нечего показать. Считать
    надо отказы на **любой** заявке пути выхода, а не только на снятии.
    """
    return replace(state, exit_blocked_bars=state.exit_blocked_bars + 1)


def _after_cancel(state: EngineState, order: OrderRequest) -> EngineState:
    """Снятие принято: сторожимого уровня больше нет.

    Гасится и уровень у позиции — иначе движок продолжал бы считать, что
    позиция защищена, и рисовал бы линию тейка там, где у брокера уже пусто.
    Достигнутая скользящим тейком лучшая цена при этом **сохраняется**:
    уровень не едет назад, и вернуть его на место должно вооружение
    с той же вершины, а не расчёт заново от цены входа.
    """
    pending = _without_order(state.pending, order.target_id or "")
    position = state.position
    if position is not None and take_order_id(position) == order.target_id:
        position = replace(position, take=replace(position.take, level=None))
        return replace(state, pending=pending, position=position)
    return replace(state, pending=pending)


def process_closed_candle(
    state: EngineState,
    bar: object,
    decision: Decision,
    settings: EngineSettings,
) -> Outcome:
    """Десять шагов на одной закрытой свече.

    :param state: что движок помнит между свечами. Не меняется на месте.
    :param bar: закрытая свеча торгового модуля — та же, что подана модулю.
        Несёт `closes_at`, время **закрытия**.
    :param decision: намерение модуля на этой свече.
    :param settings: общие настройки движка.
    :raises TypeError: подана не свеча торгового модуля — например, свеча слоя
        данных, где время означает НАЧАЛО. Функция публичная: её зовут и прогон
        по истории, и сверка, и не через один только `Engine`, поэтому проверка
        формы стоит здесь, а не только на входе в движок.
    """
    check_bar(bar)
    at: datetime = bar.closes_at  # type: ignore[attr-defined]
    writer = _Journal(state.quiet_note, at)
    steps: list[Step] = []
    orders: list[OrderRequest] = []
    working = state

    # ---- шаг 1: режим «Выключен» ------------------------------------------
    # Стоит первым дословно как у прототипа. ⚠️ Но свечи торговому модулю
    # подаются ДО этой функции и подаются ВСЕГДА, в том числе в «Выключен»:
    # у прототипа индикатор считает платформа независимо от режима, и десять
    # минут в «Выключен» не должны выбрасывать свечи из средней. Режимом
    # фильтруется намерение, а не подача.
    steps.append(Step.MODE_OFF)
    if settings.mode is Mode.OFF:
        if state.position is not None and not state.position.is_open:
            # Выключение поверх уже поданной заявки на выход. Заявка живёт
            # у брокера, а робот за её исполнением больше не следит: сделка
            # придёт — узнать о ней будет неоткуда, кроме приложения брокера.
            # Отдельная строка нужна ровно поэтому: общая «позиция осталась»
            # умалчивает про висящую заявку.
            writer.quiet(
                "off-with-closing",
                "Робот выключен, заявка на выход осталась у брокера",
                f"Режим «Выключен»: свеча не разбирается. По позиции "
                f"({state.position.side.label.lower()}, объём "
                f"{_volume(state.position.volume)}) заявка на выход уже подана "
                "и сделки по ней ещё не было. Робот за ней больше не следит — "
                "проверьте её в приложении брокера",
                JournalLevel.WARNING,
            )
        elif state.position is not None:
            # ⚠️ Вооружённый тейк «Выключен» НЕ снимает — и это решено, а не
            # получилось само. Снятие стопа с открытой позиции меняет её риск
            # без просьбы владельца счёта, а выключение робота не должно само
            # по себе ни приводить к сделке, ни убирать защиту. Следствие:
            # уровень остаётся у брокера и может сработать. Журнал обязан
            # сказать об этом прямо — иначе владелец счёта узнает, как оно
            # устроено, по факту сработавшего стопа.
            writer.quiet(
                "off-with-position",
                "Робот выключен, позиция осталась",
                f"Режим «Выключен»: свеча не разбирается. Открытая позиция "
                f"({state.position.side.label.lower()}, объём "
                f"{_volume(state.position.volume)}) не закрывается — выключение "
                "само по себе не должно приводить к сделке. Робот ею больше "
                "не управляет: переворот по средней к ней не применяется, "
                "тейк не переставляется"
                + _armed_note(state.position),
                JournalLevel.WARNING,
            )
        else:
            writer.quiet(
                "off",
                "Робот выключен",
                "Режим «Выключен»: свечи в решениях не участвуют. Средняя "
                "при этом считается — она не зависит от режима",
            )
        return _done(writer, state, steps, orders, at)

    # ---- шаг 2: свечей <= периода средней ---------------------------------
    # `skip_bar` означает «свеча в обработку не идёт ЦЕЛИКОМ»: выход отсюда,
    # то есть ДО шага 5 (переставить тейк) и ДО шага 6 (закрытие по концу
    # окна). Это не то же самое, что «намерение NONE» — при `NONE` обработка
    # продолжается. Прочитать одно как другое сверка с прототипом не поймает:
    # на эталонном отрезке прогрев приходится на время, когда позиции ещё нет,
    # и шаги 5 и 6 пустые. Вылезет на прогоне, начатом внутри открытой позиции.
    steps.append(Step.WARMUP)
    if decision.skip_bar:
        writer.quiet(
            "skip" if decision.warmed_up else "warmup",
            "Свеча в обработку не идёт",
            decision.reason,
        )
        return _done(writer, state, steps, orders, at)

    # ---- шаг 3: снимок открытых позиций — ДО закрытия ----------------------
    # Ключевая деталь всего порядка. Заявка на выход подаётся ниже, позиция
    # переходит в «закрывается», но из снимка не исчезает — и на шаге 10
    # проверка «снимок пуст» не проходит. Отсюда «переворот через свечу»:
    # вход в обратную сторону подаётся только на закрытии СЛЕДУЮЩЕЙ свечи.
    steps.append(Step.SNAPSHOT)
    snapshot = state.position
    # ⚠️ Был ли сторожимый уровень У БРОКЕРА до этой свечи. Не «есть ли он
    # сейчас»: шаг 5 ниже может поставить его на этой же свече, и тогда снимать
    # у брокера нечего — заявка вооружения до него не дойдёт вовсе (`_settle`).
    # Спросив текущее состояние, движок подал бы снятие несуществующей заявки
    # и написал бы в журнал «снимаем тейк X», которого не было.
    armed_before = snapshot is not None and snapshot.take.armed

    # ---- шаг 4: время закрытия свечи = начало + таймфрейм ------------------
    # Само сложение сделано раньше, в `engine/bars.py`: у свечи слоя данных
    # хранится только начало, и перекладка в свечу модуля — единственное
    # место, где закрытие вычисляется. Здесь шаг отмечен, чтобы номера
    # не разъезжались с документом.
    steps.append(Step.CLOSE_TIME)
    closes_at = at

    # ---- шаг 5: переставить тейк каждой открытой позиции -------------------
    # У неподвижного тейка уровень считается от цены входа и не двигается,
    # поэтому перестановка ничего не меняет — она означает, что заявка живёт
    # всё время позиции (PROTOTYPE.md §5) и что снятую не нами заявку следующая
    # свеча вооружит заново. У скользящего уровень может поехать, и тогда это
    # настоящая операция у брокера.
    #
    # Позиция в состоянии «закрывается» тейк НЕ получает — так у прототипа,
    # и мы это правило воспроизводим. Цена его известна и названа вслух
    # (решение 0008, пункт 3): между снятием тейка и исполнением выхода
    # позиция стоит без уровня целую свечу, а если выход не исполнится —
    # останется без него насовсем. Поэтому здесь же считаются свечи ожидания.
    steps.append(Step.REARM_TAKE_PROFIT)
    working, refused, halt = _rearm_take_profit(
        working, bar, closes_at, orders, writer, settings
    )
    if halt:
        return _done(
            writer, refused, steps, orders, closes_at, snapshot, halt=halt,
        )

    # ---- предохранитель: дневной лимит убытка (между шагами 5 и 6) ---------
    working, halt = _daily_loss_guard(
        working, bar, closes_at, orders, writer, settings, armed_before
    )
    if halt:
        return _done(writer, refused, steps, orders, closes_at, snapshot, halt=halt)

    # ---- шаг 6: вне окна или нерабочий день --------------------------------
    steps.append(Step.WINDOW)
    inside = settings.window.contains(closes_at)
    trading = _day_of(closes_at, settings).trading
    if not inside or not trading:
        cause, why, farewell = _why_outside(closes_at, settings)
        # Механизм двухуровневый (PROTOTYPE.md §2, уточнение 2). ВНЕШНЯЯ
        # проверка — по СНИМКУ: он решает, звать ли логику выхода. ВНУТРЕННЯЯ —
        # по ТЕКУЩЕМУ состоянию: оно решает, подавать ли заявку.
        #
        # ⚠️ Сегодня оба ответа совпадают, и после Э1-8 тоже: сработавший тейк
        # закрывает позицию в обмене ВНУТРИ свечи, то есть ДО шага 3, — снимок
        # к моменту разбора уже пуст. Разойтись они могут только там, где
        # сделка придёт между шагом 3 и шагом 6, а чистая функция такого
        # не допускает по построению. Проверка остаётся, потому что она
        # воспроизводит устройство прототипа, а не потому, что различает
        # что-то сегодня: реализация, спрашивающая на шагах 6, 7 и 10 текущее
        # состояние вместо снимка, на истории даст те же сделки, а в бою —
        # другие (PROTOTYPE.md §2, уточнение 2).
        current = working.position
        if snapshot is not None and current is not None and current.is_open:
            if settings.close_on_time_end or farewell is not None:
                kind, headline, intent = _leaving(
                    current, why, farewell, by_time=settings.close_on_time_end
                )
                working = _exit(
                    orders, working, current, closes_at, kind, intent, armed_before
                )
                writer.action(
                    headline, orders[-1].reason, key=orders[-1].order_id, intent=intent
                )
            elif exit_signal(current.side, decision.intent):
                intent = (
                    f"{why}. «Закрывать в конце окна» выключено, поэтому выход "
                    f"только по средней: {decision.reason}"
                )
                working = _exit(
                    orders, working, current, closes_at, ExitReason.SIGNAL,
                    intent, armed_before,
                )
                writer.action(
                    f"Выход из {current.side.label.lower()}а по сигналу средней",
                    orders[-1].reason, key=orders[-1].order_id, intent=intent,
                )
            else:
                writer.quiet(
                    f"outside-{cause}-hold:{current.side.value}",
                    "Позиция остаётся вне окна",
                    f"{why}. «Закрывать в конце окна» выключено, сигнала "
                    f"на выход нет: {decision.reason}",
                )
        elif snapshot is not None:
            writer.quiet(*_no_exit_now(current, cause, why))
        else:
            writer.quiet(
                f"outside-{cause}", "Торговли нет", f"{why}. Входов нет"
            )
        return _done(
            writer, refused, steps, orders, closes_at, snapshot, inside, trading
        )

    # ---- шаг 7: снимок не пуст → закрытие по сигналу средней ---------------
    steps.append(Step.CLOSE_BY_SIGNAL)
    if snapshot is not None:
        # Внешняя проверка — по снимку (позиция в состоянии «закрывается»
        # из него не исчезает), внутренняя — по ТЕКУЩЕМУ состоянию: повторную
        # заявку на выход закрывающаяся позиция не получает, а закрытой
        # позиции заявка не нужна вовсе. Так же устроен прототип: логика
        # выхода сама перечитывает список и фильтрует его по состоянию.
        current = working.position
        if (
            current is not None
            and current.is_open
            and exit_signal(current.side, decision.intent)
        ):
            intent = (
                f"{decision.reason} — обратный сигнал. Закрываем "
                f"{current.side.label.lower()}"
            )
            working = _exit(
                orders, working, current, closes_at, ExitReason.SIGNAL,
                intent, armed_before,
            )
            writer.action(
                f"Выход из {current.side.label.lower()}а по обратному сигналу",
                orders[-1].reason, key=orders[-1].order_id, intent=intent,
            )

    # ---- шаг 8: режим «только закрытие» ------------------------------------
    steps.append(Step.CLOSE_ONLY)
    if settings.mode is Mode.CLOSE_ONLY:
        if not orders:  # заявка уже объяснена своей строкой, дубля не нужно
            writer.quiet(
                "close-only",
                "Только закрытие",
                "Режим «Только закрытие»: новых входов нет, открытая позиция "
                "доводится до выхода по обычным правилам",
            )
        return _done(
            writer, refused, steps, orders, closes_at, snapshot, inside, trading
        )

    # ---- шаг 9: «стоп после тейка» и тейк уже был сегодня ------------------
    # Здесь только СРАВНЕНИЕ: дата тейка против даты времени ЗАКРЫТИЯ текущей
    # свечи, «начало + таймфрейм». Место шага в порядке значимо — он стоит
    # после закрытия по сигналу и до открытия, то есть выйти из позиции в день
    # тейка робот ещё может, а войти уже нет.
    #
    # ⚠️ Саму дату выставляет разбор сделки, и пишет он ПУТЬ Б: время СДЕЛКИ,
    # то есть дата НАЧАЛА свечи исполнения. Сравнение здесь идёт с датой
    # ЗАКРЫТИЯ текущей свечи — то есть с датой, посчитанной иначе. Асимметрия
    # воспроизводится как есть (PROTOTYPE.md §5).
    #
    # Путь А (по событию активации тейка) не воспроизводится и не должен:
    # оба пути пишут в ОДНО поле, путь Б срабатывает позже и побеждает
    # у любого завершённого тейка, а события активации без закрытия наш
    # контракт порта не даёт намеренно. Прежнее требование «воспроизводить
    # оба» снято 31.08.2026 разбором журнала прототипа: пути расходятся
    # не на полуночи, а после разрыва в ряде, и путь А даёт там СТАРШУЮ дату.
    steps.append(Step.STOP_AFTER_TAKE)
    if (
        settings.stop_after_take_profit
        and state.take_profit_date is not None
        and state.take_profit_date == in_moscow(closes_at).date()
    ):
        if not orders:
            writer.quiet(*_stop_after_take(working))
        return _done(
            writer, refused, steps, orders, closes_at, snapshot, inside, trading
        )

    # ---- шаг 10: снимок пуст → логика открытия -----------------------------
    # Внешняя проверка по снимку и внутренняя по текущему состоянию —
    # у прототипа их тоже две: логика открытия сама ещё раз перечитывает
    # список открытых позиций. Третья проверка — наша: неподтверждённая
    # заявка на вход. У прототипа её нет, потому что у него заявка исполняется
    # мгновенно и всегда; у брокера ответ может не дойти, и тогда без этой
    # проверки на следующей свече уходит вторая заявка на вход — двойной объём.
    #
    # ⚠️ Момент переворота (решение 0004) живёт ровно здесь — одной строкой
    # ниже. «Через свечу» (умолчание и поведение прототипа): снимок не пуст,
    # входа нет, заявка на вход уходит только на закрытии следующей свечи.
    # «В одной свече» (предложение ТЗ §4.4 Б): позиция, которую мы закрываем
    # ЭТОЙ ЖЕ свечой, рынка не покидает — выход и вход подаются подряд.
    # Различие только в этом условии, и оно ДОЛЖНО быть здесь, а не в модуле:
    # модуль отдаёт намерение, а как быстро оно становится позицией — дело
    # движка.
    steps.append(Step.OPEN)
    working = _step_open(
        working, snapshot, decision, closes_at, orders, writer, settings
    )

    return _done(
        writer, refused, steps, orders, closes_at, snapshot, inside, trading
    )


