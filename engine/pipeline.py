"""Десять шагов обработки закрытой свечи. Чистая синхронная функция.

Порядок значим: перестановка шагов не падает — она даёт другие сделки при тех же
настройках. Последовательность дословно из PROTOTYPE.md §2::

     1.  Режим == «Выключен»                  → выход
     2.  свечей <= периода средней            → выход (прогрев индикатора)
     3.  снимок открытых позиций              ← СНИМОК ДО ЗАКРЫТИЯ
     4.  время закрытия свечи = начало + таймфрейм
     5.  для каждой открытой позиции          → переставить тейк-профит
     6.  вне окна ИЛИ нерабочий день:
             есть позиция и «закрывать в конце окна»    → выход в деньги
             есть позиция и НЕ «закрывать в конце окна» → выход по сигналу средней
             → выход из обработки в любом случае
     7.  снимок не пуст                       → логика закрытия по сигналу средней
     8.  Режим == «только закрытие»           → выход
     9.  «стоп после тейка» И тейк был сегодня → выход
    10.  снимок пуст                          → логика открытия

Почему это синхронная функция без единого `await`
--------------------------------------------------
Сверка с прототипом обязана быть детерминированной и воспроизводимой — это
главный пункт приёмки (ТЗ §9). Разбор свечи корутиной затянул бы в каждую
построчную сверку цикл событий, и воспроизводимость стала бы зависеть
от планировщика. `async` живёт только на двух портах-адаптерах
(`engine/ports.py`, `engine/runner.py`), решение 0005, уточнение
к пунктам 14–15/18.

Ввода-вывода здесь нет вообще: на входе состояние, свеча и намерение модуля,
на выходе новое состояние, заявки и строки журнала. Заявки эта функция
не подаёт — она их возвращает. Подаёт их адаптер.

Отсюда важное следствие про состояние. Разбор возвращает **два** состояния:
`Outcome.state` — если исполнитель принял все заявки, и `Outcome.state_if_refused` —
если не принял ни одной. Фиксирует одно из них адаптер, и только **после**
ответа исполнителя. Обратный порядок — сначала записать «заявка подана»,
потом подавать — даёт при отказе брокера позицию, которая по журналу закрыта,
а на счёте открыта, и робота, который её больше не трогает.

Чего здесь нет по построению
----------------------------
Ни одного `if режим == тестер`. Движок не знает, откуда пришла свеча
и кто исполнит заявку (ARCHITECTURE.md §1). Ни одного обращения к бирже,
к брокеру, к базе и к часам: «сейчас» — это время закрытия поданной свечи,
а не `datetime.now()`. Функция, которая посмотрит на системное время,
перестанет одинаково работать на истории и в бою.

Тейк-профит: движок считает уровень, сторожит его исполнитель
--------------------------------------------------------------
Здесь есть **расчёт** уровня (шаг 5 и сделка открытия) и **нет** проверки,
достигнут ли он. Проверка живёт за портом, а факт срабатывания приходит
сделкой, сославшейся на нашу же заявку вооружения (решение 0008).

Отсюда два запрета, которые надо знать, читая этот файл:

* **`high` и `low` здесь не читаются вообще.** Ни для срабатывания, ни для
  «лучшей достигнутой цены» скользящего тейка — та едет по закрытиям. Запрет
  проверяется разбором исходников всего `engine/`;
* **причина выхода не выводится сравнением цен.** Она берётся из заявки,
  на которую сослалась сделка. На истории сравнение цен совпало бы ровно,
  в бою не совпало бы никогда — проскальзывание и шаг цены, — и одна и та же
  сделка получила бы разные причины в тестере и в бою.

Три предохранителя по деньгам стоят здесь же, и место каждого значимо
-----------------------------------------------------------------------
**Дневной лимит убытка** проверяется между шагом 5 и шагом 6 — то есть после
перестановки тейка и **до** проверки торгового окна. Ниже поставить нельзя:
шаг 6 выходит из обработки в любом случае, и лимит перестал бы работать вне
окна — ровно там, где позиция законно живёт при выключенном «закрывать
в конце окна». Выше — тоже нельзя: шаги 1 и 2 (режим «Выключен» и прогрев)
обязаны оставаться сильнее любого предохранителя, иначе выключенный робот
начнёт управлять позицией.

**Потолок объёма** и **запас свободных средств** живут на шаге 10, в логике
открытия: они про заявку на вход и только про неё. Заявка на выход через них
не проходит никогда — позиция, которая больше потолка, иначе осталась бы
в рынке навсегда.

Сами вычисления — в `engine/guards.py`, здесь только слова для человека.

Чего здесь нет пока
-------------------
Третьего варианта поведения после тейка — «сразу восстановить позицию»
(ТЗ §4.4 В): однозначного прочтения у него нет, прототипом он не воспроизводился,
разбор — в `engine/settings.py`. Интервалов пауз, предела числа сделок за день
(решение 0021) и сверки позиции с брокером — этап 2.
"""

