class _Journal:
    """Лента строк одной свечи. Каждая строка знает, от какой заявки зависит.

    Действие робота пишется **всегда** — но «всегда» здесь означает «если
    оно состоялось». Строка «Выход из лонга по обратному сигналу» уровня
    TRADE, написанная рядом со строкой «Заявка отклонена исполнителем»,
    утверждает выход, которого не было, — а TRADE это сильнейший уровень
    журнала решений, по нему потом объясняют сделки.

    Поэтому строка действия **привязывается к имени заявки** и публикуется
    только вместе с её приёмом. Привязка пустая — строка безусловная: так
    пишутся объяснения молчания и всё, что не зависит от исполнителя.

    Причина молчания пишется только когда она сменилась: иначе один прогон
    по истории даёт десять тысяч одинаковых строк «вне торгового окна»,
    и настоящие события в них тонут.
    """

    __slots__ = ("_quiet", "_written", "_at")

    def __init__(self, quiet: str, at: datetime) -> None:
        self._quiet = quiet
        self._at = at
        self._written: list[tuple[str, JournalEntry]] = []

    @property
    def quiet_note(self) -> str:
        return self._quiet

    @property
    def written(self) -> tuple[tuple[str, JournalEntry], ...]:
        return tuple(self._written)

    def action(
        self, event: str, reason: str, key: str = "", intent: str = ""
    ) -> None:
        """Действие робота. `key` — имя заявки, без которой действия не было.

        :param intent: чем действие объясняется, **без механики подачи**.
            Умолчание — `reason`. Расходятся они на выходе: причина заявки
            говорит «сначала снимаем тейк 211 050, и только потом подаём
            заявку на выход», и в строке про несостоявшееся действие это
            читалось бы обещанием снятия, которого не было.

        ⚠️ Заявка на выход и заявка на вход — именно такой случай: пока
        исполнитель их не принял, ничего не произошло.

        Пишется **две** строки, а не одна: сильная (TRADE) — если заявку
        приняли, и сниженная (INFO) — если не приняли. Молчание вместо второй
        стоило целой причины в журнале: цепочка выхода это снятие и закрытие,
        строка действия привязана к закрытию, и определённый отказ именно
        в закрытии выбрасывал её вовсе. Оставался один отказ, а **зачем** робот
        выходил — не сказано нигде, и так каждую свечу до самой остановки.

        Дихотомия «либо TRADE-неправда, либо молчание» ложная: сниженный
        уровень с явной оговоркой «действия не было» не утверждает сделки
        и не прячет причину.
        """
        self._quiet = ""
        self._written.append((key, JournalEntry(
            at=self._at, event=event, reason=reason, level=JournalLevel.TRADE,
        )))
        if key:
            self._written.append((_unless(key), JournalEntry(
                at=self._at,
                event="Решение принято, заявки нет",
                reason=(
                    "⚠️ Исполнитель заявку не принял — действия не было, оно "
                    f"осталось намерением. Робот решал так: «{event}. "
                    f"{intent or reason}». Строка стоит здесь затем, чтобы "
                    "рядом с отказом было видно, зачем робот действовал"
                ),
                level=JournalLevel.INFO,
            )))

    def note(
        self, event: str, reason: str, level: JournalLevel, key: str = ""
    ) -> None:
        """Событие, которое не сделка, но и не молчание. Пишется всегда.

        Сюда идёт смена сторожимого уровня. Само по себе повторное вооружение
        на **том же** уровне событием не является: «вооружить» — это состояние
        «у позиции сторожится ровно один уровень», и восстановление того же
        состояния ничего не меняет. Писать его каждые пять минут значило бы
        похоронить настоящие решения под десятью тысячами одинаковых строк
        за один прогон по истории.

        Две причины держать строку до ответа исполнителя, и обе про одно:
        **строка про уровень не должна появляться раньше, чем уровень появился
        у брокера**. На свече, где подана заявка на закрытие, вооружение
        до брокера не доходит вовсе (`_settle`). И даже дошедшую заявку
        исполнитель может не принять — тогда рядом встают «Тейк-профит
        выставлен, уровень 211 050 — окупается» и «Заявка отклонена»,
        а у брокера нет ничего. Для скользящего тейка хуже вдвойне:
        «уровень подтянут 211 050 → 212 000», а сторожится прежний.
        """
        self._quiet = ""
        self._written.append(
            (key, JournalEntry(at=self._at, event=event, reason=reason, level=level))
        )

    def quiet(
        self,
        key: str,
        event: str,
        reason: str,
        level: JournalLevel = JournalLevel.INFO,
    ) -> None:
        if key == self._quiet:
            return
        self._quiet = key
        self._written.append(
            ("", JournalEntry(at=self._at, event=event, reason=reason, level=level))
        )


def _done(
    writer: _Journal,
    base: EngineState,
    steps: list[Step],
    orders: list[OrderRequest],
    closes_at: datetime,
    snapshot: Position | None = None,
    inside: bool | None = None,
    trading: bool | None = None,
    halt: str = "",
) -> Outcome:
    """Собрать ответ разбора.

    ⚠️ **Состояние «принято всё» считается здесь переигрыванием заявок
    от состояния «не принято ничего», а не берётся у разбора готовым.**
    Так инвариант `state == state_if_refused + заявки` держится
    **по построению**, а не проверкой.

    Он был бы нарушен без этого: шаг 5 переставляет тейк раньше, чем шаги 6
    и 7 решают выйти, поэтому на свече выхода вооружение до брокера
    не доходит (`_settle`) — а его последствие осталось бы в состоянии.
    Движок считал бы позицию защищённой уровнем, которого никто не сторожит,
    и рисовал бы за ним линию на графике.

    `base` — состояние, каким оно было до подачи заявок. Причина молчания
    одна и та же в обоих: она относится к строкам журнала, а не к заявкам.
    """
    kept = _settle(orders)
    state = base
    for order in kept:
        state = after_submit(state, order)
    quiet = writer.quiet_note
    return Outcome(
        state=replace(state, quiet_note=quiet),
        state_if_refused=replace(base, quiet_note=quiet),
        orders=kept,
        written=writer.written,
        steps=tuple(steps),
        snapshot=snapshot,
        closes_at=closes_at,
        in_window=inside,
        trading_day=trading,
        halt=halt,
    )


def _settle(orders: list[OrderRequest]) -> tuple[OrderRequest, ...]:
    """Убрать вооружение с той свечи, на которой позиция уходит с рынка.

    Шаг 5 стоит **до** шагов 6 и 7 — так у прототипа, и переставлять его
    нельзя. Поэтому на свече выхода движок сначала переставляет тейк, а через
    два шага подаёт заявку на закрытие. Логически верно, а у брокера это две
    настоящие операции подряд, из которых первая ничего не даёт: сторож
    поставлен ради позиции, которая эту же свечу покидает.

    Хуже, чем «не даёт»: если снятие не подаётся (уровня до этой свечи
    не было), вооружение и рыночный выход уходят к брокеру **вместе** —
    ровно та гонка двух заявок, ради устранения которой снятие и заведено.

    Поэтому правило одно и простое: **есть заявка на закрытие — вооружения
    в этой свече нет**. Снятие при этом остаётся: его подаёт `_exit`, и только
    тогда, когда уровень действительно стоял у брокера до этой свечи.

    ⚠️ Схлопывается **список заявок**, а состояние считается по нему же
    (`_done`), — иначе движок остался бы с уровнем, которого никто не сторожит.
    """
    if not any(order.action is OrderAction.CLOSE for order in orders):
        return tuple(orders)
    return tuple(
        order for order in orders
        if order.action is not OrderAction.ARM_TAKE_PROFIT
    )


def _submitted(
    orders: list[OrderRequest], state: EngineState, order: OrderRequest
) -> EngineState:
    """Заявка добавлена к подаче, состояние — как после её приёма.

    Единственное место, где заявка попадает в список: последствие заявки
    и сама заявка не должны появляться порознь. Отсюда же берётся
    `Outcome.state`, а `Outcome.state_if_refused` — из `base`, которого
    эта функция не касается.
    """
    orders.append(order)
    return after_submit(state, order)


def _mark_closing(state: EngineState) -> EngineState:
    """Позиция переходит в «закрывается» и остаётся в состоянии движка.

    Убрать её сразу — значит разрешить вход в обратную сторону на этой же
    свече и получить другой список сделок.
    """
    if state.position is None:
        return state
    return replace(
        state, position=replace(state.position, state=PositionState.CLOSING)
    )


def _close_order(
    position: Position, at: datetime, reason: ExitReason, text: str
) -> OrderRequest:
    return OrderRequest(
        action=OrderAction.CLOSE,
        side=position.side,
        volume=position.volume,
        submitted_at=at,
        reason=text,
        order_id=f"close:{position.side.value}:{at.isoformat()}",
        exit_reason=reason,
    )


def _entry_side(decision: Decision, settings: EngineSettings) -> Side | None:
    """Сторона входа — или `None`, если входа нет.

    Порядок проверок дословно как у прототипа: сначала лонг при
    «режим != только шорт», затем шорт при «режим != только лонг».
    Неравенства строгие, при закрытии ровно на средней намерение `NONE`
    и входа нет.

    Отделено от сборки заявки ради одного: сторона обязана выясниться
    **до** предохранителей. Иначе молчание там, где сигнала не было вовсе,
    объяснялось бы потолком объёма — и владелец счёта пошёл бы править
    настройку, которая ни при чём.
    """
    if decision.intent is Intent.LONG and settings.mode.opens_long:
        return Side.LONG
    if decision.intent is Intent.SHORT and settings.mode.opens_short:
        return Side.SHORT
    return None


def _open_order(
    side: Side, decision: Decision, at: datetime, volume: float, note: str
) -> OrderRequest:
    """Заявка на вход. Объём — тот, что разрешили предохранители.

    :param note: хвост причины от предохранителей: урезание объёма
        и непроверенный лимит. Составляет его вызывающий — здесь только
        сборка заявки.

    ⚠️ Хвост читает не только владелец счёта: тот же текст уходит боевому
    адаптеру полем `reason` и встаёт в строку журнала про заявку, которую
    исполнитель не принял.
    """
    reason = f"{decision.reason} → {side.label.lower()} {_volume(volume)}{note}"
    return OrderRequest(
        action=OrderAction.OPEN,
        side=side,
        volume=volume,
        submitted_at=at,
        reason=reason,
        order_id=f"open:{side.value}:{at.isoformat()}",
    )


def _cut_note(sizing: Sizing, settings: EngineSettings) -> str:
    """Хвост про уменьшенный объём. Пусто, если объём не урезали.

    Урезание — это одноразовое снижение уже введённого числа под конкретную
    заявку (решения 0014 и 0015), а не формула, выводящая объём. Молча оно
    происходить не должно: заявка меньше настроенной — это меньший риск,
    но и другой результат, чем ждал владелец счёта.
    """
    if not sizing.cut:
        return ""
    return (
        f". ⚠️ Объём уменьшен с {_volume(sizing.wanted)}: свободных средств "
        f"с запасом {percent(settings.free_funds_reserve_percent)}% хватает "
        f"на {_volume(sizing.affordable or 0.0)}. Сигнал не пропущен — вход "
        "меньшим объёмом"
    )


def _blind_note(blind: Unchecked, settings: EngineSettings) -> str:
    """Хвост про предохранитель, который включён, а проверить его нечем.

    Пишется в строку **входа** — там, где робот собирается занять деньги.
    Это единственное место, где молчание стоит дороже шума: число в окне
    стоит, владелец счёта считает защиту работающей, а движку её считать
    не от чего.

    ⚠️ Названная цена: строка появляется только при входе. Пока позиция
    открыта и входов нет, о непроверенном лимите не напоминает никто.
    """
    if not blind:
        return ""
    which = []
    if blind.daily_limit:
        which.append(
            f"дневной лимит убытка {percent(settings.daily_loss_limit_percent)}% "
            "— движку не сообщён размер счёта на эту дату"
        )
    if blind.free_funds:
        which.append(
            f"запас свободных средств {percent(settings.free_funds_reserve_percent)}% "
            "— движку не сообщены свободные средства и ГО контракта"
        )
    return ". ⚠️ НЕ ПРОВЕРЕНО: " + "; ".join(which)


def _no_entry(decision: Decision, settings: EngineSettings) -> tuple[str, str, str]:
    """Почему на пустом рынке входа не было — ключ, событие, причина."""
    if decision.intent is Intent.LONG and not settings.mode.opens_long:
        return (
            "mode-blocks-long",
            "Вход не открыт: режим",
            f"{decision.reason}, но режим «{settings.mode.label}» — "
            "лонги не открываются",
        )
    if decision.intent is Intent.SHORT and not settings.mode.opens_short:
        return (
            "mode-blocks-short",
            "Вход не открыт: режим",
            f"{decision.reason}, но режим «{settings.mode.label}» — "
            "шорты не открываются",
        )
    return ("no-signal", "Сигнала нет", f"{decision.reason} — вне рынка")


def _holding(position: Position, decision: Decision) -> tuple[str, str, str]:
    """Позиция держится: сигнала на выход не было."""
    if not position.is_open:
        return (
            "closing",
            "Ждём исполнения выхода",
            "Заявка на выход подана на прошлой свече, сделки ещё не было. "
            "Вход в обратную сторону — не раньше, чем позиция закроется",
        )
    return (
        f"hold:{position.side.value}",
        f"{position.side.label} держим",
        f"{decision.reason} — сигнала на выход нет",
    )


def _no_entry_now(state: EngineState, decision: Decision) -> tuple[str, str, str]:
    """Шаг 10 входа не дал, а заявок на этой свече не было — почему."""
    entry = state.entry_in_flight()
    if entry is not None and state.position is None:
        return (
            "pending-entry",
            "Ждём исполнения входа",
            f"Заявка ({order_words(entry)}) уже у исполнителя, "
            "сделки по ней ещё не было. Вторую заявку на вход движок "
            "не подаёт: потерянное подтверждение дало бы двойной объём "
            "на счёте",
        )
    if state.position is not None:
        return _holding(state.position, decision)
    return (
        "left-the-market",
        "Входа на этой свече нет",
        "Позиция закрылась на этой свече. Вход в обратную сторону — "
        "не раньше следующей: это «переворот через свечу»",
    )


def _no_exit_now(
    position: Position | None, cause: str, why: str
) -> tuple[str, str, str]:
    """Вне окна позиция была в снимке, а заявки на выход не будет — почему."""
    if position is None:
        return (
            f"outside-{cause}-gone",
            "Торговли нет",
            f"{why}. Позиция закрылась на этой свече — закрывать больше нечего",
        )
    return (
        f"outside-{cause}-closing",
        "Торговли нет",
        f"{why}. Заявка на выход по позиции уже подана — ждём сделки",
    )


def _armed_note(position: Position) -> str:
    """Хвост про уровень, оставшийся у брокера после выключения робота.

    Тейк — **состояние у брокера**, а не событие движка. Уже вооружённый
    уровень переживает и выключение робота, и закрытие программы, и сработать
    он может без всякого участия «Терминала». Умолчать об этом дороже, чем
    сказать: поверив, что тейка нет, владелец счёта поставит свой стоп
    и получит два.
    """
    if not position.take.armed:
        return (
            ". Сторожимого уровня у этой позиции нет — ни тейк, ни переворот "
            "к ней больше не применяются"
        )
    return (
        f". ⚠️ Но выставленный тейк {_price(position.take.level or 0.0)} "
        "остаётся у брокера и может сработать: это заявка на его стороне, "
        "а не расчёт внутри программы. Снять её можно в приложении брокера"
    )


def _stop_after_take(state: EngineState) -> tuple[str, str, str]:
    """Шаг 9: тейк сегодня уже был.

    Формулировка ТЗ §4.6 «сделок сегодня больше не будет» верна только
    на пустом рынке. С открытой позицией сделка сегодня ещё возможна: выход
    по обратному сигналу и выход по концу окна стоят в порядке ДО этого шага
    и запретом не накрыты. Обещать в журнале обратное — значит объяснять
    владельцу счёта то, чего робот не делает.
    """
    if state.position is not None:
        return (
            "stop-after-take-holding",
            "Новых входов сегодня больше не будет",
            "Сработало правило «стоп после тейка»: сегодня тейк уже был. "
            f"Открытая позиция ({state.position.side.label.lower()}, объём "
            f"{_volume(state.position.volume)}) при этом закрывается "
            "по обычным правилам — сделка сегодня ещё возможна",
        )
    return (
        "stop-after-take",
        "Сделок сегодня больше не будет",
        "Сработало правило «стоп после тейка»: сегодня тейк уже был, "
        "новых входов до конца календарной даты нет",
    )


def _day_of(closes_at: datetime, settings: EngineSettings) -> DayVerdict:
    """Решение про день этой свечи: торговый ли он и почему именно.

    Единственное место движка, где спрашивают про день. Календарь владельца
    счёта и дни, названные биржей, едут сюда вместе — правило одно на всех
    (`engine/window.py::_DAY_RULES`), и второй его реализации нет.
    """
    return day_verdict(
        closes_at,
        trade_in_weekend=settings.trade_in_weekend,
        calendar=settings.calendar,
        exchange=settings.exchange_days,
    )


def _why_outside(
    closes_at: datetime, settings: EngineSettings
) -> tuple[str, str, DayVerdict | None]:
    """Ключ причины, её объяснение человеческим языком и завтрашний выходной.

    Ключ отличает выходной от «вне окна»: без этого переход вечера пятницы
    в субботу не породил бы новой строки в журнале, и владелец счёта увидел бы
    «вне окна» там, где робот молчал из-за выходных. С появлением календаря
    ключей стало больше — «вы пометили день нерабочим» и «биржа закрыта» это
    разные события, и склеивать их в одну строку нельзя (решение 0038).

    Третьим значением — **вердикт завтрашнего дня, если завтра нерабочий**
    и позицию пора закрывать. `None` значит «повода закрываться нет».
    Считается здесь, а не отдельным вызовом, чтобы место решения про день
    осталось одно.
    """
    verdict = _day_of(closes_at, settings)
    if not verdict.trading:
        return verdict.rule.value, verdict.why, None
    moment = in_moscow(closes_at)
    return "window", (
        f"Свеча закрылась в {moment:%H:%M}, торговое окно "
        f"{settings.window.label} — это вне окна"
    ), _before_day_off(verdict, moment, settings)


def _before_day_off(
    today: DayVerdict, moment: datetime, settings: EngineSettings
) -> DayVerdict | None:
    """Завтрашний день, если он нерабочий, а сегодняшнее окно уже позади.

    Решение 0038: позиция через нерабочий день не переносится, и закрывается
    она **по концу окна** — то есть не утром того же дня, когда окно ещё
    впереди. Отсюда проверка по времени: свеча, закрывшаяся до конца окна,
    поводом не является, иначе позиция, доставшаяся с вечера четверга,
    закрылась бы в пятницу в 09:30 и целый торговый день пропал бы.

    ⚠️ Два случая исключены, и это названо, а не спрятано:

    * **окно через полночь** (начало позже конца) — там «завтра» наступает
      внутри окна, и закрытие по календарной границе резало бы окно пополам;
    * **сегодня и так нерабочий день** — закрывать перед нерабочим днём,
      находясь в нерабочем дне, поздно: заявку принимать некому.

    Окно «весь день» (начало равно концу) сюда не доходит вовсе: `contains`
    для него истинен всегда, и в ветку «вне окна» на торговом дне не попасть.
    """
    window = settings.window
    if window.whole_day or window.over_midnight or not today.trading:
        return None
    if minutes_of_day(moment) < minutes_of_day(window.end):
        return None
    tomorrow = verdict_of_day(
        today.day + timedelta(days=1),
        trade_in_weekend=settings.trade_in_weekend,
        calendar=settings.calendar,
        exchange=settings.exchange_days,
    )
    return None if tomorrow.trading else tomorrow


def _leaving(
    position: Position, why: str, farewell: DayVerdict | None, *, by_time: bool
) -> tuple[ExitReason, str, str]:
    """Причина выхода, заголовок строки журнала и объяснение — одним ответом.

    Два разных события, и человек обязан их различать (решение 0038,
    следствие 2). «Конец торгового окна» случается каждый день; «нерабочий
    день впереди» — только перед днём, в который робота не будет, и случается
    **даже при снятой галочке «закрывать в конце окна»**: иначе снятая галочка
    молча отменила бы решение владельца счёта.

    ⚠️ При включённой галочке причина остаётся прежней — «конец окна», — хотя
    завтра и выходной. Так и есть: выход произошёл по расписанию окна, он
    случился бы и без всякого календаря. Писать в этом случае «перед нерабочим
    днём» значило бы каждую пятницу подменять причину у события, которое
    ни капли не изменилось.
    """
    side = position.side.label.lower()
    if by_time or farewell is None:
        return (
            ExitReason.WINDOW_END,
            f"Выход из {side}а по концу окна",
            f"{why} — выходим в деньги, без оглядки на среднюю",
        )
    return (
        ExitReason.NON_TRADING_DAY,
        f"Выход из {side}а перед нерабочим днём",
        f"{why}. Завтра {farewell.why}. «Закрывать в конце окна» выключено, "
        "но через нерабочий день позицию не переносим — выходим в деньги",
    )


def _volume(value: float) -> str:
    """Объём для журнала: «1 контракт», «3 контракта», «0,5 контракта».

    Дробный объём тоже с единицей: «0,5» без слова читается как «половина
    чего» — и в строке про частичное исполнение это уже не мелочь.
    """
    if float(value).is_integer():
        return f"{int(value)} контракт{_plural(int(value))}"
    return f"{value:g}".replace(".", ",") + " контракта"


def plural(count: int, one: str, few: str, many: str) -> str:
    """Слово в форме, согласованной с числом: 1 заявка, 2 заявки, 5 заявок.

    Публичная: тем же правилом пользуются строки движка про заявки, которые
    не подавались вовсе. Второй такой же функции рядом быть не должно —
    разъедутся они молча, а читать это владельцу счёта.
    """
    tail = abs(count) % 100
    if 11 <= tail <= 14:
        return many
    return {1: one, 2: few, 3: few, 4: few}.get(tail % 10, many)


def _plural(count: int) -> str:
    """Окончание слова «контракт» по числу."""
    return plural(count, "", "а", "ов")


def _price(value: float) -> str:
    """Цена для журнала: `284 812,53`. Оформление как в `strategies`."""
    text = f"{value:,.6f}"
    whole, _, fraction = text.partition(".")
    fraction = fraction.rstrip("0")
    whole = whole.replace(",", " ")
    return f"{whole},{fraction}" if fraction else whole


def money(value: float) -> str:
    """Рубли для журнала. **Одно место на весь движок** — двух быть не должно.

    Публичная ровно поэтому: тем же правилом печатает деньги склейка
    (`engine/runner.py`), когда принимает снимок счёта. Второй форматтер
    рядом разъехался бы молча, а читает это владелец счёта.
    """
    return f"{_price(value)} ₽"


def _points(value: float) -> str:
    sign = "+" if value > 0 else ""
    return f"{sign}{_price(value)}"


def _commission(fill: Fill) -> str:
    """Комиссия отдельной строкой — или честное «не сообщена».

    Валовая прибыль в этом проекте результатом не считается (DOMAIN.md §5).
    Подставить ноль вместо неизвестной комиссии — значит превратить журнал
    в неправду там, где реверсная система делает много переворотов.
    """
    if fill.commission is None:
        return ". Комиссия исполнителем не сообщена"
    return f". Комиссия {_price(fill.commission)} ₽"
