"""Уровень тейк-профита: неподвижный от цены входа и скользящий за ценой.

Здесь только **расчёт уровня**. Кто его сторожит и как узнаётся срабатывание —
не здесь и вообще не в движке: уровень уходит за порт заявкой «вооружить»,
а факт срабатывания приходит обратно сделкой ([решение 0008](
../.docs/decisions/0008-take-profit-port-contract.md)). В этом модуле нет
ни одного обращения к `high`, `low` и ни одного сравнения цены с уровнем —
и это проверяется отдельным тестом по исходникам всего `engine/`.

Почему уровень считает движок, а не тот, кто его сторожит
----------------------------------------------------------
42 выхода из 127 в эталонном журнале прототипа идут по уровню тейка, и сверка
сравнивает **цены выхода**. Уровень, посчитанный за портом, сверялся бы моделью
исполнения сам с собой, а боевой адаптер остался бы не проверенным ничем.
Второй довод: тот же уровень рисуется линией на графике и пишется в журнал —
уехав за порт, он дал бы разные линии в тестере и в бою при одинаковых
настройках. Третий: за портом расчёт существовал бы в двух копиях, и первая же
правка процента развела бы их молча.

Два тейка, а не один с надстройкой
----------------------------------
**Неподвижный** — прототип: уровень от цены входа, не двигается, живёт всё время
позиции (PROTOTYPE.md §5). Он и сверяется с прототипом.

**Скользящий** — надстройка «Терминала» (ТЗ §4.4 В, [решение 0009](
../.docs/decisions/0009-trailing-take-in-stage-one.md)). Пока прибыль меньше
порога включения, уровня **нет вовсе** — позицию держит переворот по средней.
Дошла до порога — запоминается лучшая достигнутая цена, уровень встаёт на отступе
от неё и дальше едет только в сторону прибыли.

⚠️ **Скользящий заменяет неподвижный, а не добавляется к нему.** Так написано
в ТЗ §4.4 В: «пока прибыль меньше порога, работает обычный стоп-лосс», а стоп-лосс
в этом алгоритме — переворот по средней (правка заказчика 4.4 Г). Включить оба
сразу нельзя: у позиции один сторожимый уровень.

⚠️ **Сверкой с прототипом скользящий тейк не проверяется и не будет.** В прототипе
его нет. Единственная его проверка — правило «едет только в сторону прибыли и ни разу
не откатился назад» (ТЗ §9) плюс отдельный прогон Э1-19 двумя цифрами рядом.

По какой цене едет скользящий уровень — и почему это выбор, а не мелочь
-----------------------------------------------------------------------
**По закрытиям свечей.** Лучшая достигнутая цена обновляется на шаге 5, то есть
на закрытии свечи, значением `close`.

Взять `high`/`low` было бы точнее по смыслу «лучшая достигнутая», но нельзя
дважды:

* решение 0008 запрещает движку читать `high`/`low` вообще — запрет держится
  разбором исходников всего `engine/`, потому что иначе граница «срабатывание
  тейка приходит только сделкой» обходится за три шага без всякого злого умысла;
* решение внутри свечи — дефект по правилу проекта: всё, кроме срабатывания
  самого тейка, решается на закрытии.

Цена выбора названа вслух: всплеск внутри бара, не удержавшийся к закрытию,
уровень **не** двигает. Цифр по скользящему тейку у проекта нет ни одной
(решение 0009), поэтому сравнить два варианта сегодня не с чем. Это записано
как открытый вопрос, а не как проверенное решение.

Параметры замораживаются на входе в позицию
-------------------------------------------
`TakeProfit` собирается один раз — в момент сделки открытия — и дальше не читает
настройки. Причина в ТЗ §4.4 А: изменение настройки действует **со следующей
сделки** и открытую позицию не трогает. Иначе смена процента на ходу двигала бы
уровень уже стоящей позиции, а включение скользящего тейка посреди неё меняло бы
сам механизм выхода.

⚠️ Прототип устроен иначе: его шаг 5 каждый раз пересчитывает уровень из текущего
значения параметра. Расхождение недостижимо сверкой — она идёт на неизменных
настройках, — и выбран вариант ТЗ, а не прототипа. Названо здесь, чтобы это
не выглядело недосмотром.

Отсюда же ответ на открытый вопрос решения 0009 «что при отключении скользящего
тейка на ходу»: **ничего**. Открытая позиция доживает со своим замороженным
планом и достигнутым уровнем, новая настройка работает со следующей сделки.
Возврат к неподвижному уровню от цены входа означал бы, что уровень поехал
назад, — а это прямо запрещено приёмочным правилом.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, replace
from decimal import ROUND_HALF_EVEN, Decimal

__all__ = [
    "TakeProfit",
    "round_level",
    "fixed_level",
    "target_profit",
    "covers_commission",
]


def round_level(value: float) -> float:
    """Уровень тейка → целое, половина к чётному (банковское округление).

    Не до шага цены инструмента: на эталонном инструменте шаг 25, а уровни тейка
    в журнале прототипа сплошь вне этой сетки — 217 180, 231 452, 230 542.
    Замерено перебором режимов округления на 127 сделках подряд:

    ==================================  ==================
    Как получен уровень                 Расхождений из 127
    ==================================  ==================
    **до целого, половина к чётному**   **0**
    до целого, половина вверх           1
    до целого, половина вниз            2
    до целого вниз, отбрасыванием       21
    без округления                      21
    до шага цены 25                     39
    ==================================  ==================

    Ровно на «половину» попадают 18 уровней из 127, и три из них различают
    гипотезы **в обе стороны**: 217 180,5 прототип свёл вниз, а 231 451,5
    и 230 541,5 — вверх. Одного случая для такого вывода не хватило бы.

    ⚠️ Считается в десятичном типе, а не в двоичном, и это не украшение.
    Половина — единственное место, где двоичное представление врёт заметно:
    `x,4999999999` вместо `x,5` меняет сторону округления и цену выхода.
    На эталонном отрезке двоичный расчёт дал бы те же 127 уровней (проверено,
    0 расхождений) — то есть выбор сделан ради устойчивости, а не ради сверки.
    Общий вопрос «двоичная арифметика против десятичной» остаётся открытым
    (ROADMAP §9.6а).

    ⚠️ Проверено только для инструмента с целой ценой. Поведение при ненулевом
    числе знаков после запятой прототипом не воспроизводилось.
    """
    return float(Decimal(repr(float(value))).quantize(Decimal(1), rounding=ROUND_HALF_EVEN))


def _percent_of(price: float, percent: float) -> float:
    """`цена * процент / 100` в десятичном типе — порядок действий как у прототипа.

    Порядок множителей значим ровно там же, где значимо округление: сначала
    умножение, потом деление на сто.
    """
    return float(Decimal(repr(float(price))) * Decimal(repr(float(percent))) / Decimal(100))


def fixed_level(entry_price: float, side_sign: int, percent: float) -> float | None:
    """Неподвижный уровень от цены входа. `None` — тейка нет.

    ::

        уровень = цена входа ± цена входа * (процент / 100)
        процент <= 0 → тейка нет

    :param side_sign: `+1` для лонга, `−1` для шорта.

    Процент, равный нулю, — не вырожденный случай, а рабочая конфигурация:
    два прогона эталонного архива сделаны именно так, и без неё воспроизводить
    их нечем (PROTOTYPE.md §1). Движок при этом не подаёт вооружения **вовсе**,
    а не вооружает на недостижимом уровне.
    """
    if not math.isfinite(percent) or percent <= 0:
        return None
    return round_level(entry_price + side_sign * _percent_of(entry_price, percent))


@dataclass(frozen=True, slots=True)
class TakeProfit:
    """План тейка одной позиции: параметры с момента входа и текущий уровень.

    `level` — то, что сторожит исполнитель. `None` означает «сторожить нечего»:
    тейк выключен, процент не положителен, или скользящий тейк ещё не дошёл
    до порога включения.

    `peak` — лучшая достигнутая цена по закрытиям свечей. `None` — скользящий
    тейк ещё не включился. Поле осмысленно только при `trailing`.

    ⚠️ Значение неизменяемое: `advance()` возвращает новый план, а не правит
    этот. Иначе снимок позиции, взятый на шаге 3, менялся бы прямо во время
    обработки свечи — а на нём стоит весь порядок обработки.
    """

    percent: float = 0.0
    trailing: bool = False
    start_percent: float = 0.0
    offset_percent: float = 0.0
    step_percent: float = 0.0
    level: float | None = None
    peak: float | None = None

    @property
    def armed(self) -> bool:
        """Есть ли уровень, который кто-то сторожит."""
        return self.level is not None

    @property
    def moving(self) -> bool:
        """Скользящий тейк включился и уровень поехал."""
        return self.trailing and self.peak is not None

    def initial(self, entry_price: float, side_sign: int) -> "TakeProfit":
        """План в момент сделки открытия.

        У неподвижного тейка уровень известен сразу — от цены входа. У скользящего
        уровня в этот момент нет вовсе: прибыль равна нулю, порог не достигнут,
        и позицию держит переворот по средней (ТЗ §4.4 В).
        """
        if self.trailing:
            return replace(self, level=None, peak=None)
        return replace(self, level=fixed_level(entry_price, side_sign, self.percent))

    def advance(
        self, entry_price: float, side_sign: int, close: float
    ) -> "TakeProfit":
        """Пересчёт на закрытии свечи. Шаг 5 порядка обработки.

        У неподвижного тейка результат тот же самый — уровень от цены входа
        не двигается, и перестановка означает лишь, что заявка живёт всё время
        позиции. У скользящего уровень может поехать.

        :param side_sign: `+1` для лонга, `−1` для шорта.
        :param close: закрытие только что закрывшейся свечи.
        """
        if not self.trailing:
            return replace(self, level=fixed_level(entry_price, side_sign, self.percent))
        if not math.isfinite(close):
            return self

        profit = side_sign * (close - entry_price)
        if self.peak is None:
            # Порог включения. Пока не дошли — уровня нет, и это не «уровень
            # далеко», а именно его отсутствие: сторожить нечего.
            if entry_price == 0 or profit / entry_price * 100 < self.start_percent:
                return self
            candidate = self._offset_from(close, side_sign)
            if side_sign * (candidate - entry_price) <= 0:
                # ⚠️ Уровень фиксации прибыли, стоящий по убыточную сторону
                # от цены входа, — не тейк, а стоп-лосс под чужим именем.
                # Такое сочетание порога и отступа настройки отвергают
                # (`EngineSettings`), но арифметика на границе всё равно
                # проверяется здесь: при пороге, лишь чуть большем отступа,
                # первый же уровень может лечь ровно на цену входа.
                # Приёмочное правило ТЗ §9 этот случай НЕ ловит — уровень
                # едет вперёд честно, он просто начинается в убытке.
                #
                # ⚠️ Вершина при этом НЕ запоминается: скользящий тейк
                # не включился вовсе, и порог на следующей свече считается
                # заново от цены входа. Следствие: если цена постоит в этой
                # узкой полосе и уйдёт выше, уровень встанет от НОВОЙ вершины,
                # а не от исторического максимума. Осознанно: включиться
                # с уровнем в убытке хуже, чем не включиться.
                return self
            return replace(self, peak=close, level=candidate)

        peak = close if side_sign * (close - self.peak) > 0 else self.peak
        candidate = self._offset_from(peak, side_sign)
        if self.level is None:
            if side_sign * (candidate - entry_price) <= 0:
                return replace(self, peak=peak)
            return replace(self, peak=peak, level=candidate)

        # `gain` — движение уровня **в сторону прибыли**, со знаком. Одно
        # сравнение держит два правила, и оба надо назвать вслух:
        #
        #   gain < 0        — откат. Приёмочное правило ТЗ §9: уровень никогда
        #                     не едет назад. Лучшая достигнутая цена
        #                     не обновилась, уровень остаётся там, где стоял;
        #   0 <= gain < шаг — движение есть, но мелкое. Шаг подтяжки это
        #                     ограничитель нагрузки, а не украшение: у скользящего
        #                     тейка каждое движение уровня это НАСТОЯЩАЯ операция
        #                     у брокера, снять и поставить заново. Без шага каждая
        #                     свеча с новым максимумом даёт обращение — за час
        #                     позиции до двенадцати (решение 0009).
        #
        # ⚠️ Сравнение **со знаком, а не по модулю**, и это не мелочь: `abs(gain)`
        # пропустил бы назад любой откат больше шага подтяжки. Двумя отдельными
        # проверками это было записано раньше, и вторая поглощала первую —
        # запрет ехать назад оказывался мёртвым кодом, который не мог сломаться
        # ни на одной ломаной цен.
        gain = side_sign * (candidate - self.level)
        if gain < abs(self.level) * self.step_percent / 100:
            return replace(self, peak=peak)
        return replace(self, peak=peak, level=candidate)

    def _offset_from(self, peak: float, side_sign: int) -> float:
        """Уровень на отступе от лучшей достигнутой цены.

        Ниже неё для лонга, **выше для шорта** — знак отступа определяется
        стороной позиции, и перепутать его значит закрывать шорт по уровню,
        который цена уже прошла.
        """
        return round_level(peak - side_sign * _percent_of(peak, self.offset_percent))


def target_profit(
    entry_price: float,
    level: float,
    volume: float,
    side_sign: int,
    *,
    ruble_per_point: float = 1.0,
) -> float:
    """Сколько рублей даст выход по этому уровню. **Со знаком.**

    ⚠️ По модулю мерить нельзя, и это не придирка. Уровень скользящего тейка
    может встать по убыточную сторону от цены входа — при пороге включения
    меньше отступа он там и окажется. Модуль превращает убыток 1 604 ₽
    в «цель 1 604 ₽», и строка журнала объявляет её окупающей комиссию.
    """
    return (level - entry_price) * side_sign * volume * ruble_per_point


def covers_commission(
    entry_price: float,
    level: float,
    volume: float,
    side_sign: int,
    *,
    commission_per_side: float | None,
    ruble_per_point: float = 1.0,
) -> bool | None:
    """Окупает ли цель по прибыли комиссию **обеих** сторон. `None` — тариф не задан.

    Требование ТЗ §4.4 В: «нижняя граница тейка не произвольна: цель должна
    окупать комиссию обеих сторон. Программа обязана проверять это правило
    и не ставить цель ниже издержек».

    ⚠️ **Цель считается со знаком** (`target_profit`), а не по модулю: уровень
    по убыточную сторону от цены входа комиссию не окупает никогда, сколько бы
    пунктов до него ни было.

    ⚠️ **Проверить в момент ввода настройки нельзя, и это не отговорка.**
    Цель в рублях — это `(уровень − цена входа) × знак стороны × объём`,
    то есть она зависит
    от цены входа, которой в момент правки настроек ещё нет. Поэтому движок
    проверяет цель тогда, когда она становится конкретной — при вооружении
    тейка, — и пишет в журнал, когда она не окупается. Запрет на ввод такого
    процента — дело окна настроек, где рядом есть цена инструмента.

    ⚠️ **Отказаться вооружать неокупаемый тейк движок не вправе.** Снятая
    защита стоит дороже маленькой цели: позиция осталась бы вообще без уровня,
    и узнать об этом владелец счёта смог бы только по факту убытка. Поэтому
    здесь предикат и строка в журнале, а не отказ.

    :param commission_per_side: рублей за контракт на **одну** сторону.
        `None` — тариф движку не сообщён, проверка невыполнима; молча
        подставленный ноль превратил бы её в вечное «окупается».
    :param ruble_per_point: сколько рублей в одном пункте цены. Свойство
        инструмента, а не настройка стратегии: на эталонном фьючерсе единица
        (PROTOTYPE.md §6). Переедет в карточку инструмента, когда инструментов
        станет больше одного (DOMAIN.md §9).
    """
    if commission_per_side is None:
        return None
    target = target_profit(
        entry_price, level, volume, side_sign, ruble_per_point=ruble_per_point
    )
    return target > 2 * commission_per_side * volume
