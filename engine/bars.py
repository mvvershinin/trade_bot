"""Перекладка свечи из слоя данных в свечу торгового модуля. Одна явная строка.

Зачем отдельный модуль на одно преобразование
---------------------------------------------
У свечи слоя данных поле `time` — это **начало** свечи. У свечи торгового
модуля поле `closes_at` — время **закрытия**, и поля `time` у неё нет вовсе.
Величины различаются на таймфрейм, а имена не различались никак: формы классов
совпадали, соответствие в проекте структурное, проверок типа нет — и утиная
типизация подменяла одно другим молча. Ровно это уже сдвинуло на один бар
весь график с метками; заметить можно было только сравнением с чужим
терминалом (ARCHITECTURE.md §2, докстринг `ui/models.py`).

Поэтому перекладку делает движок, и делает её **явной строкой, которую видно
в ревью**, а не молчаливой передачей объекта. Это стоит одной функции против
расхождения сверки, которое искали бы в стратегии.

Проверка стоит с обеих сторон:

* `strategies.check_bar` отвергает объект с полем `time` — свечу слоя данных,
  попавшую в модуль;
* `check_market_candle` ниже отвергает объект с полем `closes_at` — свечу
  модуля или окна, попавшую в источник свечей движка.

Что движок отсеивает до модуля
------------------------------
Незакрытые (`unsettled`) свечи — всегда: решение по незакрытой свече это дефект,
а не настройка (QUALITY.md §6). Повторно поданные — всегда. Неполные
(`filled_minutes` меньше таймфрейма) — по настройке, умолчание «принимать».
В контракте торгового модуля этих полей нет намеренно: отсеивать — обязанность
движка, и соблазна «а вдруг пригодится» у модуля возникнуть не должно.

Почему повтор ловит движок, а не торговый модуль
------------------------------------------------
Повтор последней свечи после переподключения — **штатное поведение потока**,
а не сбой. Принятая молча, такая свеча входит в среднюю дважды и сдвигает
прогрев: другой список сделок без единого падения по дороге. Хуже того,
в движке она проходит все десять шагов заново и на пустом снимке даёт **вторую
заявку на вход**.

Защита есть и в модуле №1 — там она про порядок его собственного ряда, и она
остаётся. Но полагаться на неё нельзя: это гарантия **транспорта**, общая для
всех сменных модулей, а по ARCHITECTURE.md §3 общее живёт в движке
и в каждом модуле не дублируется. Второй торговый модуль, не скопировавший
защиту, при первом же переподключении подал бы вторую заявку.

⚠️ Ход времени **назад** здесь не гасится: это порча ряда, и она обязана
останавливать прогон, а не превращаться в пропущенную свечу. Отвергает её
торговый модуль исключением — по своему собственному ряду, который он и ведёт.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta

from strategies import Bar

from engine.settings import PartialCandles
from engine.window import in_moscow

__all__ = [
    "Intake",
    "check_market_candle",
    "close_time",
    "to_bar",
    "intake",
]


def check_market_candle(candle: object) -> None:
    """Объект годится на роль свечи из источника — или отказ вслух.

    ⚠️ `filled_minutes` входит в обязательные поля, хотя движок читает его
    только при настройке «пропускать неполные свечи». Иначе получается галочка,
    которая работает в тестере и роняет цикл в бою: источник, не умеющий
    сообщать полноту, проходил бы приём молча, а отказ вылезал бы позже —
    на первой же свече после включения настройки, изнутри обработки. Поле
    объявлено в порту, и источник, не умеющий его отдать, отказывает
    на границе (`engine/ports.py`, `MarketCandle`).

    :raises TypeError:
        подан объект не той формы: свеча торгового модуля или окна
        (поле `closes_at`), либо не свеча вовсе, либо источник не сообщает
        полноту свечи.
    """
    if hasattr(candle, "closes_at"):
        raise TypeError(
            "у свечи есть поле `closes_at` — это объект другого слоя, где время "
            "означает ЗАКРЫТИЕ свечи. Источник свечей отдаёт движку свечу "
            "со временем НАЧАЛА в поле `time`, а закрытие движок считает сам: "
            "начало + таймфрейм. Принять её как есть — значит сдвинуть торговое "
            "окно и весь график на один бар"
        )
    missing = [
        name
        for name in (
            "time", "timeframe", "open", "high", "low", "close",
            "unsettled", "filled_minutes",
        )
        if not hasattr(candle, name)
    ]
    if missing:
        raise TypeError(
            f"это не свеча источника: нет полей {', '.join(missing)}. "
            "Ожидается объект формы market.Candle"
        )
    if not hasattr(candle.timeframe, "minutes"):
        raise TypeError(
            "у таймфрейма свечи нет размера в минутах: время закрытия "
            "считается как начало + таймфрейм, считать нечем"
        )


def close_time(candle: object) -> datetime:
    """Шаг 4 порядка обработки: время закрытия = начало свечи + таймфрейм.

    У свечи хранится только начало. «Терминал» обязан считать так же, как
    прототип, иначе торговое окно сдвинется на одну свечу (PROTOTYPE.md §4).

    Время без часового пояса отвергается **здесь**, до того как свеча уйдёт
    в торговый модуль. Проверить его позже — на шаге 6, когда считается окно, —
    значит уронить разбор уже после того, как закрытие вошло в среднюю:
    ряд модуля окажется испорчен, а прогон придётся начинать заново.

    :raises ValueError: время начала свечи без часового пояса.
    """
    check_market_candle(candle)
    in_moscow(candle.time)  # type: ignore[attr-defined]
    return candle.time + timedelta(minutes=candle.timeframe.minutes)  # type: ignore[attr-defined]


def to_bar(candle: object) -> Bar:
    """Свеча слоя данных → свеча торгового модуля. Та самая явная строка.

    Ни одного поля не переносится «как есть» по имени: время закрытия
    вычисляется, и это единственное место в программе, где это происходит.
    """
    closes_at = close_time(candle)
    return Bar(
        closes_at=closes_at,
        open=float(candle.open),      # type: ignore[attr-defined]
        high=float(candle.high),      # type: ignore[attr-defined]
        low=float(candle.low),        # type: ignore[attr-defined]
        close=float(candle.close),    # type: ignore[attr-defined]
        volume=float(getattr(candle, "volume", 0.0) or 0.0),
    )


@dataclass(frozen=True, slots=True)
class Intake:
    """Что движок сделал со свечой, пришедшей из источника.

    `bar` пуст — свеча в обработку не пошла, и `skipped` объясняет почему
    человеческим языком.

    `unsettled` отличает два вида отказа, и различать их обязательно:
    незакрытая свеча приходит в живом потоке постоянно, и строка журнала
    на каждый её приход утопила бы настоящие события; отброшенная неполная
    свеча — редкость и меняет ряд, по которому считается средняя.

    `repeat` — третий вид: свеча за то же время подана ещё раз. Событие
    штатное (переподключение к потоку), поэтому строка журнала у неё
    спокойная, а не тревожная.
    """

    closes_at: datetime
    bar: Bar | None = None
    skipped: str = ""
    unsettled: bool = False
    repeat: bool = False

    @property
    def accepted(self) -> bool:
        return self.bar is not None


def intake(
    candle: object,
    *,
    partial: PartialCandles = PartialCandles.ACCEPT,
    previous: datetime | None = None,
) -> Intake:
    """Приём свечи: отсеять незакрытую, повторную и, по настройке, неполную.

    Незакрытая и повторная отсеиваются всегда. Неполная — по настройке; почему
    это настройка, а не зашитый выбор, разобрано в
    `engine.settings.PartialCandles`.

    :param previous: время закрытия последней **принятой** свечи. `None` —
        принятых ещё не было. Свеча с тем же временем закрытия дальше
        не идёт: она уже учтена, и второй раз в среднюю входить не должна.
        Свеча более ранняя тоже отсеивается — но не здесь: порядок своего ряда
        ведёт торговый модуль, и порчу ряда он останавливает исключением
        (см. шапку модуля).
    """
    closes_at = close_time(candle)
    if getattr(candle, "unsettled", False):
        return Intake(
            closes_at=closes_at,
            unsettled=True,
            skipped=(
                "Свеча ещё не закрыта — в обработку не идёт. Решение по "
                "незакрытой свече даёт сигнал, которого в бою не будет"
            ),
        )
    if previous is not None and closes_at == previous:
        return Intake(
            closes_at=closes_at,
            repeat=True,
            skipped=(
                f"Свеча за {in_moscow(closes_at):%d.%m %H:%M} подана повторно — "
                "уже учтена, в обработку не идёт. Так бывает после "
                "переподключения к потоку. Принять её второй раз значило бы "
                "посчитать по ней среднюю дважды и подать вторую заявку"
            ),
        )
    if partial is PartialCandles.SKIP:
        # `filled_minutes` обязателен на приёме (`check_market_candle`), так что
        # сюда дойдёт только источник, умеющий его сообщать.
        filled = candle.filled_minutes  # type: ignore[attr-defined]
        size = candle.timeframe.minutes  # type: ignore[attr-defined]
        if filled < size:
            return Intake(
                closes_at=closes_at,
                skipped=(
                    f"В свече {filled} минут из {size} — по настройке неполные "
                    "свечи пропускаются. Она не войдёт ни в среднюю, ни в прогрев. "
                    "Сделки, случившиеся к её началу, движок при этом принимает: "
                    "заявка, поданная на прошлой свече, исполняется по первой "
                    "цене этого интервала — торги в нём шли, неполна наша сборка"
                ),
            )
    return Intake(closes_at=closes_at, bar=to_bar(candle))
