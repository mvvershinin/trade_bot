@dataclass(frozen=True, slots=True)
class EngineSettings:
    """Общие настройки движка. Неизменяемое значение.

    Меняются на ходу, без перезапуска: `Engine.apply_settings()` подменяет
    значение целиком и пишет в журнал прежнее и новое (ТЗ §4.4 А). Новое
    значение действует **со следующей сделки** — открытую позицию оно
    не трогает, потому что объём читается только в момент подачи заявки
    на вход, а окно и режим на уже открытую позицию не смотрят.
    """

    mode: Mode = Mode.OFF
    window: TradingWindow = TradingWindow()
    close_on_time_end: bool = True
    trade_in_weekend: bool = False
    volume: float = 1.0
    reversal: Reversal = Reversal.THROUGH_BAR
    take_profit: bool = True
    take_profit_percent: float = 0.5
    trailing_take_profit: bool = False
    trailing_start_percent: float = 0.5
    trailing_offset_percent: float = 0.2
    trailing_step_percent: float = 0.05
    stop_after_take_profit: bool = True
    partial_candles: PartialCandles = PartialCandles.ACCEPT
    #: Жёсткий потолок объёма: число контрактов, **выше** которого заявка
    #: на вход не подаётся вовсе (DOMAIN.md §5). `None` — потолка нет,
    #: и это умолчание: у прототипа потолка нет, а сверка с ним обязана
    #: сходиться 127 сделок из 127.
    #:
    #: ⚠️ Неравенство строгое: объём, **равный** потолку, проходит. Потолок —
    #: это «не больше чем», а не «меньше чем», и владелец счёта, поставивший
    #: объём ровно по потолку, торговать обязан.
    #:
    #: ⚠️ Потолок сторожит **вход**, и только его. Заявка на выход через него
    #: не проходит никогда: позиция, которая больше потолка, иначе осталась бы
    #: в рынке навсегда — потолок, поставленный против опечатки, сам стал бы
    #: ловушкой.
    volume_cap: float | None = None
    #: Дневной лимит убытка в процентах от размера счёта **на утро**. Ноль —
    #: лимита нет, и так же подписано поле в окне («0,00 % — лимита нет»).
    #:
    #: Считается от снимка счёта, первым пришедшего в эту календарную дату,
    #: и внутри дня не пересчитывается: иначе просадка сама уменьшала бы порог
    #: и остановка наступала бы всё раньше (DOMAIN.md §4). В убыток входит
    #: **бумажная** переоценка открытой позиции вместе с зафиксированным
    #: (решение 0014), а возобновление после срабатывания — **только вручную**.
    daily_loss_limit_percent: float = 0.0
    #: Доля свободных средств, которую робот не трогает. Ноль — запаса нет,
    #: то есть под ГО можно занять все свободные деньги.
    #:
    #: ⚠️ Само по себе это поле ничего не включает и не выключает: проверка ГО
    #: работает тогда и только тогда, когда движку сообщили деньги счёта
    #: (`EngineState.funds`) вместе с ГО контракта. Нет снимка — считать
    #: не от чего, и движок говорит об этом строкой журнала.
    free_funds_reserve_percent: float = 0.0
    #: Комиссия за контракт на сторону. `None` — «тариф не задан», и это НЕ то же
    #: самое, что ноль: при `None` движок пишет «НЕ ПРОВЕРЕНО» на каждой позиции,
    #: потому что окупаемость цели без тарифа не проверить (ТЗ §4.4 В).
    #:
    #: ⚠️ Явный `0.0` разрешён намеренно — разобрано 03.09.2026, это не недосмотр.
    #: Повод для разбора: `backtest.Tariff` тогда же научился отвергать нулевой
    #: биржевой сбор, где ноль давал правдоподобную комиссию 254 ₽ вместо 3 556 ₽
    #: при непустой колонке — то есть сливал два смысла молча. Здесь слияния нет:
    #: из окна ноль недостижим, `ui/settings_dialog.py:611` переводит `<= 0`
    #: в `None`, поле показывает «не задан» и печатает рядом, что именно
    #: без тарифа не проверяется. Единственный потребитель явного нуля —
    #: граничный тест `tests/test_engine_take_profit.py:1947`: цель ровно
    #: на цене входа даёт ноль прибыли, а ноль прибыли не окупает даже нулевых
    #: издержек. Запрет сломал бы осмысленное утверждение и не закрыл бы ничего.
    commission_per_side: float | None = None
    ruble_per_point: float = 1.0
    #: Сколько закрытых свечей робот ждёт исполнения выхода, прежде чем
    #: остановиться и позвать человека.
    #:
    #: ⚠️ **На этом числе стоит безопасность умолчания `Refusal.UNKNOWN`.**
    #: Исполнитель, не назвавший причину отказа, заставляет движок считать
    #: сторожа живым и ждать сделку. Ошибка в эту сторону ограничена и громкая:
    #: позиция без управления несколько свечей, дальше счётчик и остановка.
    #: Ошибка в обратную — шорт на полный объём, и движок про него не узнает
    #: никогда. Гарантию даёт счётчик, а не умолчание само по себе: поднимет
    #: владелец счёта ожидание — граница ошибки вырастет ровно во столько же.
    #:
    #: Отсюда две вещи, и обе проверяются кодом, а не обещанием:
    #:
    #: * **верхняя граница** `MAX_CLOSE_WAIT_BARS` в `__post_init__`. Без неё
    #:   утверждение выше было бы неправдой: `close_wait_bars=100` — это
    #:   восемь часов в рынке через вечернюю сессию со сторожем, которого
    #:   считают живым, и никакой границы ошибки не остаётся;
    #: * **строка в журнале** при изменении на ходу (`changes_from`). Поля
    #:   в окне настроек у этого числа нет, но `apply_settings` принимает
    #:   `EngineSettings` целиком — то есть подменить его может кто угодно,
    #:   кто соберёт новое значение. Молча такая подмена проходить не должна.
    #:
    #: ⚠️ Граница считает **свечи, а не минуты**: таймфрейм движку задаёт
    #: источник, и на дневных свечах даже умолчание означает трое суток.
    #: Это ограничение границы названо вслух, а не спрятано.
    close_wait_bars: int = 3
    #: Календарь владельца счёта: дни, про которые он сказал сам —
    #: «в этот день не торгуем» или «этот день торговый, хоть и суббота».
    #: Пусто — умолчание, и это в точности прототип: будни торговые, суббота
    #: и воскресенье нет. На пустом календаре стоит сверка, 127 сделок из 127.
    #:
    #: ⚠️ Календарь **действует и на истории**. Иначе проверка на истории
    #: перестала бы отвечать на вопрос «что было бы»: прогон торговал бы
    #: в дни, в которые робот заведомо промолчит.
    calendar: DayMarks = NO_MARKS
    #: Что сказала **биржа** про конкретные дни (расписание брокера,
    #: `broker/schedule.py`). Отдельным полем от календаря владельца счёта
    #: намеренно: это факт про мир, а не воля, и мышкой он не снимается.
    #:
    #: ⚠️ Биржа **только запрещает**. «Не работает» перебивает отметку
    #: «торгуем» (решение 0038), а «работает» отменяет лишь календарный
    #: выходной — но не отметку владельца счёта «не торгуем»: его воля
    #: сильнее, он вправе не входить в рынок в любой день.
    #:
    #: ⚠️ **Сегодня сюда никто ничего не кладёт.** У брокера метод расписания
    #: отвечает только про сегодняшний день, а проводка живого ответа
    #: в движок не сделана (`F-002`, долг назван вслух). Пустой набор
    #: означает «не знаем», и это НЕ «закрыто»: программа ведёт себя так же,
    #: как вела до появления расписания.
    exchange_days: DayMarks = NO_MARKS

    def plan(self) -> TakeProfit:
        """План тейка для следующей сделки — то, что заморозится на входе.

        Читается ровно один раз, в момент сделки открытия. Дальше позиция живёт
        со своим планом и настроек больше не спрашивает: новое значение
        действует **со следующей сделки** и открытую позицию не трогает
        (ТЗ §4.4 А).
        """
        percent = self.take_profit_percent if self.take_profit else 0.0
        return TakeProfit(
            percent=percent,
            trailing=self.take_profit and self.trailing_take_profit,
            start_percent=self.trailing_start_percent,
            offset_percent=self.trailing_offset_percent,
            step_percent=self.trailing_step_percent,
        )

    def __post_init__(self) -> None:
        """Отказать на негодном значении, до того как оно уйдёт в заявку.

        Порядок вызовов — порядок проверок в исходном коде: если испорчено
        сразу несколько полей, наружу уходит первый по этому списку отказ,
        и это поведение не меняется разбором на методы. Каждый метод —
        свой смысл: `changes_from` выше устроен таблицей, потому что все
        семнадцать полей проверяются одинаково («изменилось — да/нет»); здесь
        шесть числовых правил различаются по существу (денежные асимметрии
        перечислены в докстринге каждого метода), и слияние их в одну таблицу
        стёрло бы эти различия — поэтому здесь методы, а не таблица.
        """
        self._check_enum_fields()
        self._check_calendar_fields()
        self._check_bool_fields()
        self._check_volume()
        self._check_percent_fields()
        self._check_trailing_pair()
        self._check_commission()
        self._check_ruble_per_point()
        self._check_close_wait_bars()
        self._check_volume_cap()
        self._check_guard_percents()

    def _check_enum_fields(self) -> None:
        """Тип `mode`, `window`, `reversal`, `partial_candles` — и только тип."""
        for name, expected, phrase in _ENUM_FIELD_CHECKS:
            value = getattr(self, name)
            if not isinstance(value, expected):
                raise TypeError(f"{phrase}, получено {value!r}")

    def _check_calendar_fields(self) -> None:
        """Тип двух наборов отметок — и только тип.

        Проверка нужна ровно за тем же, за чем она нужна перечислениям:
        словарь вместо `DayMarks` не упал бы здесь, а `answer()` у него нет —
        и отметки молча перестали бы действовать, оставшись видимыми в окне.
        """
        for name in ("calendar", "exchange_days"):
            value = getattr(self, name)
            if not isinstance(value, DayMarks):
                raise TypeError(
                    f"настройка `{name}` — engine.DayMarks, получено {value!r}"
                )

    def _check_bool_fields(self) -> None:
        """Тип пяти булевых полей — и только тип."""
        for name in (
            "close_on_time_end", "trade_in_weekend", "stop_after_take_profit",
            "take_profit", "trailing_take_profit",
        ):
            if not isinstance(getattr(self, name), bool):
                raise TypeError(f"настройка `{name}` — булево, получено {getattr(self, name)!r}")

    def _check_volume(self) -> None:
        """Объём: число и положительное.

        ⚠️ Без `math.isfinite` — намеренно не в этой фазе:
        `EngineSettings(volume=float("nan"))` проходит, это заведённый долг
        (`ROADMAP.md` §9.10). Дописать проверку здесь значило бы поменять
        поведение под видом сохраняющего рефакторинга — план Э1-0г это
        запрещает.
        """
        if isinstance(self.volume, bool) or not isinstance(self.volume, (int, float)):
            raise TypeError(f"объём — число, получено {self.volume!r}")
        if self.volume <= 0:
            raise ValueError(f"объём должен быть положительным: {self.volume}")

    def _check_percent_fields(self) -> None:
        """Тип и конечность четырёх процентов тейка.

        ⚠️ Знак НЕ проверяется здесь намеренно: «процент <= 0 — тейка нет»
        — правило прототипа (PROTOTYPE.md §5), и ноль (как и отрицательное)
        здесь рабочая конфигурация, а не вырожденная. Двумя прогонами
        эталонного архива сделана именно она, и без неё их воспроизводить
        нечем.
        """
        for name in (
            "take_profit_percent", "trailing_start_percent",
            "trailing_offset_percent", "trailing_step_percent",
        ):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise TypeError(f"настройка `{name}` — число, получено {value!r}")
            if not math.isfinite(value):
                raise ValueError(f"настройка `{name}` не число: {value!r}")

    def _check_trailing_pair(self) -> None:
        """Знак и парность `trailing_*` — но только пока трейлинг включён.

        Метод на `self`, а не свободная функция с двумя позиционными
        `float`: на месте вызова такие позиционные аргументы можно
        перепутать местами, а это тот же класс дефекта, что и развязанная
        парная проверка (мутация приёмки №5).
        """
        if not self.trailing_take_profit:
            return
        if self.trailing_offset_percent <= 0:
            raise ValueError(
                "у скользящего тейка отступ должен быть положительным: "
                "уровень на нулевом отступе стоит ровно на цене, получено "
                f"{self.trailing_offset_percent!r}"
            )
        if self.trailing_step_percent < 0:
            # ⚠️ Опора на «шаг не бывает отрицательным» стала явной, когда
            # два сравнения в `TakeProfit.advance` слились в одно: там
            # порог сравнивается со ЗНАКОВЫМ движением уровня, и
            # отрицательный шаг разрешил бы уровню ехать назад ровно
            # на его величину. Приёмочное правило ТЗ §9 этого не допускает.
            raise ValueError(
                "шаг подтяжки скользящего тейка не может быть "
                f"отрицательным: {self.trailing_step_percent!r}. Уровень "
                "поехал бы назад на его величину"
            )
        if self.trailing_start_percent <= self.trailing_offset_percent:
            # ⚠️ Замерено: порог 0,1 при отступе 1,0, лонг от 200 000,
            # закрытие 200 400 → уровень 198 396, то есть выход в убыток
            # 1 604 ₽ на контракт. Приёмочное правило ТЗ §9 этот случай
            # НЕ ловит: уровень едет вперёд честно, он просто начинается
            # в убытке. Отсюда запрет на границе настроек, а не только
            # проверка в расчёте.
            raise ValueError(
                "порог включения скользящего тейка должен быть больше "
                f"отступа: {self.trailing_start_percent!r} против "
                f"{self.trailing_offset_percent!r}. Иначе уровень встаёт "
                "по убыточную сторону от цены входа, и «фиксация прибыли» "
                "оказывается стоп-лоссом под чужим именем"
            )

    def _check_commission(self) -> None:
        """Комиссия: `None` разрешён явно, иначе число, конечное, не меньше нуля.

        ⚠️ Явный `0.0` тоже разрешён намеренно — разобрано 03.09.2026,
        граничный тест `tests/test_engine_take_profit.py:1947`: цель ровно
        на цене входа даёт ноль прибыли, а ноль прибыли не окупает даже
        нулевых издержек. `None` — другой смысл: «тариф не задан».
        """
        if self.commission_per_side is None:
            return
        if isinstance(self.commission_per_side, bool) or not isinstance(
            self.commission_per_side, (int, float)
        ):
            raise TypeError(
                "комиссия за контракт на сторону — число или None, "
                f"получено {self.commission_per_side!r}"
            )
        if not math.isfinite(self.commission_per_side) or self.commission_per_side < 0:
            raise ValueError(
                f"комиссия не может быть такой: {self.commission_per_side!r}"
            )

    def _check_ruble_per_point(self) -> None:
        """Рублей в пункте: число, конечное, строго больше нуля."""
        if isinstance(self.ruble_per_point, bool) or not isinstance(
            self.ruble_per_point, (int, float)
        ):
            raise TypeError(f"рублей в пункте — число, получено {self.ruble_per_point!r}")
        if not math.isfinite(self.ruble_per_point) or self.ruble_per_point <= 0:
            raise ValueError(f"рублей в пункте должно быть больше нуля: {self.ruble_per_point!r}")

    def _check_close_wait_bars(self) -> None:
        """Ожидание выхода: целое от 1 до `MAX_CLOSE_WAIT_BARS` включительно."""
        if isinstance(self.close_wait_bars, bool) or not isinstance(self.close_wait_bars, int):
            raise TypeError(
                f"ожидание выхода — целое число свечей, получено {self.close_wait_bars!r}"
            )
        if self.close_wait_bars < 1:
            raise ValueError(
                "ждать исполнения выхода надо хотя бы одну свечу: у прототипа "
                "заявка исполняется по открытию следующей, и ноль означал бы "
                f"остановку на каждом штатном выходе, получено {self.close_wait_bars!r}"
            )
        if self.close_wait_bars > MAX_CLOSE_WAIT_BARS:
            # ⚠️ Граница, а не совет. На этом числе стоит обещание «ошибка
            # умолчания `Refusal.UNKNOWN` ограничена и громкая»: движок
            # считает сторожа живым и ждёт сделку ровно столько свечей.
            # Подняв ожидание, вызывающий продлевает время, которое позиция
            # проводит без управления, — и делает это молча, потому что
            # `apply_settings` принимает `EngineSettings` целиком.
            raise ValueError(
                "ждать исполнения выхода дольше "
                f"{MAX_CLOSE_WAIT_BARS} свечей нельзя: на пятиминутках это "
                "уже дольше умолчательного торгового окна, а всё это время "
                "позиция стоит без управления и со сторожем, которого движок "
                f"считает живым. Получено {self.close_wait_bars!r}"
            )

    def _check_volume_cap(self) -> None:
        """Потолок объёма: `None` разрешён явно, иначе число, конечное, больше нуля.

        ⚠️ `None` и ноль — **разные** смыслы, и слить их нельзя. `None` значит
        «потолка нет»; ноль значил бы «не подавать ни одной заявки», то есть
        выключенного робота под видом предохранителя. Такое выключение обязано
        делаться режимом и быть видно в окне, а не прятаться в поле объёма.
        """
        if self.volume_cap is None:
            return
        if isinstance(self.volume_cap, bool) or not isinstance(
            self.volume_cap, (int, float)
        ):
            raise TypeError(
                f"потолок объёма — число или None, получено {self.volume_cap!r}"
            )
        if not math.isfinite(self.volume_cap) or self.volume_cap <= 0:
            raise ValueError(
                "потолок объёма должен быть больше нуля: "
                f"{self.volume_cap!r}. «Потолка нет» выражается значением None, "
                "а не нулём: ноль означал бы робота, которому запрещён любой вход"
            )

    def _check_guard_percents(self) -> None:
        """Два процента предохранителей: от нуля включительно и меньше ста.

        Ноль у обоих — рабочая настройка, а не вырожденная: «лимита нет»
        и «запаса нет». Сто и больше — нет: лимит убытка в сто процентов счёта
        означает, что робот останавливается, только потеряв счёт целиком,
        а запас в сто процентов свободных средств — что торговать нельзя
        никогда. Обе величины выглядят предохранителем и им не являются.
        """
        for name, what in (
            ("daily_loss_limit_percent", "дневной лимит убытка"),
            ("free_funds_reserve_percent", "запас свободных средств"),
        ):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise TypeError(f"{what} — число процентов, получено {value!r}")
            if not math.isfinite(value):
                raise ValueError(f"{what} не число: {value!r}")
            if value < 0:
                raise ValueError(
                    f"{what} не может быть отрицательным: {value!r}. "
                    "«Не задан» выражается нулём"
                )
            if value >= MAX_GUARD_PERCENT:
                raise ValueError(
                    f"{what} в {value!r}% предохранителем не является: "
                    "он либо не сработает никогда, либо не даст торговать "
                    "ни разу"
                )

    def replace(self, **changes: object) -> "EngineSettings":
        return replace(self, **changes)  # type: ignore[arg-type]

    def changes_from(self, previous: "EngineSettings") -> list[str]:
        """Что изменилось — строками для журнала, с прежним и новым значением.

        ТЗ §4.4 А требует писать изменение настройки с обоими значениями:
        «было 1 контракт, стало 2», а не «объём изменён».

        Одна строка кода на поле, а не одна строка на поле руками: список
        `_CHANGE_ROWS` — единственное место, где поле называется, порядок
        строк журнала — порядок этого списка. Компаратор у каждого поля
        свой и с полем не путается: три перечисления (`mode`, `reversal`,
        `partial_candles`) сравниваются тождеством — их значения синглтоны,
        и это безопасно, — четырнадцать остальных сравниваются на равенство,
        потому что `app/convert.py:277` пересобирает `volume` заново при
        каждом вызове (`float(values.volume)`): тождество увидело бы смену
        там, где значение то же самое
        (`tests/test_app_convert.py::test_an_unchanged_pair_produces_no_journal_lines`).
        """
        lines: list[str] = []
        for name, title, by_identity, render in _CHANGE_ROWS:
            was, now = getattr(previous, name), getattr(self, name)
            changed = was is not now if by_identity else was != now
            if changed:
                lines.append(f"{title}: {render(was)} → {render(now)}")
        return lines


def _yes_no(value: bool) -> str:
    return "да" if value else "нет"


def _percent(value: float) -> str:
    return f"{value:g}".replace(".", ",")


def _money(value: float | None) -> str:
    """Тариф для журнала. `None` — честное «не задана», а не подставленный ноль."""
    if value is None:
        return "не задана"
    return f"{value:g}".replace(".", ",") + " ₽"


def _cap(value: float | None) -> str:
    """Потолок для журнала. `None` — честное «нет», а не подставленное число."""
    if value is None:
        return "нет"
    return _volume(value)


def _limit(value: float) -> str:
    """Процент предохранителя. Ноль печатается словами: «нет» читается однозначно."""
    if value <= 0:
        return "нет"
    return f"{value:g}".replace(".", ",")


def _bars(count: int) -> str:
    """Свечи для журнала: «1 свеча», «3 свечи», «12 свечей»."""
    tail = abs(count) % 100
    if 11 <= tail <= 14:
        return f"{count} свечей"
    return {
        1: f"{count} свеча", 2: f"{count} свечи",
        3: f"{count} свечи", 4: f"{count} свечи",
    }.get(tail % 10, f"{count} свечей")


def _volume(value: float) -> str:
    """Объём для журнала: целое пишется без дробной части."""
    if float(value).is_integer():
        return str(int(value))
    return f"{value:g}".replace(".", ",")


def _label(value: Mode | Reversal | PartialCandles | TradingWindow | DayMarks) -> str:
    """Подпись перечисления, окна или календаря для журнала — общий рендер."""
    return value.label


