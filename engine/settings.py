"""Общие настройки движка: окно, режим, выходные, объём.

Здесь живёт то, что общее для **всех** торговых модулей и потому не дублируется
в каждом из них (ARCHITECTURE.md §3): торговое окно, дни недели, режим работы,
объём, поведение на границе окна. Настройки самого модуля — период средней,
тип средней, поведение при закрытии ровно на средней — живут в модуле
и сохраняются отдельно.

Умолчания взяты из ТЗ и DOMAIN.md §4, а **не** из прототипа: у того окно
09:30–11:30, у ТЗ 10:05–11:00. Цифры ТЗ получены подбором на том же отрезке
истории, на котором проверялись, — это подгонка, и она проговорена вслух
(PROTOTYPE.md §1). При сверке с прототипом все параметры задаются явно
с обеих сторон, умолчания не используются.

Чего здесь пока нет
-------------------
Потолка объёма, дневного лимита убытка, проверки ГО и интервалов пауз
(этап 2); способов расчёта объёма кроме «в контрактах» — они опираются
на текущую лучшую цену и состояние портфеля, по свечам их не воспроизвести
(PROTOTYPE.md §1).

⚠️ Из трёх вариантов поведения после сработавшего тейка (ТЗ §4.4 В) здесь
выражены **два**: `stop_after_take_profit` включён — «не входить до конца дня»,
выключен — «вход по обычным правилам, то есть по следующему сигналу средней».
Третьего, «сразу восстановить позицию», в движке нет: у него нет однозначного
прочтения — в какую сторону восстанавливать, на какой свече и по какой цене, —
а прототипом он не воспроизводился и данными не подкреплён ничем. Писать его
по догадке значило бы поставить непроверенную ветку на путь, по которому идут
деньги. Вариант остаётся долгом Э1-19 и требует ответа заказчика.
"""

