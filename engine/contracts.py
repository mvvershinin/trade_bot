"""Значения, которыми движок обменивается с внешним миром и с самим собой.

Здесь нет ни одного правила торговли — только формы. Правила живут
в `engine/pipeline.py`, ввод-вывод — в `engine/ports.py` и `engine/runner.py`.

Три вещи, ради которых эти типы объявлены отдельно:

**Заявка — не сделка.** `OrderRequest` означает «подать», `Fill` — «исполнилось».
У прототипа между ними ровно одна свеча: заявка, поданная на закрытии свечи *i*,
исполняется по `open` свечи *i+1*, и временем сделки записывается **начало**
свечи *i+1* (PROTOTYPE.md §2). Движок этого правила не знает и знать не должен:
когда именно заявка станет сделкой, решает исполнитель за портом — модель
исполнения на истории или брокер в бою. Слить два понятия в одно значило бы
зашить модель исполнения в движок и потерять §1 архитектуры.

**Позиция живёт в двух состояниях.** `OPEN` и `CLOSING`. Заявка на выход подана —
позиция переходит в `CLOSING` и **остаётся в снимке**. Именно поэтому вход
в обратную сторону не подаётся на той же свече: снимок не пуст. Это и есть
«переворот через свечу» (PROTOTYPE.md §2). Убрать `CLOSING` и удалять позицию
сразу при подаче заявки — значит получить другой список сделок.

**Журнал решений — часть работы движка, а не логирование.** Каждое действие
робота обязано иметь строку с причиной человеческим языком (ТЗ §4.6).
Действие без строки — дефект, даже если оно верное.
"""

