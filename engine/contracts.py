def _check_volume(value: float, what: str) -> None:
    """Объём положителен и конечен.

    `nan` проверку «больше нуля» проходит молча — любое сравнение с ним ложно,
    поэтому конечность проверяется отдельно и первой.
    """
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TypeError(f"{what} — число, получено {value!r}")
    if not math.isfinite(value):
        raise ValueError(f"{what} не число: {value!r}")
    if value <= 0:
        raise ValueError(f"{what} должен быть положительным: {value!r}")


def _check_money(value: float, what: str) -> None:
    """Денежная величина: число и конечное. Знак **не** проверяется.

    Отрицательное здесь законно и означает ровно то, что означает у брокера:
    свободных средств не хватает, счёт в минусе, день закрыт в убыток.
    Запрет знака превратил бы честную цифру в отказ на ровном месте.
    `nan` — другое дело: он проходит любое сравнение молча и расползается
    по лимиту, превращая «убыток достиг порога» в вечное «нет».
    """
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TypeError(f"{what} — число, получено {value!r}")
    if not math.isfinite(value):
        raise ValueError(
            f"{what} не число: {value!r}. Такая величина не падает, "
            "а делает любое сравнение с лимитом ложным"
        )


def _check_price(value: float, what: str) -> None:
    """Цена конечна. Ноль допустим: он бывает у комиссии, а `nan` — никогда."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TypeError(f"{what} — число, получено {value!r}")
    if not math.isfinite(value):
        raise ValueError(
            f"{what} не число: {value!r}. Такая цена не падает, а расползается "
            "по результату в пунктах и по уровню тейка"
        )
