"""Три предохранителя по деньгам: потолок объёма, дневной лимит, запас ГО.

Здесь только **числа и вердикты**. Ни одной строки для человека: слова про
предохранители пишет журнал решений в `engine/pipeline.py`, рядом со всеми
остальными словами робота, и одними и теми же средствами оформления цен
и объёмов. Два места, форматирующие рубли, разъехались бы молча, а читает
это владелец счёта.

Почему отдельный модуль, а не ветки внутри разбора свечи
--------------------------------------------------------
Предохранители — это цепочка «условие → отказ или дальше», и таких звеньев
три (`CLAUDE.md`, правило 9). Ветками они дали бы четвёртое перечисление
полей настроек руками. Здесь каждое звено — чистая функция с проверяемым
значением на выходе, и порядок звеньев виден на месте вызова.

Откуда движок берёт деньги счёта
--------------------------------
Из `EngineState.funds` — снимка, **положенного внутрь снаружи**
(`Engine.on_funds`). Движок за деньгами не ходит: ссылки на поставщика
у него нет, метода «спроси портфель» нет, импорта `broker/` нет и быть
не может (ARCHITECTURE.md §2). Кто положил снимок — боевой адаптер, читающий
портфель у брокера, или прогон по истории, — движку неизвестно и неразличимо.
Это тот же приём, которым внутрь попадают настройки, и та же граница §1.

⚠️ **Снимка может не быть вовсе, и это умолчание.** Прогон по истории
и сверка с прототипом деньгами счёта не пользуются: у прототипа
предохранителей нет, и любое их срабатывание дало бы другой список сделок.
Поэтому «данных нет» здесь не отказ и не остановка, а честный вердикт
«проверить нечем» — который движок обязан сказать словами, а не проглотить.

Три состояния счёта, а не два
-----------------------------
Их именно три, и путать средние два — значит либо торговать вслепую, либо
не торговать вовсе:

1. **снимка не было ни разу** (`state.funds is None`) — прогон по истории,
   наблюдение на живом потоке. Предохранители молчат словами, вход открыт;
2. **снимок был и устарел** (`funds_stale`) — источник счёта подключён
   и замолчал. Это боевая работа с ослепшим предохранителем: **вход
   запрещён** (решение 0037), причина говорится словами;
3. **снимок годен** — считаем.

Разница между 1 и 2 — **в данных, а не в режиме**. Движку не сообщают,
боевой он или нет: поле «я в бою» было бы тем самым `if режим == тестер`,
ради запрета которого построен весь проект (ARCHITECTURE.md §1).

⚠️ Отдельный случай, который в эти три не попадает: **ГО под контракт
не сообщено**. По HTTP брокер отдаёт его только делением `lockedForFutures`
открытой позиции на количество (`broker/account.py`), то есть **до первого
входа за день ГО неизвестно всегда**. Запрети вход и здесь — робот
не откроет ни одной позиции никогда, потому что число, которого он ждёт,
берётся из позиции. Поэтому «ГО не сообщено» остаётся вердиктом
«НЕ ПРОВЕРЕНО» и вход не запрещает; решение 0037 говорит про **размер
счёта**, а не про любую слепоту.

Решения, на которые опирается этот модуль
------------------------------------------
`0014` — бумажный убыток считается вместе с зафиксированным, возобновление
только вручную, нехватка ГО уменьшает объём. `0015` — объём штуками.
`0034` — потолок отказывает в заявке, а не урезает её. `0035` — деньги счёта
кладут внутрь, а не спрашивают. `0036` — до скольки урезать и что делать,
если не хватает даже на один контракт. `0037` — предохранитель, не знающий
размера счёта, вход запрещает. `0040` — как именно снимок протухает и кто
его обновляет.

Чего здесь нет
--------------
Расчёта объёма от риска — его в продукте не будет вовсе (решение 0015):
объём задаётся целым числом контрактов. Урезание под ГО — это одноразовое
снижение уже введённого числа под конкретную заявку, а не формула,
выводящая объём.
"""

