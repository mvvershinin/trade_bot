"""Два порта движка: источник свечей и исполнитель заявок.

Это единственное место, где боевой режим и прогон по истории расходятся.
Всё остальное — общий код (ARCHITECTURE.md §2):

======================  ==============================  ============================
Порт                    Боевая реализация               Реализация для прогона
======================  ==============================  ============================
Источник свечей         поток брокера + догрузка        чтение из базы по периоду
Исполнитель заявок      заявки в API брокера            модель исполнения
======================  ==============================  ============================

Движок не знает их реализаций и не имеет способа их различить: у портов
нет ни признака «это тестер», ни метода, который есть только у одной стороны.
Любое `if режим == тестер` внутри `engine/` — архитектурное нарушение, которое
не падает и оставляет тесты зелёными, а продукт возвращает к состоянию
«тестер врёт, доказать нечем» (ARCHITECTURE.md §1).

Почему `async` только здесь
---------------------------
Разбор свечи — чистая синхронная функция без ввода-вывода: сверка с прототипом
обязана быть сравнением списков, а не прогоном через цикл событий
(решение 0005). Асинхронность живёт на портах, где она физически нужна:
сеть брокера и чтение базы. Порт с синхронной подписью заставил бы
боевую реализацию блокировать поток интерфейса.

Про форму свечи
---------------
Источник отдаёт свечу слоя данных: время в поле `time` — это **начало**,
и время закрытия движок считает сам, прибавляя таймфрейм. Объект со временем
закрытия (`closes_at`) порт отвергает вслух — см. `engine/bars.py`.
Соответствие структурное: `market/` про `engine/` не знает и знать не должен.
"""

