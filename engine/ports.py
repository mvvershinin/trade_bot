class Refusal(enum.Enum):
    """Почему исполнитель не принял заявку. **Значение, а не текст.**

    ⚠️ Различие не оформительское: от него зависят разные действия движка,
    и оба варианта достижимы каждый торговый день.

    `NO_SUCH_ORDER` — заявки у брокера **нет**. Для снятия тейка это значит,
    что сторож исчез не по нашей команде: истёк срок, снятие на клиринге,
    переподключение. Уровень гасится, заявка вооружения убирается из полёта,
    следующая свеча вооружает заново.

    `ALREADY_TRIGGERED` — заявка **жива и исполняется**: уровень задет,
    сделка вот-вот придёт. Здесь всё наоборот: уровень остаётся, заявка
    вооружения остаётся в полёте (иначе её сделка окажется несопоставленной
    и остановит робота на штатной гонке), рыночный выход **не подаётся**
    и движок ждёт сделку.

    `UNKNOWN` — причина не названа, и это **умолчание**. Движок обязан вести
    себя как при `ALREADY_TRIGGERED`, то есть считать сторожа живым.
    Обратное умолчание стоит дороже всего: погасив уровень, движок на
    следующей свече подаст **голый рыночный выход поверх живого сторожа**,
    рыночная закроет лонг, а сторож при следующем касании продаст ещё раз —
    и получится шорт на полный объём без сигнала и без строки в журнале.

    ⚠️ Отказ обязан быть выразим **обеими** реализациями порта, и обе причины
    по отдельности. Модель исполнения должна уметь выдать любую из них
    по требованию теста — иначе ветка обработки отказа существует только
    в бою и первый раз выполняется на реальных деньгах (решение 0008,
    пункт 3). Сверкой с прототипом эти ветки не проходятся **никогда**:
    отказов в снятии в эталонном прогоне ноль из 85.
    """

    NO_SUCH_ORDER = "no_such_order"
    ALREADY_TRIGGERED = "already_triggered"
    UNKNOWN = "unknown"

    @property
    def label(self) -> str:
        return {
            Refusal.NO_SUCH_ORDER: "такой заявки у брокера нет",
            Refusal.ALREADY_TRIGGERED: "заявка уже исполняется",
            Refusal.UNKNOWN: "причина не названа",
        }[self]

    @property
    def order_is_alive(self) -> bool:
        """Осталась ли заявка живой у брокера.

        `UNKNOWN` отвечает «да» намеренно: не знать и считать, что сторожа
        нет, — самая дорогая из двух ошибок.
        """
        return self is not Refusal.NO_SUCH_ORDER


class ExecutionRefused(Exception):
    """Исполнитель заявку **не принял**, и это известно точно.

    Отличается от всего остального, что может прилететь из `submit`, ровно
    одним — определённостью. Обрыв связи, время ожидания, «слишком часто»
    оставляют движок в неведении: дошла заявка до брокера или нет, — и там
    единственный правильный ответ это остановка и человек. Здесь ответ
    получен, и вместе с ним получена **причина**.

    Зачем причина, а не только факт. Снятие тейка не удаётся по двум разным
    поводам, и действия движка на них **противоположны**: «нет такой заявки»
    означает, что сторожа нет и уровень надо гасить; «уровень уже задет»
    означает, что сторож жив и трогать нельзя ничего. Разобрать оба одним
    действием нельзя — любой выбор одного из них ломает другой случай,
    и оба достижимы каждый торговый день.

    ⚠️ Причина — **значение** (`Refusal`), а не текст сообщения: по тексту
    боевого брокера движку решать нельзя, он не наш и меняется без нас.
    Умолчание — `Refusal.UNKNOWN`, то есть «считаем заявку живой».

    :param reason: что именно ответил исполнитель.
    """

    def __init__(self, message: str, reason: Refusal = Refusal.UNKNOWN) -> None:
        super().__init__(message)
        if not isinstance(reason, Refusal):
            raise TypeError(
                f"причина отказа — engine.Refusal, получено {reason!r}. "
                "Текстом здесь решать нельзя: сообщение брокера не наше "
                "и меняется без нас"
            )
        self.reason = reason


