@runtime_checkable
class MarketCandle(Protocol):
    """Свеча, как её отдаёт источник.

    ⚠️ `time` — **начало** свечи. Поля со временем закрытия здесь нет
    намеренно: закрытие вычисляет движок, и это единственное место, где
    сложение «начало + таймфрейм» происходит (шаг 4 порядка обработки).

    `unsettled` — интервал бара ещё не закончился. Такая свеча в решении
    не участвует никогда. `filled_minutes` — сколько минуток нашлось внутри
    интервала; для неликвидного времени неполнота это норма, поведение
    задаётся настройкой.

    ⚠️ `filled_minutes` — **обязательное** поле порта, а не необязательное
    дополнение, хотя движок читает его только при включённой настройке
    «пропускать неполные свечи». Источник, который его не сообщает, обязан
    отказать на границе: иначе получается галочка, которая работает в тестере
    и роняет цикл обработки в бою — на первой свече после того, как владелец
    счёта настройку включит.

    ⚠️ И следствие для источников: значение обязано быть **посчитанным**,
    а не проставленным «сколько положено». Источник, который для пятиминутки
    всегда пишет 5, и источник, который считает минутки честно, дают при
    включённой настройке **разные ряды баров на одном и том же отрезке** —
    то есть разные сделки. Ровно это главное правило §1 и обязано делать
    невозможным.
    """

    @property
    def time(self) -> datetime: ...
    @property
    def timeframe(self) -> Timeframe: ...
    @property
    def open(self) -> float: ...
    @property
    def high(self) -> float: ...
    @property
    def low(self) -> float: ...
    @property
    def close(self) -> float: ...
    @property
    def unsettled(self) -> bool: ...
    @property
    def filled_minutes(self) -> int: ...


