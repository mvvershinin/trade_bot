class Engine:
    """Один инструмент, один торговый модуль, одна позиция.

    `journal` — куда уходят строки журнала решений. Движок их не копит:
    за прогон по истории их сотни, а за месяц боевой работы — тысячи, и место
    для них не в памяти движка, а в базе. Строки возвращаются и из методов —
    сверке и тестам удобнее иметь их на руках.
    """

    __slots__ = (
        "_strategy", "_settings", "_state", "_journal", "_last_closes_at", "_halted",
    )

    def __init__(
        self,
        strategy: Strategy,
        settings: EngineSettings | None = None,
        *,
        state: EngineState | None = None,
        journal: Callable[[JournalEntry], None] | None = None,
    ) -> None:
        self._strategy = strategy
        self._settings = EngineSettings() if settings is None else settings
        self._state = EngineState() if state is None else state
        self._journal = journal
        self._last_closes_at: datetime | None = None
        self._halted = ""

    # --- что видно снаружи --------------------------------------------------

    @property
    def strategy(self) -> Strategy:
        return self._strategy

    @property
    def settings(self) -> EngineSettings:
        return self._settings

    @property
    def state(self) -> EngineState:
        return self._state

    @property
    def position(self) -> Position | None:
        return self._state.position

    @property
    def halted(self) -> str:
        """Почему робот остановлен. Пустая строка — работает.

        Останавливают две вещи, и обе означают «дальше решать нельзя»:
        исполнитель не принял заявку (движок не знает, дошла ли она до брокера)
        и журнал решений не принял строку (объяснить свои действия робот
        больше не может, а действие без строки — дефект).

        Остановка **не закрывает позицию**: выключение и остановка сами по себе
        не должны приводить к сделке. Позиция остаётся, робот ею не управляет,
        и сказать об этом крупно обязана программа (DOMAIN.md §3).

        Снимается `reset()` — то есть осознанным решением человека начать ряд
        заново, а не «попробуем ещё раз» на следующей свече.
        """
        return self._halted

    # --- синхронное ядро ----------------------------------------------------

    def analyse(self, candle: MarketCandle) -> Outcome:
        """Разобрать свечу. Состояние движка и журнал **не трогает**.

        Возвращает решение: заявки, строки журнала и два состояния — на случай,
        что исполнитель заявки примет, и на случай, что нет. Закрепляет одно
        из них `accept()`, и только после ответа исполнителя.

        Что здесь всё-таки меняется: свеча уходит в торговый модуль и входит
        в его ряд, а время её закрытия становится «сейчас» для движка. Это
        не решение робота, а факт истории — он не зависит от того, примет ли
        брокер заявку.
        """
        taken = intake(
            candle,
            partial=self._settings.partial_candles,
            previous=self._last_closes_at,
        )
        if taken.bar is None:
            return self._not_taken(taken)
        # «Сейчас» движка двигает только разобранная свеча. У незакрытой время
        # закрытия лежит в БУДУЩЕМ, и записью настроек по нему в журнале
        # появились бы события, которых ещё не произошло.
        self._last_closes_at = taken.closes_at

        # Подача в торговый модуль — до любой проверки режима: см. шапку модуля.
        decision = self._strategy.on_closed_bar(taken.bar)
        return process_closed_candle(
            self._state, taken.bar, decision, self._settings
        )

    def accept(
        self, outcome: Outcome, accepted: int | None = None, shown: int | None = None
    ) -> None:
        """Закрепить разбор: состояние движка и строки журнала.

        :param accepted: сколько заявок принял исполнитель. `None` — все.
            Число меньше поданного означает отказ на одной из заявок:
            принятые забывать нельзя, они уже у брокера.
        :param shown: сколько заявок **показывать в журнале**. По умолчанию
            столько же, сколько принято.

            ⚠️ Расходятся эти два числа ровно в одном случае, и он важен:
            **неопределённый** отказ — таймаут, обрыв связи. Заявка могла
            дойти до брокера, движок этого не знает; состояние не применяется,
            но решение робота в журнале остаться обязано — иначе человек
            видит «Заявка не подана» и не видит, что именно робот решал.
            Показывается при этом весь разбор свечи: строка действия висит
            на **последней** заявке цепочки выхода, и «принятые плюс одна»
            её не достаёт.

            При **определённом** отказе наоборот: заявки у брокера точно нет,
            и строка «Выход из лонга по обратному сигналу» уровня TRADE
            утверждала бы выход, которого не было. Молчания при этом тоже
            нет: вместо строки действия печатается её сниженная замена
            с оговоркой «действия не было» — иначе в журнале свечи остаётся
            один отказ, а зачем робот действовал, не сказано нигде.
        """
        count = len(outcome.orders) if accepted is None else accepted
        self._state = outcome.state_after(count)
        self._publish(outcome.lines(count if shown is None else shown))
        # Разбор мог прийти к выводу «дальше решать нельзя» — сегодня это
        # заявка на выход, не ставшая сделкой. Строка уже в журнале: её
        # написал сам разбор, чтобы причина стояла на своём месте по времени.
        if outcome.halt:
            self._halt_text(outcome.halt)

    def on_candle(self, candle: MarketCandle) -> Outcome:
        """Разобрать свечу и закрепить результат. Заявки **не подаёт**.

        ⚠️ Состояние закрепляется так, **будто исполнитель принял все заявки**.
        Для того, кто заявки не подаёт — прогон, проверяющий решения, — это
        верно. Для того, кто подаёт, это ловушка: при отказе брокера позиция
        окажется закрытой в журнале и открытой на счёте, а робот перестанет
        ею управлять. Подающий обязан идти через `on_market_candle` либо
        звать `analyse()` и `accept(outcome, accepted=...)` по ответу
        исполнителя.
        """
        if self._halted:
            return self._while_halted(candle)
        outcome = self.analyse(candle)
        self.accept(outcome)
        return outcome

    def on_fill(self, fill: Fill) -> FillOutcome:
        """Исполнитель сообщил о сделке. Возвращает заявки, рождённые ею.

        Сегодня такая заявка одна: вооружить тейк сразу при открытии позиции.
        Уровень считается от цены входа, а цену входа назначает исполнитель —
        значит раньше сделки его не знает никто.

        ⚠️ Метод **не подаёт** заявки: он синхронное ядро, ввода-вывода здесь
        нет. Подаёт их адаптер, и подаёт **до** того, как спросит сделки
        в следующий раз, — иначе уровень, вооружённый сделкой открытия, дойдёт
        до исполнителя после того, как тот уже разобрал свой бар. Строки
        Строки, привязанные к заявкам (`FillOutcome.tied`), публикует он же —
        и только по принятым.

        ⚠️ Сделка, не сопоставившаяся ни с одной заявкой в полёте,
        **останавливает робота**. Пока она не разобрана человеком, движок
        не знает, что на счёте: следующая заявка может удвоить объём или уйти
        на счёт, где позиции уже нет.
        """
        result = apply_fill(self._state, fill, self._settings)
        self._state = result.state
        # Строки, привязанные к заявкам, здесь НЕ публикуются: их публикует
        # тот, кто подал заявку и получил ответ (`_exchange`). Публикуется
        # только безусловная часть — сама сделка.
        self._publish(result.lines(0))
        if result.halt:
            self._halt_text(result.halt)
        return result

    def apply_settings(
        self, settings: EngineSettings, *, at: datetime | None = None
    ) -> tuple[JournalEntry, ...]:
        """Новые общие настройки — на ходу, без перезапуска.

        Новое значение действует **со следующей сделки**: открытую позицию
        оно не трогает. Так получается само собой, а не проверкой — объём
        читается только в момент подачи заявки на вход, а окно и режим
        на уже открытую позицию не смотрят. Иначе робот начал бы «доливать»
        и «отрезать» на ровном месте.

        В журнал пишется **прежнее и новое** значение каждого изменённого
        поля (ТЗ §4.4 А).

        :param at: момент, которым помечается запись. У движка нет своих
            часов: «сейчас» для него — это время закрытия последней свечи.
            До первой свечи момент обязан назвать вызывающий.
        """
        moment = at if at is not None else self._last_closes_at
        if moment is None:
            raise ValueError(
                "движок не знает, который час: своих часов у него нет, "
                "а свечей ещё не было. Момент записи в журнал обязан "
                "назвать вызывающий — параметр `at`"
            )
        changes = settings.changes_from(self._settings)
        self._settings = settings
        entries = tuple(
            JournalEntry(
                at=moment,
                event="Настройка изменена",
                reason=f"{line}. Действует со следующей сделки, открытую "
                       "позицию не меняет",
            )
            for line in changes
        )
        self._publish(entries)
        return entries

    def on_funds(self, funds: AccountFunds) -> tuple[JournalEntry, ...]:
        """Внешний мир сообщил деньги счёта. **Движок за ними не ходит.**

        Симметрично `apply_settings`: значение кладут внутрь, а не движок
        спрашивает наружу. Ссылки на поставщика у него нет, метода «спроси
        портфель» нет, импорта `broker/` нет и быть не может
        (ARCHITECTURE.md §2). Кто зовёт — боевой адаптер, читающий портфель
        у брокера, или прогон по истории — движку неизвестно и неразличимо,
        и это ровно та граница, ради которой всё построено (§1).

        Что происходит со снимком:

        * он становится **последним известным** состоянием денег. По нему
          считается, на сколько контрактов хватает свободных средств;
        * **первый** снимок каждой календарной даты становится размером счёта
          «на утро», от которого считается дневной лимит убытка. Внутри дня
          он не пересчитывается — иначе просадка сама уменьшала бы порог
          и остановка наступала бы всё раньше (DOMAIN.md §4).

        ⚠️ «На утро» — обещание, которое движок сдержать не может: программу
        могли запустить в середине дня. Поэтому в журнал печатается **время
        снимка**, а не слово «утро», и владелец счёта видит, от чего на самом
        деле считается его лимит.

        ⚠️ Строка пишется только когда база даты **появилась**. Снимки
        приходят опросом портфеля, то есть часто; строка на каждый
        превратила бы журнал решений в поток данных.
        """
        if not isinstance(funds, AccountFunds):
            raise TypeError(
                f"состояние счёта — engine.AccountFunds, получено {funds!r}"
            )
        today = in_moscow(funds.at).date()
        day = self._state.day
        fresh = day is None or day.date != today or day.opening is None
        if day is None or day.date != today:
            day = DayMoney(date=today, opening=funds)
        elif day.opening is None:
            day = DayMoney(date=today, opening=funds, realized=day.realized)
        self._state = replace(self._state, funds=funds, day=day)
        if not fresh:
            return ()
        entry = JournalEntry(
            at=funds.at,
            event="Размер счёта принят",
            reason=self._funds_words(funds),
        )
        self._publish((entry,))
        return (entry,)

    def _funds_words(self, funds: AccountFunds) -> str:
        """Что именно принято и что теперь считается — человеческим языком."""
        limit = self._settings.daily_loss_limit_percent
        if limit > 0:
            about = (
                f"Дневной лимит убытка {percent(limit)}% от него — это "
                f"{money(abs(funds.equity) * limit / 100.0)}: дойдя до него, "
                "робот закроет позицию и остановится до вашего вмешательства"
            )
        else:
            about = (
                "⚠️ Дневной лимит убытка не задан — по деньгам робот "
                "не остановится ни при каком убытке"
            )
        return (
            f"Счёт {money(funds.equity)} на момент снимка "
            f"{in_moscow(funds.at):%d.%m %H:%M}, свободных "
            f"{money(funds.free)}, ГО контракта "
            f"{_margin_words(funds)}. От этого числа считается день, внутри "
            f"дня оно не пересчитывается. {about}"
        )

    def reset(self) -> None:
        """Новый отрезок: модуль забывает ряд, движок — позицию и запреты.

        Прогрев отсчитывается от начала поданного ряда, предыстории у модуля
        нет (PROTOTYPE.md §3). Поэтому сброс — это смена ряда, а не очистка
        кэша: тот же файл с другой начальной даты даёт другой список сделок.
        """
        self._strategy.reset()
        self._state = EngineState()
        self._last_closes_at = None
        # Снимается и остановка: начать ряд заново — это решение человека,
        # принятое после разбора того, что случилось. Само по себе время
        # остановку не снимает.
        #
        # ⚠️ Вместе с состоянием уходят и деньги счёта: и последний снимок,
        # и размер счёта на утро, и зафиксированный за день результат.
        # Иначе после ручного перезапуска дневной лимит считался бы
        # от вчерашних денег и от чужого убытка. Тот, кто снимки кладёт,
        # обязан положить новый — до тех пор лимит честно считается
        # непроверенным.
        self._halted = ""

    # --- адаптер: здесь и только здесь ввод-вывод ---------------------------

    async def run(self, source: CandleSource, executor: OrderExecutor) -> None:
        """Работать, пока источник отдаёт свечи или пока робот не остановлен.

        В бою поток не кончается сам; прогон по истории кончается последней
        свечой отрезка. Движок не различает эти случаи и не может: у порта
        нет признака, по которому это делается.

        ⚠️ Возврат из этого метода означает одно из двух: свечи кончились или
        робот остановлен. Различает их `halted`, и вызывающий обязан её
        спросить: молча продолжить после остановки нельзя — движок не знает,
        что стало с последней заявкой.

        ⚠️ Обрыв самого потока свечей здесь **не** гасится и уходит наверх:
        переподключение — дело источника и того, кто его собрал, а не движка.
        Разница с отказом исполнителя принципиальна: при обрыве потока движок
        ничего не решил и ничего не подал, а после отказа исполнителя он
        не знает, что стало с заявкой.
        """
        async for candle in source.candles():
            await self.on_market_candle(candle, executor)
            if self._halted:
                break

    async def on_market_candle(
        self, candle: MarketCandle, executor: OrderExecutor
    ) -> Outcome:
        """Одна свеча целиком: сделки исполнителя, разбор, подача заявок.

        Порядок — из шапки модуля, и последний его пункт значим: состояние
        и журнал закрепляются **после** ответа исполнителя, а не до подачи.

        Отказ исполнителя не роняет цикл свечей: он пишет строку уровня ERROR
        и останавливает робота явно (`halted`).
        """
        if self._halted:
            return self._while_halted(candle)

        await self._exchange(candle, executor)
        if self._halted:
            return self._while_halted(candle)

        outcome = self.analyse(candle)
        accepted, failure, declined = await self._submit_all(
            outcome.orders, executor
        )
        # Состояние и журнал закрепляются ДО остановки: иначе строка причины
        # встала бы раньше строк самой свечи, а состояние осталось бы
        # незакреплённым — и принятые заявки движок бы забыл.
        #
        # ⚠️ На неопределённом отказе показывается **весь** разбор свечи,
        # а не «принятые плюс одна». Умолчательная форма выхода кладёт две
        # заявки — снятие, затем закрытие, — а строка «Выход из лонга
        # по обратному сигналу» привязана к закрытию. Таймаут на снятии
        # оставлял бы в журнале одну строку «Заявка не подана» со словами
        # про снятие тейка: робот остановлен, причина про сторожа, а **зачем
        # он собирался выходить — не сказано нигде**. Разбор начинался бы
        # с «робот зачем-то снимал тейк» вместо «робот шёл на выход
        # и не дошёл».
        #
        # Неправдой это не становится: строка остановки прямо говорит, что
        # часть заявок не подавалась вовсе и решение осталось намерением.
        # При **определённом** отказе показывается ровно принятое: там
        # неизвестности нет, и обещать выход, которого не было, нельзя.
        # Причина при этом не пропадает: вместо строки действия встаёт её
        # сниженная замена с оговоркой «действия не было» (`_Journal.action`).
        self.accept(
            outcome, accepted,
            shown=len(outcome.orders) if failure is not None else accepted,
        )
        # ⚠️ Отказ применяется ПОСЛЕ `accept`, а не внутри подачи: `accept`
        # переписывает состояние целиком по числу принятых заявок и стёр бы
        # последствия отказа молча. Строка отказа печатается там же и потому
        # же: у всех строк одной свечи одинаковое время, и порядок публикации
        # это единственное, чем они различаются при чтении.
        self._apply_decline(declined)
        if failure is not None:
            self._halt(failure)
        return outcome

    async def _exchange(self, candle: MarketCandle, executor: OrderExecutor) -> None:
        """Обмен внутри одной свечи: сделки → разбор → заявки → снова сделки.

        Круг вертится, **пока порт отдаёт сделки**. Это условие остановки
        и есть контракт: не счётчик кругов и не признак «это модель».
        Первый круг отдаёт исполнение отложенных заявок по открытию свечи,
        на следующих приходят внутрибарные события — и приходят уже после
        того, как движок ответил заявкой вооружить тейк от полученной цены
        входа.
        """
        for round_number in range(_MAX_ROUNDS + 1):
            try:
                fills = await executor.fills_at(candle)
            except Exception as error:  # noqa: BLE001 — исполнитель чужой, любой
                # Не узнать о сделках так же опасно, как не подать заявку:
                # разбор пошёл бы по устаревшему состоянию и дал вторую заявку
                # по тому же поводу. Поэтому не «продолжим без сделок»,
                # а остановка.
                self._halt(self._executor_silent(error, close_time(candle)))
                return
            if not fills:
                return
            if round_number >= _MAX_ROUNDS:
                self._halt(self._executor_endless(close_time(candle)))
                return
            for number, fill in enumerate(fills):
                result = self.on_fill(fill)
                # Строку журнала о сделке мог не принять приёмник, а сама сделка
                # могла не сопоставиться ни с одной заявкой — в обоих случаях
                # робот уже остановлен, и решать по этой свече нельзя.
                if self._halted:
                    self._warn_lost_fills(fills[number + 1:])
                    return
                if result.orders:
                    accepted, failure, declined = await self._submit_all(
                        result.orders, executor
                    )
                    # Последствия заявки записываются ПОСЛЕ ответа исполнителя
                    # и до следующего вопроса о сделках: сработавший уровень
                    # придёт сделкой, сославшейся на эту заявку, и найти её
                    # разбор обязан среди заявок в полёте.
                    for order in result.orders[:accepted]:
                        self._state = after_submit(self._state, order)
                    # ⚠️ Строки — строго по ПРИНЯТЫМ заявкам, при любом исходе.
                    # Здесь стояло «при неопределённом отказе показать все»,
                    # и это давало «Тейк-профит выставлен. Уровень 211 050»
                    # рядом с «Заявка не подана»: заявка от сделки ровно одна,
                    # значит оговорка «ещё N заявок не подавались вовсе»
                    # не печаталась, а уровня не было ни у брокера, ни
                    # в состоянии движка. Владелец счёта оставлял позицию
                    # под тейком, которого нет. Довод «иначе не сказано, зачем
                    # робот действовал» здесь не работает: безусловная строка
                    # «Лонг открыт» стоит рядом и всё уже сказала.
                    self._publish(result.tied(accepted))
                    self._apply_decline(declined)
                    if failure is not None:
                        self._halt(failure)
                        self._warn_lost_fills(fills[number + 1:])
                        return

    async def _submit_all(
        self, orders: Sequence[OrderRequest], executor: OrderExecutor
    ) -> tuple[int, JournalEntry | None, _Declined | None]:
        """Подать заявки по одной. **Ничего не публикует.**

        Возвращает три вещи: сколько принято, причину остановки (если была)
        и определённый отказ. Последний нужен вызывающему дважды: последствия
        отказа записываются **после** того, как он закрепит состояние по числу
        принятых заявок (иначе `accept` сотрёт их молча), а строка журнала
        печатается **после** строк самой свечи — времена у них одинаковые,
        и порядок публикации это единственное, чем они различаются при чтении.

        Две разных беды, и путать их нельзя:

        * **определённый отказ** (`ExecutionRefused`) — заявки у брокера точно
          нет. Робот не останавливается: пишется строка, а **остальные заявки
          этой свечи не подаются**. Так и надо: снятие тейка — предусловие
          заявки на выход, и подавать выход после неудавшегося снятия значит
          согласиться на двойное исполнение. Заявка вооружения предусловием
          не является, но и не имеет за собой ничего: на свече выхода она
          вовсе не подаётся (`_settle`), а на прочих свечах она последняя;
        * **всё остальное** — таймаут, обрыв связи, «слишком часто». Движок
          НЕ ЗНАЕТ, дошла ли заявка. Ни «повторим», ни «считаем, что не подана»,
          только остановка и человек.

        `Exception`, а не `BaseException`: отмена задачи (`CancelledError`)
        обязана пройти насквозь.
        """
        accepted = 0
        for order in orders:
            try:
                await executor.submit(order)
            except ExecutionRefused as refusal:
                reason = _named_reason(refusal)
                return accepted, None, _Declined(
                    order, reason, self._order_declined(order, refusal, reason)
                )
            except Exception as error:  # noqa: BLE001 — разбор выше, по одному
                rest = len(orders) - accepted - 1
                return accepted, self._order_refused(order, error, rest), None
            accepted += 1
        return accepted, None, None

    def _apply_decline(self, declined: _Declined | None) -> None:
        """Строка отказа в журнал и его последствия. Разбираются **обе** заявки выхода.

        Снятие тейка — по причине: «нет такой заявки» гасит уровень, «уровень
        уже задет» не трогает ничего и ждёт сделку. Разбор — в
        `after_refused_cancel`; путать их нельзя, действия противоположны.

        Заявка на **закрытие** — третья дорога к той же беде: снятие прошло,
        сторожа нет, а рыночный выход отклонён (аукцион, инструмент
        недоступен, лимит риск-менеджера). Позиция остаётся открытой и без
        уровня, и без счётчика это повторяется каждую свечу — позиция ночует
        и проводит выходные без сторожа, а робот считает себя работающим.

        Отказ во **входе** последствий не имеет: позиция не открылась,
        следующая свеча попробует снова. Отказ в **вооружении** — тоже:
        уровень просто не встал, и держит позицию переворот по средней.
        """
        if declined is None:
            return
        self._publish((declined.entry,))
        order, reason = declined.order, declined.reason
        if order.action is OrderAction.CANCEL_TAKE_PROFIT:
            self._state = after_refused_cancel(self._state, order, reason)
        elif order.action is OrderAction.CLOSE:
            self._state = after_refused_exit(self._state, order)

    # --- внутреннее ---------------------------------------------------------

    def _while_halted(self, candle: MarketCandle) -> Outcome:
        """Робот остановлен: свеча не разбирается и заявок не будет.

        Строка в журнал здесь не пишется намеренно: причина уже записана
        уровнем ERROR в момент остановки, а повторять её на каждой свече
        значило бы утопить её же. Свеча в торговый модуль тоже не идёт —
        ряд после остановки всё равно придётся подавать заново (`reset`).
        """
        return Outcome(
            state=self._state,
            closes_at=close_time(candle),
            skipped=f"Робот остановлен. {self._halted}",
        )

    # ⚠️ Текст исключения попадает в журнал решений, а журнал читает человек
    # и уносит в отчёт. Это допустимо ровно потому, что слой брокера обязан
    # не помещать токен ни в текст исключения, ни в трассировку, и это у него
    # закрыто отдельными тестами. Движок токена не знает и вычистить его
    # не может — значит опираемся на гарантию соседа и называем её вслух.

    def _order_refused(
        self, order: OrderRequest, error: BaseException, rest: int = 0
    ) -> JournalEntry:
        """Строка про непринятую заявку. Уровень ERROR, причина словами.

        :param rest: сколько заявок этой свечи не подавалось вовсе. Строки
            их решений в журнале выше есть — иначе непонятно, зачем робот
            вообще что-то делал, — и надо прямо сказать, что они остались
            намерением.
        """
        tail = (
            f" ⚠️ Ещё {rest} "
            f"{plural(rest, 'заявка', 'заявки', 'заявок')} этой свечи "
            f"не {plural(rest, 'подавалась', 'подавались', 'подавались')} "
            "вовсе: строки их решений выше показывают, что робот собирался "
            "сделать, а не что он сделал."
            if rest > 0 else ""
        )
        return JournalEntry(
            at=order.submitted_at,
            event="Заявка не подана",
            reason=(
                f"Исполнитель не принял заявку ({order_words(order)}): "
                f"{type(error).__name__}: {error}. Робот остановлен — он "
                "не знает, дошла ли заявка до брокера, и вторая такая же "
                "заявка означала бы двойной объём." + tail
                + " Остановка робота сама по себе позицию не закрывает: "
                "ни выключение, ни остановка не должны приводить к сделке. "
                + self._what_may_happen_alone(order)
                + " Проверьте позицию и список заявок в приложении брокера"
            ),
            level=JournalLevel.ERROR,
        )

    @staticmethod
    def _what_may_happen_alone(order: OrderRequest) -> str:
        """Что может произойти БЕЗ робота — строго по действию заявки.

        ⚠️ Здесь стояло одно утверждение на все четыре действия: «позиция
        не закрывается сама». Про робота это правда, про счёт — нет, и ложно
        оно во всех четырёх случаях сразу. Соседнее предложение той же строки
        честно говорит, что движок **не знает**, дошла ли заявка; после этого
        обещать судьбу позиции нельзя ни в какую сторону.

        Цена ошибки названа в решении 0008: владелец счёта читает «не
        закрывается сама», ставит свой стоп руками — и получает два стопа
        на одной позиции. Один сработает, второй откроет обратную на полный
        объём.
        """
        if order.action is OrderAction.CANCEL_TAKE_PROFIT:
            return (
                "⚠️ Сторожимый уровень при этом может быть ЖИВ у брокера: "
                "снятие могло не дойти. Тогда позицию закроет он, без робота, "
                "и свой стоп поверх него означал бы два стопа на одной "
                "позиции — второй откроет обратную на полный объём."
            )
        if order.action is OrderAction.CLOSE:
            return (
                "⚠️ Заявка на выход при этом могла дойти до брокера — тогда "
                "позиция закроется без робота. Считать её открытой, пока это "
                "не проверено, нельзя."
            )
        if order.action is OrderAction.OPEN:
            return (
                "⚠️ Позиции сейчас нет, но она может ОТКРЫТЬСЯ без робота: "
                "заявка на вход могла дойти до брокера. Управлять ею робот "
                "не будет — ни тейка, ни переворота у неё не появится."
            )
        return (
            "⚠️ Сторожимый уровень при этом мог встать у брокера — тогда он "
            "закроет позицию без робота, по своей цене."
        )

    def _order_declined(
        self, order: OrderRequest, refusal: BaseException, reason: Refusal
    ) -> JournalEntry:
        """Строка про определённый отказ. Робот работает дальше.

        Уровень WARNING, а не ERROR: определённый отказ бывает штатным.
        Снятие тейка не удаётся ровно тогда, когда уровень уже задет
        и заявка исполняется, — а значит сделка о нём вот-вот придёт.
        Останавливать робота на этом нельзя; подать после этого рыночный
        выход — тем более.

        ⚠️ Объяснение — **по той заявке, которую отклонили**. Прежняя
        редакция объясняла любой отказ снятием тейка, и владелец счёта читал
        про сторожа там, где отклонили вход.

        ⚠️ **И утверждение о судьбе заявки у брокера — тоже по причине.**
        Здесь стояло «заявки у брокера нет — это известно точно», и печаталось
        оно для всех трёх причин, в том числе рядом со словами «сторожимый
        уровень остаётся у брокера». Два взаимоисключающих утверждения в одной
        строке, и ложное — про живой стоп: владелец счёта читает «известно
        точно» и в приложение брокера **не идёт**. Через двадцать пять минут
        робот остановится, а цена к тому времени может задеть уровень — тейк
        продаёт, лонга больше нет, сторож при следующем касании продаёт ещё
        раз, и получается шорт на полный объём.

        ⚠️ **И только для снятия.** `Refusal` описан вокруг снятия и говорит
        про заявку, названную `target_id`, — про **сторожимый уровень**, а не
        про ту заявку, которую отклонили. Для входа, выхода и вооружения
        судьба поданной заявки известна из контракта `ExecutionRefused`:
        не принята, без вариантов. Печатать там «движок считает её ЖИВОЙ»
        значило бы писать неправду и действовать наоборот — что движок
        и делал: на отклонённом вооружении журнал обещал живую заявку,
        а состояние тут же оставалось без уровня. На отклонённом закрытии
        это дороже всего: строка обещала «заявка жива и уже исполняется»,
        а следующая свеча подавала **вторую рыночную заявку на выход**.

        Слов «известно точно» при неназванной причине быть не может
        по построению.
        """
        return JournalEntry(
            at=order.submitted_at,
            event="Заявка отклонена исполнителем",
            reason=(
                f"Исполнитель отклонил заявку ({order_words(order)}): "
                f"{reason.label}. {refusal}. {self._not_accepted(order, reason)} "
                "Робот продолжает работать. "
                + self._what_declining_means(order, reason)
            ),
            level=JournalLevel.WARNING,
        )

    @classmethod
    def _not_accepted(cls, order: OrderRequest, reason: Refusal) -> str:
        """Что известно о судьбе заявки. Для снятия — о судьбе уровня."""
        if order.action is OrderAction.CANCEL_TAKE_PROFIT:
            return cls._where_the_guard_is(reason)
        return (
            "Саму заявку исполнитель не принял — это известно точно: "
            "исполнения по ней не будет."
        )

    @staticmethod
    def _where_the_guard_is(reason: Refusal) -> str:
        """Что известно о судьбе СТОРОЖИМОГО УРОВНЯ. Строго по причине отказа.

        ⚠️ Речь про заявку, которую снимали (`target_id`), а не про снятие.
        Причина отказа говорит именно о ней — так устроен `Refusal`.
        """
        if reason is Refusal.NO_SUCH_ORDER:
            return "Сторожимого уровня у брокера нет — это известно точно."
        if reason is Refusal.ALREADY_TRIGGERED:
            return (
                "Сторожимый уровень у брокера жив: он уже задет, и сделка "
                "по нему вот-вот придёт."
            )
        return (
            "⚠️ Исполнитель не сказал, что стало со сторожимым уровнем. "
            "Движок считает его ЖИВЫМ — это безопасное умолчание, но проверить "
            "заявку в приложении брокера всё равно нужно."
        )

    @staticmethod
    def _what_declining_means(order: OrderRequest, reason: Refusal) -> str:
        """Что означает отказ именно в этой заявке — человеческим языком.

        ⚠️ **«Следующая свеча вооружит заново» — обещание, которое отменяет
        `_settle`.** Пока робот выходит, шаг 5 вооружает, шаг 6 или 7 подаёт
        выход, а `_settle` вооружение выбрасывает: на свече, где подаётся
        закрытие, тейк до брокера не доходит вовсе. Значит после отказа
        в снятии или в закрытии позиция стоит **без сторожимого уровня**
        столько свечей, сколько длятся отказы, — и обещать ей уровень
        на следующей свече нельзя.
        """
        if order.action is OrderAction.CANCEL_TAKE_PROFIT:
            if reason is Refusal.ALREADY_TRIGGERED:
                return (
                    "Сторожимый уровень уже задет и вот-вот станет сделкой: "
                    "заявка на выход не подаётся, робот ждёт её. Подать выход "
                    "сейчас значило бы исполнить обе заявки и получить позицию "
                    "в обратную сторону на полный объём"
                )
            if reason.order_is_alive:
                return (
                    "Движок ведёт себя так, будто уровень жив: заявка на выход "
                    "не подаётся, робот ждёт сделку по уровню. Подать выход, "
                    "не зная, снят ли сторож, значило бы согласиться на двойное "
                    "исполнение — рыночная закроет позицию, а сторож при "
                    "следующем касании откроет обратную на полный объём"
                )
            return (
                "Сторожа у брокера нет — снимать было нечего. Уровень погашен "
                "и у движка, а заявка на выход этой свечой уже не подаётся: "
                "её подаст следующая, и уйдёт она без снятия. ⚠️ Вооружить "
                "уровень заново до самого выхода не выйдет — на свече, где "
                "подаётся закрытие, тейк не выставляется, и всё это время "
                "позицию держит только переворот по средней"
            )
        if order.action is OrderAction.CLOSE:
            return (
                "Позиция остаётся открытой и без сторожимого уровня: тот, "
                "что стоял до этой свечи, снимается перед выходом, а новый "
                "на свече выхода не выставляется. Выход повторит следующая "
                "свеча — и уровня она тоже не поставит. Пока робот выходит, "
                "позицию держит только переворот по средней. Если отказы "
                "продолжатся, робот остановится и позовёт человека"
            )
        if order.action is OrderAction.OPEN:
            return (
                "Позиция не открыта. Следующая свеча решит заново — "
                "по своему сигналу, а не по этому отказу"
            )
        return (
            "Позиция осталась без сторожимого уровня: её держит переворот "
            "по средней. Следующая свеча вооружит заново — если только "
            "на ней робот не пойдёт на выход: на свече закрытия тейк "
            "не выставляется"
        )

    def _warn_lost_fills(self, rest: Sequence[Fill]) -> None:
        """Остаток пачки сделок при остановке посреди неё.

        ⚠️ Молча их выбросить нельзя: это уже случившиеся сделки, движок про
        них не узнает, а человек, разбирающий остановку, обязан знать, что
        состояние движка отстало от счёта не на одну сделку, а на несколько.
        Соседняя ветка (остановка по числу кругов) про это предупреждает,
        а эта раньше молчала.
        """
        if not rest:
            return
        self._publish((JournalEntry(
            at=rest[0].at,
            event="Сделки исполнителя не разобраны",
            reason=(
                f"Робот остановлен посреди пачки: ещё {len(rest)} сделок "
                "пришли от исполнителя и в состояние движка НЕ вошли. Первая "
                f"из них — {rest[0].side.label.lower()}, объём "
                f"{rest[0].volume:g}, цена {rest[0].price:g}. Сверьте позицию "
                "и список заявок в приложении брокера"
            ),
            level=JournalLevel.ERROR,
        ),))

    def _executor_endless(self, at: datetime) -> JournalEntry:
        """Исполнитель не замолкает: круг обмена внутри свечи не сходится."""
        return JournalEntry(
            at=at,
            event="Исполнитель отдаёт сделки без конца",
            reason=(
                f"Обмен внутри одной свечи не сошёлся за {_MAX_ROUNDS} кругов. "
                "Круг обязан заканчиваться пустым ответом порта, а сам порт "
                "обязан отдавать всё накопленное за один вызов; исполнитель, "
                "сливающий очередь по одной сделке за круг, неисправен так же, "
                "как исполнитель, не замолкающий вовсе. Робот остановлен — "
                "иначе цикл свечей завис бы молча. ⚠️ Сделки этого круга "
                "движком НЕ разобраны и в состояние не вошли: сверьте позицию "
                "и список заявок в приложении брокера"
            ),
            level=JournalLevel.ERROR,
        )

    def _executor_silent(
        self, error: BaseException, at: datetime
    ) -> JournalEntry:
        """Исполнитель не смог рассказать о сделках. Тоже остановка."""
        return JournalEntry(
            at=at,
            event="Сделки исполнителя не получены",
            reason=(
                f"Исполнитель не ответил на запрос сделок: "
                f"{type(error).__name__}: {error}. Робот остановлен: решать "
                "по устаревшему состоянию — значит подать вторую заявку "
                "по тому же поводу. Проверьте позицию в приложении брокера"
            ),
            level=JournalLevel.ERROR,
        )

    def _halt_text(self, why: str) -> None:
        """Остановить робота по причине, уже написанной в журнал.

        Строку писать не надо: её написал разбор — чтобы она встала на своё
        место по времени, рядом с событием, а не после него.
        """
        if not self._halted:
            self._halted = why

    def _halt(self, entry: JournalEntry) -> None:
        """Остановить робота явно: строка в журнал и флаг `halted`.

        Строка пишется ДО установки флага: `_publish` при неудаче ставит свой
        флаг, и затирать его не надо — причина «журнал недоступен» важнее.
        """
        self._publish((entry,))
        if not self._halted:
            self._halted = f"{entry.event}. {entry.reason}"

    def _not_taken(self, taken: Intake) -> Outcome:
        """Свеча не дошла до разбора. Строку в журнал — не всегда.

        Незакрытая свеча — **не событие**: поток реального времени присылает
        текущий, ещё не закрытый бар постоянно, и строка на каждый такой
        приход превратила бы журнал решений в поток данных. Робот на такой
        свече ничего не решает, значит и объяснять нечего. Прохождение самих
        данных — дело технического лога, а не журнала решений.

        Отброшенная **неполная** свеча — другое дело: это решение изменить
        ряд, по которому считается средняя, и оно меняет список сделок.
        Такое пишется всегда.

        Повтор свечи после переподключения — событие штатное, поэтому строка
        спокойная (INFO), а не тревожная: тревога на штатном событии со
        временем перестаёт читаться.

        Строки здесь только собираются. Публикует их `accept()` — общий путь
        для всех строк одной свечи.
        """
        entries: tuple[tuple[str, JournalEntry], ...] = ()
        if not taken.unsettled:
            entries = (("", JournalEntry(
                at=taken.closes_at,
                event="Свеча пропущена",
                reason=taken.skipped,
                level=JournalLevel.INFO if taken.repeat else JournalLevel.WARNING,
            )),)
        return Outcome(
            state=self._state,
            written=entries,
            closes_at=taken.closes_at,
            skipped=taken.skipped,
        )

    def _publish(self, entries: Sequence[JournalEntry]) -> None:
        """Отдать строки наружу. Отказ приёмника останавливает робота.

        Запись журнала — синхронный ввод-вывод (база, файл, окно), и падать он
        может. Раньше исключение отсюда улетало наверх и убивало цикл свечей —
        причём уже после того, как состояние было изменено. Теперь наоборот:
        строки публикуются последними, а отказ приёмника означает, что робот
        больше не может объяснить свои действия, — а действие без строки
        в журнале это дефект (ТЗ §4.6). Значит останавливаемся.

        ⚠️ Саму причину остановки записать некуда: приёмник и есть то, что
        отказало. Она видна только в `halted` — и это тот случай, когда
        показать её обязано окно.
        """
        if self._journal is None:
            return
        for entry in entries:
            try:
                self._journal(entry)
            except Exception as error:  # noqa: BLE001 — приёмник чужой, любой
                self._halted = (
                    "Журнал решений не принял строку: "
                    f"{type(error).__name__}: {error}. Робот остановлен: "
                    "действие без строки в журнале — дефект, а объяснить "
                    "свои действия он больше не может"
                )
                return
