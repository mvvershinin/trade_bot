"""Движок: свеча из порта → торговый модуль → десять шагов → заявка в порт.

Здесь и только здесь встречаются ввод-вывод и торговая логика. Разделены они
намеренно и жёстко:

* **синхронное ядро** — `on_candle`, `on_fill`, `apply_settings`. Ни одного
  `await`, ни одного обращения наружу. Это то, чем пользуется прогон
  по истории и сверка с прототипом: детерминированная последовательность
  без цикла событий (решение 0005);
* **адаптер** — `run` и `on_market_candle`. Асинхронные, потому что за портами
  сеть и база.

Второе построено на первом, а не рядом с ним: боевой путь и прогон по истории
проходят через одни и те же строки. Различить их движок не может — у портов
нет признака, по которому это делается (ARCHITECTURE.md §1).

Порядок внутри одной свечи
--------------------------
::

    1. ОБМЕН ПО КРУГУ, пока порт отдаёт сделки:
         сделки исполнителя → состояние движка → заявки, рождённые сделкой
    2. приём свечи: незакрытая, повторная и (по настройке) неполная не идут дальше
    3. перекладка свечи слоя данных в свечу модуля    → одна явная строка
    4. свеча подаётся торговому модулю                → ВСЕГДА, при любом режиме
    5. десять шагов                                   → заявки и журнал
    6. заявки уходят исполнителю
    7. и ТОЛЬКО ПОТОМ — состояние движка и строки журнала

Шаг 1 стоит первым потому, что заявка, поданная на прошлой свече, у прототипа
исполняется по `open` текущей: к моменту, когда текущая свеча закроется,
позиция уже открыта или уже закрыта. Поменять местами с разбором — значит
принимать решение по устаревшему состоянию.

Почему шаг 1 — круг, а не один вопрос
--------------------------------------
Тейк вооружается **от цены входа**, цену входа назначает исполнитель, а `high`
и `low` **той же свечи** уже сторожат уровень: у прототипа есть три сделки
из 127, открывшиеся и закрывшиеся внутри одной свечи (PROTOTYPE.md §5).
Значит заявка «вооружить», рождённая сделкой открытия, обязана дойти
до исполнителя **до того**, как он закончит разбирать тот же бар. Одного
вопроса «отдай сделки» на свечу для этого не хватает.

Условие остановки круга — **пустой ответ порта**, и оно одно и то же для обеих
реализаций: не счётчик кругов и не признак «это модель». В бою второй круг
обычно пуст, в прогоне по истории на нём приходит тейк; код при этом один,
и движок не знает, на каком он свете (решение 0008, пункт 1).

Шаг 7 стоит последним, и это не стиль
--------------------------------------
Здесь стоял обратный порядок: состояние переводилось в «закрывается», строка
«заявка на выход подана» уходила в журнал, и только после этого заявка шла
исполнителю. Отказ брокера — таймаут, «слишком часто», обрыв связи — давал
при таком порядке позицию, **закрытую в журнале и открытую на счёте**, а само
исключение улетало из цикла свечей: цикл умирал молча, без строки и без уровня
ERROR. Дальше становилось только хуже: на следующей свече вне окна ветка
«заявка уже подана — ждём сделки» писала одну строку, а со второй свечи
подавление повторов гасило и её. Лонг оставался на счёте через выходные,
робот молчал, журнал утверждал, что выход подан.

Поэтому: разбор ничего не фиксирует (`analyse`), заявки уходят исполнителю,
и только по его ответу состояние и журнал закрепляются (`accept`). Отказ даёт
строку уровня ERROR и **явную остановку** робота — не смерть задачи, а флаг
`halted`, по которому видно, что случилось и почему нельзя просто продолжить.

Чего здесь нет и почему
-----------------------
Разбора зависшей заявки: движок помнит её (`EngineState.pending`) и второй раз
по тому же поводу не подаёт, но решать, что делать с заявкой, по которой сделки
так и не было, — дело сверки позиции с брокером (этап 2, открытый вопрос №4).
Придумать это правило здесь значило бы придумать и цену ошибки.

Шаг 4 — не «когда режим позволяет», а всегда. Буквальное чтение PROTOTYPE.md §2
ставит проверку режима шагом 1, до счётчика прогрева, и тогда десять минут
в режиме «Выключен» дадут другой список сделок: свечи не попадут в среднюю.
У прототипа индикатор считает платформа, независимо от режима робота. Режимом
фильтруется намерение, а не подача.
"""

