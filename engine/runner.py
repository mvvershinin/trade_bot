def _margin_words(funds: AccountFunds) -> str:
    """ГО контракта словами. `None` — честное «не сообщено», а не ноль.

    Ноль здесь означал бы «свободных средств хватает на любой объём», то есть
    выключенную проверку под видом работающей.
    """
    if funds.margin_per_contract is None:
        return (
            "не сообщено — пока его не сообщат, свободные средства "
            "перед заявкой не проверяются"
        )
    return money(funds.margin_per_contract)


def _named_reason(refusal: ExecutionRefused) -> Refusal:
    """Причина отказа. Подкласс, не позвавший конструктор, — дефект адаптера.

    ⚠️ Читается не «поля может не быть»: поле обязательно, его ставит
    `ExecutionRefused.__init__`. Но обработчик отказа — не место для второй
    аварии: свой подкласс, не позвавший `super().__init__`, уронил бы движок
    внутри `except`, и вместо понятной строки в журнале человек получил бы
    трассировку. Поэтому такой отказ разбирается как «причина не названа».

    ⚠️ **Осторожность этого умолчания — только про снятие.** `Refusal`
    описывает судьбу заявки, названной `target_id`, то есть сторожимого
    уровня: там «считаем живым» действительно самый дешёвый из двух промахов.
    На входе, выходе и вооружении причина движку не меняет ничего — он и так
    знает из контракта `ExecutionRefused`, что заявку не приняли, — и
    осторожное умолчание там было бы обратным по смыслу. Отсюда правило
    журнала: про живой уровень пишем только для снятия.
    """
    reason = getattr(refusal, "reason", None)
    return reason if isinstance(reason, Refusal) else Refusal.UNKNOWN


@dataclass(frozen=True, slots=True)
class _Declined:
    """Определённый отказ: заявка, причина и уже написанная строка журнала.

    Строка **не публикуется** на месте отказа: она уходит в журнал после
    строк самой свечи. Времена у всех строк одной свечи одинаковые, и порядок
    публикации — единственное, чем они различаются при чтении. Строка отказа,
    вставшая раньше строк разбора, читается как «робот отказался, а потом
    зачем-то решал».
    """

    order: OrderRequest
    reason: Refusal
    entry: JournalEntry


