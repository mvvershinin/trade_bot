"""«Данных нет»: программа запущена там, где нет ни базы, ни настроек, ни ключа брокера.

`D-080`, решение 0064. Данные лежат рядом с программой, и обновление заменой
папки или распаковка новой версии не туда дают окно с пустым графиком —
без единого слова о том, что свечи, настройки и ключ остались в прежней
папке и возвращаются копированием. Молчание здесь — самостоятельный дефект
(правило 13), поэтому текст ниже уходит в окно плашкой, а не только в лог.

Чистая функция: путь на входе, текст на выходе, ничего не создаёт и не меняет.

⚠️ **Зовётся до чтения настроек** (`app/main.py::_run`, до `_stored_settings`).
`SettingsStore.load` переименовывает испорченный `settings.json`, и снимок
после него сказал бы «данных нет» человеку, у которого они есть.

⚠️ **Файл ключа не открывается и не читается** — только `Path.exists()`
(правило 7). `TokenStore` здесь не зовётся: его чтение пишет в лог
и проверяет права, а вопрос «лежит ли файл» ни того, ни другого не требует.

Признаком данных **не являются** `logs/`, `instance.lock` и `.write-probe`:
их заводят раньше (`setup_logging`, замок «одна копия» в `main()`, проба
записи `ensure_userdata_dir`), и на пустом месте они уже есть.
"""

from __future__ import annotations

from pathlib import Path

from app.settings_store import SETTINGS_FILE_NAME
from broker.token_store import TOKEN_FILE_NAME

__all__ = ("missing_data_notice",)


def missing_data_notice(database: Path) -> str:
    """Текст «данных нет» или пустая строка, если хоть что-то из данных на месте.

    :param database: база этого запуска — по умолчанию или из ключа `--db`.
        Проверяется **сама база**, а не имя по умолчанию в её папке: при
        `--db` имя файла бывает другим. Настройки и ключ — в той же папке,
        где их читают `SettingsStore` и `TokenStore`.

    Пути в тексте абсолютные: человек копирует папку руками, и относительный
    путь от неизвестно какой текущей папки отправил бы его не туда.

    `PermissionError` от `exists()` здесь не ловится намеренно: до этой
    функции `_userdata_ready` уже записал и стёр пробный файл в той же папке,
    а без права заходить в папку записать в неё нельзя.
    """
    folder = database.resolve().parent
    present = (database, folder / SETTINGS_FILE_NAME, folder / TOKEN_FILE_NAME)
    if any(path.exists() for path in present):
        return ""
    return (
        f"Данных нет: в папке {folder} нет ни базы свечей, ни настроек, ни ключа "
        "брокера. Если это первый запуск программы — так и должно быть. "
        "Если вы обновляли программу: закройте обе копии — прежнюю и эту, "
        "перенесите папку userdata из прежней папки программы сюда: "
        f"{folder.parent} — и на вопрос о замене файлов ответьте «Заменить»."
    )
