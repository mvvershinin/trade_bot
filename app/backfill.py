@dataclass(frozen=True, slots=True)
class Fetched:
    """Что источник ответил догрузке. Отказ — тоже ответ, но со словами.

    Исключения дальше адаптера не летят намеренно: знание о том, чем швыряется
    конкретная библиотека (`BrokerError` у брокера, `IssError` у биржи),
    остаётся при ней. Перебору источников остаётся один вопрос — ответили
    или отказали, — и он не обязан помнить оба списка исключений.

    `covered_until` — докуда выдача **доведена**, не включая сам момент.
    `None` означает «не доведена никуда»: подтверждать по такому ответу
    нечего. `partial` — чем оборвалась выдача, человеческим языком; пусто —
    не обрывалась. Оборванный ответ остаётся ответом: часть записывается,
    но дыра закрытой не считается.
    """

    candles: tuple[Candle, ...] = ()
    covered_until: datetime | None = None
    refusal: str = ""
    technical: str = ""
    partial: str = ""
    pages: int = 0
    requests: int = 0
    retries: int = 0
    duplicates: int = 0

    @property
    def answered(self) -> bool:
        """Источник ответил — пусть даже пустотой или половиной ряда."""
        return not self.refusal


