@dataclass(frozen=True, slots=True)
class Wording:
    """Как источник называется в журнале решений. Тексты живут при источнике.

    Отдельный тип, а не `if источник is биржа` в пяти местах: развилка
    на источник, размазанная по тексту, — это ровно тот паттерн, который
    в проекте назван вслух и запрещён (`CLAUDE.md`, правило 9). Добавится
    третий источник — здесь появится третья строка, а не пятнадцатая ветка.

    Все четыре поля — **текст для человека**. Кодов отказа, HTTP-статусов
    и тел ответов здесь нет и быть не должно: владелец счёта не программист,
    а сырой HTML в окне 05.09.2026 он уже видел.
    """

    #: Родительный падеж названия источника: «брокера», «биржи».
    #: Из него собирается «у брокера» — см. `at`.
    whose: str
    #: Начало фразы про пустой ответ. Целиком, потому что род разный:
    #: «Брокер не прислал свечей за», «Биржа не прислала свечей за».
    nothing: str
    #: Одна строка «откуда взяты минуты и почему не у первого источника».
    #: Говорится **один раз за сеанс** — текст постоянный, и повтор гасит
    #: `Backfiller._tell`.
    origin: str
    #: Хвост предупреждения о несошедшемся объёме. У брокера объём **выведен**
    #: из оборота делением на цену, и запись временна; у биржи он итоговый,
    #: и расхождение говорит уже о живом потоке.
    volume_tail: str

    @property
    def at(self) -> str:
        """«у брокера», «у биржи» — куда ходили за свечами."""
        return f"у {self.whose}"


