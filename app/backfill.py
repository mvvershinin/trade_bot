"""Догрузка пропущенного: дыра в данных закрывается сама, без человека.

Чья это боль
------------
Владелец счёта, 04.09.2026: «пустой промежуток меня тоже не устраивает — надо
догружать данные если проебал». На его графике между 13:08 и 14:03 нет данных,
и вечером того же дня он подтвердил наблюдением: новые минуты с 14:45 пишутся,
а пустой час так и остался пустым. Живой поток пишет **только вперёд** —
канал «последняя свеча» шлёт текущую минуту и ничего больше, — поэтому дыра
за обрывом не закрывается никогда и ничем. Решение
[0022](../.docs/decisions/0022-linux-is-a-workstation-not-a-server.md) убрало
возможность лечить *причину*: машина рабочая, а не постоянно включённая.
Догрузка — единственная защита от дыр, которая у программы будет.

Кто здесь что делает
--------------------
* `broker/candles.py` — **разговор с брокером**: период → свечи, куски
  по 1440 баров, `HistoryIncomplete` на обрыве посреди догрузки;
* `market/iss.py` — **разговор с биржей**: открытые данные МосБиржи,
  бесплатно и без токена, вход из цикла событий — `MarketWorker.fetch_minutes`;
* `market/backfill.py` — **политика над временами**: где дыра, что просить,
  что из ответа писать. Чистые функции, ни сети, ни базы;
* этот модуль — **проводка**: у кого спросить, когда, что сказать человеку,
  что отметить в учёте и что после этого перерисовать.

Два источника и порядок между ними
----------------------------------
05.09.2026 владелец счёта запустил программу и вместо свечей получил в консоли
сырой HTML: догрузка стучалась к брокеру по неверному адресу (в пути стояло
не то имя сервиса) и получала 404 от шлюза. Адрес починен, но урок дороже
опечатки: **программа, у которой источник один, при первой же его осечке
не рисует ничего.**

Поэтому источник здесь не один, а **кортеж с порядком**: сперва брокер,
затем открытые данные биржи. Порядок — данные, а не развилка в коде, и
из этого следуют три вещи, каждая по делу:

* **основной источник — брокер.** Он досчитан до текущей минуты заведомо:
  это то же подключение, которое только что прислало снимок и задало границу.
  У биржи задержка публикации не измерена, и ставить её первой значило бы
  поменять известное на предполагаемое;
* **к бирже идут на любом отказе брокера**, а не на конкретном коде ответа.
  Развилка «если 404» была бы догадкой о чужом сервере: сегодня осечка
  приходит четырёхсотым от прокси, завтра тот же прокси ответит 502 или
  отдаст страницу с кодом 200, а послезавтра просто кончится токен. Правило,
  привязанное к коду, ломается молча и в худшую сторону — дыра остаётся;
* **вкомпилированного «брокер сломан» здесь нет.** Выбор идёт по факту
  ответа, поэтому день, когда брокер заработает, не потребует правки:
  ответивший первым просто становится источником, а второго не спрашивают
  вовсе.

Разбор порядка и рангов — решение 0029,
[`0029-backfill-falls-back-to-the-exchange.md`](../.docs/decisions/0029-backfill-falls-back-to-the-exchange.md).

⚠️ Оборванная выдача (`HistoryIncomplete`) — это **ответ**, а не отказ:
второй источник за остатком не идёт. Иначе каждая дёрганая связь давала бы
два запроса вместо одного. Остаток дыры ждёт следующего подключения.

Пять вопросов, на которые модуль отвечает
-----------------------------------------
**1. Когда ищется дыра.** На каждом успешном подключении потока — в тот
момент, когда пришёл первый снимок. Этим накрываются все три случая разом:
запуск программы с ключом `--stream`, включение потока кнопкой и
восстановление связи после обрыва (обрывы у владельца счёта частые, это его
слова). Раньше подключения искать нечем: догрузка ходит к брокеру, а токен
до просьбы о связи не трогается вовсе (`LiveLink`) — и это правило, а не
оптимизация.

**2. Какой период.** От **первой отсутствующей** минуты до границы потока,
но не глубже `MAX_SPAN` (четверо суток). «Последняя минутка + 1» здесь
не работает: дыра лежит *перед* минутами, которые поток уже записал после
переподключения, — ровно то, на что жаловался владелец счёта. Ночь и выходные
внутри окна запрашиваются вместе со всем отрезком; пустой ответ на них —
это и есть доказательство «торгов не было». Дыра глубже окна — не дыра обрыва,
а отсутствие истории: догрузки нет, в журнале сказано, чем это лечится.

**3. Как отличить «мы потеряли» от «торгов не было».** Никак — по самому ряду
(`market/gaps.py`: биржа не отдаёт минуту, в которую не было сделок). Отличить
можно **только фактом запроса**, и он записывается двумя разными способами,
потому что случаи разные:

* **прошедший день** — отметкой в учёте (`data_day`, `mark_days_requested`).
  Она переживает перезапуск программы, и с ней `CandleStore.bars` перестаёт
  звать хвостовой бар дня незакрытым;
* **сегодняшний день** — границей `HistoryPort.history_confirmed`. Отметить
  сегодня в учёте нельзя по построению (`settled = день < сегодня`), и это
  верно: половина сессии ещё впереди.

После догрузки пустой промежуток означает «биржа ничего не дала», и подпись
«Данных нет» над ним правдива.

**4. Что в журнале решений.** Человеческим языком и по делу: «Догружено 56
минут за 04.09 13:08–14:03». Оставшийся пропуск называется отдельной строкой,
и в ней сказано главное — это настоящая пустота, а не потеря программы.
Одно и то же второй раз не говорится: на дёрганой связи подключений много,
а клиринговый перерыв 14:00–14:05 остаётся пустым всегда.

**5. Что если не удалось.** `HistoryIncomplete` несёт полученную часть
и `covered_until`. Часть записывается, но **дыра при этом не считается
закрытой** — она только ужимается: граница подтверждения двигается до
`covered_until`, ни один день в учёте не отмечается, и в журнал уходит
предупреждение с остатком. Отметка дня необратима (`days_to_request` больше
этот день не отдаст), а `covered_until` — это последний **полученный** бар,
а не конец запрошенного периода: отметить по нему значило бы закрыть дыру,
о которой уже никто не узнает. Повторяет догрузку следующее подключение —
своего цикла повторов здесь нет (отдельный запрос и так переживает обрыв
внутри `BrokerSession.read`).

Чего этот модуль **не** делает
------------------------------
Не трогает движок и не говорит ему, откуда пришла свеча. Происхождение живёт
в колонке `minute_candle.source` и здесь; ни одного нового поля у `Candle`,
которое читает `engine/bars.py`, не появилось и появиться не должно —
догруженная свеча это просто свеча.

Не переписывает существующие строки. Первый и главный рубеж — **отбор
до записи**: `market.backfill.pick_new` оставляет только пустые минуты строго
левее границы потока. Отсюда безопасность повтора: запустили дважды — данных
столько же.

⚠️ Второй рубеж есть **не у всякого источника**, и это названо вслух.
У свечей брокера ранг `broker_history` = 0, ниже всех: хранилище физически
не даст им тронуть существующую строку. У свечей биржи ранг `iss` = 2, выше
потока, — понизить его значило бы разрешить потоку брокера переписывать
итоговые данные самой биржи (решение 0029, §2). Значит, при откате на биржу
за отбором никто не подстраховывает, и поэтому запись, которая всё-таки
что-то обновила, — **строка предупреждения владельцу счёта**, а не тихое
число в отчёте.

⚠️ Не пишет **растущую** минуту, и это отдельное правило, а не следствие.
Признака «свеча закрыта» у брокера нет ни в HTTP-ответе, ни в потоке; период,
дотянутый до «сейчас», вернул бы текущую недобранную минуту, а `close` у неё
не окончательный — то есть средняя сдвинулась бы, и переворот случился бы
там, где его нет. Граница режется дважды: по минуте первого снимка подписки
и по часам программы (`run`), и берётся меньшая из двух.

Двух писателей одной минуты не бывает **по построению**: догрузка пишет
строго левее границы, поток — строго правее неё. Это не соглашение между
задачами, а разделение диапазонов: `known` читается до запроса, минуты правее
границы отбрасываются счётчиком `beyond`, и пересечься диапазонам негде.

⚠️ Единица объёма
-----------------
`volume` у HTTP-свечей брокера — **оборот в рублях**, а в базе лежат
контракты (замер 05.09.2026: отношение 2,199 × 10⁵ на 3858 общих минутах;
словарь полей брокера говорит то же прямым текстом). Пересчёт делает
`to_minute` — один раз, на самой границе слоя, — и дальше по программе
идут контракты. Делится оборот на середину разброса минуты: замер на 1000
настоящих минут показал, что она ближе к средней цене сделок, чем закрытие,
в 2,2 раза (`market.volume`). Свечи, у которой в колонке контрактов лежат
рубли, **не существует ни секунды**: перекладка либо пересчитала, либо
отказала.

Отказ здесь не беда, а запасной путь: источник, объём которого не похож
на оборот, откатывается на биржу, где контракты — итоговые (`_gather`).
Ранг 0 делает записанное временным в любом случае: первая же заливка тех же
минут с биржи заменит их итоговыми данными.

У свечей биржи пересчёта нет вовсе — там контракты по построению. Замер
на нахлёсте при этом работает у обоих источников и означает одно и то же:
сошлось ли. У брокера расхождение говорит о пересчёте, у биржи — о живом
потоке, который считает контракты по приращениям оборота. Поэтому текст
предупреждения берётся у источника (`Wording.volume_tail`), а не пишется
один на оба случая.
"""

