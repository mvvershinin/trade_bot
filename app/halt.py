"""Перевод «исход команды брокеру неизвестен» в остановку робота.

Чья это боль
------------
`OutcomeUnknown` — самое опасное из состояний, в которых программа умеет
оказаться: команда ушла, ответа нет, и **неизвестно, изменилось ли что-то
на счёте**. Обычный отказ говорит «не вышло» и позволяет решать дальше;
этот не говорит ничего. Робот, продолживший торговать в таком состоянии,
считает, что не в рынке, и входит ещё раз — на реверсной системе это
удвоенный объём и удвоенное обеспечение при цене ошибки в рублях (`B-002`,
`D-086`).

Почему отдельный модуль, а не строка в двух местах
--------------------------------------------------
Мест, откуда неизвестный исход может прийти, уже четыре: поток котировок,
опрос счёта, расписание торгов и догрузка пропущенного. Слова, которыми
об этом говорят человеку, обязаны быть **одни на всю программу**: строка
журнала решений и надпись в окне читаются вместе, и два разных объяснения
одного события — это разбор, начинающийся с вопроса «а это одно и то же?».
`app/live_feed.py` уже импортирует `app/backfill.py`, поэтому общий дом
для этих слов не может лежать ни в том, ни в другом.

⛔ **Движок про этот модуль не знает и знать не должен.** `OutcomeUnknown` —
тип из `broker/`, и провести его внутрь `engine/` значило бы научить движок
различать, откуда пришла свеча (`ARCHITECTURE.md` §1). Наружу отсюда уходит
**причина человеческим языком**, а не тип исключения; принимает её порт
(`HistoryPort.halt`), и дальше она живёт ровно там же, где живёт остановка
самого движка, — и снимается только рукой человека.
"""

from __future__ import annotations

import logging
from typing import Callable, Final

from broker.errors import OutcomeUnknown

log = logging.getLogger(__name__)

#: Заголовок строки журнала решений. Одно событие — один заголовок.
HALT_EVENT: Final[str] = "Исход команды брокеру неизвестен"

#: Что дописывается к словам самого отказа. Сам отказ говорит, **что**
#: случилось и что проверить; здесь говорится, **что из этого следует** для
#: робота. Разделено так, потому что первую половину пишет слой брокера
#: и она одинакова для любого вызывающего, а вторая — решение приложения.
HALT_CONSEQUENCE: Final[str] = (
    "Робот остановлен и новых решений не принимает. Продолжить, не зная "
    "позиции, значило бы открыть вторую поверх той, о которой программа "
    "не знает. Остановка снимается только вручную, после того как вы "
    "посмотрите заявки и позицию у брокера."
)

#: Куда слой приложения отдаёт остановку: событие и причина, оба —
#: человеческим языком. Тип исключения сюда не проходит намеренно.
Halt = Callable[[str, str], None]


def halt_reason(unknown: OutcomeUnknown) -> str:
    """Причина остановки: слова самого отказа плюс следствие для робота.

    Слова отказа берутся **как есть** (`human`), а не пересказываются:
    их пишет слой брокера, они уже очищены от секретов при создании отказа
    (`broker/errors.py`) и в них стоит главное указание владельцу счёта —
    проверить заявки и позицию у брокера. Второго текста про то же событие
    в программе не заводится: разошлись бы они молча.
    """
    return f"{unknown.human} {HALT_CONSEQUENCE}"


def halt_on_unknown_outcome(unknown: OutcomeUnknown, halt: Halt) -> None:
    """Неизвестный исход команды → остановка робота и строка человеку.

    Два адресата, и оба обязательны. Технический лог получает `technical`:
    адрес, код и причина — по ним разбирают, что именно осталось без ответа.
    Журнал решений получает человеческий текст: молчаливая остановка — это
    мёртвое окно, и владелец счёта уже трижды за сутки принимал исправное
    молчание за поломку (правило 13 `CLAUDE.md`).

    Порядок не безразличен: сначала лог, потом человек. Приёмник журнала
    чужой и падать вправе; запись в технический лог обязана остаться
    в любом случае — иначе разбирать будет нечего.
    """
    log.warning("исход команды брокеру неизвестен: %s", unknown.technical)
    halt(HALT_EVENT, halt_reason(unknown))
