"""Как позвать эту программу — на той машине, где она сейчас работает.

Зачем это существует
--------------------
Замер 06.09.2026 живым запуском собранного `.exe` в виртуалке Windows, где
питон удалён, а `PATH` урезан до `system32`:

    > Terminal.exe --inspect MXU6
    Базы свечей нет: ...userdata/candles.sqlite3
    Она появится сама при первой загрузке: python3 -m app.main --fetch MXU6

Программа работала и советовала команду, **которой на машине владельца счёта
нет и не будет**: питона там не существует, в этом и смысл поставки одним
файлом. Совет, ведущий в никуда, хуже отсутствующего: человек тратит время
на попытку его выполнить (`B-024`).

Различается **не система, а способ запуска.** `sys.frozen` ставит сборщик
(Nuitka, PyInstaller) в собранном приложении; из рабочей копии его нет ни
на Windows, ни на Linux. Проверка по имени системы ответила бы неверно
на обеих: разработчик на Windows запускает `python -m app.main`, а владелец
счёта на Linux — собранный файл.

Чего здесь нет
--------------
Ни одной строки про торговлю и ни одного обращения к диску, кроме имени
собственного исполняемого файла. Модуль отвечает ровно на один вопрос:
какую команду человеку можно показать, чтобы она у него сработала.
"""

from __future__ import annotations

import pathlib
import sys

__all__ = ["HISTORY_BUTTON", "command", "frozen", "how_to_fetch"]

#: Где в окне лежит загрузка истории. Строка одна на все места, где об этом
#: надо сказать: разойдясь, два описания одного пути отправили бы человека
#: в разные меню.
HISTORY_BUTTON = (
    "кнопкой «Загрузить историю…» в меню «Программа» главного окна"
)


def frozen() -> bool:
    """Программа собрана в один файл, питона рядом нет.

    ⚠️ **`sys.frozen` для этого недостаточно, замер 06.09.2026.** Nuitka
    в режиме `--standalone` его **не ставит**: собранная программа отвечала
    `False` и советовала владельцу счёта набрать `python3 -m app.main`,
    которого на его машине нет и не будет (`B-024`). Проверено запуском
    готового файла, а не чтением документации.

    Свой признак Nuitka кладёт иначе — модулям выдаётся `__compiled__`.
    Поэтому смотрим на оба, а сверх того на `sys.executable`: у собранной
    программы это наш файл, у запуска из исходников — интерпретатор.
    Три признака вместо одного потому, что цена ошибки здесь — совет
    в никуда, а он уже однажды выдавался.
    """
    if bool(getattr(sys, "frozen", False)):
        return True
    if "__compiled__" in globals():
        return True
    name = pathlib.Path(sys.executable).name.lower()
    return not (name.startswith("python") or name.startswith("pypy"))


def command(*arguments: str) -> str:
    """Команда запуска с этими ключами — та, которая сработает здесь и сейчас.

    Из рабочей копии это `python3 -m app.main …`; из собранного файла —
    имя самого файла. Имя берётся у `sys.executable`, а не пишется
    константой: собранный файл владелец счёта вправе переименовать,
    и совет с чужим именем снова окажется советом в никуда.
    """
    if frozen():
        # ⚠️ Имя берётся у `sys.argv[0]`, а НЕ у `sys.executable`. Замер
        # 06.09.2026 на готовой сборке: у собранной Nuitka программы
        # `sys.executable` называется `python`, и совет выходил
        # «python --fetch MXU6» — команда, которой нет. `argv[0]` —
        # это то, чем программу позвали на самом деле.
        called = sys.argv[0] or sys.executable
        head = [pathlib.Path(called).name]
    else:
        head = ["python3", "-m", "app.main"]
    return " ".join([*head, *arguments])


def how_to_fetch(symbol: str) -> str:
    """Как загрузить историю — сначала мышкой, потом из консоли.

    Порядок именно такой, и он не вкусовой: владелец счёта не программист
    и работает мышкой, а консольная команда нужна тому, кто и так в консоли.
    Пока она стояла первой и единственной, поставка выглядела сломанной
    (`B-024`).
    """
    return (
        f"Загрузите историю {HISTORY_BUTTON}. "
        f"Из консоли то же самое: {command('--fetch', symbol)}"
    )
