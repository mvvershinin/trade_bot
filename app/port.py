_BY_KEY: dict[str, _Work] = {work.key: work for work in _WORKS}


@dataclass(frozen=True, slots=True)
class _Span:
    """Закреплённый отрезок истории: что показывает окно вместо последних дней.

    Появляется от «Прогона на истории» и живёт до «Вернуться к текущим
    данным». Пока он стоит, порт ведёт себя иначе в трёх местах, и каждое
    названо, потому что каждое молча ломается:

    * `_candles` берёт границы отсюда, а не из глубины показа и не из ключа
      ``--until``;
    * `_advance` идёт прогоном по истории **мимо живого хода движка**: бары
      июня, поданные наблюдателю, легли бы в его среднюю, и она перестала бы
      быть той, что была бы у робота в бою;
    * `_shown` отвечает «рисовать нечего», то есть живые свечи на закреплённый
      отрезок не приходят вовсе.

    Последнее и есть причина, по которой окно обязано показывать плашку:
    график, застывший в прошлом при живом потоке, выглядит как потерянная
    связь.

    `source` — чем гнали, словами: «текущие настройки» либо имя шаблона.
    Хранится, чтобы плашка и отчёт называли одно и то же.
    """

    since: datetime
    until: datetime
    source: str = ""


@dataclass(slots=True)
class _Backtest:
    """Прогон на истории по просьбе владельца счёта: отрезок и обещанный отчёт.

    Значение, а не два поля в `__init__`, по той же причине, что и `_Watch`:
    поля с объяснениями раздували сборку порта за предел длины
    (`tests/test_function_size.py`), а объяснение полей — не то, ради чего
    читают сборку объекта.

    `span` — закреплённый отрезок истории; `None` означает обычный показ
    последних дней (`HistoryPort._days`). Переживает сколько угодно проходов
    и снимается только человеком (`show_recent`).

    `pending` — просьба, отчёт по которой ещё не отправлен. Живёт ровно один
    проход: ставится в `run_backtest`, снимается в `_pass`. Поле, а не довод
    прохода, потому что проход ставится в очередь цикла событий (`refresh`),
    а не вызывается напрямую.

    ⚠️ Разъединять их нельзя: отрезок без просьбы — это «смотрим прошлое,
    отчёта не будет» (так после `show_recent` и после второго прохода),
    а просьба без отрезка невозможна по построению — `run_backtest` ставит
    оба разом.

    `options` — задача чтения списка инструментов для диалога. Лежит здесь,
    а не отдельным полем порта, ровно затем, чтобы её видели `wait` и
    `aclose`: незакрытая задача, читающая базу, переживает закрытие базы
    и падает «поток данных остановлен» уже в закрывающейся программе.
    """

    span: _Span | None = None
    pending: BacktestRequest | None = None
    options: asyncio.Task[None] | None = None


