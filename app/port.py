@dataclass(slots=True)
class _Stuck:
    """Часы долгих работ: кто когда подал голос и о чём уже сказано.

    Заведено по `B-025`, пойманному на владельце счёта 06.09.2026: задача
    прогона осталась навсегда незавершённой, порт после этого отказывал
    **каждой** команде — по делу, он действительно был занят, — и окно
    выглядело мёртвым. Отказ до окна не доезжал, а о самой застрявшей
    задаче не говорил никто.

    `heard` — когда работа в последний раз подала признак жизни, по монотонным
    часам. Не время начала: прогон на годе минуток идёт семь секунд и всё это
    время шлёт долю сделанного, и мерить от начала значило бы объявить
    застрявшей исправную длинную работу. Отсчёт ведётся от **молчания**.

    `told` — о застревании какой работы уже сказано. Сторож смотрит на часы
    раз в секунду, и без этого он писал бы в журнал одну и ту же строку
    ежесекундно, похоронив её под собой же (тот же приём, что `_Halt.said`).

    `refused` — о занятости какой работы уже написана строка **в журнал**.
    В окно отказ уходит каждый раз (человек нажал сейчас и ответа ждёт
    сейчас), а в журнал — однажды: `refresh` зовётся на каждом закрытом баре
    живого хода.

    `shown` — что сейчас висит в окне плашкой. Пустая строка — плашки нет.
    Хранится, чтобы сигнал уходил на **смену** текста, а не ежесекундно.

    `timer` — чем сторож просыпается. **Таймер Qt, а не задача asyncio**,
    и это не вкус, а замер 06.09.2026.

    Задача с `asyncio.sleep` под `qasync` заводит таймер Qt внутри самого
    цикла (`qasync._SimpleTimer.add_callback` зовёт `startTimer`), а снимает
    его только собственным срабатыванием: `stop()` цикла ставит флаг и живой
    таймер не убивает. Сторож, спящий в момент закрытия цикла, оставляет
    поэтому висящий таймер на объекте, который вот-вот уберёт сборщик мусора,
    — и процесс падает в чужом месте и не сразу:

        Thread 1 received signal SIGSEGV
        QCoreApplication::notifyInternal2(QObject*, QEvent*)
        QTimerInfoList::activateTimers()

    Воспроизведено на `tests/test_app_port.py`: с задачей — падение в трёх
    прогонах из трёх, каждый раз на **разном** тесте (58-й, 72-й, 89-й);
    без неё — 122 passed. Это же, по всей видимости, и есть необъяснённое
    `D-032`.

    Таймер Qt этой беды не имеет: он дитя порта, гаснет вместе с ним
    и снимается явно (`aclose`). Вдобавок он будит сторожа **вне шага
    корутины** — то есть плашка не рискует поднять вложенный цикл событий
    посреди чужой задачи (`B-026`).

    `after` — общий срок молчания вместо своего у каждой работы. `None` —
    брать из таблицы `_WORKS`, и это рабочее умолчание. Значение существует
    ради проверок: сторож, ждущий тридцать секунд, — плохой тест.
    """

    heard: dict[str, float] = dataclasses.field(default_factory=dict)
    told: set[str] = dataclasses.field(default_factory=set)
    refused: set[str] = dataclasses.field(default_factory=set)
    shown: str = ""
    timer: QTimer | None = None
    tick: float = STUCK_TICK
    after: float | None = None

    @classmethod
    def watching(cls, after: float | None) -> _Stuck:
        """Часы с общим сроком молчания. `None` — свой у каждой работы.

        Шаг сторожа выводится из срока, а не задаётся рядом с ним: сторож,
        просыпающийся раз в секунду при сроке в полсекунды, объявил бы
        застревание вдвое позже обещанного, и проверка мерила бы не то,
        что написано у неё в имени. Четверть срока — чтобы обещанная
        точность была хотя бы вчетверо мельче самого срока.
        """
        if after is None:
            return cls()
        return cls(tick=min(STUCK_TICK, max(after / 4, 0.005)), after=after)


class HistoryPort(TerminalPort):
    """Окно ↔ прогон по истории.

    :param worker: поток данных `market/`; база живёт внутри него.
    :param values: настройки окна — те же, что показывает диалог настроек.
    :param mode: режим робота. Умолчание — рабочий режим стратегии: прогон
        в режиме «Выключен» не сделает ни одной сделки, и окно будет пустым
        не потому, что робот так решил, а потому, что его не спросили.
    :param days: сколько последних календарных дней брать. `0` — всю историю.
    :param until: по какой момент показывать историю. `None` — по последнюю
        свечу в базе. Нужен, чтобы посмотреть прошедший день целиком, а не
        только хвост ряда.
    :param sanitize: чистка секретов. Обязательна, умолчания не имеет.
        Через неё проходит **всё**, что порт отправляет в окно, — разбор
        в докстринге `_send`.
    :param redraw_gap: не чаще чем раз в столько секунд перерисовывается
        растущая свеча. Умолчание и его обоснование — `REDRAW_GAP`.
        Параметр существует ради проверки: порог, зашитый числом, нельзя
        проверить иначе как ожиданием реального времени в тесте.
    :param stuck_after: через сколько секунд молчания работа считается
        застрявшей — общий срок вместо своего у каждой. `None` — свой,
        из таблицы `_WORKS`, и это рабочее умолчание. Довод существует
        по той же причине, что `redraw_gap`: тест, ждущий тридцать секунд,
        — плохой тест. Частота взгляда на часы выводится отсюда же
        (`_Stuck.watching`), вторым доводом не заводится: срок и шаг
        осмысленны только вместе, а разъехавшись — дают сторожа, который
        просыпается реже, чем истекает его собственный срок.
    """

    def __init__(
        self,
        worker: MarketWorker,
        *,
        values: Settings | None = None,
        mode: Mode = Mode.REVERSE,
        days: int = 30,
        until: datetime | None = None,
        parent: QObject | None = None,
        sanitize: Sanitize,
        redraw_gap: float = REDRAW_GAP,
        stuck_after: float | None = None,
    ) -> None:
        super().__init__(parent)
        self._worker = worker
        self._sanitize = sanitize
        self._values = values or Settings()
        self._mode = mode
        self._days = days
        self._until = until
        self._engine_settings = convert.engine_settings(self._values, self._mode)
        self._notes: list[DecisionRow] = []
        self._journal: tuple[DecisionRow, ...] = ()
        self._run: HistoryRun | None = None
        self._task: asyncio.Task[None] | None = None
        #: Просьба пересчитать, пришедшая во время прогона. Не флаг, а причина:
        #: она же уходит в технический лог, если прогон не удастся.
        self._again = ""
        #: Состояние связи с брокером. `UNKNOWN` — связь не заводилась вовсе,
        #: и это честное умолчание: прогон по истории брокера не спрашивает.
        #: Живой поток (Э1-5) выставляет сюда настоящее состояние; пока его нет,
        #: значение не меняется никогда, и окно говорит «не подключено».
        #:
        #: ⚠️ Поле, а не сигнал: состояние читается при сборке снимка `_state`,
        #: то есть попадает в окно тем же путём, что и всё остальное. Отдельный
        #: сигнал дал бы второй путь к панели состояния — и два ответа на один
        #: вопрос, расходящиеся во времени.
        self.connection = Connection.UNKNOWN
        #: Кто включает и выключает поток котировок и кому сказать, что
        #: инструмент в окне сменился (`B-020`). Ставит сборка (`app/main.py`),
        #: обе разом и одной командой: подключение к брокеру — её забота,
        #: а раздельная проводка завела бы случай «поток включается, но
        #: за настройкой не идёт». Разбор — в `attach_stream`.
        self._stream: Callable[[bool], str | None] | None = None
        self._retarget: Callable[[str], None] | None = None
        #: Последний снимок состояния, ушедший в окно. Нужен `restate`: связь
        #: меняется чаще, чем данные, и переотправить снимок с новым полем
        #: `connection` дешевле, чем гонять ради него прогон по всей истории.
        self._last_state: RobotState | None = None
        self._trust = _Trust()  # граница доверия к барам; разбор полей — в `_Trust`
        #: Что нарисовано справа на графике. `None` — не нарисовано ничего.
        self._edge: _Edge | None = None
        #: Время закрытия самого свежего **закрытого** бара, который порт уже
        #: видел в базе. По нему живая свеча отличает «бар ещё набирается»
        #: (рисуем, прогон не нужен) от «бар закрылся» (на нём движок мог
        #: принять решение — нужен прогон).
        self._settled_seen: datetime | None = None
        #: Задача дорисовки живой свечи. Отдельная от прогона: прогон читает
        #: всю историю и считает стратегию, дорисовка читает хвост и рисует.
        self._draw: asyncio.Task[None] | None = None
        #: Задача перерисовки **растущей** свечи и время последней такой
        #: перерисовки по монотонным часам.
        #:
        #: ⚠️ Слот свой, а не общий с `_draw`, и это не экономия. Общий слот
        #: означал бы, что растущая свеча способна **вытеснить** дорисовку
        #: закрытой минуты, — а именно та решает, гнать ли прогон на закрытии
        #: бара (`B-009`). Пропущенный прогон — это молча не появившиеся метки
        #: сделок; пропущенное дрожание свечи — полсекунды несвежей картинки.
        #: Поэтому приоритет обратный: растущая свеча уступает дорисовке,
        #: дорисовка не уступает никому.
        self._growing: asyncio.Task[None] | None = None
        self._grown_at = float("-inf")
        self._redraw_gap = redraw_gap
        #: Кто пишет в базу строку прогона: с чем гнали, на чём и что вышло.
        #: Порт зовёт её вокруг каждого прохода движка (`_replay`) — иначе
        #: число из отчёта живёт отдельно от условий, при которых получено,
        #: и на вопрос «почему такой убыток» ответить нечем ни владельцу
        #: счёта, ни разбору.
        self._runs = RunLog(worker, warn=self._warn, note=self.note)
        self._back = _Backtest()  # прогон на истории; разбор полей — в `_Backtest`
        self._watch = _Watch()  # живой ход движка; разбор полей — в `_Watch`
        #: Остановка робота. Живёт **вне** `_Watch` намеренно: та гаснет
        #: вместе с ходом, а остановка обязана его пережить (`_Halt`, `D-033`).
        self._halt = _Halt()
        self._point = _Point()  # стоимость пункта; разбор полей — в `_Point`
        self._history = _History()  # загрузка истории; разбор полей — в `_History`
        self._stuck = _Stuck.watching(stuck_after)  # часы долгих работ; см. `_Stuck`

    # ------------------------------------------------------- выход наружу

    def _send(self, signal: SignalInstance, *payload: object) -> None:
        """Отправить событие в окно. **Единственный выход порта наружу.**

        Здесь стоит первый рубеж чистки секретов, и стоит он именно здесь,
        а не у каждого получателя. Причина названа замером: у одной строки
        журнала решений четыре выхода — ячейка таблицы, всплывающая подсказка,
        строка состояния окна (`ui/main_window.py::show_error`) и выгрузка
        в файл. Пока чистка стояла только на выгрузке, три из четырёх оставались
        открытыми, а скриншот окна и пересланный файл выносят токен одинаково
        (докстринг `broker/redaction.py` про скриншот говорит прямо).

        Путь реальный. `_refresh` ловит `Exception as error` и кладёт `{error}`
        и в причину решения, и в `failed`; на Э1-5 туда придёт тело ответа
        сервера брокера. Движок делает то же самое: `engine.Engine` пишет
        в строку журнала `f"{type(error).__name__}: {error}"`.

        ⚠️ Прямой `signal.emit` из этого класса — нарушение, и его стережёт
        `tests/test_app_port.py`: новый сигнал, отправленный мимо `_send`,
        обходит рубеж молча.
        """
        signal.emit(*(_scrubbed(item, self._sanitize) for item in payload))

    # ------------------------------------------------------------- команды

    def attach_stream(
        self,
        control: Callable[[bool], str | None],
        *,
        retarget: Callable[[str], None] | None = None,
    ) -> None:
        """Назначить, чем включается поток котировок. Зовётся при сборке.

        `control` возвращает `None`, если команда принята, и причину
        человеческим языком, если включить нельзя, — токен не введён, файл
        испорчен, папка названа не так. Что с причиной делать, решает порт
        (`stream`), а не сборка: разговор об отказах с окном один, и ведёт
        его порт — через тот же рубеж чистки, что и всё остальное.

        `retarget` получает код инструмента при каждом применении настроек
        (`apply_settings`). Без него поток остаётся на инструменте, выбранном
        при сборке, и после смены в окне пишет **старый**, молча, — это
        `B-020`. Умолчание `None` оставлено ради проверок, которые до потока
        не доходят вовсе; что сборка его передаёт, стережёт тест.
        """
        self._stream = control
        self._retarget = retarget

    def attach_exchange(self, ask: Callable[[str], Awaitable[PointValue]]) -> None:
        """Чем спрашивать у биржи карточку инструмента. Зовётся при сборке.

        Та же проводка, что у потока котировок (`attach_stream`), и по той же
        причине: порт решает **когда** спрашивать, сборка — **чем**. Без
        проводки порт в сеть не ходит ни разу, поэтому проверки, собирающие
        порт напрямую, остаются без интернета — а прогон тестов, который
        молча уходит на биржу, это девять секунд ожидания на каждую проверку
        и красный прогон на машине без сети.

        Ради чего это заведено, названо в `B-021`: без спрошенной величины
        в движок уходит умолчание 1 ₽ за пункт, верное для одного контракта
        из шести. По `RIU6` итог занижен в 1,74 раза, по `BRV6` — в 869 раз,
        и ошибка тихая: сделки те же, деньги другие.
        """
        self._point.ask = ask

    def stream(self, on: bool) -> None:
        """Команда окна: подключиться к брокеру или отключиться.

        ⚠️ Порт не знает, кто подключается, и не должен: окно просит связь,
        сборка решает, чем её дать. Без обработчика — отказ вслух, а не тишина:
        нажатая кнопка, не сделавшая ничего, хуже отсутствующей.

        Отказ сборки — тоже вслух, и с состоянием: единственный источник правды
        о связи — поле `connection`, окно узнаёт о нём снимком `_state`, поэтому
        после смены — прогон, а не второй сигнал. Без этого кнопка оставалась
        бы нажатой при связи, которой нет.
        """
        if self._stream is None:
            self._refuse(
                "поток котировок",
                "Подключение к брокеру не собрано: программа запущена без него.",
            )
            return
        refusal = self._stream(on)
        if refusal is None:
            self._observe(on)
            return
        self.connection = Connection.OFFLINE
        self._refuse("Подключение к брокеру", refusal)
        self.restate()

    def history_confirmed(self, symbol: str, until: datetime) -> bool:
        """Биржа подтвердила полноту минуток по `until` (не включая его).

        Зовёт догрузка пропущенного (`app/backfill.py`) после того, как отрезок
        `[дыра, until)` запрошен у брокера и записан. С этого момента пустая
        минута внутри отрезка означает «сделок не было», а не «программа
        прозевала», — и бар, собранный не из всех минут, снова вправе считаться
        закрытым (`_trusted`).

        Три условия, и каждое стоит по названной причине.

        **Только вверх.** Подтверждение — это знание, а знание не отменяется:
        сдвиг границы назад молча выбросил бы из прогона бары, которым уже
        поверили, и они пропали бы с графика до перезапуска.

        **Не до `coverage.last`, а до `until`.** В базе к этому моменту уже
        лежат минуты, записанные живым потоком в этом сеансе, — они выше
        границы `until` по построению (`market/backfill.pick_new`) и
        подтверждёнными не являются: их полноту никто не проверял. Сдвиг
        до конца базы выдал бы поток за данные биржи.

        **Только свой инструмент.** Граница своя у каждого инструмента
        (`_Trust.end`), поэтому испортить показанный ряд чужое подтверждение
        уже не может. Отказ остаётся по другой причине: ответ `True`
        вызывающий читает как «есть что перерисовать» и гонит прогон, а прогон
        идёт по показанному инструменту. Подтверждение по тому, на который
        никто не смотрит, дало бы прогон впустую; когда владелец счёта на него
        переключится, границу поставит первый взгляд (`_first_look`) по самой
        базе — там к тому моменту уже лежит догруженное.

        Прогон отсюда **не** запускается: решение «перерисовать» принимает
        вызывающий, потому что он один знает, записалось ли что-нибудь.
        Догрузка, не давшая ни одной минуты, границу двигать может (брокер
        ответил «пусто» — это тоже ответ), а перерисовывать нечего. Ответ
        `True` означает «граница сдвинулась» — по нему вызывающий и решает,
        нужен ли прогон: без сдвига и без записи показывать нечего нового.
        """
        try:
            shown = convert.instrument_of(self._values.instrument)
        except convert.SettingsRefused:
            return False
        if symbol != shown:
            return False
        return self._confirm(symbol, in_moscow(until) - timedelta(minutes=1))

    def stream_leads(self, symbol: str, minute: datetime) -> None:
        """Живой поток подписался и ведёт ряд с этой минуты. Возврат немедленный.

        Зовёт звено при **каждом** подключении (`app/live_feed.py`,
        `Watchers.connected`), а запоминается только **первая** минута
        по инструменту. Причина названа: у второго подключения слева от его
        первой минуты лежит дыра обрыва, и объявить её проверенной историей
        значило бы отдать движку бар, собранный не из всех минут (`_trusted`).
        Дыру закрывает догрузка, и она же двигает границу — `history_confirmed`.

        Зачем это вообще нужно, разобрано в `_first_look`: с тех пор как поток
        следует за сменой инструмента в окне (`B-020`), он способен дописать
        в базу по инструменту, на который порт ещё ни разу не смотрел. Тогда
        `coverage.last` показывает уже на минуту потока и границей служить
        не может, а эта минута — может.

        Ни прогона, ни чтения базы отсюда: вызов идёт из чтения сокета,
        и ожидание здесь остановило бы приём снимков.
        """
        self._trust.lead.setdefault(symbol, in_moscow(minute))

    def _confirm(self, symbol: str, last_minute: datetime | None) -> bool:
        """Подвинуть границу подтверждённого по инструменту. Сдвинулась ли она."""
        if last_minute is None:
            return False
        known = self._trust.end.get(symbol)
        if known is not None and last_minute <= known:
            return False
        self._trust.end[symbol] = last_minute
        return True

    def restate(self) -> None:
        """Снимок состояния с текущей связью — сейчас же и без прогона.

        Зовётся тем, кто поменял `connection`. Всё остальное в снимке
        принадлежит последнему прогону и не менялось, поэтому он
        переотправляется с одним новым полем. Гонять ради поля прогон по всей
        истории нельзя: связь меняется на каждой попытке подключения, и при
        негодном токене это был бы шторм прогонов (ворота `/validate`,
        04.09.2026). Прогона ещё не было — снимка нет: он придёт с первым
        прогоном и возьмёт связь из того же поля.

        ⚠️ Окно зеркалит кнопку связи из этого снимка, а не помнит нажатие
        (`ui/main_window.py`). Отказ подключения без снимка оставил бы кнопку
        нажатой при связи, которой нет.
        """
        if self._last_state is None:
            return
        self._publish_state(
            dataclasses.replace(self._last_state, connection=self.connection)
        )

    def start(self) -> None:
        self._refuse("Запуск робота", f"Робот не запущен: {NO_LIVE}")

    def stop(self) -> None:
        self._refuse(
            "Остановка робота",
            f"Останавливать нечего: {NO_LIVE}",
        )

    def close_position(self) -> None:
        self._refuse(
            "Закрытие позиции",
            "Закрывать нечего: заявки на биржу не уходят, позиция в окне — "
            "результат прогона по истории, а не позиция на счёте.",
        )

    def set_mode(self, mode: Mode) -> None:
        """Сменить режим и пересчитать прогон.

        Режим меняет **сделки**, а не оформление: в «Только лонг» шортов
        не будет вовсе. Поэтому прогон гоняется заново, а не фильтруется.
        """
        if mode is self._mode:
            return
        # ⚠️ Режим живёт в двух местах — в порте (его показывает окно) и внутри
        # настроек движка. Обновить только первое значит поменять подпись
        # в панели и оставить прогон прежним: окно говорит «Только закрытие»,
        # а робот на графике продолжает входить.
        fresh = convert.engine_settings(self._values, mode, self._engine_settings)
        changes = fresh.changes_from(self._engine_settings)
        self._mode = mode
        self._engine_settings = fresh
        self._apply(
            "Режим изменён",
            "; ".join(changes) + ". Прогон по истории пересчитан с новым режимом."
            if changes else f"Режим «{mode.label}» уже стоял",
        )

    def apply_settings(self, settings: Settings) -> None:
        """Принять настройки окна и пересчитать прогон.

        Разбор строк окна — громкий: незнакомый размер свечи и пустой
        инструмент отвергаются с объяснением, а не подменяются умолчанием.

        Строки изменений собираются из **трёх** источников, и это не мелочь:
        движок (`EngineSettings.changes_from`) и торговый модуль
        (`EmaReverseSettings.changes_from`) знают только свои поля, а пять
        полей окна не принадлежат ни одному из них — инструмент, размер свечи
        и три поля предохранителей. Пока их строки писал только движок, смена
        инструмента давала в журнал «Значения совпали с прежними», после чего
        программа грузила **другой инструмент**. ТЗ §4.4 А требует обратного:
        строку с прежним и новым значением на каждое изменение.

        Три поля предохранителей выделены в отдельную строку уровня
        «предупреждение»: за ними сегодня не стоит ничего, и молчаливое
        «принято» читалось бы как «ограничение поставлено».
        """
        try:
            fresh = convert.engine_settings(settings, self._mode, self._engine_settings)
            convert.timeframe_of(settings.timeframe)
            convert.instrument_of(settings.instrument)
            module = convert.strategy_settings(settings)
        except convert.SettingsRefused as refusal:
            self._refuse("Настройки не приняты", str(refusal))
            return
        except (ValueError, TypeError) as error:
            # ⚠️ Проверки самих настроек (`__post_init__` движка и торгового
            # модуля) бросают не `SettingsRefused`. Из диалога такие значения
            # сегодня не приходят, но `apply_settings` — публичная команда
            # порта и зовётся из слота Qt: непойманное исключение здесь
            # означает трассировку в консоль и молчащее окно.
            self._refuse(
                "Настройки не приняты",
                f"Значение не годится: {error}. Прежние настройки остались в силе.",
            )
            return

        changes = convert.window_changes(self._values, settings)
        changes += fresh.changes_from(self._engine_settings)
        rule_changed = module.changes_from(convert.strategy_settings(self._values))
        changes += rule_changed
        if rule_changed:
            # ⚠️ Одной строкой мало: «Период средней: 15 → 20» говорит, что
            # поменяли, и не говорит, каким стало **правило**. Через месяц
            # разбирают именно правило — «почему в тот день робот повёл себя
            # иначе», — а восстанавливать его из чисел по памяти некому.
            # Строка собрана из той же таблицы утверждений, что и решения
            # модуля, поэтому разойтись с ними не может.
            changes.append(
                f"Правило теперь читается так — {convert.rule_headline_of(module)}"
            )
        guards = convert.guard_changes(self._values, settings)
        self._values = settings
        self._engine_settings = fresh
        if self._retarget is not None:
            # Поток котировок идёт за настройкой, а не остаётся на инструменте,
            # выбранном при сборке (`B-020`). Зовётся **всегда**, даже когда
            # инструмент тот же: решение «менять или нет» принимает тот, кто
            # знает, на что подписан сейчас, а порт этого не знает.
            self._retarget(convert.instrument_of(settings.instrument))
        self._send(self.settings_applied, settings)
        self._send(self.strategy_rule_changed, convert.rule_of(module))
        if guards:
            self.note(
                "Предохранители изменены",
                "; ".join(guards) + f". {NO_GUARDS}",
                DecisionLevel.WARNING,
            )
        if changes:
            reason = "; ".join(changes)
        elif guards:
            reason = "Торговые значения не изменились"
        else:
            reason = "Значения совпали с прежними"
        self._apply("Настройки изменены", reason)

    def request_settings(self) -> None:
        """Текущие настройки и текущее правило робота словами.

        Два сигнала, а не один: правило `ui/` посчитать не может — окно
        не импортирует торговые слои (ARCHITECTURE.md §2). Отправляется оно
        **вместе** с настройками и здесь, и при их применении: окно, спросившее
        настройки при открытии, иначе показывало бы поля без объяснения,
        что робот с ними делает, до первого «Применить».
        """
        self._send(self.settings_applied, self._values)
        self._send(
            self.strategy_rule_changed,
            convert.strategy_rule(self._values),
        )

    def request_chart(self, instrument: str, timeframe: str) -> None:
        self.apply_settings(self._values.replace(instrument=instrument, timeframe=timeframe))

    def set_depth(self, days: int) -> None:
        """Сколько последних календарных дней показывать. `0` — всю историю.

        Отдельная команда, а не поле `EngineSettings`: глубина показа —
        настройка **программы**, а не торговли, и в настройках движка ей места
        нет — там каждое поле стережётся сверкой с прототипом (`D-026`).
        Список сделок от глубины не зависит: она меняет, сколько их видно.

        Прогон здесь не запускается. Сборка зовёт это из обработчика
        «настройки приняты», а прогон идёт следом сам — иначе на одно
        «Применить» приходилось бы два прохода по всей истории.

        ⚠️ Живой ход движка от этой команды **не пересобирается** (`D-033`):
        глубины показа нет в том, чем ход задан (`_watch_key`). Прежде она
        там была, и остановленный робот после смены глубины торговал дальше.
        """
        self._days = days

