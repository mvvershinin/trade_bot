    # -------------------------------------------- прогон на истории по кнопке

    def _right_edge(self) -> datetime | None:
        """По какой момент читается история. `None` — по последнюю свечу базы.

        Одно место на весь порт, потому что край спрашивают двое и разными
        словами: чтение свечей (`_candles`) и решение «рисовать ли живую
        свечу» (`_shown`). Разойдись они — окно рисовало бы живую минуту
        поверх графика, закреплённого на июне.

        Закреплённый прогон главнее ключа ``--until``: ключ задаёт край
        на весь запуск, а прогон — это то, что человек попросил только что.
        """
        if self._back.span is not None:
            return self._back.span.until
        return self._until

    def request_backtest_options(self) -> None:
        """Из чего выбирать в диалоге прогона. Ответ придёт сигналом.

        Возврат немедленный: список инструментов и границы их истории лежат
        в базе, а чтение базы идёт в своём потоке (`MarketWorker`). Ожидание
        здесь означало бы окно, замершее на открытии меню.
        """
        self._back.options = self._begin("options", self._backtest_options())

    async def _backtest_options(self) -> None:
        """Инструменты базы с границами их истории. Собранных рядов тут нет.

        ⚠️ Ряд, собранный нами из ближних контрактов (`@MX`), в список выбора
        не попадает — решение 0049. Заявку по коду, которого на бирже нет,
        подать нельзя, а цены на его стыках не подгоняются: показанный
        в списке, он рано или поздно был бы выбран. Отсев делает слой сборки,
        потому что окно про синтетические ряды знать не должно.

        Отказ базы — не пустой список, а названная причина: пустой список
        читается как «истории нет», и это другое утверждение.
        """
        try:
            symbols = await self._worker.symbols()
            found = []
            for symbol in symbols:
                if is_synthetic(symbol):
                    continue
                coverage = await self._worker.coverage(symbol)
                found.append(InstrumentInfo(
                    symbol=symbol,
                    first=coverage.first,
                    last=coverage.last,
                    minutes=coverage.count,
                ))
        except asyncio.CancelledError:
            raise
        except Exception as error:  # окно не должно падать вместе с базой
            log.exception("список инструментов не прочитан")
            self._send(self.backtest_options_ready, BacktestOptions(
                trouble=f"Базу свечей {self._worker.path} прочитать не удалось: "
                        f"{_plain(error)}. Какие инструменты в ней есть — неизвестно.",
            ))
            return
        self._send(
            self.backtest_options_ready, BacktestOptions(instruments=tuple(found))
        )

    def run_backtest(self, request: BacktestRequest) -> None:
        """Прогнать робота по истории на выбранном отрезке.

        **Настройки применяются обычным путём** — тем же `apply_settings`,
        которым их применяет «Применить» в окне настроек. Второго пути
        к движку здесь не заводится, и журнал изменений пишется как всегда:
        владелец счёта, выбравший шаблон, обязан увидеть в решениях, что
        именно поменялось, а не только итог прогона.

        Порядок строк не вкусовой. Проверка идёт **до** записи отрезка:
        негодные настройки шаблона иначе оставили бы за собой закреплённый
        отрезок при прежних настройках — то есть график уехал бы в прошлое
        от неудачной попытки.
        """
        if self._task is not None and not self._task.done():
            self._refuse_busy(
                "run",
                "Прогон на истории не начат",
                "Дождитесь его конца или нажмите «Отменить» — два прогона "
                "разом дали бы в окно два разных ответа на один вопрос.",
            )
            return
        if request.until < request.since:
            self._refuse(
                "Прогон на истории не начат",
                "Конец отрезка раньше его начала. Проверьте даты «от» и «до».",
            )
            return
        try:
            convert.engine_settings(request.settings, self._mode, self._engine_settings)
            convert.timeframe_of(request.settings.timeframe)
            convert.instrument_of(request.settings.instrument)
            convert.strategy_settings(request.settings)
        except (convert.SettingsRefused, ValueError, TypeError) as error:
            self._refuse(
                "Прогон на истории не начат",
                f"Настройки не годятся: {error}. Ни отрезок, ни настройки "
                "не изменились.",
            )
            return
        self._back.span = _Span(request.since, request.until, request.settings_source)
        self._back.pending = request
        self.note(
            "Прогон на истории запрошен",
            f"{convert.instrument_of(request.settings.instrument)}, "
            f"{request.settings.timeframe}: с {_when(request.since)} "
            f"по {_when(request.until)} МСК. Настройки: "
            f"{request.settings_source or 'текущие'}. Живые свечи на "
            "закреплённый отрезок не приходят, пока он не снят.",
        )
        self.apply_settings(request.settings)
        if self._task is None or self._task.done():
            # Прохода не будет — значит не будет и отчёта. Оставить за собой
            # закреплённый отрезок означало бы график, уехавший в прошлое
            # от неудавшейся попытки.
            self._forget_report()
            self._back.span = None

    def cancel_backtest(self) -> None:
        """Снять идущий прогон. Отрезок при этом остаётся закреплённым.

        Отрезок остаётся намеренно: человек его выбрал, и отменил он счёт,
        а не выбор. Снимается отрезок отдельной командой (`show_recent`) —
        так отмена не делает молча второго дела.

        ⚠️ Чего это не закрывает: снятый прогон остаётся в журнале прогонов
        **без времени конца**, то есть читается как прерванный. Закрыть его
        значило бы ещё раз обратиться к хранилищу из отменяемой задачи
        (`RunLog.around`), а её отменяют и при выходе из программы, когда
        хранилище закрывается следом.
        """
        task = self._task
        if task is None or task.done():
            self._refuse("Отмена прогона", "Отменять нечего: прогон не идёт.")
            return
        self._back.pending = None
        self._again = ""
        task.cancel()
        self.note(
            "Прогон отменён",
            "Счёт остановлен по кнопке. На графике осталось то, что было "
            "нарисовано до него; в журнале прогонов эта запись останется "
            "без времени конца, то есть прерванной.",
        )

    # ---------------------------------------------- загрузка истории с биржи

    def request_history_facts(self, symbol: str) -> None:
        """Опись того, что по инструменту уже есть в базе. Ответ — сигналом.

        Возврат немедленный: опись считается по всем минуткам инструмента,
        а на годовом ряде это триста тысяч отметок времени. Ожидание здесь
        означало бы окно, замершее на открытии меню.
        """
        code = symbol.strip() or self._values.instrument.strip()
        self._history.facts = self._begin("facts", self._history_facts(code))

    async def _history_facts(self, symbol: str) -> None:
        """Прочитать опись и отправить её окну.

        Отказ базы — не пустая опись, а названная причина: пустые числа
        читаются как «в базе ничего нет», и это другое утверждение.
        """
        try:
            inventory = await self._worker.inventory(symbol)
        except asyncio.CancelledError:
            raise
        except Exception as error:  # окно не должно падать вместе с базой
            log.exception("опись базы не прочитана")
            self._send(self.history_facts_ready, HistoryFacts(
                symbol=symbol,
                trouble=f"Базу свечей {self._worker.path} прочитать не удалось: "
                        f"{_plain(error)}. Что по инструменту уже загружено — неизвестно.",
            ))
            return
        self._send(self.history_facts_ready, _facts_of(symbol, inventory))

    def load_history(self, request: HistoryLoadRequest) -> None:
        """Скачать историю с биржи и положить в базу. Ход и конец — сигналами.

        Проверки стоят **до** задачи, а не внутри неё: отказ по пустому коду
        или по собранному нами ряду обязан прийти сразу, пока диалог ещё
        на экране, а не через секунду после того, как он закрылся.
        """
        try:
            code = convert.instrument_of(request.symbol)
        except convert.SettingsRefused as error:
            self._refuse_load(request.symbol, str(error))
            return
        if is_synthetic(code):
            self._refuse_load(code, _SYNTHETIC_REFUSAL)
            return
        if self._history.load is not None and not self._history.load.done():
            self._refuse_load(
                code,
                f"Программа занята: {self._busy_with('load')}. Дождитесь её "
                "конца или нажмите «Отменить»: две загрузки разом заняли бы "
                "поток данных и мешали бы друг другу.",
            )
            return
        self._history.chunk = None
        self._history.candles = 0
        self._history.pages = 0
        self._history.load = self._begin(
            "load", self._load_history(dataclasses.replace(request, symbol=code))
        )

    def cancel_history_load(self) -> None:
        """Остановить идущую загрузку. Скачанное остаётся в базе.

        Просьба уходит **мимо очереди потока данных**: сам поток занят
        загрузкой целиком, и просьба, поставленная в ту же очередь, дождалась
        бы конца того, что отменяет. Загрузка прервётся на ближайшей границе
        страницы (`market.iss.IssClient.stop`).

        ⚠️ Останавливаются **все** идущие обращения к бирже, а не только это.
        Второе такое обращение бывает одно — догрузка дыр живого потока
        (`app/backfill.py`); она сама возобновится на следующей свече, и цена
        ошибки здесь — одна лишняя пауза, а не потерянные данные.
        """
        task = self._history.load
        if task is None or task.done():
            self._refuse_load("", "Отменять нечего: загрузка не идёт.")
            return
        self._worker.stop_loading()
        self.note(
            "Загрузка истории отменяется",
            "Остановка запрошена. Скачанное и записанное к этому моменту "
            "остаётся в базе — повторная загрузка продолжит с этого места.",
        )

    async def _load_history(self, request: HistoryLoadRequest) -> None:
        """Снять отметки (если просили заново), загрузить, рассказать итог."""
        symbol = request.symbol
        since, until = _load_span(request, now=datetime.now(MSK))
        self.note("Загрузка истории начата", _load_lead(request, since, until))
        try:
            if request.replace:
                await self._worker.forget_day_marks(symbol, since, until)
            outcome = await self._worker.load_history(
                HistoryRequest(
                    symbol=symbol,
                    market=FUTURES,
                    since=since,
                    until=until,
                    warmup=warmup_bars(max(self._values.average_period, 1)),
                    timeframe=convert.timeframe_of(self._values.timeframe),
                ),
                progress=lambda result: self._load_tick(since, until, result),
            )
        except asyncio.CancelledError:
            raise
        except IssStopped as stopped:
            self._done_loading(HistoryLoadOutcome(
                symbol=symbol, cancelled=True,
                headline="Загрузка остановлена",
                detail=str(stopped),
            ))
            return
        except Exception as error:  # окно не должно падать вместе с биржей
            log.exception("загрузка истории не удалась")
            self._done_loading(HistoryLoadOutcome(
                symbol=symbol,
                headline="Загрузка не удалась",
                trouble=f"{_plain(error)}. Скачанное до обрыва записано и отмечено: "
                        "повторная загрузка продолжит с этого места, а не "
                        "с начала.",
            ))
            return
        self._done_loading(_load_result(outcome))

    def _load_tick(self, since: date, until: date, result: FetchResult) -> None:
        """Ход загрузки — в окно. **Зовётся в потоке данных**, на каждой странице.

        Доля считается по датам, а не по страницам: сколько страниц отдаст
        биржа, заранее не знает никто, а «дошли до 12 августа из 6 сентября» —
        это ответ на вопрос, который человек и задаёт, глядя на полоску.
        """
        state = self._history
        if result is not state.chunk:
            if state.chunk is not None:
                state.candles += state.chunk.loaded
                state.pages += state.chunk.pages
            state.chunk = result
        # Страница с биржи — признак жизни загрузки. ⚠️ Зовётся в потоке
        # данных; почему это безопасно, разобрано в `_alive`.
        self._alive("load")
        candles = state.candles + result.loaded
        seen = result.last_seen
        span = max((until - since).days, 1)
        done = 0 if seen is None else (in_moscow(seen).date() - since).days
        self._send(
            self.history_progress,
            max(0, min(100, round(done * 100 / span))),
            f"Загружено {candles} свечей"
            + (f", по {seen:%d.%m.%Y}" if seen is not None else ""),
        )

    def _done_loading(self, outcome: HistoryLoadOutcome) -> None:
        """Итог загрузки: строка в журнал, сигнал окну, перерисовка графика."""
        self.note(
            "Загрузка истории закончена" if outcome.ok else "Загрузка истории",
            " ".join(part for part in (
                outcome.headline, outcome.detail, outcome.trouble
            ) if part),
            level=DecisionLevel.INFO if outcome.ok else DecisionLevel.WARNING,
        )
        self._send(self.history_finished, outcome)
        if not outcome.cancelled or outcome.ok:
            # Свечи в базе изменились — на графике обязано появиться новое.
            # Отменённая загрузка тоже что-то записала, поэтому перерисовка
            # идёт и после неё.
            self.refresh("Загрузка истории")

    def _refuse_load(self, symbol: str, reason: str) -> None:
        """Отказ до начала загрузки: и в журнал, и в окно, одной фразой."""
        self._refuse("Загрузка истории не начата", reason)
        self._send(self.history_finished, HistoryLoadOutcome(
            symbol=symbol, headline="Загрузка не начата", trouble=reason,
        ))

    def show_recent(self) -> None:
        """Снять закреплённый отрезок и вернуться к показу последних дней."""
        if self._back.span is None:
            return
        self._back.span = None
        self._back.pending = None
