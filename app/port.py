@dataclass(frozen=True, slots=True)
class _Work:
    """Долгая работа порта: как её зовут человеку и когда о ней тревожатся.

    Таблица (`_WORKS`) вместо разбора по полям заведена ради двух свойств,
    и оба проверяются: имя есть **у каждой** работы и срок есть у каждой.
    Работа, забытая в таблице, — это работа, о застревании которой никто
    не скажет и о занятости которой окно ответит «занята чем-то»; забыть
    её мешает `tests/test_app_port.py`, сверяющий таблицу с полями порта.

    `title` — как назвать работу человеку. Не имя поля и не имя корутины:
    в окно уходит «прогон робота по истории», а не `_refresh`.

    `limit` — сколько секунд молчания делают работу застрявшей.

    `advice` — что человек может сделать **именно с этой** работой. У прогона
    и у загрузки есть кнопка «Отменить», у чтения базы её нет, и обещать
    её там нельзя: совет, которого не выполнить, — это то же молчание,
    только вежливое.
    """

    key: str
    title: str
    limit: float
    advice: str = ""


#: Все долгие работы порта. Порядок — от того, что человек запускает сам,
#: к тому, что делается за него.
#:
#: ⚠️ Ключи — латиницей и совпадают с полями порта не по имени, а по таблице
#: `HistoryPort._tasks`. Через ту же таблицу отвечает `_busy`, то есть строка,
#: выпавшая отсюда, ломает и ожидание — это заметно сразу, а не когда-нибудь.
_WORKS: tuple[_Work, ...] = (
    _Work(
        "run", "прогон робота по истории", STUCK_AFTER,
        "Прогон останавливается кнопкой «Отменить» в окошке хода.",
    ),
    _Work(
        "load", "загрузка истории с биржи", STUCK_AFTER_ONLINE,
        "Загрузка останавливается кнопкой «Отменить» в окошке хода; "
        "скачанное к этому времени в базе остаётся.",
    ),
    _Work("facts", "чтение описи базы свечей", STUCK_AFTER),
    _Work("options", "чтение списка инструментов из базы", STUCK_AFTER),
    _Work("draw", "дорисовка свечи по живому потоку", STUCK_AFTER),
    _Work("growing", "перерисовка текущей свечи", STUCK_AFTER),
    _Work("point", "запрос стоимости пункта у биржи", STUCK_AFTER_ONLINE),
    _Work("retire", "закрытие живого хода робота", STUCK_AFTER),
    _Work("halt", "запись остановки робота в базу", STUCK_AFTER),
)

#: Та же таблица ключом наружу. Собирается из `_WORKS`, а не пишется руками:
