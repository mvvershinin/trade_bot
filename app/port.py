"""Порт окна: команды сверху вниз, события снизу вверх. Решений здесь нет.

`ui/ports.py` объявляет границу, `app/` её реализует — так и записано в его
докстринге. Эта реализация ведёт окно **к прогону по истории**, потому что
боевого хода в программе ещё нет: нет потока котировок (Э1-5) и нет ни одного
из трёх предохранителей (потолок объёма, дневной лимит убытка, запас свободных
средств). Врать об этом окну нельзя, поэтому:

* `start()` и `close_position()` отвечают **отказом с объяснением**, а не делают
  вид, что робот пошёл. Кнопка, которая молча ничего не делает, хуже кнопки,
  которая говорит почему;
* состояние всегда `simulation=True`, связь — «не подключено»;
* при старте в журнал решений уходит строка о том, чего в программе нет.

Что здесь **не** происходит
---------------------------
Ни одного торгового решения. Заявки, входы, выходы, уровни, причины — всё
приходит готовым из `engine/` через прогон `backtest.replay`. Порт только
перекладывает результат в объекты `ui.models` (`app/convert.py`) и рассылает
сигналами.

Про потоки и цикл событий
--------------------------
Всё, что здесь есть, живёт в потоке интерфейса, в его цикле событий
([решение 0005](../.docs/decisions/0005-concurrency-model.md)): движок
исполняется там же, где окно, а единственная синхронная часть — база —
изолирована потоком данных `MarketWorker`. Поэтому `signal.emit` отсюда —
обычный вызов в своём потоке, а не пересечение границы.

Длинную работу порт **не выполняет в слоте**: команда окна ставит задачу
(`asyncio.ensure_future`) и возвращается немедленно. Сам прогон отдаёт
управление циклу событий каждые несколько сотен свечей (`backtest.HistorySource`),
поэтому окно перерисовывается и отвечает на мышь всё время прогона.
"""

