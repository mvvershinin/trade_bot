def _facts_of(symbol: str, inventory: Inventory) -> HistoryFacts:
    """Опись базы → числа для окна. Ни одно из них здесь не считается заново.

    Плотные и редкие дни разделяет `market.inventory`, и разделяет по доле
    от самого плотного дня ряда. Второй такой расчёт в окне разошёлся бы
    с первым молча, и владелец счёта увидел бы в диалоге загрузки одно число,
    а в описи из консоли — другое.
    """
    return HistoryFacts(
        symbol=symbol,
        first=inventory.first,
        last=inventory.last,
        trading_days=len(inventory.dense) + len(inventory.sparse),
        dense_days=len(inventory.dense),
        sparse_days=len(inventory.sparse),
        minutes=inventory.minutes,
    )


def _load_span(request: HistoryLoadRequest, *, now: datetime) -> tuple[date, date]:
    """Границы загрузки: что просили, приведённое к календарю. Обе включительно.

    Правая граница — сегодня, и выбора для неё нет намеренно: история грузится
    «по сейчас». Левая — либо названная дата, либо «последние N дней, считая
    сегодняшний»; ровно так же считает командная строка (`app/fetch.py`),
    и два разных счёта одного и того же дали бы разные отрезки на одну просьбу.
    """
    until = in_moscow(now).date()
    if request.since is not None:
        return min(request.since, until), until
    return until - timedelta(days=max(request.days, 1) - 1), until


def _load_lead(request: HistoryLoadRequest, since: date, until: date) -> str:
    """Что именно начали грузить — строкой в журнал решений, до загрузки.

    Строка пишется **до** обращения к бирже: загрузка идёт минутами, и запись
    «начата» отвечает на вопрос «что программа делает прямо сейчас». Без неё
    в журнале был бы разрыв ровно на то время, когда человек ждёт.
    """
    how = (
        "отметки «уже спрашивали» сняты, отрезок запрашивается заново"
        if request.replace else
        "запрашиваются только дни, за которые биржу ещё не спрашивали"
    )
    return (
        f"{request.symbol}: {since:%d.%m.%Y} — {until:%d.%m.%Y} МСК, {how}. "
        "Свечи берутся у биржи; токен брокера для этого не нужен."
    )


def _load_result(outcome: HistoryOutcome) -> HistoryLoadOutcome:
    """Итог загрузки → фразы для окна. Разбор беды делает слой данных.

    ⚠️ Окно не решает, беда это или нет: «опечатка в коде», «период вне
    истории», «мало данных для прогрева» разбирает `HistoryOutcome.problem`,
    и здесь этот ответ только переносится. Второй разбор того же разошёлся бы
    с первым — и разошёлся бы молча, потому что оба выглядели бы верно.
    """
    trouble = outcome.problem()
    report = outcome.report
    got = 0 if report is None else report.fetched
    lines = [
        f"Пришло с биржи {got} свечей."
        if report is None else
        f"Пришло с биржи {got} свечей: {report.inserted} новых, "
        f"{report.updated} обновлено"
        + (f", {report.kept} отвергнуто" if report.kept else "")
        + ".",
    ]
    if outcome.since is not None and outcome.until is not None:
        days = (outcome.until - outcome.since).days + 1
        lines.append(
            f"Отрезок {outcome.since:%d.%m.%Y} — {outcome.until:%d.%m.%Y} "
            f"({days} дн.)"
            + (", подрезан под глубину биржи." if outcome.clamped else ".")
        )
    lines.append(
        f"Баров {outcome.request.timeframe.name}: {outcome.bars} закрытых, "
        f"средней для прогрева нужно {outcome.request.warmup}."
    )
    lines.append(f"Заняло {outcome.seconds:.0f} с.")
    return HistoryLoadOutcome(
        symbol=outcome.symbol,
        ok=trouble is None,
        headline=(
            "История загружена" if trouble is None else "История загружена не вся"
        ),
        detail=" ".join(lines),
        trouble=trouble or "",
    )


def _lasting(seconds: float) -> str:
    """Сколько работа уже идёт, словами: «12 с», «1 мин», «1 мин 30 с».

    Доли секунды отброшены: человеку важен порядок величины, а «12,4 с»
    читается как точность, которой здесь нет — сторож смотрит на часы
    раз в секунду.
    """
    whole = max(int(seconds), 0)
    if whole < _IN_A_MINUTE:
        return f"{whole} с"
    minutes, rest = divmod(whole, _IN_A_MINUTE)
    return f"{minutes} мин" if rest == 0 else f"{minutes} мин {rest} с"


def _stuck_words(work: _Work, silence: float) -> str:
    """Что сказать человеку о застрявшей работе: что стало и что делать.

    Три части, и третья — главная. «Программа не отвечает» без продолжения
    это то же молчание, только вежливое: владелец счёта уже потратил на такое
    полночи (`B-025`) и не знал, ждать ему или перезапускать.

    ⚠️ Совет обещает только то, что в окне есть. Кнопка «Отменить» стоит
    у прогона и у загрузки, а у чтения базы её нет, и предлагать её там
    значило бы отправить человека искать несуществующее.
    """
    return (
        f"Не отвечает: {work.title}. Работа идёт уже {_lasting(silence)} "
        "и за это время ничего о себе не сообщила. Команды, которые её ждут, "
        "программа сейчас отклоняет. "
        + (f"{work.advice} " if work.advice else "")
        + "Если через минуту ничего не изменится — закройте программу "
        "и запустите заново: база свечей, журналы и настройки лежат на диске "
        "и не потеряются."
    )


def _when(moment: datetime) -> str:
    """Момент времени одной подписью, по МСК.

    Пара к `_moment`, но для границы, которую назвал человек, а не для свечи.
    Формат тот же — расхождение формы даты в одной строке журнала читалось бы
    как два разных времени.
    """
    return in_moscow(moment).strftime("%d.%m.%Y %H:%M")


def _moment(candle: MarketCandle) -> str:
    """Свеча одной подписью — по времени **закрытия**.

    В окне всё размечено закрытиями: и ось графика, и журнал решений. Подпись
    периода по началу свечи разошлась бы с ними на один таймфрейм, и сверять
    строку журнала с графиком стало бы нельзя.
    """
    return close_time(candle).strftime("%d.%m.%Y %H:%M")


async def _quiet(task: asyncio.Task[None]) -> None:
    """Дождаться задачи, не подхватив её отказ и не приняв её отмену на себя.

    `await task` пробросил бы и исключение задачи, и `CancelledError` —
    а завершение программы не должно падать из-за прогона, который не доехал.
    """
    await asyncio.wait({task})
