@dataclass(frozen=True, slots=True)
class _HaltWrite:
    """Одна правка остановки в базе: поднять причину либо снять её.

    Значение, а не два метода, потому что правки **выстраиваются в очередь**:
    запись идёт в поток данных, а причины приходят из цикла событий и ждать
    не умеют. Очередь из значений сохраняет порядок; два независимых вызова
    его не гарантируют, а порядок здесь — это то, какая причина окажется
    самой ранней.

    `cause` — причину поднять. `lift` — причину с таким текстом снять.
    Заполнено ровно одно из двух.
    """

    cause: HaltRecord | None = None
    lift: str = ""

    async def apply(self, worker: MarketWorker) -> None:
        """Сделать правку в базе."""
        if self.cause is not None:
            await worker.raise_halt(self.cause)
            return
        await worker.lift_halt(self.lift)

    @property
    def trouble(self) -> str:
        """Чем грозит несделанная правка. Двум случаям — два ответа.

        ⚠️ Последствия **разные**, и одно из них опасное. Незаписанная
        причина исчезнет при перезапуске программы: предохранитель отменится
        тем самым действием, которое человек делает первым (`D-043`). Неснятая
        причина, наоборот, встанет заново — робот останется закрытым, а это
        сторона безопасная. Один общий текст на оба случая соврал бы в одном
        из них.
        """
        if self.cause is not None:
            return (
                "Причина остановки не записана в базу. Робот остановлен "
                "и сейчас, но после перезапуска программы этот запрет "
                "не восстановится: робот пойдёт работать. Не перезапускайте "
                "программу, пока не разберётесь с причиной."
            )
        return (
            "Снятая причина остановки не убрана из базы. Сейчас робот "
            "работает, но после перезапуска программы эта причина встанет "
            "снова, и его придётся возобновлять ещё раз."
        )


@dataclass(slots=True)
class _Halt:
    """Остановка робота: **переживает** пересборку живого хода.

    Отдельное значение, а не поле `_Watch`, и разница здесь денежная,
    а не оформительская. `_Watch` гаснет вместе с ходом: сменилась торговая
    настройка — старый движок закрыт, новый рождён с чистого листа, и всё,
    что он помнил, пропало. Для средней это верно (посчитанная наполовину
    по прежнему периоду, она не соответствует ни старым настройкам,
    ни новым), для остановки — нет.

    Сценарий, ради которого значение вынесено, найден аудитом `/risk`
    05.09.2026: робот встал по дневному лимиту убытка, владелец счёта
    поменял период средней — посмотреть, что было бы, — ход пересобрался,
    и робот пошёл торговать дальше. Решение
    [0014](../.docs/decisions/0014-daily-loss-limit-and-margin-shortfall.md)
    обещает «возобновление только вручную», а тут остановка снималась
    настройкой.

    ⚠️ Дневной лимит на тех же барах воспроизвёлся бы прогревом и остановил
    бы нового движка снова — а вот отказ исполнителя, отказ журнала и обрыв
    связи не воспроизводятся ничем: их причина в прошлом, которого в барах
    нет. Именно они и терялись молча.

    ⚠️ **Причин бывает несколько, и они не отменяют друг друга** (`D-086`,
    аудит `/risk` 06.09.2026). До правки хранилась одна, первая: вторая беда
    на уже остановленном роботе пропадала целиком — ни строки в журнале,
    ни надписи в окне. Цена названа в рублях: робот встал по дневному лимиту
    убытка, следом опрос счёта получил «исход команды неизвестен», владелец
    счёта согласился с убытком и снял остановку — и снял вместе с ней
    **неизвестную позицию у брокера**, о которой ему никто не сказал.

    Поэтому здесь список, а не строка. Причина, попавшая в список, оттуда
    уходит только рукой человека и **по одной**: `HistoryPort.resume`
    снимает самую раннюю и называет ту, что осталась.

    `causes` — причины остановки в порядке появления; пусто — не остановлен.
    Одна и та же причина второй раз не добавляется: опрос счёта повторяет
    заход каждые полминуты, и без этого журнал получил бы сто двадцать
    одинаковых строк в час. Дедупликация точная, по тексту, и держится
    на том, что текст причины — константа (`app/halt.py`).

    `reason` — все причины **одной строкой**: это то, что видит владелец
    счёта в плашке остановки и в журнале прогонов. Пока причина одна,
    строка равна ей самой, символ в символ.

    `said` — причина, уже сказанная в журнал решений. Живой ход проходит
    на каждом закрытом баре, и повтор одной строки хоронит её под собой же.

    `explained` — сказано ли, что пересборка хода отложена до снятия
    остановки. Тоже однажды: настройки крутят подряд.
    """

    causes: list[str] = dataclasses.field(default_factory=list)
    said: str = ""
    explained: bool = False
    #: Что известно о каждой причине сверх её текста: вид, время, откуда
    #: взялась. Ключ — тот же текст причины, что лежит в `causes`.
    #:
    #: ⚠️ Отдельный словарь, а не поле элемента списка. Логика складывания
    #: причин прошла аудит `/risk` 06.09.2026 и в этой правке не менялась
    #: ни на строку: `add`, `drop_first` и `reason` те же самые. Наполняет
    #: и чистит словарь порт — там же, где зовёт `add` и `drop_first`.
    marks: dict[str, _Mark] = dataclasses.field(default_factory=dict)
    #: Правки, ждущие записи в базу, в порядке появления.
    writes: list[_HaltWrite] = dataclasses.field(default_factory=list)
    #: Задача, разбирающая очередь. Одна на порт: две писали бы вперемешку.
    saving: asyncio.Task[None] | None = None

    @property
    def reason(self) -> str:
        """Все причины остановки одной строкой; пусто — робот не остановлен.

        Одна причина отдаётся как есть: плашка окна, снимок состояния
        и журнал прогонов читают это поле, и заворачивать единственную
        причину в перечисление значило бы менять текст, который владелец
        счёта видит каждый день, ради случая, который бывает редко.
        """
        if len(self.causes) == 1:
            return self.causes[0]
        if not self.causes:
            return ""
        listed = " ".join(
            f"({number}) {cause}" for number, cause in enumerate(self.causes, 1)
        )
        return f"Причин остановки {len(self.causes)}. {listed}"

    def add(self, reason: str) -> bool:
        """Добавить причину. `False` — говорить нечего: пусто или уже есть."""
        if not reason or reason in self.causes:
            return False
        self.causes.append(reason)
        return True

    def drop_first(self) -> str:
        """Снять самую раннюю причину и вернуть её. Остальные остаются.

        Самую раннюю, а не последнюю: разбираются с того, с чего всё
        началось. В том самом сценарии владелец счёта снимает дневной лимит
        убытка — и упирается в оставшуюся «исход команды неизвестен» вместо
        того, чтобы снять её заодно, не прочитав.
        """
        return self.causes.pop(0)


