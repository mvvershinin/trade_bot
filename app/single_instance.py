"""Одна копия «Терминала» на одну папку данных.

[Решение 0039](../.docs/decisions/0039-one-copy-per-data-folder.md).

Зачем
-----
Две копии программы работают с одной базой свечей, одними настройками
и одним техническим логом: вторая затирает `userdata/settings.json`, обе
тратят квоту брокера в 5 запросов в секунду, обе пишут в один файл лога.
В бою это дороже на порядок — два робота на одном счёте видят одну позицию,
оба решают и оба подают заявки: удвоенный объём и встречные сделки.

Портативная поставка (решение 0001) случай обостряет: папку копируют мышкой,
и ярлыков на одну и ту же папку легко оказывается два.

Замок держит **система**, а не файл
-----------------------------------
Главная трудность задачи — не занять папку, а понять, что прежний владелец
замка умер. Программу убили, машина выключилась — что осталось на диске?

Поэтому замком здесь **не** является файл. Замком является системный вызов
на **открытом дескрипторе** этого файла: `flock` на POSIX, `msvcrt.locking`
на Windows. Такой замок живёт в ядре и снимается ядром — при обычном выходе,
при `kill -9`, при синем экране, при выдернутом шнуре. После перезагрузки
замков не существует вовсе. Просроченного состояния не бывает, потому что
состояния нет: чистить нечего.

Файл `instance.lock` — **записка**, а не замок. В нём номер процесса, время
запуска и папка, и всё это нужно ровно для одной фразы человеку: «запущена
в 10:03». Отсюда три правила, каждое проверено тестом:

* существование файла **никогда** не читается как «занято». Занято — это
  отказ системного вызова, и ничто другое;
* файл **не удаляется** при выходе. Удаление означало бы гонку: пока мы
  удаляем, другая копия уже открыла тот же файл;
* испорченная или пустая записка отнимает у фразы одну строку и ничего больше.

Чем это лучше очевидного PID-файла
----------------------------------
Очевидный путь — записать номер процесса и проверять, жив ли он. Он ломается
на перезагрузке: номера переиспользуются, под номером 4242 живёт чужая
программа, проверка говорит «жив», и «Терминал» не запускается **никогда**,
пока человек не найдёт файл, о котором не знает. `QLockFile` из Qt делает
ровно это же плюс срок давности в 30 секунд — то есть живая программа,
замершая под отладчиком, считается мёртвой, и копий становится две.
`QSharedMemory` на Unix переживает падение процесса и даёт первый дефект
в чистом виде.

Что закрывает собой, а что нет
------------------------------
Замок берётся **по папке данных** — той, куда смотрит `--db`, а не по
номеру счёта: счёт до подключения к брокеру неизвестен, а токен при старте
не трогается намеренно. Значит две **копии папки** с одним токеном этот
замок не поймает; это долг к Э1-9, названный в решении 0039 §«Чего это
решение не закрывает».
"""

from __future__ import annotations

import errno
import logging
import os
import pathlib
import sys
from dataclasses import dataclass
from datetime import datetime
from enum import Enum
from typing import Final

__all__ = ["LOCK_FILE_NAME", "OneCopy", "Purpose", "Verdict"]

log = logging.getLogger(__name__)

#: Имя латиницей — правило 6 `CLAUDE.md`: кириллица в имени ломает пути
#: в консоли и в сборке Nuitka под Windows.
LOCK_FILE_NAME: Final[str] = "instance.lock"

#: Права как у соседей по `userdata/` — токена, настроек и лога. Файл
#: создаётся сразу с ними через `os.open`, а не создаётся и потом правится:
#: между созданием и `chmod` есть окно, в котором файл читает кто угодно.
FILE_MODE: Final[int] = 0o600

#: Смещение запираемого байта на Windows. Там замок **обязательный**:
#: запертый участок нельзя прочитать, а записку читать надо. Поэтому байт
#: берётся за пределами любого мыслимого содержимого — приём и адрес взяты
#: у SQLite (`PENDING_BYTE`), где он стоит ровно по той же причине.
LOCK_OFFSET: Final[int] = 0x40000000

#: Сколько байт записки читать. Больше не нужно: в ней три строки.
_NOTE_BYTES: Final[int] = 4096

#: Потолок длины значения из записки, попадающего в текст человеку.
#: Испорченный файл не должен вываливать в окно килобайт мусора.
_VALUE_LIMIT: Final[int] = 40

#: На Windows `os.open` без этого флага переводит переводы строк. Записку
#: пишем и читаем байтами, поэтому флаг нужен; на POSIX его нет и он равен нулю.
_BINARY: Final[int] = getattr(os, "O_BINARY", 0)


class Purpose(Enum):
    """Зачем берётся замок. От этого зависит только совет человеку."""

    #: Обычный запуск с окном, включая `--shot` и `--stream`.
    WINDOW = "window"
    #: Команда без окна, которая пишет в базу, — сегодня это `--fetch`.
    COMMAND = "command"


@dataclass(frozen=True)
class Verdict:
    """Что делать вызывающему.

    `taken` — единственное, на что смотрит `app/main.py`. Оговорка
    в `trouble` бывает при обоих исходах, и смысл у неё разный:

    * `taken=False` — замок у другой копии, `trouble` объясняет это человеку;
    * `taken=True` и `trouble` не пуст — папка замок держать не умеет.
      Программа идёт дальше, но говорит об этом громко;
    * `taken=True` и `trouble` пуст — обычный запуск.
    """

    taken: bool
    trouble: str = ""


class _Grab(Enum):
    """Исход системного вызова. Три состояния, и все три разные."""

    TAKEN = "taken"
    BUSY = "busy"
    UNSUPPORTED = "unsupported"


def _grab(fd: int) -> tuple[_Grab, str]:
    """Взять системный замок на дескриторе. Второе значение — текст для лога.

    ⚠️ Здесь и только здесь расходятся Windows и POSIX, и расходятся они
    открытым текстом, а не за обёрткой.

    **POSIX.** `flock` вешает замок на открытое описание файла. Занято —
    `EWOULDBLOCK` (он же `EAGAIN`). Всё остальное — «эта файловая система
    так не умеет»: такое бывает на части сетевых монтирований.

    **Windows.** `msvcrt.locking` запирает участок от текущей позиции в файле,
    поэтому позиция сначала переставляется на `LOCK_OFFSET`, а потом
    возвращается в начало — записку писать и читать с нуля. Занято —
    `EACCES` (`_locking`: «Locking violation»), при повторных попытках
    системы — `EDEADLOCK`.

    ⚠️ Ветка Windows на машине разработчика **не исполняется ни разу**
    и типами проверяется только запуском `mypy --platform win32`.
    """
    if sys.platform == "win32":
        import msvcrt  # noqa: PLC0415 — модуль есть только на Windows,
        # наверху он уронил бы импорт всего слоя на Linux

        try:
            os.lseek(fd, LOCK_OFFSET, os.SEEK_SET)
            msvcrt.locking(fd, msvcrt.LK_NBLCK, 1)
        except OSError as error:
            busy = {errno.EACCES, errno.EDEADLOCK, errno.EDEADLK}
            return (_Grab.BUSY, "") if error.errno in busy else (_Grab.UNSUPPORTED, str(error))
        finally:
            os.lseek(fd, 0, os.SEEK_SET)
        return _Grab.TAKEN, ""

    import fcntl  # noqa: PLC0415 — тот же приём: модуля нет на Windows

    try:
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError as error:
        busy = {errno.EWOULDBLOCK, errno.EAGAIN, errno.EACCES}
        return (_Grab.BUSY, "") if error.errno in busy else (_Grab.UNSUPPORTED, str(error))
    return _Grab.TAKEN, ""


def _drop(fd: int) -> None:
    """Снять замок. Закрытие дескриптора снимает его и само.

    Явное снятие — ради Windows: документация `_locking` требует снимать
    участок тем же смещением и той же длиной, которыми он заперт. Отказ
    здесь глушится намеренно: дескриптор всё равно закрывается следующей
    строкой, а исключение при выходе из программы хуже незакрытого замка.
    """
    try:
        if sys.platform == "win32":
            import msvcrt  # noqa: PLC0415 — см. `_grab`

            os.lseek(fd, LOCK_OFFSET, os.SEEK_SET)
            msvcrt.locking(fd, msvcrt.LK_UNLCK, 1)
            os.lseek(fd, 0, os.SEEK_SET)
        else:
            import fcntl  # noqa: PLC0415 — см. `_grab`

            fcntl.flock(fd, fcntl.LOCK_UN)
    except OSError as error:
        log.debug("замок «одна копия» снят закрытием дескриптора: %s", error)


class OneCopy:
    """Замок «одна копия на папку данных».

    ⚠️ Объект обязан жить, пока живёт программа. Дескриптор здесь — голое
    число из `os.open`, и сборщик мусора его не закрывает; но `release()`
    закрывает, и вызвать его раньше времени значит снять замок с работающей
    программы. В `app/main.py` он стоит в `finally` самого верхнего уровня.
    """

    def __init__(self, folder: pathlib.Path) -> None:
        self.folder = folder
        self.path = folder / LOCK_FILE_NAME
        self._fd: int | None = None

    def take(self, purpose: Purpose = Purpose.WINDOW) -> Verdict:
        """Занять папку под эту копию."""
        if self._fd is not None:  # уже наш; повторный вызов — не ошибка
            return Verdict(taken=True)
        try:
            self.folder.mkdir(parents=True, exist_ok=True)
            fd = os.open(self.path, os.O_RDWR | os.O_CREAT | _BINARY, FILE_MODE)
        except OSError as error:
            # Писать в папку нельзя вовсе. Это скажет `ensure_userdata_dir`
            # фразой и остановит запуск; здесь — не мешать ему это сделать.
            log.warning("файл замка %s не открылся: %s", self.path, error)
            return Verdict(taken=True, trouble=_cannot_lock(self.folder))
        state, detail = _grab(fd)
        if state is _Grab.TAKEN:
            self._fd = fd
            _write_note(fd, self.folder)
            return Verdict(taken=True)
        note = _read_note(fd) if state is _Grab.BUSY else {}
        os.close(fd)
        if state is _Grab.BUSY:
            log.info("вторая копия отказана: папка %s занята", self.folder)
            return Verdict(taken=False, trouble=_busy_text(purpose, self.folder, note))
        log.warning("папка %s не умеет держать замок «одна копия»: %s", self.folder, detail)
        return Verdict(taken=True, trouble=_cannot_lock(self.folder))

    def release(self) -> None:
        """Освободить папку. Файл при этом **не удаляется** — см. шапку модуля."""
        if self._fd is None:
            return
        fd, self._fd = self._fd, None
        _drop(fd)
        os.close(fd)

    def __enter__(self) -> Verdict:
        return self.take()

    def __exit__(self, *_: object) -> None:
        self.release()


#: Формат записки. Первые строки — человеку, который нашёл файл и не понимает,
#: что это; дальше пары `ключ=значение` латиницей (правило 6 `CLAUDE.md`).
_NOTE = (
    "# Отметка о том, что «Терминал» сейчас запущен.\n"
    "# Замок держит не этот файл, а операционная система. Пока программа\n"
    "# закрыта, файл ничего не значит и его можно удалить.\n"
    "pid={pid}\n"
    "started={started}\n"
    "folder={folder}\n"
)


def _write_note(fd: int, folder: pathlib.Path) -> None:
    """Оставить записку в занятом файле. Отказ записи замка не отменяет.

    Замок к этому моменту уже наш, и записка — только текст для фразы.
    Уронить запуск из-за неё было бы обменом важного на неважное.
    """
    text = _NOTE.format(
        pid=os.getpid(),
        started=datetime.now().strftime("%d.%m.%Y %H:%M:%S"),
        folder=folder,
    )
    try:
        os.ftruncate(fd, 0)
        os.lseek(fd, 0, os.SEEK_SET)
        os.write(fd, text.encode("utf-8"))
    except OSError as error:
        log.warning("записка в файле замка не обновлена: %s", error)


def _read_note(fd: int) -> dict[str, str]:
    """Что известно про держателя замка: время запуска и номер процесса.

    Всё здесь — «по возможности». Файл пустой, обрезанный, от прошлой версии,
    испорчен диском — фраза человеку обязана состояться в любом случае,
    просто без одной строки.

    Читаются оба поля разом, одним проходом по строкам: время говорит,
    та ли это копия, про которую человек думает, а номер процесса — чем
    её снять, когда она зависла и окна у неё уже нет. Ровно этого не хватило
    владельцу счёта 06.09.2026 (`B-028`).
    """
    try:
        os.lseek(fd, 0, os.SEEK_SET)
        raw = os.read(fd, _NOTE_BYTES).decode("utf-8", errors="replace")
    except OSError as error:
        log.debug("записку из файла замка прочитать не удалось: %s", error)
        return {}
    wanted = ("started", "pid")
    found: dict[str, str] = {}
    for line in raw.splitlines():
        key, _, value = line.partition("=")
        name = key.strip()
        if name not in wanted or name in found:
            continue
        value = value.strip()[:_VALUE_LIMIT]
        # Управляющие символы из испорченного файла в окно не пускаем.
        if value.isprintable():
            found[name] = value
    return found


def _busy_text(purpose: Purpose, folder: pathlib.Path, note: dict[str, str]) -> str:
    """Отказ второй копии — фразой, которую владелец счёта поймёт без нас.

    Ни кода, ни английского, ни номера ошибки: человек за этим экраном
    не программист, и «Errno 11» ему не говорит ничего. Сказано четыре
    вещи — что случилось, **кто держит папку**, что делать прямо сейчас
    и почему так сделано.

    ⚠️ Номер процесса назван намеренно, и это `B-028`. Прежняя редакция
    советовала переключиться на открытое окно — а окна не было: держателем
    оказалась копия, зависшая тремя часами раньше. Совет вёл в никуда,
    и снять зависшую копию человеку было нечем.
    """
    if purpose is Purpose.WINDOW:
        head = (
            "«Терминал» уже запущен на этом компьютере.\n"
            "Окно открытой программы — в панели задач, переключитесь на него."
        )
    else:
        head = (
            "«Терминал» уже запущен, поэтому команда не выполняется.\n"
            "Закройте окно «Терминала» и повторите её."
        )
    where = f"Папка данных: {folder}"
    if note.get("started"):
        where = f"Запущена: {note['started']}. {where}"
    if note.get("pid"):
        where = (
            f"{where}\nНомер процесса той копии: {note['pid']}. Если её окна "
            "нигде нет — она зависла, и снять её можно по этому номеру: "
            "в диспетчере задач Windows или командой «kill» в консоли Linux."
        )
    return (
        f"{head}\n\n"
        "Вторая копия не запускается намеренно: обе работали бы с одной базой "
        "свечей и одними настройками, а в бою подали бы две заявки на один "
        f"сигнал.\n\n{where}"
    )


def _cannot_lock(folder: pathlib.Path) -> str:
    """Папка замок держать не умеет. Программа идёт дальше — но не молча.

    Причина отказа системы сюда не попадает: она по-английски и человеку
    не нужна. Её пишет в технический лог тот, кто её получил.
    """
    return (
        f"Папка данных {folder} не позволяет поставить замок «одна копия» — "
        "так бывает на сетевых дисках. Программа запускается, но проследите "
        "сами, чтобы «Терминал» не был открыт дважды: две копии работают "
        "с одной базой свечей и одними настройками и затирают работу друг друга."
    )
