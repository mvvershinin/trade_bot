"""Настройки переживают закрытие программы. Файл в `userdata/`, права как у токена.

Зачем
-----
До 05.09.2026 настроек не сохранял никто: `app/main.py` создавал `Settings()`
при каждом запуске, то есть чистые умолчания. Владелец счёта подобрал ночью
набор, на котором он в плюсе, — и выяснилось, что закрой он окно, всё пропало
бы; цифры снимали со снимков экрана вручную
(`.docs/quality/owner-settings-2026-09-05.md`).

Где лежит и почему именно там
-----------------------------
`userdata/settings.json`, рядом с базой свечей и файлом токена
([решение 0003](../.docs/decisions/0003-runtime-data-location.md)). Папка
переносится целиком: поставка портативная, и «резервная копия = копия папки»
обязана включать настройки. Права файла — `0600`, не шире, чем у соседа
с токеном: в настройках нет секретов, но файл создаётся в той же папке теми же
руками, и одно правило на папку проще держать, чем два.

Три вопроса, на которые формат обязан отвечать заранее
------------------------------------------------------
**1. Файл испорчен.** Потерять настройки молча — худшее из возможного:
владелец счёта увидит умолчания и не поймёт, что его набор стёрт. Поэтому
разбор двухуровневый.

* JSON не разбирается вовсе (обрыв записи, чужой файл, битый диск) — файл
  **не удаляется и не переписывается**, а переименовывается в
  `settings.broken-ГГГГММДД-ЧЧММСС.json`, и об этом говорится фразой
  с полным путём. Испорченный файл — единственный след настроек, которые
  человек подбирал ночью; выбросить его нельзя даже ради чистоты.
* JSON разобрался, а одно поле негодное («период средней»: «пятнадцать») —
  теряется **это поле**, а не весь набор. Оно берётся умолчанием, названо
  в отдельной строке журнала, остальные поля остаются как были.

**2. Настройки нет в файле — она появилась позже.** Берётся умолчание,
и это нормальный путь обновления, а не поломка. Строка в журнале всё равно
пишется: «настройка X впервые появилась в этой сборке, взято умолчание Y» —
иначе новое поле молча начинает влиять на деньги.

**3. Настройки нет в программе — она была в файле от более новой сборки.**
Ключ **сохраняется** и пишется обратно при следующей записи. Причина
практическая: откатились на сборку постарше, поработали, вернулись обратно —
и настройки новой сборки на месте. Выбросить незнакомый ключ значило бы
уничтожить чужие данные за то, что мы их не понимаем.
⚠️ Знание о чужих ключах живёт от `load()` до `save()`. Запись без чтения
(так делать незачем, и сборка так не делает) чужих ключей не сохранит.

Почему поля не перечислены руками
---------------------------------
Список полей `Settings` здесь не повторяется ни разу: укладку держит
**таблица по типу поля** в `ui/settings_codec.py`, а список полей берётся
у самого класса. Отсюда следствие, ради которого это и сделано: поле,
заведённое завтра, сохраняется само. Забыть его негде.

⚠️ Таблица живёт в `ui/`, а не здесь, с 05.09.2026: тем же файлом сохраняется
библиотека шаблонов настроек (`ui/templates.py`), которую открывает окно,
а `ui/` не имеет права импортировать `app/` (ARCHITECTURE.md §2). Вторая
таблица укладки разошлась бы с первой молча — настройка, заведённая завтра,
сохранялась бы в настройках и терялась в шаблонах.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Final

from ui.models import Settings
from ui.settings_codec import encode_fields, field_codecs, read_fields
from ui.userdata_file import write_atomically

__all__ = [
    "FORMAT_VERSION",
    "SETTINGS_FILE_NAME",
    "Loaded",
    "SettingsStore",
]

#: Имя файла настроек внутри `userdata/`.
SETTINGS_FILE_NAME: Final[str] = "settings.json"

#: Версия формата. Читатель обязан уметь сказать «файл новее меня», а не молча
#: разобрать половину полей.
FORMAT_VERSION: Final[int] = 1

_KEY_VERSION: Final[str] = "format_version"
_KEY_VALUES: Final[str] = "settings"


@dataclass(frozen=True, slots=True)
class Loaded:
    """Что прочиталось и что при этом стоит сказать вслух.

    Два списка фраз, а не один, потому что они попадают в журнал решений
    с разной важностью, и смешать их значило бы либо кричать на первом
    запуске, либо промолчать о потерянных настройках.

    `notes` — обычный ход дела: файла ещё нет, поле появилось в новой сборке,
    в файле лежит чужой ключ.

    `troubles` — **настройки потеряны или могли быть потеряны**: файл не
    прочёлся и отложен в сторону, поле отвергнуто, формат новее нашего.
    Каждая такая строка обязана дойти до владельца счёта предупреждением:
    молча вернуть умолчания — худшее из возможного, он не поймёт, что
    подобранный ночью набор стёрт.
    """

    values: Settings
    notes: tuple[str, ...] = ()
    troubles: tuple[str, ...] = ()

# ---------------------------------------------------------------------------
# Сам файл
# ---------------------------------------------------------------------------

class SettingsStore:
    """Чтение и запись `userdata/settings.json`.

    :param directory: папка `userdata/`. Файл в ней создаётся при первой записи;
        чтение отсутствующего файла — не отказ, а первый запуск.
    """

    def __init__(self, directory: Path) -> None:
        self._directory = directory
        self._path = directory / SETTINGS_FILE_NAME
        #: Ключи, которых программа не знает: из файла более новой сборки.
        #: Держатся до записи и уходят в файл обратно — см. шапку модуля.
        self._unknown: dict[str, object] = {}

    @property
    def path(self) -> Path:
        """Полный путь к файлу настроек. Показывается в журнале как есть."""
        return self._path

    # ------------------------------------------------------------- чтение

    def load(self, base: Settings | None = None) -> Loaded:
        """Прочитать настройки. Пропавшее и негодное берётся у `base`.

        :param base: с чего начинать. `None` — умолчания продукта. Довод есть,
            чтобы ключ командной строки (`--symbol`) перебивал файл, а не
            наоборот, и чтобы это было видно на месте вызова.
        """
        start = base if base is not None else Settings()
        if not self._path.exists():
            return Loaded(start, (
                f"Файл настроек {self._path} ещё не создан — это первый запуск "
                "или папку перенесли без него. Взяты значения по умолчанию; "
                "они сохранятся, как только вы нажмёте «Применить».",
            ))
        try:
            body = self._path.read_text(encoding="utf-8")
            payload = json.loads(body)
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
            return Loaded(start, troubles=self._quarantine(error))
        if not isinstance(payload, dict):
            return Loaded(start, troubles=self._quarantine(
                ValueError("в файле не набор настроек, а что-то другое")
            ))
        return self._decode(payload, start)

    def _decode(self, payload: dict[str, object], start: Settings) -> Loaded:
        """Разобрать разобравшийся JSON: поле за полем, с оговорками."""
        troubles = list(_version_notes(payload.get(_KEY_VERSION), self._path))
        raw = payload.get(_KEY_VALUES)
        if not isinstance(raw, dict):
            return Loaded(start, troubles=self._quarantine(
                ValueError(f"в файле нет раздела «{_KEY_VALUES}» с настройками")
            ))
        notes: list[str] = []
        table = field_codecs()
        self._unknown = {key: item for key, item in raw.items() if key not in table}
        if self._unknown:
            notes.append(
                "Настройки, которых эта сборка не знает, оставлены в файле "
                "нетронутыми: " + ", ".join(sorted(self._unknown)) + ". Скорее "
                "всего файл сделан более новой сборкой программы."
            )
        changes, refused, missing = read_fields(raw, table, start)
        troubles.extend(refused)
        if missing:
            notes.append(
                "Настройки, которых в файле нет, взяты по умолчанию: "
                + ", ".join(missing)
                + ". Так бывает после обновления программы."
            )
        return Loaded(start.replace(**changes), tuple(notes), tuple(troubles))

    def _quarantine(self, error: Exception) -> tuple[str, ...]:
        """Отложить испорченный файл в сторону и сказать, куда именно.

        Файл не удаляется и не переписывается: это единственный след настроек,
        которые подбирали руками. Не удалось отложить — говорим и об этом,
        иначе следующая запись затрёт его молча.
        """
        why = _why(error)
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        spare = self._path.with_name(f"{self._path.stem}.broken-{stamp}.json")
        try:
            self._path.rename(spare)
        except OSError as failure:
            return (
                f"Файл настроек {self._path} не читается: {why}. Отложить его "
                f"в сторону тоже не удалось ({failure.strerror or failure}). "
                "Взяты значения по умолчанию. ⚠️ Первое же «Применить» "
                "перезапишет этот файл — если настройки из него нужны, "
                "скопируйте его сейчас.",
            )
        return (
            f"Файл настроек не читается: {why}. Он сохранён как {spare} "
            "и не тронут — открыть его можно любым текстовым редактором. "
            "Взяты значения по умолчанию.",
        )

    # ------------------------------------------------------------- запись

    def save(self, values: Settings) -> str:
        """Записать настройки. Пустая строка — записано, иначе фраза об отказе.

        Отказ **возвращается, а не бросается**: запись зовётся из слота Qt по
        сигналу «настройки приняты», и исключение оттуда означало бы трассировку
        в консоль и молчащее окно. Вызывающий обязан положить фразу в журнал.

        Запись атомарная (`ui.userdata_file.write_atomically`): временный файл
        рядом, потом подмена на месте. Обрыв питания в середине оставляет
        прежний файл целым — потерять настройки из-за выключенного света
        нельзя.
        """
        payload = {
            _KEY_VERSION: FORMAT_VERSION,
            _KEY_VALUES: {**self._unknown, **encode_fields(values)},
        }
        body = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        try:
            write_atomically(self._path, body)
        except OSError as error:
            return (
                f"Настройки не сохранены в {self._path}: {error}. В этом сеансе "
                "они действуют, но при следующем запуске программа возьмёт "
                "прежние. Проверьте, что папка существует и в неё можно писать."
            )
        return ""

def _why(error: Exception) -> str:
    """Почему файл не прочёлся — по-русски и без кода библиотеки.

    `json` объясняется по-английски («Expecting property name enclosed in
    double quotes»), а это текст для владельца счёта, не для разработчика.
    Место поломки при этом называется: по номеру строки файл чинится вручную,
    а без него остаётся только удалить.
    """
    if isinstance(error, json.JSONDecodeError):
        return (
            f"файл испорчен — разбор оборвался на строке {error.lineno}, "
            f"знак {error.colno}"
        )
    if isinstance(error, UnicodeDecodeError):
        return "файл записан не в той кодировке: ожидался обычный текст UTF-8"
    if isinstance(error, OSError):
        return f"файл не открылся ({error.strerror or error})"
    return str(error)


def _version_notes(version: object, path: Path) -> tuple[str, ...]:
    """Что сказать про версию формата. Молчание — только на своей версии."""
    if version == FORMAT_VERSION:
        return ()
    if isinstance(version, int) and not isinstance(version, bool) and version > FORMAT_VERSION:
        return (
            f"Файл настроек {path} сделан более новой сборкой программы "
            f"(формат {version}, эта сборка знает {FORMAT_VERSION}). Прочитано "
            "то, что понятно; остальное оставлено в файле нетронутым.",
        )
    return (
        f"У файла настроек {path} не назван формат (ожидался {FORMAT_VERSION}). "
        "Прочитан как есть — проверьте значения в окне настроек.",
    )
