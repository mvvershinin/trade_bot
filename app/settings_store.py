class SettingsStore:
    """Чтение и запись `userdata/settings.json`.

    :param directory: папка `userdata/`. Файл в ней создаётся при первой записи;
        чтение отсутствующего файла — не отказ, а первый запуск.
    """

    def __init__(self, directory: Path) -> None:
        self._directory = directory
        self._path = directory / SETTINGS_FILE_NAME
        #: Ключи, которых программа не знает: из файла более новой сборки.
        #: Держатся до записи и уходят в файл обратно — см. шапку модуля.
        self._unknown: dict[str, object] = {}

    @property
    def path(self) -> Path:
        """Полный путь к файлу настроек. Показывается в журнале как есть."""
        return self._path

    # ------------------------------------------------------------- чтение

    def load(self, base: Settings | None = None) -> Loaded:
        """Прочитать настройки. Пропавшее и негодное берётся у `base`.

        :param base: с чего начинать. `None` — умолчания продукта. Довод есть,
            чтобы ключ командной строки (`--symbol`) перебивал файл, а не
            наоборот, и чтобы это было видно на месте вызова.
        """
        start = base if base is not None else Settings()
        if not self._path.exists():
            return Loaded(start, (
                f"Файл настроек {self._path} ещё не создан — это первый запуск "
                "или папку перенесли без него. Взяты значения по умолчанию; "
                "они сохранятся, как только вы нажмёте «Применить».",
            ))
        try:
            body = self._path.read_text(encoding="utf-8")
            payload = json.loads(body)
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
            return Loaded(start, troubles=self._quarantine(error))
        if not isinstance(payload, dict):
            return Loaded(start, troubles=self._quarantine(
                ValueError("в файле не набор настроек, а что-то другое")
            ))
        return self._decode(payload, start)

    def _decode(self, payload: dict[str, object], start: Settings) -> Loaded:
        """Разобрать разобравшийся JSON: поле за полем, с оговорками."""
        troubles = list(_version_notes(payload.get(_KEY_VERSION), self._path))
        raw = payload.get(_KEY_VALUES)
        if not isinstance(raw, dict):
            return Loaded(start, troubles=self._quarantine(
                ValueError(f"в файле нет раздела «{_KEY_VALUES}» с настройками")
            ))
        notes: list[str] = []
        table = field_codecs()
        # Поля убранного алгоритма (решение 0063) в «незнакомые» не идут
        # и обратно в файл не пишутся: им больше некому принадлежать.
        self._unknown = {
            key: item for key, item in raw.items()
            if key not in table and key not in RETIRED_KEYS
        }
        # Выключенные на этапе предохранители объясняются **своими словами**,
        # а не общим «файл новее»: ПРЕДОХРАНИТЕЛЬ ВЫКЛЮЧЕН НА ЭТАПЕ (D-113).
        # В файле они при этом остаются — `self._unknown` их держит.
        guards_notes, guards_troubles = _guards_off_in_the_file(raw, table)
        notes.extend(guards_notes)
        troubles.extend(guards_troubles)
        strangers = sorted(
            set(self._unknown) - {name for row in _GUARDS_OFF for name in row[:2]}
        )
        if strangers:
            notes.append(
                "Настройки, которых эта сборка не знает, оставлены в файле "
                "нетронутыми: " + ", ".join(strangers) + ". Скорее "
                "всего файл сделан более новой сборкой программы."
            )
        changes, refused, missing = read_fields(raw, table, start)
        troubles.extend(refused)
        if missing:
            notes.append(
                "Настройки, которых в файле нет, взяты по умолчанию: "
                + ", ".join(f"«{caption_of(name)}»" for name in missing)
                + ". Так бывает после обновления программы. Что выбрано, видно "
                "в окне «Настройки»; в файл они запишутся, когда вы сами "
                "примените настройки."
            )
        values = start.replace(**changes)
        values, unknown_algorithm = _known_algorithm(values)
        troubles.extend(unknown_algorithm)
        # Порядок значим: требования принадлежат алгоритму, а какой он —
        # решает строка выше.
        values, unmet_demands = _demanded_settings(values, frozenset(missing))
        troubles.extend(unmet_demands.values())
        # Порядок с двумя проверками выше безразличен: ни одна из них не трогает
        # полей фиксации прибыли. Стоит последней, потому что читается как
        # продолжение — «а теперь то же самое про способ фиксации».
        values, both_ways = _one_way_to_take_profit(values)
        troubles.extend(both_ways)
        return Loaded(
            values, tuple(notes), tuple(troubles), tuple(unmet_demands.items())
        )

    def _quarantine(self, error: Exception) -> tuple[str, ...]:
        """Отложить испорченный файл в сторону и сказать, куда именно.

        Файл не удаляется и не переписывается: это единственный след настроек,
        которые подбирали руками. Не удалось отложить — говорим и об этом,
        иначе следующая запись затрёт его молча.
        """
        why = _why(error)
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        spare = self._path.with_name(f"{self._path.stem}.broken-{stamp}.json")
        try:
            self._path.rename(spare)
        except OSError as failure:
            return (
                f"Файл настроек {self._path} не читается: {why}. Отложить его "
                f"в сторону тоже не удалось ({failure.strerror or failure}). "
                "Взяты значения по умолчанию. ⚠️ Первое же «Применить» "
                "перезапишет этот файл — если настройки из него нужны, "
                "скопируйте его сейчас.",
            )
        return (
            f"Файл настроек не читается: {why}. Он сохранён как {spare} "
            "и не тронут — открыть его можно любым текстовым редактором. "
            "Взяты значения по умолчанию.",
        )

    # ------------------------------------------------------------- запись

    def save(self, values: Settings) -> str:
        """Записать настройки. Пустая строка — записано, иначе фраза об отказе.

        Отказ **возвращается, а не бросается**: запись зовётся из слота Qt по
        сигналу «настройки приняты», и исключение оттуда означало бы трассировку
        в консоль и молчащее окно. Вызывающий обязан положить фразу в журнал.

        Запись атомарная (`ui.userdata_file.write_atomically`): временный файл
        рядом, потом подмена на месте. Обрыв питания в середине оставляет
        прежний файл целым — потерять настройки из-за выключенного света
        нельзя.
        """
        payload = {
            _KEY_VERSION: FORMAT_VERSION,
            _KEY_VALUES: {**self._unknown, **encode_fields(values)},
        }
        body = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        try:
            write_atomically(self._path, body)
        except OSError as error:
            return (
                f"Настройки не сохранены в {self._path}: {error}. В этом сеансе "
                "они действуют, но при следующем запуске программа возьмёт "
                "прежние. Проверьте, что папка существует и в неё можно писать."
            )
        return ""

    def patch(self, values: Settings, names: tuple[str, ...]) -> str:
        """Переписать в файле только поля `names`, остальное — байт в байт как было.

        Для единственной записи без «ОК» — перехода с истёкшего контракта
        (`HistoryPort._switch_to_current`). `save` записал бы всё прочитанное:
        с подменами при чтении и с ключами, которых в файле не было, — а это
        и есть правка файла владельца без его ведома (`B-050`). Здесь
        меняются только названные ключи, отсутствующие и незнакомые остаются
        как есть.

        Файла нет или он не читается — не пишется ничего, и это фраза:
        первый «ОК» человека создаст файл сам, а до него смена живёт только
        в памяти — молчать об этом при строке «записан в файл» нельзя.
        """
        if not self._path.exists():
            return (
                f"Файла настроек {self._path} ещё нет: смена действует до "
                "закрытия программы, файл появится с первым «ОК» в настройках."
            )
        # Не читается — тоже фраза, а не «успех» (аудит /risk 06.10.2026):
        # прежде здесь стояло `return ""`, и переход с истёкшего контракта
        # сообщал «записан в файл», хотя не записано ничего. Файл при этом
        # не перезаписывается умолчаниями: он чужой, его чинит человек.
        kept = "смена действует до закрытия программы, файл оставлен как есть."
        try:
            payload = json.loads(self._path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
            return f"Файл настроек {self._path} не читается ({_why(error)}): {kept}"
        stored = payload.get(_KEY_VALUES) if isinstance(payload, dict) else None
        if not isinstance(stored, dict):
            return f"В файле настроек {self._path} нет раздела настроек: {kept}"
        encoded = encode_fields(values)
        stored.update({name: encoded[name] for name in names})
        body = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        try:
            write_atomically(self._path, body)
        except OSError as error:
            return (
                f"Настройки не сохранены в {self._path}: {error}. В этом сеансе "
                "они действуют, но при следующем запуске программа возьмёт прежние."
            )
        return ""

    @staticmethod
    def patched(values: Settings, names: tuple[str, ...]) -> str:
        """Что записала `patch`, словами для журнала: подписи окна и значения."""
        return (
            "В файле настроек изменено только: "
            + ", ".join(f"«{caption_of(name)}» — {getattr(values, name)}" for name in names)
            + ". Остальное в файле не тронуто."
        )


def _why(error: Exception) -> str:
    """Почему файл не прочёлся — по-русски и без кода библиотеки.

    `json` объясняется по-английски («Expecting property name enclosed in
    double quotes»), а это текст для владельца счёта, не для разработчика.
    Место поломки при этом называется: по номеру строки файл чинится вручную,
    а без него остаётся только удалить.
    """
    if isinstance(error, json.JSONDecodeError):
        return (
            f"файл испорчен — разбор оборвался на строке {error.lineno}, "
            f"знак {error.colno}"
        )
    if isinstance(error, UnicodeDecodeError):
        return "файл записан не в той кодировке: ожидался обычный текст UTF-8"
    if isinstance(error, OSError):
        return f"файл не открылся ({error.strerror or error})"
    return str(error)


def _version_notes(version: object, path: Path) -> tuple[str, ...]:
    """Что сказать про версию формата. Молчание — только на своей версии."""
    if version == FORMAT_VERSION:
        return ()
    if isinstance(version, int) and not isinstance(version, bool) and version > FORMAT_VERSION:
        return (
            f"Файл настроек {path} сделан более новой сборкой программы "
            f"(формат {version}, эта сборка знает {FORMAT_VERSION}). Прочитано "
            "то, что понятно; остальное оставлено в файле нетронутым.",
        )
    return (
        f"У файла настроек {path} не назван формат (ожидался {FORMAT_VERSION}). "
        "Прочитан как есть — проверьте значения в окне настроек.",
    )
