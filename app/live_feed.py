@dataclass(frozen=True, slots=True)
class MinuteTally:
    """Счёт контрактов одной минуты по снимкам брокера. Неизменяемый итог.

    Брокер шлёт минуту многократно, и в каждом снимке `volume` — оборот
    в валюте **нарастающим итогом** (`broker/stream.py`). Контракты считаются
    по приращениям, а не делением итога (миниплан Э1-5, §4.5):

        контракты = Σ round((оборот_i − оборот_{i−1}) / close_i),  оборот_0 = 0

    На записи пробы 04.09.2026 это даёт ровно 136; деление итога на последнюю
    цену — 136,001, но на минуте с разбросом 0,3 % и 40 000 контрактами ошибка
    была бы ~120 контрактов. Погрешность приращения — `qty × разброс / цена`,
    и между минутами она не переносится: смена минуты обнуляет счёт.

    `minute` — начало минуты по `floor_to_minute`: МСК, секунды отброшены.
    `refusal` — почему **последний** снимок отвергнут; `None` — принят.
    `refused` — сколько снимков минуты отвергнуто: ноль — минута чистая.
    """

    minute: datetime
    #: Последний принятый оборот — база следующего приращения.
    turnover: float
    contracts: int
    refusal: str | None = None
    refused: int = 0


def _shape_problem(snapshot: CandleSnapshot) -> str | None:
    """Чем свеча снимка негодна сама по себе, без истории минуты.

    Проверяются все четыре цены, а не одна `close`: свеча с нулевым `low`
    выглядит касанием любого уровня выхода, и тейк «сработал» бы там, где
    сделки не было; `high < low` и открытие вне размаха — свеча, которой
    не бывает. Отрицательный оборот — тоже.
    """
    prices = (snapshot.open, snapshot.high, snapshot.low, snapshot.close)
    if min(prices) <= 0:
        return "цена не положительна: " + ", ".join(f"{price:g}" for price in prices)
    if snapshot.high < snapshot.low:
        return f"максимум {snapshot.high:g} ниже минимума {snapshot.low:g}"
    if not (
        snapshot.low <= snapshot.open <= snapshot.high
        and snapshot.low <= snapshot.close <= snapshot.high
    ):
        return (
            f"открытие {snapshot.open:g} или закрытие {snapshot.close:g} "
            f"вне размаха [{snapshot.low:g}, {snapshot.high:g}]"
        )
    if snapshot.turnover < 0:
        return f"оборот отрицательный: {snapshot.turnover:.0f}"
    return None


def tally_after(previous: MinuteTally | None, snapshot: CandleSnapshot) -> MinuteTally:
    """Итог минуты после этого снимка. Чистая функция: сокета здесь нет.

    Всё состояние — в `previous`, поэтому пересчёт проверяется на списке
    снимков без сети: свернуть список этой функцией и сравнить с числом
    пробы (136).

    Минута снимка — `floor_to_minute`: брокер сегодня шлёт метку, выровненную
    по минуте, но метка с секундами превратила бы **каждый** снимок в новую
    минуту, то есть в «законченную» — и вернула бы запись формирующейся
    минуты (шапка модуля) целиком.

    Смена минуты обнуляет счёт (`оборот_0 = 0`): первый снимок новой минуты
    даёт весь её оборот к этому моменту одним приращением. Так же выглядит
    первый снимок после подписки посреди минуты — наторгованное до подписки
    делится на одну цену; точнее по этому каналу не бывает. Округление —
    штатное `round`: дробные части приращений на пробе не больше 0,01,
    а ровно половина — совпадение оборота с ценой, не смещение.

    ⚠️ Снимок отвергается вслух, а не подгоняется, в четырёх случаях: негодная
    свеча (`_shape_problem`); минута **раньше** ведомой — снимок пришёл не
    по порядку, и принять его значило бы закрыть формирующуюся минуту как
    законченную; оборот **меньше** прежнего — нарастающий итог не убывает,
    это либо чужой порядок сообщений, либо сброс счётчика на сервере, и что
    из двух, не узнать. Отвергнутый снимок не открывает новой минуты,
    не сдвигает базу и не добавляет контрактов: программа объём не выдумывает.
    Минута помечается сомнительной (`refused`); догрузки, которая заменила бы
    её точной, в этой версии нет — строка остаётся какая есть.
    """
    minute = floor_to_minute(snapshot.opened_at)
    problem = _shape_problem(snapshot)
    if problem is None and previous is not None and minute < previous.minute:
        problem = f"снимок минуты {minute:%H:%M} пришёл после минуты {previous.minute:%H:%M}"
    if problem is not None:
        base = previous if previous is not None else MinuteTally(minute, 0.0, 0)
        return dataclasses.replace(base, refusal=problem, refused=base.refused + 1)
    if previous is None or previous.minute != minute:
        previous = MinuteTally(minute, 0.0, 0)
    delta = snapshot.turnover - previous.turnover
    if delta < 0:
        refusal = (
            f"оборот уменьшился: был {previous.turnover:.0f}, "
            f"пришёл {snapshot.turnover:.0f}"
        )
        return dataclasses.replace(previous, refusal=refusal, refused=previous.refused + 1)
    return MinuteTally(
        minute,
        snapshot.turnover,
        previous.contracts + round(delta / snapshot.close),
        refused=previous.refused,
    )


def to_minute(
    snapshot: CandleSnapshot, contracts: int, *, unsettled: bool = False
) -> MarketCandle:
    """Снимок брокера → минутка слоя данных. Единственное место перекладки.

    Объём приходит **параметром**, а не считается здесь: контракты — итог
    по приращениям (`tally_after`), а у одного снимка приращения нет.
    Время — та же `floor_to_minute`, что и ключ минуты в счёте: две разные
    формулы разошлись бы молча.

    Два разных повода перекладывать, и оба ходят сюда, а не каждый своей
    формулой (иначе цена растущей свечи и цена записанной разъехались бы
    молча — ровно `D-015`, но уже в деньгах):

    * `unsettled=False` — **последний принятый снимок законченной минуты**,
      тот, что пишется в базу. Интервал минуты закончился, и это доказано
      снимком следующей;
    * `unsettled=True` — **снимок ещё идущей минуты**, тот, что рисуется.
      В базу он не идёт никогда: колонки под признак там нет, и записанная
      формирующаяся минута объявила бы бар закрытым раньше времени (шапка
      модуля). Признак нужен тому, кто рисует: бар, собранный с такой
      минуткой, обязан остаться незакрытым (`market.build_bars`).

    ⚠️ Часовой пояс сохраняется. Первая версия снимала его (`replace(tzinfo=None)`),
    и слой данных отказал вслух: «время без часового пояса… иначе торговое окно
    молча сдвигается». Отказ верный — окно 10:05–11:00 московское, а брокер шлёт
    UTC, и без пояса разница в три часа потерялась бы без единого сообщения.
    Наивное время сюда не доходит: `broker/stream.py` отвергает его при разборе.
    """
    return MarketCandle(
        time=floor_to_minute(snapshot.opened_at),
        open=snapshot.open,
        high=snapshot.high,
        low=snapshot.low,
        close=snapshot.close,
        volume=float(contracts),
        unsettled=unsettled,
    )


