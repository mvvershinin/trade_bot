@dataclass(frozen=True, slots=True)
class Watchers:
    """Куда поток сообщает о себе. Три разных получателя, не один.

    Разделены намеренно: состояние связи идёт в панель, записанная минута —
    в перерисовку графика, а событие — строкой в журнал решений. Слить их
    в один вызов значило бы решать за окно, что из этого показывать.
    """

    #: Связь появилась, оборвалась, восстанавливается.
    connection: Callable[[Connection], None]
    #: Минута закончилась и записана в базу.
    closed_minute: Callable[[str], None]
    #: Минута **ещё идёт**, и вот её состояние на этот снимок: инструмент
    #: и минутка, помеченная `unsettled`. Зовётся на каждом принятом снимке,
    #: то есть примерно девять раз в минуту (замер брокера), — это `B-007`:
    #: без него свеча текущей минуты появлялась готовой и с опозданием.
    #:
    #: ⚠️ Получатель обязан вернуться **немедленно**: вызов идёт из чтения
    #: сокета, и ожидание здесь остановило бы приём снимков — то есть лечение
    #: запаздывания само стало бы запаздыванием. Ни записи в базу, ни прогона
    #: по этому вызову не бывает: растущая минута рисуется и только.
    growing_minute: Callable[[str, MarketCandle], None]
    #: Событие, причина и важность — человеческим языком, в журнал решений.
    #: Важность называет поток, а не получатель: «поток открыт» и «брокер
    #: отказал» — разные строки, и знает это тот, у кого случилось.
    say: Callable[[str, str, DecisionLevel], None]
    #: Подписка открыта, и вот **минута первого снимка**: с неё и правее ряд
    #: ведёт поток, всё, что левее, — забота догрузки пропущенного.
    #:
    #: Поток сообщает **факт**, а не команду: он не знает ни про догрузку,
    #: ни про то, что с этой минутой сделают. Догрузка подключается сюда
    #: сборкой (`LiveLink`), как и три получателя выше.
    connected: Callable[[datetime], None]
    #: Остановить робота: событие и причина человеческим языком.
    #:
    #: Отдельно от `say`, и разница не в громкости. `say` — это рассказ:
    #: получатель волен показать строку и жить дальше. Здесь — **запрет
    #: решать**, который снимает только человек. Зовётся ровно на одном
    #: событии: `OutcomeUnknown`, то есть тогда, когда программа не может
    #: доказать, что на счёте ничего не изменилось (`D-086`). Умолчания
    #: у поля нет нарочно: собирающий поток обязан ответить, кто у него
    #: останавливает робота, а не получить эту дыру молча.
    halt: Callable[[str, str], None]


class LiveFeed:
    """Подписка на инструмент: пишет законченные минутки, держит состояние.

    Один экземпляр — один инструмент. Задача снимается при закрытии окна;
    всё завершение внутри главной корутины (решение 0005, п. 4).

    Что означает каждое состояние связи — и это контракт с кнопкой окна,
    которая зеркалит снимок (`ui/main_window.py`, `STREAM_BUTTON`):

    * `RECONNECTING` — связи нет, но её **просили**: первое подключение
      или пауза между попытками после обрыва;
    * `ONLINE` — пришёл первый снимок;
    * `OFFLINE` — поток **снят**: по кнопке или на отказе, которому повтор
      не поможет. В паузе между попытками `OFFLINE` не ставится: панель
      красила бы осознанное ожидание как аварию, а окно не могло бы отличить
      его от отключения по команде;
    * `MARKET_CLOSED` — **торгов нет, и это не сбой**: расписание брокера
      сказало «закрыто», поток ждёт открытия и попыток не тратит. Отличать
      это от `RECONNECTING` обязательно: владелец счёта уже потерял полчаса,
      приняв закрытую биржу за поломку (`B-022`).

    ⚠️ Внутри этих четырёх значений поток различает шесть фаз (`LinkPhase`),
    и в панель они складываются таблицей `PHASES`, а не развилками по коду.
    Единственное место, откуда состояние уходит в окно, — `_phase`; он же
    пишет фазу в технический лог и не отправляет одно и то же дважды.
    """

    def __init__(
        self,
        session: BrokerSession,
        worker: MarketWorker,
        *,
        ticker: str,
        class_code: str,
        watchers: Watchers,
    ) -> None:
        self._session = session
        self._worker = worker
        self._ticker = ticker.strip()
        self._class_code = class_code
        self._watch = watchers
        #: Расписание торгов, `follow`. `None` — расписания нет, и поток ведёт
        #: себя как до `B-022`: подключается всегда.
        self._hours: TradingHours | None = None
        #: Какое состояние связи ушло в окно последним. Одно и то же второй раз
        #: не отправляется: панель зеркалит снимок, и повтор означал бы лишний
        #: снимок из порта на каждую попытку (`LiveFeed._phase`).
        self._shown: Connection | None = None
        self._task: asyncio.Task[None] | None = None
        #: Задачи, снятые кнопкой и ещё закрывающие сокет. Следующее включение
        #: дожидается их до открытия нового сокета, `aclose` — всех разом.
        self._retired: list[asyncio.Task[None]] = []
        #: Итог минуты, которую поток ведёт сейчас, и её последний принятый
        #: снимок. Смена минуты в итоге означает, что предыдущая закончилась:
        #: канал шлёт только последнюю свечу, и данных по прошлой минуте
        #: не будет никогда — вот тогда она и пишется.
        self._tally: MinuteTally | None = None
        self._last: CandleSnapshot | None = None
        #: Последняя причина обрыва и все виды чужих снимков, сказанные
        #: в журнал. Одно и то же второй раз не говорится: при негодном
        #: токене попытки идут до конца сеанса, чужие снимки могут идти потоком.
        self._complaint: str | None = None
        self._foreign: set[str] = set()
        #: Виды незнания расписания, о которых уже сказано в журнал решений.
        #: По одной строке на вид **за всё время жизни потока**, а не за круг:
        #: расписание спрашивается перед каждой попыткой подключения, и
        #: за выходные их 192. Журнал из 192 одинаковых строк — то же
        #: молчание, только громкое.
        self._doubted: set[ScheduleDoubt] = set()

    def follow(self, hours: TradingHours) -> None:
        """Дать потоку расписание торгов: закрытую биржу он тогда не долбит.

        Отдельным вызовом, а не шестым параметром конструктора: шестой ловит
        `PLR0913` (порог 5, `pyproject.toml`), а сводить `ticker` и `class_code`
        в бандл ради этого значило бы переписать три места сборки и все
        проверки — правка формы там, где вопрос в содержании.

        ⚠️ Забыть этот вызов молча нельзя: что `LiveLink` его делает при
        сборке потока, стережёт `tests/test_app_live_feed.py`. Без него поток
        работает — просто без расписания, то есть как до `B-022`.
        """
        self._hours = hours

    def start(self) -> None:
        """Начать слушать. На работающем потоке ничего не делает.

        ⚠️ Работает и сразу после `request_stop`. Снятая задача ещё закрывает
        сокет — рукопожатие закрытия занимает до десяти секунд, — и второе
        нажатие в это окно прежде молча пропадало: кнопка нажата, потока нет.
        Теперь новая задача дожидается снятой **до** открытия сокета (`_ride`),
        то есть прежний сокет закрыт раньше нового: лимит брокера — двадцать
        соединений, и полумёртвые у сервера считаются (миниплан §4.6).
        """
        if self._task is not None and not self._task.done():
            return
        self._task = asyncio.ensure_future(self._ride())

    def request_stop(self) -> None:
        """Отключиться по нажатию кнопки. Возврат немедленный.

        Окно живёт в том же цикле событий, что и поток (решение 0005), поэтому
        ждать здесь нельзя: интерфейс замер бы на время закрытия сокета.
        Задача снимается и откладывается; дожидается её следующий `start`
        или `aclose` при закрытии программы.
        """
        self._retire_task()
        self._phase(LinkPhase.DOWN)
        self._watch.say(
            "Связь с брокером", "Отключено по команде из окна.", DecisionLevel.INFO
        )

    def retarget(self, ticker: str) -> None:
        """Сменить инструмент подписки. Работающий поток переоткрывается (`B-020`).

        До 05.09.2026 тикер задавался один раз при сборке: после смены
        инструмента в окне поток продолжал писать **старый**, а снимки нового
        отбрасывал бы как чужие — молча, потому что чужим он считает как раз
        то, на что не подписан.

        ⚠️ Счёт минуты и последний снимок сбрасываются здесь — **страховкой**,
        а не единственным способом: `_listen` начинает счёт заново на каждом
        подключении, и сегодня этого хватает. Держать вместе новый тикер
        и снимок прежнего инструмента всё равно незачем: `_close_minute` пишет
        по текущему `self._ticker`, и первая же правка, которая тронет `_last`
        вне `_listen`, положила бы минуту чужого инструмента под новый символ.

        ⚠️ Код класса не меняется — он задан ключом `--stream-class` и в окне
        не редактируется. Инструмент другого рынка под прежним классом брокер
        не найдёт, и поток снимется вслух (`NOT_FOUND` повтору не поддаётся):
        громко и неверно, но не молча.
        """
        fresh = ticker.strip()
        if not fresh or fresh == self._ticker:
            return
        was, self._ticker = self._ticker, fresh
        running = self._retire_task()
        self._tally = None
        self._last = None
        self._complaint = None
        self._foreign.clear()
        self._watch.say(
            "Инструмент подписки изменён",
            f"Поток котировок: {was} → {fresh}."
            + (
                " Переподключаемся к брокеру."
                if running
                else " Подписка начнётся при подключении."
            ),
            DecisionLevel.INFO,
        )
        if running:
            self.start()

    def _retire_task(self) -> bool:
        """Снять задачу, оставив её закрывать сокет. Была ли она жива.

        Отдельно от `request_stop`: там за снятием следуют «Отключено
        по команде из окна» и `OFFLINE`, а при смене инструмента поток
        продолжается — просто на другом инструменте.
        """
        task, self._task = self._task, None
        if task is None or task.done():
            return False
        task.cancel()
        self._retired.append(task)
        return True

    async def aclose(self) -> None:
        """Снять подписку и дождаться всех задач — текущей и отложенных."""
        tasks = [
            task for task in (*self._retired, self._task)
            if task is not None and not task.done()
        ]
        self._retired.clear()
        self._task = None
        for task in tasks:
            task.cancel()
        if tasks:
            await asyncio.wait(tasks, timeout=CLOSE_WAIT)

    # ------------------------------------------------------------ внутреннее

    async def _ride(self) -> None:
        """Подключаться, читать, при обрыве ждать и подключаться снова.

        Три исхода одного захода:

        * отказ брокера или связи (`BrokerError`) — повторяем, если отказу
          повтор помогает (`retryable`): нет сети, таймаут, неполадка у брокера,
          `NO_DATE`. Не помогает — снимаем поток: просроченный или отвергнутый
          токен, инструмент не найден, чужой формат свечи;
        * любое другое исключение — **ошибка программы или машины, не сеть**:
          база не открылась, диск, разбор. Сеть и рукопожатие слой `broker/`
          переводит в `BrokerError` сам (`candle_stream`), поэтому здесь
          повтору лечить нечего: поток снимается со словами, трассировка уходит
          в технический лог. Прежде такая беда считалась обрывом и крутила
          переподключение вечно — на чистой машине без базы поток не записал
          ни одной минуты и молчал (ворота `/review`, 04.09.2026);
        * заход кончился сам — брокер закрыл сокет; повторяем.

        Перед каждой попыткой спрашивается **расписание торгов** (`_shut`):
        закрыто — ждём открытия, а не удваиваем паузу вслепую (`B-022`).
        Пауза повторов при этом начинается заново: биржа открылась — первая
        попытка идёт сразу, а не через минуту, накопленную за ночь.

        Причина говорится один раз (`_complain`), а не каждые 2…60 секунд, —
        но в **технический лог** уходит каждая: по нему обрыв и разбирают.
        """
        await self._drain()
        self._complaint = None
        pause = RETRY_FIRST
        self._phase(LinkPhase.CONNECTING)
        while True:
            shut = await self._shut()
            if shut is not None:
                await self._wait_out(shut)
                pause = RETRY_FIRST
                continue
            # ⚠️ Фаза ставится **здесь**, а не в конце круга. Иначе выход
            # из ожидания объявлял бы подключение до того, как расписание
            # спрошено заново, и панель за выходные 192 раза мигнула бы
            # «Восстанавливаем связь» — по разу на каждую проверку.
            self._phase(LinkPhase.CONNECTING)
            final = False
            try:
                await self._listen()
            except asyncio.CancelledError:
                raise
            except OutcomeUnknown as unknown:
                # ⚠️ Ловится **до** `BrokerError`, и это не оформление.
                # Снять поток мало: этот отказ говорит не «не вышло»,
                # а «неизвестно, изменилось ли что-то на счёте». Робот
                # обязан встать, иначе он продолжит решать, считая себя вне
                # рынка (`D-086`). Поток при этом снимается тоже: повтор
                # у такого отказа запрещён (`retryable` False), и слепое
                # переподключение здесь ничему не поможет.
                final = True
                halt_on_unknown_outcome(unknown, self._watch.halt)
                self._complain(str(unknown), unknown.technical)
            except BrokerError as error:
                final = not error.retryable
                self._complain(str(error), error.technical)
            except Exception as error:  # трассировка уходит в log.exception ниже
                final = True
                log.exception("поток котировок снят ошибкой программы")
                self._complain(
                    f"Ошибка программы, а не связи: {type(error).__name__}: {error}. "
                    "Подробность — в выводе программы в консоли."
                )
            else:
                self._complain("Брокер закрыл поток котировок.")
            if final:
                self._phase(LinkPhase.DOWN)
                self._watch.say(
                    "Связь с брокером",
                    "Поток котировок снят: повтор здесь не поможет. Исправьте причину "
                    "и нажмите «Подключиться» снова.",
                    DecisionLevel.WARNING,
                )
                return
            self._phase(LinkPhase.PAUSED, f"{pause:.0f} с")
            await asyncio.sleep(pause)
            pause = min(pause * 2, RETRY_CAP)

    async def _wait_out(self, shut: MarketShut) -> None:
        """Биржа закрыта: сказать один раз и ждать открытия вместо повторов.

        Фазой отсюда выходит `MARKET_CLOSED`, и панель показывает **«Биржа
        закрыта»**, а не «Восстанавливаем связь»: это разные вещи, и владелец
        счёта уже потерял полчаса, приняв одно за другое. Строка журнала
        говорится один раз, а в технический лог уходит каждая проверка —
        по нему и разбирают, сколько мы прождали.

        Фазу «подключаемся» этот метод намеренно **не** ставит: её ставит
        `_ride` после того, как расписание спрошено заново и оказалось,
        что торги идут.
        """
        self._phase(LinkPhase.MARKET_CLOSED, f"проверим через {shut.wait:.0f} с")
        self._say_once("Биржа закрыта", shut.words, DecisionLevel.INFO)
        await asyncio.sleep(shut.wait)

    async def _shut(self) -> MarketShut | None:
        """Закрыта ли биржа прямо сейчас — по расписанию брокера, не по догадке.

        `None` означает «подключаться можно», и три разных случая дают его
        одинаково: торги идут; расписания у потока нет вовсе; спросить
        не удалось. Последнее — правило, а не небрежность: «не знаем» это
        не «закрыто» (`broker/schedule.py`, решение 2), и пропущенный торговый
        день дороже сотни лишних попыток.

        ⚠️ Одинаково для **поведения**, но не для слов: третий случай уходит
        строкой в журнал решений (`_doubt`), и уходит один раз за сеанс.
        Первый и второй молчат: при идущих торгах говорить не о чем, а поток
        без расписания — это прогон без сети, а не событие для человека.

        ⚠️ Ловится всё, кроме отмены. Отказы брокера расписание глотает само,
        поэтому сюда доходит только беда программы — и вставать из-за неё
        поток не вправе: до `B-022` он подключался вообще без расписания,
        и это поведение остаётся запасным.
        """
        if self._hours is None:
            return None
        try:
            status = await self._hours.status(class_code=self._class_code)
            self._doubt(status)
            if status is None or status.is_open is not False:
                return None
            today = await self._hours.daily(
                class_code=self._class_code, ticker=self._ticker
            )
        except asyncio.CancelledError:
            raise
        except Exception:  # трассировка уходит в log.exception
            log.exception("расписание торгов не спрошено (%s)", self._class_code)
            self._say_doubt(ScheduleDoubt.BROKEN, None)
            return None
        now = datetime.now(MSK)
        return MarketShut(
            words=closed_words(
                now,
                opens_at=status.next_change,
                work_day=today.is_work_day if today is not None else None,
            ),
            wait=closed_wait(now, status.next_change),
        )

    def _doubt(self, status: TradingStatus | None) -> None:
        """Разобрать ответ расписания и сказать человеку, чего мы не знаем.

        Причина спрашивается у расписания (`status_trouble`) и только тогда,
        когда ответа нет: при готовом ответе прошлый отказ уже стёрт, и
        спрашивать не о чем.

        ⚠️ Поведение потока этим не меняется ни на шаг — метод только
        говорит. «Не знаем» остаётся «подключаемся как раньше»: пропущенный
        торговый день дороже сотни лишних попыток.
        """
        failure = (
            self._hours.status_trouble(class_code=self._class_code)
            if status is None and self._hours is not None
            else None
        )
        if isinstance(failure, OutcomeUnknown):
            # ⚠️ Перехват стоит **здесь**, у вызывающего, а не в расписании.
            # Расписание глотает отказы брокера намеренно: оно чтение,
            # «не знаем» там законный ответ, и слой `broker/` не вправе
            # останавливать робота — он не знает про движок и знать
            # не должен. Но `OutcomeUnknown` означает не «расписание
            # неизвестно», а «неизвестно, изменилось ли что-то на счёте»,
            # и молчать на этом нельзя (`D-086`).
            halt_on_unknown_outcome(failure, self._watch.halt)
        doubt = schedule_doubt(status, failure)
        if doubt is not None:
            self._say_doubt(doubt, failure)

    def _say_doubt(self, doubt: ScheduleDoubt, failure: BrokerError | None) -> None:
        """Незнание расписания — в журнал решений, по одной строке на вид.

        ⛔ Мимо `_say_once`, и это не небрежность. Тот сторожит **последнюю**
        сказанную строку и обнуляется на каждом заходе `_ride`, потому что
        стережёт причину обрыва: обрыв, повторившийся через час, сказать
        надо снова. Здесь наоборот — отказ расписания повторяется каждые
        15 секунд ожидания, и сказать о нём надо **один раз за сеанс**.
        Общий на двоих счётчик дал бы либо 192 строки, либо съеденную
        причину обрыва.
        """
        if doubt in self._doubted:
            return
        self._doubted.add(doubt)
        line, level = doubt_words(doubt, failure)
        log.warning("расписание торгов: %s (%s)", doubt.value, self._class_code)
        self._watch.say(SCHEDULE_EVENT, line, level)

    def _phase(self, phase: LinkPhase, detail: str = "") -> None:
        """Фаза — в технический лог, а состояние связи — в окно. Единственный выход.

        Прямой `self._watch.connection(...)` мимо этого метода означал бы
        состояние, которого нет в логе, — то есть обрыв, который нечем
        разобрать. Одно и то же состояние второй раз не отправляется: панель
        зеркалит снимок, и повтор стоил бы лишнего снимка из порта на каждую
        из тысячи ночных попыток.
        """
        look = PHASES[phase]
        log.info(
            "поток %s (%s): %s%s",
            self._ticker,
            self._class_code,
            look.words,
            f" — {detail}" if detail else "",
        )
        if look.shown is self._shown:
            return
        self._shown = look.shown
        self._watch.connection(look.shown)

    def _say_once(self, event: str, text: str, level: DecisionLevel) -> None:
        """Строка в журнал окна, но одна и та же подряд не повторяется."""
        if text == self._complaint:
            return
        self._complaint = text
        self._watch.say(event, text, level)

    def _complain(self, text: str, technical: str = "") -> None:
        """Причина обрыва: в лог — всегда, в журнал окна — один раз.

        Технический лог получает **обе** половины отказа: человеческую фразу
        и `BrokerError.technical`. До 05.09.2026 причина уходила только
        в журнал окна, и разобрать обрыв по логу было нельзя — а лог заведён
        ровно для этого. Обе половины чистит от секретов сам `BrokerError`
        при создании (`broker/errors.py`), поэтому в лог они идут как есть.
        """
        log.warning(
            "поток %s (%s) прерван: %s%s",
            self._ticker,
            self._class_code,
            text,
            f" [{technical}]" if technical else "",
        )
        self._say_once("Связь с брокером", text, DecisionLevel.WARNING)

    async def _drain(self) -> None:
        """Дождаться задач, снятых кнопкой: прежний сокет закрывается до нового.

        Задача убирается из списка **после** ожидания: отмена посреди ожидания
        (закрытие программы) оставляет её в списке, и `aclose` дождётся её сам.
        """
        while self._retired:
            await asyncio.wait({self._retired[-1]})
            self._retired.pop()

    async def _listen(self) -> None:
        """Один заход: база открыта, подписка, чтение до обрыва.

        ⚠️ Поток данных открывается **здесь, при включении**, а не при запуске
        программы. `app/main.py` при запуске открывает базу только если файл
        есть: пустой файл превратил бы «базы нет» в «в базе нет свечей», и этот
        довод остаётся в силе. Но писать минутки некуда, пока база не открыта:
        на чистой машине первый же `put_minutes` падал, и поток считал это
        обрывом связи. Второе открытие поток данных запрещает — отсюда `opened`.

        Сокет открывается и закрывается здесь, внутри задачи потока: иначе
        `websockets` при закрытии не находит задачу и роняет
        «Timeout should be used inside a task» — разбор в `broker/stream.py`.

        Счёт минуты начинается заново на каждом подключении. Минута,
        закончившаяся за время обрыва, в базу не пишется — сколько в ней было
        сделок после обрыва, поток не знает, а усечённая минута под видом
        целой хуже отсутствующей; дыра остаётся, догрузки в этой версии нет.
        Минута, в которой связь только мигнула, считается от нарастающего
        итога первого снимка после подключения: он несёт всю минуту целиком.
        """
        if not self._worker.opened:
            await self._worker.open()
        self._tally = None
        self._last = None
        async with candle_stream(
            self._session,
            ticker=self._ticker,
            class_code=self._class_code,
            timeframe=TIMEFRAME,
        ) as socket:
            # Сокет открыт, снимков ещё нет. У брокера это 3–17 секунд
            # (замер `B-007`), и до `B-022` окно всё это время говорило
            # то же самое, что при неудачной попытке.
            self._phase(LinkPhase.AWAITING_FIRST)
            await self._read(socket)

    async def _read(self, socket: object) -> None:
        """Чтение сообщений открытого сокета до обрыва."""
        first = True
        async for raw in socket:  # type: ignore[attr-defined]
            snapshot = snapshot_of(raw)
            if snapshot is None:
                continue
            if first:
                self._complaint = None
                self._phase(LinkPhase.ONLINE)
                self._watch.say(
                    "Связь с брокером",
                    f"Поток котировок открыт: {self._ticker} ({self._class_code}).",
                    DecisionLevel.INFO,
                )
                first = False
                # ⚠️ Минута первого снимка объявляется **здесь и один раз
                # за заход**: с неё и правее ряд ведёт этот заход потока.
                # Получатель (догрузка пропущенного) обязан вернуться
                # немедленно — ожидание остановило бы чтение сокета, минуты
                # перестали бы закрываться, и лечение дыры само сделало бы
                # новую. Что делать с этой минутой, поток не знает.
                self._watch.connected(floor_to_minute(snapshot.opened_at))
            await self._accept(snapshot)

    def _foreign_of(self, snapshot: CandleSnapshot) -> str | None:
        """Чем снимок не из нашей подписки — либо `None`, если свой.

        Свеча M5, пришедшая в канал M1, легла бы в `minute_candle` минуткой:
        объём и размах пятиминутки под нашим символом. Инструмент и класс —
        по той же причине.
        """
        got = (snapshot.ticker, snapshot.class_code, snapshot.timeframe)
        expected = (self._ticker, self._class_code, TIMEFRAME)
        if got == expected:
            return None
        return (
            f"пришла свеча {got[0]} ({got[1]}, {got[2]}), "
            f"а подписка — {expected[0]} ({expected[1]}, {expected[2]})"
        )

    async def _accept(self, snapshot: CandleSnapshot) -> None:
        """Один снимок: сверка с подпиской, счёт, рисунок; на смене минуты — запись.

        ⚠️ Отвергнутый снимок (`after.refusal`) не рисуется — выход стоит
        **до** вызова рисующего, и это его единственная защита. Сомнительная
        цена на графике неотличима от настоящей, а по графику принимают
        решения глазами. Молчанием отказ при этом не становится: первый
        отвергнутый снимок минуты уходит строкой в журнал решений, и в ней
        сказано, что растущая свеча замерла.
        """
        foreign = self._foreign_of(snapshot)
        if foreign is not None:
            if foreign not in self._foreign:
                self._foreign.add(foreign)
                self._watch.say(
                    "Чужой снимок", f"{foreign}. Снимок отброшен.", DecisionLevel.WARNING
                )
            return
        before, after = self._tally, tally_after(self._tally, snapshot)
        if before is not None and before.minute != after.minute and self._last is not None:
            await self._close_minute(self._last, before)
        self._tally = after
        if after.refusal is not None:
            # Вслух — на первом отвергнутом снимке минуты; дальше та же минута
            # молчит, иначе десяток снимков дал бы десяток одинаковых строк.
            if after.refused == 1:
                self._watch.say(
                    "Сомнительная минута",
                    f"Минута {after.minute:%H:%M} МСК: {after.refusal}. Снимок отброшен "
                    "и на график не пошёл: растущая свеча стоит на прошлом принятом "
                    "снимке. Объём и цены этой минуты могут быть неточными; догрузки "
                    "с биржи в этой версии нет.",
                    DecisionLevel.WARNING,
                )
            return
        self._last = snapshot
        # Снимок принят — растущая минута идёт в окно. **После** записи
        # закрытой минуты выше: тот, кто рисует, читает из базы минутки этого
        # же бара, и порядок «сначала записали, потом рисуем» не даёт бару
        # мигнуть без только что закончившейся минуты.
        self._watch.growing_minute(
            self._ticker, to_minute(snapshot, after.contracts, unsettled=True)
        )

    async def _close_minute(self, last: CandleSnapshot, tally: MinuteTally) -> None:
        """Минута закончилась — теперь, и только теперь, она пишется в базу.

        Пишется её последний принятый снимок с контрактами по приращениям.
        Пара «оборот → контракты» уходит в технический лог: сырой оборот в базу
        не пишется, и без этой строки он терялся бы молча (миниплан §4.5).

        Это **запись**, а не рисунок. Растущую свечу рисует `growing_minute`
        на каждом снимке; здесь порт узнаёт, что минута легла в базу, и решает
        сам, что с этим делать — дорисовать закрытую свечу или гнать прогон
        (`HistoryPort.live_candle`). Поток знает только, что минута записана.
        """
        await self._worker.put_minutes(
            self._ticker, [to_minute(last, tally.contracts)], Source.BROKER
        )
        self._last = None
        log.info(
            "минута %s: оборот %.0f → %d контрактов%s",
            tally.minute.isoformat(),
            tally.turnover,
            tally.contracts,
            f", отвергнуто снимков: {tally.refused}" if tally.refused else "",
        )
        self._watch.closed_minute(self._ticker)
        self._tell_clock()

    def _tell_clock(self) -> None:
        """Сказать, если часы машины разошлись с часами брокера (`D-045`).

        Раз в минуту, а не на каждом снимке: замер обновляется только
        HTTP-ответами брокера (заголовок `Date`), и чаще смотреть незачем.

        ⚠️ Программа часы **не подкручивает** — ни системные, ни своё
        «внутреннее время». Подкрученное время немедленно попало бы
        в журнал сделок, то есть ложь стала бы записанной. Здесь только
        слова человеку, решение принимает он (`broker/clock.py`).

        Уровень выбирается по вердикту, а не по знаку расхождения: при
        `BROKEN` торговля уже встаёт — снимок счёта протухает быстрее, чем
        приходит, и вход запрещён решением 0037.
        """
        watch = self._session.clock
        told = watch.complaint()
        if told is not None:
            headline, text = told
            self._watch.say(
                headline,
                text,
                DecisionLevel.ERROR
                if watch.verdict() is Verdict.BROKEN
                else DecisionLevel.WARNING,
            )
            return
        back = watch.matched_again()
        if back is not None:
            self._watch.say("Часы компьютера", back, DecisionLevel.INFO)


# ------------------------------------------------------------------ деньги


def funds_of(
    snapshot: AccountSnapshot,
    ticker: str,
    *,
    margin: MarginPerContract | None = None,
) -> AccountFunds | None:
    """Снимок счёта брокера → деньги, которые кладут в движок. `None` — нечего класть.

    Единственное место, где эти два вида встречаются, и оно **в `app/`**
    намеренно: `broker/` не знает про движок (зависимостей у него нет вовсе),
    движок не знает про брокера (`ARCHITECTURE.md` §2). Перевод — работа
    сборки, как и всё остальное между слоями.

    ⚠️ Пропуск не заменяется нулём **ни в одном поле**. Ноль в «свободных
    средствах» читается как «денег нет» — ложная тревога; ноль в «размере
    счёта» даёт дневной лимит убытка, равный нулю, то есть остановку робота
    на первом же убытке. Чего именно не хватает, говорит сам снимок
    (`funds_missing`), и вызывающий превращает это в строку журнала.

    ГО под контракт — единственное поле, которое имеет право быть пустым:
    брокер до первой позиции своего числа не сообщает вовсе. Движок принимает
    пустое и говорит «НЕ ПРОВЕРЕНО» (решение 0035); запрет на этом месте был бы
    вечным (см. `engine/guards.py`).

    `margin` — что удалось узнать о ГО контракта помимо открытой позиции
    (`broker/margin.py`: недавнее брокерское число либо оценка по биржевому
    ГО). Не передали — остаётся прежнее поведение: число берётся только
    из открытой позиции, а без позиции его нет.

    ⚠️ Открытая позиция **сильнее** переданного: это ответ брокера здесь
    и сейчас, а всё остальное — память или оценка. Порядок задан
    в `MarginBook.best`, и повторять его здесь развилкой нельзя — два
    написания одного правила разъезжаются молча.
    """
    free, equity = snapshot.money.free_rub, snapshot.equity_rub
    # Проверка идёт по самим числам, а не по пустоте `funds_missing()`:
    # `assert` под ключом `-O` исчезает, а проверяющий тип должен видеть,
    # что оба числа здесь не пусты. Список `funds_missing()` при этом
    # остаётся единственным местом, которое **называет** пропуск словами.
    if free is None or equity is None:
        return None
    per_contract = snapshot.margin_per_contract(ticker)
    if per_contract is None and margin is not None:
        per_contract = margin.rubles
    return AccountFunds(
        at=snapshot.taken_at,
        equity=equity,
        free=free,
        margin_per_contract=per_contract,
    )


