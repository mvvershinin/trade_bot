def closed_words(
    now: datetime, *, opens_at: datetime | None, work_day: bool | None
) -> str:
    """«Биржа закрыта, суббота: нерабочий день. Торги начнутся в понедельник в 09:00».

    Чистая функция: ни сети, ни часов внутри — момент приходит параметром,
    поэтому фраза проверяется на любой день недели без ожидания субботы.

    Момент открытия берётся **из расписания брокера** (`nextSessionDate`),
    а не выводится нашим календарём: своего календаря торгов у программы нет
    (шапка модуля). Не назвал брокер — фраза кончается на том, что известно;
    выдумывать «в понедельник в 9:00» нельзя, это и есть вторая правда.

    ⚠️ Момент **в прошлом** тоже называется как есть («сегодня в 09:00»),
    а не прячется: он означает, что брокер отстал или потерял часовой пояс,
    и человек, увидев прошедшее время, поймёт про данные больше, чем от
    молчания. Следующая проверка всё равно случится через `CLOSED_WAIT_MIN`.
    """
    today = now.astimezone(MSK)
    head = f"Биржа закрыта, {WEEKDAYS[today.weekday()]}"
    if work_day is False:
        head += ": нерабочий день"
    elif work_day is True:
        head += ": сейчас не торговое время"
    tail = (
        f" Торги начнутся {_when(today, opens_at.astimezone(MSK))}."
        if opens_at is not None
        else " Когда начнутся торги, брокер не сказал."
    )
    return (
        f"{head}.{tail} Подключаться к потоку котировок не будем, пока торги "
        "не начнутся: попытки в закрытую биржу ничего не дают."
    )


def closed_wait(now: datetime, opens_at: datetime | None) -> float:
    """Сколько ждать до следующей проверки расписания. Обоснование — у констант."""
    if opens_at is None:
        return CLOSED_WAIT_MAX
    left = (opens_at - now).total_seconds()
    return min(max(left, CLOSED_WAIT_MIN), CLOSED_WAIT_MAX)


def _when(now: datetime, then: datetime) -> str:
    """Момент в будущем словами: «сегодня в 09:00», «во вторник в 09:00»."""
    days = (then.date() - now.date()).days
    clock = f"{then:%H:%M}"
    if days <= 0:
        return f"сегодня в {clock}"
    if days == 1:
        return f"завтра в {clock}"
    if days < len(WEEKDAYS):
        return f"{WEEKDAY_WHEN[then.weekday()]} в {clock}"
    return f"{then:%d.%m} в {clock}"


class ScheduleDoubt(enum.Enum):
    """Чего именно мы не знаем о торгах. Пять видов, и слова у них разные.

    `D-062`. Прежде поток различал два случая: брокер сказал «закрыто» —
    это **знание**, и оно доезжало до панели и до журнала; всё остальное
    сливалось в `None` и не доезжало никуда. В `None` при этом сидели вещи
    разной цены — от «интернет пропал на минуту» до «адрес зашит в программу
    неверно, и расписания не будет никогда». Владельцу счёта не говорилось
    ни о первом, ни о втором.

    ⚠️ Различаются они **не полностью**, и это надо назвать вслух.
    `WRONG_ADDRESS` ставится только тогда, когда на 404 ответил шлюз брокера,
    а не его сервис (`session._wrong_address`): по телу ответа видно, что
    кода отказа в нём нет. Это ровно та беда, что случилась 05.09.2026
    со свечами (`B-010`). Но неверное имя **метода** внутри существующего
    сервиса даст обычный 404 с кодом, то есть `REFUSED`, — и от «брокер
    не нашёл данные по такому классу» он неотличим ничем. Поэтому
    у `REFUSED` слова сказаны так, чтобы годиться в обоих случаях.
    """

    #: Спросить не удалось, и повтор может помочь: нет связи, таймаут, 5xx.
    UNREACHABLE = "unreachable"
    #: Отказ, которому повтор не помогает: не найдено, неверные параметры,
    #: токен не принят, непонятный ответ. Дело не в связи, а в запросе.
    REFUSED = "refused"
    #: Шлюз брокера такого адреса не знает — ошибка в программе.
    WRONG_ADDRESS = "wrong_address"
    #: Брокер ответил, но про торги ничего не сказал: поля нет или в нём
    #: незнакомое слово.
    SILENT = "silent"
    #: Расписание уронило исключение, которого оно не обещало, — беда
    #: программы, а не связи.
    BROKEN = "broken"


@dataclass(frozen=True, slots=True)
class DoubtWords:
    """Что сказать владельцу счёта про один вид незнания и насколько громко.

    Три части, а не готовая фраза: середину — `BrokerError.human` — пишет
    слой брокера, и переписывать её здесь значило бы завести второй текст
    про тот же отказ. Пустая середина просто выпадает (`doubt_words`).
    """

    head: str
    tail: str
    level: DecisionLevel


#: Событие журнала решений, под которым идут все строки про расписание.
#: Одно на все пять видов: владелец счёта отбирает журнал по событию,
#: и пять названий одного и того же превратили бы отбор в поиск.
SCHEDULE_EVENT: Final[str] = "Расписание торгов"

#: Общий хвост: что из незнания следует. Одна строка на всю таблицу, потому
#: что следствие у всех видов одно и то же — **поток подключается как
#: раньше**, и это решение, а не оговорка: пропущенный торговый день дороже
#: сотни лишних попыток (`broker/schedule.py`, решение 2).
#:
#: ⚠️ Дословно этот хвост стоит у четырёх видов из пяти. У `WRONG_ADDRESS`
#: ту же мысль говорит сам отказ слоя брокера, и повтор её вторым
#: предложением был бы стеной, а не заботой. Что мысль сказана у **каждого**
#: вида, стережёт отдельная проверка — по готовой фразе, а не по хвосту.
WORKS_AS_BEFORE: Final[str] = (
    "Идут ли сейчас торги, проверить нечем: к потоку котировок программа "
    "подключается как обычно."
)

#: Вид незнания → слова и громкость. Таблица, а не пять развилок в `_shut`:
#: добавить вид — это строка здесь, а не ветка внутри задачи потока.
#:
#: Громкость выбрана по одному признаку: **исправится ли оно само**.
#: `UNREACHABLE` исправится, когда вернётся связь, и про саму связь скажет
#: отдельная строка — поэтому «Событие», а не «Предупреждение». `REFUSED`,
#: `WRONG_ADDRESS` и `BROKEN` сами не исправятся никогда: там нужен человек.
#:
#: ⚠️ `SILENT` намеренно тихий, хотя он тоже сам не исправится. Причина
#: в том, что мы не знаем, беда это или норма: документация помечает **все**
#: поля ответа необязательными, то есть «брокер не сказал» бывает и законным
#: ответом. Живым запросом не проверялось ничего (токена в разработке нет),
#: и объявлять предупреждением то, что может оказаться штатным ночным
#: ответом, — это приучить владельца счёта пролистывать предупреждения.
DOUBTS: Final[Mapping[ScheduleDoubt, DoubtWords]] = {
    ScheduleDoubt.UNREACHABLE: DoubtWords(
        "Расписание торгов у брокера получить не удалось.",
        f"{WORKS_AS_BEFORE} Как только связь появится, спросим снова.",
        DecisionLevel.INFO,
    ),
    ScheduleDoubt.REFUSED: DoubtWords(
        "Расписание торгов получить не удалось, и повтор не поможет: дело "
        "не в связи, а в самом запросе.",
        f"{WORKS_AS_BEFORE} Само это не пройдёт: проверьте инструмент "
        "в настройках; если он верен — дело в программе.",
        DecisionLevel.WARNING,
    ),
    # ⚠️ Хвоста `WORKS_AS_BEFORE` здесь нет, и это не пропуск. Человеческий
    # текст самого отказа (`WrongAddress.human`) уже кончается словами
    # «Программа не знает, открыта ли биржа, и **работает как раньше**»,
    # и общий хвост повторил бы ту же мысль вторым предложением подряд.
    # Первую редакцию текста про неверный адрес владелец счёта прочитал
    # и назвал стеной (`broker/errors.py`); повтор — прямая дорога туда же.
    ScheduleDoubt.WRONG_ADDRESS: DoubtWords(
        "",
        "Само это не пройдёт: адрес зашит в программу, и до его правки "
        "расписание торгов останется неизвестным.",
        DecisionLevel.WARNING,
    ),
    ScheduleDoubt.SILENT: DoubtWords(
        "Брокер ответил про расписание торгов, но не сказал, идут ли они: "
        "поля в ответе нет или в нём незнакомое программе значение.",
        f"{WORKS_AS_BEFORE} Похоже, брокер изменил ответ.",
        DecisionLevel.INFO,
    ),
    ScheduleDoubt.BROKEN: DoubtWords(
        "Расписание торгов спросить не удалось: ошибка в самой программе, "
        "а не в связи.",
        f"{WORKS_AS_BEFORE} Место ошибки записано в технический лог.",
        DecisionLevel.WARNING,
    ),
}


def schedule_doubt(
    status: TradingStatus | None, failure: BrokerError | None
) -> ScheduleDoubt | None:
    """Чего мы не знаем о торгах — или `None`, когда знаем.

    Чистая функция: ни сети, ни часов. «Знаем» — это **любой** определённый
    ответ, и «закрыто» в том числе: про закрытую биржу поток говорит своими
    словами и показывает её отдельным состоянием панели.

    Ветки разной формы, а не таблица: тип отказа, признак повторимости
    и отсутствие ответа — три разных вопроса к двум разным объектам,
    и словарь по ним читался бы хуже, чем четыре строки.

    `failure is None` при `status is None` означает, что причину спросить
    не у кого (расписание её не сохранило). Тогда `UNREACHABLE` — самое
    осторожное из возможного: оно не обвиняет ни программу, ни брокера.
    """
    if status is not None:
        return None if status.is_open is not None else ScheduleDoubt.SILENT
    if isinstance(failure, WrongAddress):
        return ScheduleDoubt.WRONG_ADDRESS
    if failure is not None and not failure.retryable:
        return ScheduleDoubt.REFUSED
    return ScheduleDoubt.UNREACHABLE


def doubt_words(
    doubt: ScheduleDoubt, failure: BrokerError | None
) -> tuple[str, DecisionLevel]:
    """Вид незнания → строка журнала решений и её громкость.

    Середина фразы — человеческий текст самого отказа: его пишет слой
    брокера (`broker/errors.py`), и он уже очищен от секретов при создании
    отказа. Второго текста про тот же отказ здесь не заводится.
    """
    words = DOUBTS[doubt]
    why = failure.human if failure is not None else ""
    return " ".join(part for part in (words.head, why, words.tail) if part), words.level


