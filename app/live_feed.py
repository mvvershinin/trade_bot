class LiveLink:
    """Сессия брокера и поток свечей, которые строятся при первом включении.

    ⚠️ При сборке окна не создаётся ничего, и это правило, а не оптимизация:
    **токен не трогается, пока связь не попросили.** Первая редакция строила
    `BrokerSession(TokenStore(userdata))` при каждом запуске, а `TokenStore`
    — верно, по решению 0003 — отказывает, если каталог назван не `userdata`.
    Программа выходила с кодом 1 до окна, хотя подписку никто не просил;
    три теста `tests/test_app_main.py` запускают её ровно из такого каталога.

    Сессия одна на весь запуск: второе включение её не пересобирает,
    выключение её не закрывает — `httpx.AsyncClient.aclose` асинхронен,
    а команда окна обязана вернуться немедленно. Закрывает `aclose`
    при завершении программы, и закрывает ровно то, что было построено.

    Отказ построения — ответ на нажатие, а не исключение из слота Qt:
    `switch` возвращает причину человеческим языком, а порт делает из неё
    строку журнала уровня «предупреждение», строку состояния и состояние
    связи «нет связи» (`HistoryPort.stream`). Файл токена читается здесь же,
    в момент включения, а не в задаче потока: иначе «токен не введён» стал бы
    строкой цикла переподключения, повторяемой раз в минуту до конца сеанса.
    Пока файл не прочитан, каждое нажатие пробует снова — токен, положенный
    в папку при работающей программе, подхватывается без перезапуска.
    """

    def __init__(
        self,
        port: HistoryPort,
        worker: MarketWorker,
        *,
        userdata: Path,
        ticker: str,
        class_code: str,
    ) -> None:
        self._port = port
        self._worker = worker
        self._userdata = userdata
        self._ticker = ticker.strip()
        self._class_code = class_code
        #: Кому класть деньги счёта. `None` — **никому**, и это умолчание.
        #:
        #: ⚠️ Умолчание здесь не осторожность, а граница главного правила.
        #: Прогон по истории и наблюдение на живом потоке денег счёта
        #: не получают и получать не должны: движок, которому в одном режиме
        #: сообщают счёт, а в другом нет, начинает вести себя по-разному
        #: на одной и той же свече (`ARCHITECTURE.md` §1, решение 0037,
        #: следствие 1). Получатель появляется **только** в боевой сборке,
        #: и появляется отдельной строкой, которую видно (`deliver_funds_to`).
        self._funds_to: Callable[[AccountFunds], None] | None = None
        #: Код биржи для выбора рублёвого блока «Лимитов»: их приходит
        #: несколько (фондовый рынок и срочный), и какой наш — знает сборка,
        #: а не слой брокера (`broker/account.py`, `_ruble_block`).
        self._exchange: str | None = None
        self._session: BrokerSession | None = None
        self._feed: LiveFeed | None = None
        self._backfill: Backfiller | None = None
        self._funds: FundsWatch | None = None
        #: Догрузки прежних инструментов, отложенные сменой инструмента.
        #: Сняты в момент смены (`_retire_backfill`), здесь дожидаются
        #: закрытия: `Backfiller.aclose` асинхронна, а смена инструмента
        #: приходит из слота Qt и обязана вернуться немедленно.
        self._retired: list[Backfiller] = []
        #: Расписание торгов. Одно на весь запуск: у него своя память ответов,
        #: и пересборка на каждом подключении сделала бы её бесполезной.
        self._hours: Schedule | None = None

    def deliver_funds_to(
        self,
        receiver: Callable[[AccountFunds], None],
        *,
        exchange: str | None = None,
    ) -> None:
        """Сказать звену, кому класть деньги счёта. **Только боевая сборка.**

        Отдельным вызовом, а не параметром конструктора, по двум причинам,
        и обе по делу. Первая механическая: седьмой довод ловит `PLR0913`,
        и тот же приём уже применён рядом (`LiveFeed.follow`). Вторая важнее:
        строка сборки, включающая чтение портфеля, обязана быть **видна
        отдельно**. Прогон по истории и наблюдение на живом потоке денег
        счёта не получают и получать не должны — иначе движок начнёт
        различать, откуда пришла свеча (`ARCHITECTURE.md` §1, решение 0037).
        Параметр со значением по умолчанию проще не заметить, чем вызов.

        `exchange` — код биржи, чьи рубли наши: «Лимиты» приходят массивом
        по валюте и бирже, и на счёте с фондовым и срочным рынком рублёвых
        блоков два (`broker/account.py`).

        Звать до первого включения потока: после сборки опроса счёта
        получателя не подменить.
        """
        self._funds_to = receiver
        self._exchange = exchange

    def switch(self, on: bool) -> str | None:
        """Команда окна: включить или выключить поток. Причина — если нельзя.

        Опрос счёта снимается вместе с потоком, а включается не здесь,
        а по состоянию связи (`_show_connection`): спрашивать портфель,
        пока сокет не открыт, значит тратить жетоны ограничителя на попытки,
        которым всё равно нечем помочь.
        """
        if not on:
            if self._feed is not None:
                self._feed.request_stop()
            if self._funds is not None:
                self._funds.request_stop()
            return None
        try:
            feed = self._feed or self._build()
        except BrokerError as error:
            # ⚠️ `OutcomeUnknown` сюда прийти не может, и отдельной ветки под
            # него здесь нет намеренно (`D-086`). `_build` в сеть не ходит
            # вовсе: он собирает объекты и читает файл токена с диска. Отказы
            # отсюда — «файла нет», «права чужие», «формат не тот»; ни один
            # из них не оставляет у брокера команду с неизвестным исходом,
            # и останавливать робота на них было бы ложной тревогой ценой
            # ручного возобновления. Появится здесь запрос к брокеру — ветку
            # обязан завести тот, кто его добавит.
            #
            # Человеку — фраза, её отдаст порт; технику — причина с путём.
            # Оба текста отказ брокера чистит сам при создании (`broker/errors.py`).
            log.warning(
                "подключение к брокеру не собрано: %s", error.technical or error.human
            )
            return str(error)
        self._feed = feed
        feed.start()
        return None

    def retarget(self, instrument: str) -> None:
        """Инструмент в окне сменился — подписка идёт за ним (`B-020`).

        Зовётся портом на **каждое** применение настроек, в том числе когда
        инструмент не менялся: решение «менять или нет» принимает тот, кто
        знает текущий тикер подписки, а не тот, кто знает настройки.

        Меняется здесь всё, что было собрано под прежний инструмент: тикер
        для будущих подключений, догрузка пропущенного и — если поток
        работает — сама подписка. Расписание торгов не пересобирается:
        оно спрашивается по коду класса, а тот не менялся.
        """
        fresh = instrument.strip()
        if not fresh or fresh == self._ticker:
            return
        self._ticker = fresh
        if self._funds is not None:
            # ГО под контракт считается по позиции этого тикера, а тикер
            # сменился. Опрос при этом не пересобирается: сессия и счёт
            # у него те же.
            self._funds.retarget(fresh)
        session = self._session
        if self._feed is None or session is None:
            # Звена ещё нет: новый тикер запомнен, подписка начнётся сразу
            # с него. Строить догрузку тут нельзя — она ходит в сеть, а токен
            # до включения не трогается (шапка класса).
            return
        self._retire_backfill()
        self._backfill = self._backfiller(session)
        self._feed.retarget(fresh)

    async def aclose(self) -> None:
        """Снять поток и закрыть сессию — ровно то, что было построено.

        ⚠️ Порядок не произвольный. Догрузка снимается **первой**: она пишет
        в базу и ходит в сеть через ту же сессию, и оставленная позади она
        писала бы в закрывающееся хранилище. Дальше опрос счёта, дальше
        поток, дальше сессия. Догрузки прежних инструментов закрываются
        здесь же: смена инструмента их только откладывает.
        """
        for backfill in (*self._retired, self._backfill):
            if backfill is not None:
                await backfill.aclose()
        self._retired.clear()
        if self._funds is not None:
            await self._funds.aclose()
        if self._feed is not None:
            await self._feed.aclose()
        if self._session is not None:
            await self._session.close()

    def _retire_backfill(self) -> None:
        """Снять догрузку прежнего инструмента и отложить её закрытие.

        ⚠️ Именно **снять**, а не только отложить (правка 05.09.2026).
        Прежде заход прежнего тикера доживал своё: он занимал общий
        ограничитель частоты, из которого берут жетоны догрузка нового
        инструмента и опрос состояния счёта, и дописывал в журнал строки
        про инструмент, которого на экране уже нет. Дыра прежнего
        инструмента при этом не теряется — она закроется на следующем
        подключении к нему.

        Ожидание задачи остаётся за `aclose`: `Backfiller.aclose`
        асинхронна, а смена инструмента приходит из слота Qt и обязана
        вернуться немедленно.
        """
        if self._backfill is not None:
            self._backfill.request_stop()
            self._retired.append(self._backfill)
        self._backfill = None

    def _build(self) -> LiveFeed:
        """Сессия (один раз) и файл токена (пока не прочитан) — при включении."""
        if self._session is None:
            # Имя каталога проверяет `TokenStore` (решение 0003); файл
            # на этом шаге ещё не читается.
            self._session = BrokerSession(TokenStore(self._userdata))
        # Есть ли файл, какие права, тот ли формат. Отказ — ответ на нажатие;
        # успех сессия запоминает, и при подключении второго чтения не будет.
        stored = self._session.stored()
        if stored.permissions_were_loose:
            self._port.note(
                "Права файла с токеном",
                "Файл с токеном мог читать не только владелец; программа "
                "сузила права до владельца. Если файл действительно читал "
                "кто-то ещё, выпустите новый токен в личном кабинете БКС.",
                DecisionLevel.WARNING,
            )
        self._hours = Schedule(self._session)
        self._backfill = self._backfiller(self._session)
        if self._funds_to is not None and self._funds is None:
            self._funds = FundsWatch(
                Account(self._session, exchange=self._exchange),
                ticker=self._ticker,
                watchers=self._funds_watchers(self._funds_to),
                exchange_margin=self._exchange_margin,
            )
        feed = LiveFeed(
            self._session,
            self._worker,
            ticker=self._ticker,
            class_code=self._class_code,
            watchers=Watchers(
                connection=self._show_connection,
                closed_minute=self._redraw,
                growing_minute=self._grow,
                say=self._port.note,
                connected=self._led,
                halt=self._port.halt,
            ),
        )
        feed.follow(self._hours)
        return feed

    def _funds_watchers(
        self, funds: Callable[[AccountFunds], None]
    ) -> FundsWatchers:
        """Куда опрос счёта сообщает о себе. Отдельным методом — ради проверки.

        Выделено не ради красоты `_build`, а потому что иначе эту проводку
        не проверить ничем: `_build` строит сессию брокера и читает файл
        токена, и обойти это в проверке дороже, чем сама проводка. Замер
        06.09.2026 показал цену: мутация `halted=lambda: False` в этой строке
        не роняла **ни одной** из 3565 проверок, хотя от неё зависит, что
        владелец счёта прочтёт про открытую позицию (`D-086`, Н-2).

        ⚠️ `halted` — вопрос порту в момент жалобы, а не запомненный флаг.
        Робота останавливает и движок (дневным лимитом убытка), и слой
        приложения; опрос счёта не знает ни про одного из них и знать
        не должен, а сказать правду про позицию обязан.
        """
        return FundsWatchers(
            funds=funds,
            say=self._port.note,
            halt=self._port.halt,
            halted=lambda: bool(self._port.halted),
        )

    async def _exchange_margin(self, ticker: str) -> float | None:
        """Биржевое ГО под названный контракт (`INITIALMARGIN`) — или `None`.

        Разрывает замкнутый круг `D-046`: у брокера ГО контракта до первой
        позиции не спросить ни одним методом (разбор — `broker/margin.py`),
        а биржа отдаёт его бесплатно и без токена тем же путём, которым
        грузится история (решение 0041).

        ⚠️ Инструмент приходит **доводом**, а не берётся из `self._ticker`:
        спрашивающий (`FundsWatch`) сверяет ответ с тем тикером, для которого
        запрос затевался, и второе место, знающее текущий инструмент, эту
        сверку бы обнулило.

        Ошибок наружу не отдаёт: биржа, которая не ответила, — законный ответ
        «не знаем», а не повод уронить опрос счёта. Строку про это говорит
        `market.point`, и её видно в поле «Стоимость пункта».
        """
        answer = await self._worker.point_value(ticker)
        spec = answer.spec
        return None if spec is None else spec.initial_margin

    def _backfiller(self, session: BrokerSession) -> Backfiller:
        """Догрузка пропущенного по текущему инструменту. Один экземпляр — один тикер."""
        return Backfiller(
            History(session),
            self._worker,
            self._port,
            ticker=self._ticker,
            class_code=self._class_code,
        )

    def _led(self, minute: datetime) -> None:
        """Поток объявил минуту первого снимка. Возврат немедленный: это чтение сокета.

        Получателей два, и второй появился вместе с `B-020`. Догрузке минута
        нужна как правый край окна — с неё и правее ряд ведёт поток. Порту она
        нужна как **граница** между историей в базе и тем, что пишет поток:
        с тех пор как подписка следует за сменой инструмента, поток способен
        дописать по инструменту, на который порт ещё ни разу не смотрел, —
        и тогда `coverage.last` показывает уже на минуту потока, а границей
        служить не может (`HistoryPort._first_look`).

        Порт **первым**: он только кладёт минуту в словарь, а догрузка ставит
        задачу, и ставить её раньше значило бы допустить, что она успеет
        подтвердить границу до того, как та объявлена.
        """
        self._port.stream_leads(self._ticker, minute)
        if self._backfill is not None:
            self._backfill.start(minute)

    def _show_connection(self, state: Connection) -> None:
        # ⚠️ Здесь же включается и выключается опрос счёта, и это не «заодно».
        # Связь появилась — счёт надо перечитать **немедленно**: это шаг 2
        # порядка восстановления после обрыва (`DOMAIN.md` §7), у брокера
        # спрашивают фактическое состояние счёта. Связи нет — спрашивать
        # некого, и цикл опроса только жёг бы жетоны ограничителя частоты.
        #
        # Вызов стоит **до** рассылки снимка в окно, потому что состояние
        # связи `ONLINE` приходит раньше объявления границы потока
        # (`LiveFeed._read`), а границей начинается догрузка пропущенного.
        # Значит запрос счёта встаёт в очередь ограничителя первым — но это
        # порядок постановки, а не приоритет: ведро жетонов приоритетов
        # не знает, и на занятой очереди снимок придёт позже. Разбор этого
        # столкновения — в докстринге `FundsWatch`.
        if self._funds is not None:
            if state is Connection.ONLINE:
                self._funds.start()
            else:
                self._funds.request_stop()
        # Состояние читается при сборке снимка, поэтому после смены окно
        # получает снимок заново — **без прогона** (`HistoryPort.restate`):
        # связь меняется на каждой попытке, а прогон по всей истории ради
        # одного поля — шторм прогонов при негодном токене. Неизменившееся
        # состояние не рассылается вовсе. Второго пути к панели нет.
        if self._port.connection is state:
            return
        self._port.connection = state
        self._port.restate()

    def _grow(self, symbol: str, minute: MarketCandle) -> None:
        # ⚠️ Ни `refresh`, ни `live_candle`. Растущая минута — только рисунок:
        # в базу она не пишется (шапка модуля), в прогон не идёт (движок
        # решает по закрытым барам, `ARCHITECTURE.md` §6), а вид графика
        # не сбрасывается (`B-009`). Как часто перерисовывать и что делать,
        # если предыдущая перерисовка ещё идёт, решает порт: он один знает,
        # какой график сейчас показан.
        self._port.growing_minute(symbol, minute)

    def _redraw(self, symbol: str) -> None:
        # ⚠️ Не `refresh`. Прогон по всей истории на каждой живой минуте
        # заканчивался полной заменой набора свечей, и приближение, выставленное
        # руками, сбрасывалось к умолчанию раз в минуту (`B-009`). Решение,
        # нужен ли прогон, принимает порт: бар закрылся — прогон, набирается —
        # рисунок. Разбор — в докстринге `HistoryPort.live_candle`.
        self._port.live_candle(symbol)
