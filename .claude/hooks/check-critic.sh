#!/bin/bash
# Stop — не даёт закончить сессию, если код изменён после последнего критика.
#
# Отличие от исходного стартер-пака: правки через Bash здесь ТОЖЕ засчитываются.
# В стартер-паке хук видел только Edit/Write/NotebookEdit, и файл, записанный
# через `sed -i` или heredoc, проверку обходил молча. Проект не под git,
# поэтому сравнение git status недоступно — вместо него разбираются и вызовы Bash.
#
# Правки в .claude/, .docs/ и reference/ кодом не считаются: это документация,
# конфигурация команды и локальный архив-эталон.
#
# Скретчпад сессии (`/tmp/claude-*/`) — тоже не код: харнесс выдаёт этот каталог
# под временные файлы, в репозиторий оттуда не попадает ничего, и ревьюить там нечего.
# Добавлено 30.08.2026, после того как хук трижды заблокировал завершение хода из-за
# проб `hook_check*.py`, которыми проверялся другой предохранитель.
#
# ⚠️ Почему исключение сделано в хуке, а не обходом. Напрашивалось назвать пробы
# `.txt` — тогда `is_doc` их пропустит и хук замолчит. Это ровно тот способ, которым
# предохранители умирают: агент учится подбирать имена, при которых сторож молчит,
# вместо того чтобы упереться в него по делу. Тот же анти-приём разобран в аудите
# `live-trading-guard.sh` от 30.08.2026. Поэтому чинится причина, а не симптом.

set -uo pipefail

INPUT=$(cat)
# Сторож, который при собственной поломке молча пропускает, — хуже отсутствующего.
# Весь разбор ниже написан на `jq`; без него хук выходил с нулём и не говорил
# ни слова. Теперь говорит. Найдено аудитом 30.08.2026 — той же болезнью болел
# соседний `live-trading-guard.sh`, там она вылечена запасным разбором на python3.
# Здесь запасного разбора нет намеренно: программа ниже слишком велика, чтобы
# держать её в двух реализациях, — расхождение между ними было бы опаснее поломки.
if ! command -v jq >/dev/null 2>&1; then
    printf '⚠️ check-critic: не найден jq — СТОРОЖ КРИТИКА НЕ РАБОТАЕТ, правки кода проходят без ревью.\n' >&2
    exit 0
fi

TRANSCRIPT=$(printf '%s' "$INPUT" | jq -r '.transcript_path // empty' 2>/dev/null)

[ -n "$TRANSCRIPT" ] && [ -r "$TRANSCRIPT" ] || exit 0

# Транскрипт разбирается как JSON, а не грепается по сырым байтам: один ход
# ассистента может содержать несколько tool_use сразу, и grep по целой строке
# отбрасывал бы правку кода вместе с соседней правкой документации.
#
# jq выдаёт события в порядке документа, поэтому достаточно посмотреть,
# что в потоке последнее: Stop срабатывает в конце каждого хода, а транскрипт
# накопительный — критик из начала сессии не покрывает поздние правки.
#
# Маркер слэш-команды засчитывается только в записях user и только в блоках text,
# иначе достаточно ассистенту упомянуть /review в прозе, чтобы защита выключилась.
SCAN=$(jq -Rr '
    # Один предикат на оба правила: что считать кодом продукта.
    #
    # `.claude/hooks/` — КОД, а не конфигурация. Найдено аудитом 30.08.2026:
    # пока весь `.claude/` числился мета-файлами, предохранитель денег можно было
    # править без единого критика. За один день это произошло трижды, и отревьюены
    # те правки только потому, что аудитора позвали руками. `.claude/agents/`
    # и `.claude/skills/` — действительно конфигурация; `.claude/hooks/` —
    # исполняемая логика безопасности.
    #
    # `..` в пути — тоже код: обход каталогов освобождения не получает.
    # `/tmp/claude-1000/x/../../home/…/broker/session.py` начинается со скретчпада,
    # но правит продукт.
    def is_code_path:
        if   test("\\.\\.")                              then true
        elif test("(^|/)\\.claude/hooks/")               then true
        elif test("(^|/)(\\.claude|\\.docs|reference)/") then false
        elif test("/tmp/claude-[^/]*/")                  then false
        elif test("(^|/)(tests|tools|mockups)/")         then false
        elif test("(^|/)ui/")                            then false
        else true end;

    # ── Освобождение по слою, 03.09.2026 ────────────────────────────────────
    # Обязательное ревью на КАЖДУЮ правку означало полный прогон агента-критика
    # на любую мелочь: чтение файлов, рассуждение, отчёт. За сессию это часы.
    #
    # Освобождены слои, где правка не двигает деньги: tests/ и tools/ в поставку
    # не входят вовсе, mockups/ — картинки, ui/ по правилу проекта не содержит
    # торговой логики и это проверяется отдельным тестом
    # (tests/test_ui_no_trading_logic.py).
    #
    # ⚠️ Правило осталось «всё код, кроме перечисленного», а не наоборот.
    # Перевернуть его на список охраняемых слоёв было бы дешевле в одну строку
    # и опаснее навсегда: новый слой выпал бы из-под охраны молча, в тот день,
    # когда его завели. Отказ идёт в закрытую — незнакомый путь считается кодом.
    #
    # ⚠️ backtest/ НЕ освобождён, вопреки первоначальной постановке задачи.
    # Там лежит модель исполнения: комиссия и срабатывание тейка внутри бара.
    # Все рубли отчёта считаются оттуда, и ошибка в ней даёт правдоподобные
    # числа, которые не с чем сверить. app/ не освобождён по той же причине:
    # это точка сборки, где боевой исполнитель встречается с движком, и там же
    # ставится чистка секретов (app/main.py, sanitize=scrub).
    #
    # Охрана боевого контура не тронута: strategies/, engine/, broker/, market/,
    # backtest/, app/ и сами предохранители .claude/hooks/ блокируют Stop
    # по-прежнему.

    def is_doc:       test("\\.(md|txt|ya?ml|json|lock|toml|cfg|ini)$"; "i");

    # Освобождение висит на ЦЕЛИ ЗАПИСИ, а не на присутствии подстроки в команде.
    # Иначе достаточно приписать к команде упоминание скретчпада — комментарием,
    # соседней командой через `&&`, путём к файлу лога — и правка продукта пройдёт
    # мимо сторожа. Та же болезнь была найдена аудитом в `live-trading-guard.sh`;
    # здесь она повторилась слово в слово, потому что правило писал тот же автор.
    # ⚠️ `sed -i` берёт СКОЛЬКО УГОДНО файлов, а не один. Первая версия захватывала
    # только первую цель, и «sed -i ВЫРАЖЕНИЕ скретчпад/probe.py engine/rules.py»
    # проходил мимо: у второго файла нет перед ним ни `>`, ни `tee`, ни `sed -i`.
    # (Апострофы в этом комментарии не ставить: программа обёрнута в одинарные
    #  кавычки bash, и апостроф обрывает её на середине — jq молча падает,
    #  а сторож пропускает всё. Так уже случилось 30.08.2026.)
    # Освобождение опять оказалось не на той цели — третий раз одна и та же болезнь,
    # уже в третьем месте. Найдено аудитом 30.08.2026.
    #
    # `js` и `css` в списке потому, что вендоренная библиотека графика и страница
    # для `ui/chart/web_surface.py` — поставляемая часть продукта, а не документация.
    def code_ext: "\\.(py|pyi|pyw|sh|sql|qss|ui|spec|js|css)";
    def sed_targets:
        if test("sed[[:space:]]+-i") then
            [ match("[^[:space:]|;&\"]+" + code_ext + "\\b"; "g") | .string ]
        else [] end;
    def redir_targets:
        [ match("(?:>>?[[:space:]]*|tee[[:space:]]+)([^[:space:]|;&]+" + code_ext + ")"; "g")
          | .captures[0].string ];
    def is_src_write: ((sed_targets + redir_targets) | map(select(is_code_path)) | length) > 0;

    (fromjson? // empty) as $d
    | ($d.message.content?) as $c
    | if ($c | type) == "string" then
        if ($d.type? == "user") and ($c | test("<command-name>/(review|validate|risk|parity)</command-name>"))
        then "CRIT" else empty end
      elif ($c | type) == "array" then
        $c[]
        | select(type == "object")
        | if (.type? == "tool_use") then
            (.name? // "") as $n
            | if ($n | test("^(Edit|Write|NotebookEdit)$")) then
                ((.input.file_path? // .input.notebook_path? // "")) as $p
                | if ($p | is_code_path) and (($p | is_doc) | not) then "CODE" else empty end
              elif ($n == "Bash") then
                ((.input.command? // "")) as $b
                | if ($b | is_src_write) then "CODE" else empty end
              elif (((.input.subagent_type? // "") | test("^(code-critic|architecture-validator|risk-security-officer|parity-auditor)$"))) then
                "CRIT"
              else empty end
          elif ($d.type? == "user") and (.type? == "text")
               and ((.text? // "") | test("<command-name>/(review|validate|risk|parity)</command-name>"))
          then "CRIT"
          else empty end
      else empty end
' 2>/dev/null < "$TRANSCRIPT")

# Нет правок кода — проверять нечего
printf '%s\n' "$SCAN" | grep -qx CODE || exit 0

# Последнее событие CODE означает, что код меняли после последнего критика
if [ "$(printf '%s\n' "$SCAN" | grep -x -e CODE -e CRIT | tail -1)" = CODE ]; then
    printf '%s' '{"decision":"block","reason":"⚡ СТОП. Код изменён после последнего запуска критика. Запусти /review перед завершением. Если тронута торговая логика — ещё и /parity. Если деньги или токен — ещё и /risk."}'
fi

exit 0
