#!/usr/bin/env bash
# Предохранитель: мутация не остаётся в рабочем дереве и не уезжает в коммит.
#
# Замер 06.09.2026, ради которого хук написан. Исполнитель доказывал, что образец
# настоящего токена БКС не стережёт ни один тест. Доказательство требует мутации:
# отключить чистку и посмотреть, упадёт ли хоть что-нибудь. Мутацию он поставил
# в ОБЩЕМ рабочем дереве:
#
#     broker/redaction.py:232
#     -    result = _JWT.sub(MASK, result)
#     +    result = result
#
# В этот момент программа не маскировала токен нигде. Рядом работали ещё двое
# исполнителей, а координатор готовил коммит. Поймано глазами при разборе
# `git status`, а не проверкой.
#
# Верный способ — мутация в ОТДЕЛЬНОЙ копии дерева:
#
#     git worktree add /tmp/mutant HEAD
#     # правите и гоняете тесты ТАМ
#     git worktree remove --force /tmp/mutant
#
# Тогда рабочее дерево не трогается вовсе, а мутация физически не может уехать
# в историю. Приём не выдуман: 06.09.2026 два агента применили его сами, и они
# единственные из шести никому не помешали.
#
# Цена проверки замерена: `git status --porcelain` по продуктовым каталогам —
# 0,00 с. Хук ничего не стоит.
#
# Режимы:
#   commit  PreToolUse на Bash. ОТКАЗЫВАЕТ, если в индексе снята защита секрета.
#   finish  SubagentStop и Stop. ПРЕДУПРЕЖДАЕТ, если продуктовый код грязный.

set -uo pipefail

MODE="${1:-finish}"
PRODUCT_DIRS=(app engine market broker strategies backtest ui tools)

cd "${CLAUDE_PROJECT_DIR:-.}" || exit 0
git rev-parse --git-dir >/dev/null 2>&1 || exit 0

# --------------------------------------------------------------------------
# Режим commit: не дать закоммитить снятую защиту секрета.
#
# Ищем в индексе УДАЛЁННЫЕ строки, в которых вызывалась чистка. Правило 7:
# токен не попадает в лог, журнал, отчёт, экспорт, текст исключения и трассировку.
# Строка, которая это обеспечивала и исчезла, — либо мутация, либо правка,
# которую обязан увидеть человек. Оба случая стоят вопроса.
# --------------------------------------------------------------------------
if [ "$MODE" = "commit" ]; then
    INPUT="$(cat)"
    # Хук висит на всех Bash-вызовах; интересует только коммит.
    case "$INPUT" in
        *'git commit'*) ;;
        *) exit 0 ;;
    esac

    REMOVED="$(git diff --cached -U0 -- "${PRODUCT_DIRS[@]}" 2>/dev/null \
        | grep -E '^-[^-]' \
        | grep -E 'scrub\(|\.sub\(|MASK|_JWT|_BEARER|redact' || true)"

    [ -z "$REMOVED" ] && exit 0

    {
        echo "⛔ В индексе снята защита секрета — коммит остановлен."
        echo
        echo "Из продуктового кода исчезли строки, обеспечивавшие чистку:"
        echo
        echo "$REMOVED" | head -20 | sed 's/^/    /'
        echo
        echo "Правило 7: токен не попадает в лог, журнал, отчёт, экспорт, текст"
        echo "исключения и трассировку. Ни целиком, ни частично."
        echo
        echo "Это одно из двух:"
        echo
        echo "  1. Забытая мутация. Снимите её и ставьте в отдельной копии дерева:"
        echo "       git checkout -- <путь>"
        echo "       git worktree add /tmp/mutant HEAD   # правите и гоняете ТАМ"
        echo "       git worktree remove --force /tmp/mutant"
        echo
        echo "  2. Намеренная правка чистки. Тогда её обязан увидеть владелец"
        echo "     счёта: покажите ему diff словами и дождитесь ответа."
        echo
        echo "Своей волей этот отказ не обходить."
    } >&2
    exit 2
fi

# --------------------------------------------------------------------------
# Режим finish: продуктовый код грязный на выходе — сказать вслух.
#
# Не отказ, а предупреждение: правка продуктового кода бывает и законной.
# Смысл в том, чтобы забытая мутация не пролежала незамеченной, как 06.09.2026.
# --------------------------------------------------------------------------
DIRTY="$(git status --porcelain -- "${PRODUCT_DIRS[@]}" 2>/dev/null || true)"
[ -z "$DIRTY" ] && exit 0

# `git diff HEAD`, а не `git diff`: мутация может быть уже в индексе, и тогда
# неиндексированный diff пуст. Поймано пробой самого хука 06.09.2026 —
# первая редакция на индексированной мутации молчала про снятую чистку.
SUSPECT="$(git diff HEAD -U0 -- "${PRODUCT_DIRS[@]}" 2>/dev/null \
    | grep -E '^-[^-]' \
    | grep -E 'scrub\(|\.sub\(|MASK|_JWT|_BEARER|redact' || true)"

{
    echo "⚠️  Продуктовый код изменён и не зафиксирован:"
    echo
    echo "$DIRTY" | sed 's/^/    /'
    echo
    if [ -n "$SUSPECT" ]; then
        echo "🔴 И среди изменений снята чистка секрета:"
        echo
        echo "$SUSPECT" | head -10 | sed 's/^/    /'
        echo
        echo "Если это мутация — восстановите СЕЙЧАС: git checkout -- <путь>"
        echo
    fi
    echo "Если это мутация для доказательства — она не должна была попасть"
    echo "в рабочее дерево. Верный способ:"
    echo
    echo "    git worktree add /tmp/mutant HEAD"
    echo "    # правите и гоняете тесты ТАМ"
    echo "    git worktree remove --force /tmp/mutant"
    echo
    echo "Дерево общее: рядом работают другие исполнители и готовится коммит."
} >&2
exit 0
