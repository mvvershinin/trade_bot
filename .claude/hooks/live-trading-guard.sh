#!/bin/bash
# PreToolUse: Bash — предохранитель боевого режима.
#
# Разработка и тесты идут на симуляции. Этот хук ловит забывчивость: команду,
# которая отправила бы реальные заявки на брокерский счёт.
#
# Блокировка — exit 2 со stderr: работает независимо от версии схемы JSON у хуков.
# Хук не заменяет ответственность агентов, он ловит то, что они забыли.

set -uo pipefail

INPUT=$(cat)

# Предохранитель, который при собственной поломке молча пропускает всё, — хуже
# отсутствующего: он создаёт ложное чувство защиты. Найдено аудитом 30.08.2026.
#
# Первая правка ограничилась предупреждением в stderr. Аудит указал на третий
# вариант, который я не рассмотрел: `python3` в этом проекте — жёсткая зависимость
# всего остального, а разбор одного поля JSON занимает одну строку. Предупреждение
# ещё надо прочитать, а запасной разбор работает сам. Для хука, стерегущего доступ
# к счёту, это дешевле.
if command -v jq >/dev/null 2>&1; then
    CMD=$(printf '%s' "$INPUT" | jq -r '.tool_input.command // empty' 2>/dev/null)
elif command -v python3 >/dev/null 2>&1; then
    CMD=$(printf '%s' "$INPUT" | python3 -c \
        'import json,sys; print(json.load(sys.stdin).get("tool_input",{}).get("command",""))' 2>/dev/null)
else
    printf '⚠️ live-trading-guard: нет ни jq, ни python3 — ПРЕДОХРАНИТЕЛЬ БОЕВОГО РЕЖИМА НЕ РАБОТАЕТ.\n' >&2
    exit 0
fi

[ -n "$CMD" ] || exit 0

deny() {
    printf '⛔ ПРЕДОХРАНИТЕЛЬ БОЕВОГО РЕЖИМА\n\n%s\n\n%s\n' "$1" \
"Разработка и тесты идут на симуляции (paper). Реальные заявки подаёт только владелец
счёта, осознанно, после прохождения /go-live. Если команда действительно нужна —
попроси владельца счёта запустить её самому." >&2
    exit 2
}

# 1. Явное включение боевого режима через окружение или флаги
if printf '%s' "$CMD" | grep -Eqi '(^|[^A-Z_])(TRADING_MODE|TRADE_MODE|BROKER_MODE|APP_MODE)=[\"'"'"']?(live|real|prod|production|боев)'; then
    deny "Команда включает боевой режим через переменную окружения."
fi

if printf '%s' "$CMD" | grep -Eqi -- '--(live|real-money|production|prod)\b|--mode[= ](live|real|prod)\b|--no-(paper|dry-run|simulation)\b'; then
    deny "Команда содержит флаг боевого режима."
fi

# 1a. `--no-sandbox` — особый случай, правлен дважды 30.08.2026.
#
# В торговом контексте это выключение песочницы, то есть боевой режим, и блокируется.
# Но `--no-sandbox` — ещё и штатный флаг Chromium, а график проекта жил в QtWebEngine
# (TradingView Lightweight Charts). Хук ложно срабатывал на легитимной команде.
#
# ⚠️ 09.09.2026: QtWebEngine из программы удалён (решение 0056), и законного
# потребителя у послабления ниже больше нет — `QTWEBENGINE_CHROMIUM_FLAGS=…`
# сегодня вырезает контекст ни для чего. Поведение хука НЕ ТРОГАЛ намеренно:
# это предохранитель, и ужесточение сторожа — решение владельца счёта, а не
# попутная правка (`D-105`).
#
# Первая правка была слишком широкой, аудит её забраковал. Что исправлено:
#
#   1. Флаг ищется в команде БЕЗ значения `QTWEBENGINE_CHROMIUM_FLAGS`. Раньше хватало
#      упоминания переменной где угодно в строке — в другой команде через `&&`,
#      в комментарии, в имени файла, даже со значением `=0`. Шесть форм проходили мимо.
#   2. `QTWEBENGINE_DISABLE_SANDBOX` из условия убран: он не требует флага, а ЗАМЕНЯЕТ
#      его, и команда с ним не содержит `--no-sandbox` вовсе — то есть проходила и до
#      всей этой правки. В списке он был бесплатным ключом от замка.
#   3. Из текста отказа убран рецепт обхода. Прежний текст дословно учил приписать
#      переменную — и агент, упершийся в блок на ТОРГОВОЙ команде, выполнял это
#      буквально, по исполнительности, а не по злому умыслу.
#
# Снимать `--no-sandbox` из проверки целиком нельзя: в торговой команде он значит
# ровно то, чего мы боимся.
SANDBOX_CTX=$(printf '%s' "$CMD" | sed -E "s/QTWEBENGINE_CHROMIUM_FLAGS=('[^']*'|\"[^\"]*\"|[^ ]*)//gI")
# Флаг `I` у `s///` есть не во всякой реализации sed. Если вырезание отработало
# с ошибкой, переменная окажется пустой — и проверка пропустит команду молча.
# Отказ обязан быть в закрытую: не разобрали — проверяем исходную строку.
[ -n "$SANDBOX_CTX" ] || SANDBOX_CTX=$CMD
if printf '%s' "$SANDBOX_CTX" | grep -Eqi -- '--no-sandbox\b'; then
    deny "Команда содержит флаг боевого режима (--no-sandbox).

Если это запуск QtWebEngine, а не торговля, флаг должен стоять ВНУТРИ значения
переменной QTWEBENGINE_CHROMIUM_FLAGS, а не отдельным аргументом команды."
fi

# 2. Присвоение боевого токена в окружении
if printf '%s' "$CMD" | grep -Eqi '(BCS|BKS|BROKER)[A-Z_]*(TOKEN|SECRET|KEY|API)[A-Z_]*=[^ ]'; then
    deny "Команда задаёт токен брокера в окружении. Токен живёт только в своём файле с правами 0600."
fi

# 3. Раздел «чтение файла с токеном» УБРАН 03.09.2026 решением владельца счёта.
#
# Довод: токен разработки одноразовый, перед боевой работой заводится новый,
# и тот, на котором тестировали, не остаётся. Стеречь его ценой ложных блокировок
# обычных команд — трата. Раздел стоил 118 строк, двух правок за день, двух ложных
# срабатываний на `git add` и семи регрессий в первой редакции правки.
#
# Защитой файла токена остаются `.gitignore` на `/userdata/` и чистка
# в `broker/redaction.py` (её незакрытый дефект — `ROADMAP.md` §9.1).
# Возвращать — только если появится долгоживущий секрет, и тогда решать
# по ПУТИ `userdata/`, а не по слову в имени файла: словесная ветка и дала
# оба ложных срабатывания.

# 4. Прямой боевой вызов к API брокера
if printf '%s' "$CMD" | grep -Eqi '\b(curl|wget|http|httpie)\b' \
   && printf '%s' "$CMD" | grep -Eqi '(bcs|broker)[a-z0-9.-]*\.(ru|com)' \
   && printf '%s' "$CMD" | grep -Eqi '(order|trade|position|portfolio|execute)'; then
    deny "Команда обращается к торговому API брокера напрямую."
fi

exit 0
