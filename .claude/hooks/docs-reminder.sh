#!/bin/bash
# PostToolUse: Edit|Write — напоминание обновить документацию.
#
# В этом проекте документация не украшение: умолчания, границы окна и правила рынка
# живут в .docs/, и код, разошедшийся с ними, невозможно отревьюить.
#
# ══════════════════════════════════════════════════════════════════════════════
# ⚠️ ПЕРЕПИСАН 31.08.2026 ПО АУДИТУ. Прежняя версия не работала — вся, а не частично.
#
# 1. `systemMessage` В МОДЕЛЬ НЕ ПОПАДАЕТ. Проверено по бинарнику работающей версии:
#    в нормализации вложений `hook_system_message` возвращает пустой массив. Текст
#    рисуется только в терминале строкой «docs-reminder.sh says: …». То есть все шесть
#    прежних напоминаний («запусти /risk», «запусти /parity») видел владелец счёта,
#    который не может на них ответить, и не видел ни один агент. За два дня их не
#    прочитал никто. Санкционированный канал — `hookSpecificOutput.additionalContext`.
#
# 2. ХУК ВИДИТ НЕ ВСЕ ПРАВКИ. Из 33 записей в PROTOTYPE.md и decisions/ через
#    Edit/Write прошли 22, через Bash — 11, и именно они самые крупные: создание
#    документа, полная перезапись, семь перезаписей подряд скриптом. Это ровно тот
#    способ, которым умер check-critic.sh: сторож смотрит в один канал, работа идёт
#    в другой. Остаточный риск записан в ROADMAP §9.7 с ценой.
#
# 3. ПОВТОРЫ. 22 срабатывания на 8 различных файлов: шесть подряд на одном документе
#    за две минуты. Порог «перестанут читать» переходился внутри одной задачи.
#    Отсюда дедупликация по файлу за сессию.
# ══════════════════════════════════════════════════════════════════════════════

set -uo pipefail

INPUT=$(cat)

if ! command -v jq >/dev/null 2>&1; then
    printf '⚠️ docs-reminder: не найден jq — напоминания о документации не работают.\n' >&2
    exit 0
fi

FILE_PATH=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // empty' 2>/dev/null)
[ -n "$FILE_PATH" ] || exit 0

msg=""
case "$FILE_PATH" in
    # ── Документы, по которым ПИШУТ КОД ───────────────────────────────────────
    # Единственное исключение из правила «документация рекурсию не вызывает».
    # Добавлено по разбору ошибок координатора 30.08.2026: три худшие за сессию
    # сделаны здесь и одинаково — отчёт агента переписан в документ без проверки
    # по исходнику, при том что исходник лежал рядом. Контракт порта оказался
    # нереализуемым; пункт приёмки назвал сторожами прогоны, где проверяемого
    # не было; раздел про поведение прототипа опровергнут 21 сделкой из журнала.
    #
    # Вопрос ОДИН и он про 5.1: все три ошибки этого класса. Проверка трассировки
    # контракта (5.2) сюда не идёт — она применима к малой доле решений и
    # срабатывала бы на исправлении опечатки.
    *.docs/decisions/README.md) ;;   # оглавление, не решение
    *.docs/PROTOTYPE.md|*.docs/decisions/*)
        msg="🔍 Это документ, по которому пишут код. Утверждение о поведении прототипа проверено по исходнику или по данным — или переписано из отчёта агента?" ;;

    # ── Хуки — код по решению 0006, и правка требует критика ─────────────────
    # За 30.08.2026 live-trading-guard.sh правился 11 раз, check-critic.sh — 9,
    # и ни одна ветка на это не реагировала. Решение 0006 объявило hooks/ кодом
    # и потребовало критика — напоминать об этом было некому.
    *.claude/hooks/*)
        msg="🛡 Тронут предохранитель. По решению 0006 это код: нужен критик и независимая проверка ДО того, как на правку оперлись." ;;

    *.docs/*|*reference/*) ;;

    # ── Слои продукта ────────────────────────────────────────────────────────
    *strategies/*|*engine/*)
        msg="📝 Тронута торговая логика. Проверь .docs/PROTOTYPE.md и .docs/DOMAIN.md §3, запусти /parity." ;;
    *broker/*)
        msg="📝 Тронут слой брокера. Проверь .docs/DOMAIN.md §6-7, запусти /risk." ;;
    *market/*)
        msg="📝 Тронут слой данных. Проверь .docs/DOMAIN.md §6 и сверочный тест сборки таймфрейма." ;;
    *backtest/*)
        msg="📝 Тронут тестер. Проверь .docs/QUALITY.md и правило «подбор отдельно от проверки»." ;;
    *ui/*)
        msg="📝 Тронут интерфейс. Напоминание: в ui/ нет торговой логики." ;;
    *CLAUDE.md|*settings*.json|*pyproject.toml|*.spec)
        msg="📝 Тронут файл конфигурации проекта. Проверь актуальность .docs/ и заведи решение в .docs/decisions/, если поменялось поведение." ;;
esac

[ -n "$msg" ] || exit 0

# Дедупликация: один и тот же файл напоминает один раз за сессию.
#
# ⚠️ Ключ сессии берётся ИЗ STDIN, а не из окружения. Первая версия читала
# `CLAUDE_SESSION_ID` — такой переменной в этом харнессе НЕТ (есть
# `CLAUDE_CODE_SESSION_ID`), проверено командой `env`. Следствие было бы тихим
# и вечным: подкаталог сессии не создавался бы никогда, метка ложилась бы в общий
# каталог и жила бы **навсегда** — первое напоминание, дальше тишина во всех
# будущих сессиях. Отказ шёл не в безопасную сторону, а ровно в опасную.
#
# Имя переменной было взято из общего знания, а не проверено в окружении, где хук
# работает. Это тот же класс ошибки, который стережёт сам хук (§5.1 брифа
# координатора), допущенный при его написании. `session_id` лежит в общей части
# входа PostToolUse, и хук этот вход уже читает — окружение не нужно вовсе.
SID=$(printf '%s' "$INPUT" | jq -r '.session_id // empty' 2>/dev/null)

# Только шестнадцатеричное с дефисами: значение уходит в путь, и `..` вывело бы
# метку из-под якорного правила `.gitignore` — дефект того же сорта, против
# которого якорные правила и написаны (решение 0003).
#
# ⚠️ Не принят ключ — дедупликации НЕТ ВОВСЕ, и метка не пишется никуда.
# Прежняя версия откатывалась на общий каталог `.state`, и метка снова становилась
# вечной и межсессионной — тот же дефект, что чинили, только на редкой ветке.
# Отказ фильтра обязан означать «дедупликации нет», а не «дедупликация навсегда»:
# лишнее напоминание стоит раздражения, пропавшее — пропущенной ошибки в документе.
STATE_DIR=""
case "$SID" in
    *[!0-9a-fA-F-]*|"") ;;
    *) STATE_DIR="${CLAUDE_PROJECT_DIR:-.}/.claude/.state/$SID" ;;
esac

if [ -n "$STATE_DIR" ] && mkdir -p "$STATE_DIR" 2>/dev/null; then
    KEY=$(printf '%s' "$FILE_PATH" | md5sum 2>/dev/null | cut -c1-32)
    if [ -n "$KEY" ]; then
        [ -e "$STATE_DIR/$KEY" ] && exit 0
        : > "$STATE_DIR/$KEY" 2>/dev/null || true
    fi
fi

# Санкционированный канал: попадает в контекст модели, а не только на экран.
jq -nc --arg m "$msg" \
    '{hookSpecificOutput:{hookEventName:"PostToolUse", additionalContext:$m}}'
