# Чужие логгеры, которые способны напечатать заголовок или тело запроса при
# включённом DEBUG. Проверено на httpx 0.28.1 + httpcore 1.0.9: штатная запись
# httpx — `HTTP Request: POST <url> "HTTP/1.1 200 OK"`, заголовков в ней нет.
# Опасны не они сами, а их дети: `httpcore.http11`, `httpcore.connection`,
# `httpx._client` — из них строка `Authorization: Bearer …` уходит целиком
# при `--log-level trace`.
#
# ⚠️ **Слой брокера их не трогает, и это не забывчивость.** `httpx` — общая
# библиотека процесса: через неё ходит и загрузка истории с биржи в `market/`.
# Ставя на неё фильтр, слой брокера молча менял бы записи чужого слоя —
# `RedactingFilter` схлопывает `record.args` в пустой кортеж, и структурный
# обработчик, который поставит `app/`, получил бы записи без параметров,
# а причина осталась бы в `import broker` за тысячу строк от места разбора.
# По `ARCHITECTURE.md` §2 журналирование настраивает `app/`; см. `install`.
#
# Список остаётся здесь как точка передачи: имена веток известны слою брокера,
# а не `app/`, и угадывать их при сведении программы не надо.
FOREIGN_LOGGERS: Final[tuple[str, ...]] = ("httpx", "httpcore", "websockets")
# ⚠️ `websockets` добавлен 04.09.2026, и не про запас. Проверено по исходнику
# 17.0.1: `websockets/client.py:297` печатает **каждый заголовок рукопожатия**
