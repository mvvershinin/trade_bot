"""Затирание секретов в тексте: логи, сообщения об ошибках, трассировки.

Токен брокера — доступ к счёту на срок до 90 дней. Требование ТЗ §4.1
и `DOMAIN.md` §6: он не попадает в технический лог, журнал решений, журнал
сделок, экспортируемые отчёты, текст исключения и трассировку — ни целиком,
ни частично, ни первыми символами.

Здесь два рубежа, и они закрывают разные дыры.

**Рубеж первый — реестр.** Каждое живое значение токена известно этому модулю
(его кладёт туда `Secret` при создании). `scrub` вырезает эти значения из
любого текста. Рубеж ловит нашу же забывчивость: строку, где кто-то написал
`f"токен {значение}"` вместо `f"токен {secret}"`.

**Рубеж второй — образцы.** Реестр знает только те токены, что прошли через
`Secret`. Токен, который **прислал сервер** в теле ответа, туда не попадал —
а тело ответа мы кладём в технический лог при разборе отказа. Поэтому текст
дополнительно чистится по образцам: `Bearer …`, поля `*_token` в JSON
и в form-кодировке. Образцы не зависят от того, знаем мы значение или нет.

Ни один рубеж не заменяет главного правила: значение токена живёт внутри
`Secret` и наружу выходит единственным вызовом `reveal()` в трёх местах
(заголовок запроса, тело запроса авторизации, запись в свой файл).
Реестр и образцы — предохранители, а не способ обращения с токеном.
"""

from __future__ import annotations

import logging
import re
import threading
from collections import deque
from typing import Final, Iterable

# Маска постоянная и от значения не зависит. Маска вида `abcd…` кажется
# аккуратнее, но она сужает перебор и попадает в скриншот окна, который
# владелец счёта пришлёт в переписку. «Частично» в требовании — это про неё.
MASK: Final[str] = "<токен скрыт>"

# Имена полей собираются из кусков намеренно. Целиком написанное имя поля
# рядом с длинным выражением — тот самый образец, который ищет детектор
# секретов в `tests/test_layers.py`; собранное из кусков, оно не даёт
# ложного срабатывания на исходнике, который сам ничего не хранит.
_TOKEN_FIELDS: Final[tuple[str, ...]] = ("access", "refresh", "id", "session")

# Голое имя поля — нынешнее и прежнее. Момент разбора файла токена
# единственный, когда оба рубежа опущены разом: `Secret` ещё не создан,
# то есть реестр значения не знает, а образцы знали только английские
# составные имена. Одна строка `log().debug("файл: %s", raw)`, добавленная
# при отладке, вынесла бы файл с токеном целиком.
#
# ⚠️ **Русское имя остаётся здесь навсегда**, хотя наш файл с 06.09.2026
# пишется с ключом `token` (`token_store.LEGACY_KEYS`). Файлы прежнего
# формата никуда не делись: они лежат в резервных копиях папки данных,
# а копия папки — штатный способ перенести портативную программу на другую
# машину (решение 0001). Убрать русское имя отсюда значит перестать чистить
# ровно те файлы, которые ещё в ходу. Полноту списка стережёт тест
# `test_scrub_knows_every_name_of_our_own_file`.
#
# Порядок в переборе важен: составные имена стоят первыми, иначе
# `access_token` совпал бы по хвосту.
_BARE_FIELDS: Final[tuple[str, ...]] = ("token", "токен")
_FIELD_NAMES: Final[str] = "|".join(
    [*(f"{name}_token" for name in _TOKEN_FIELDS), *_BARE_FIELDS]
)

# Чистка обязана быть идемпотентной: один и тот же текст проходит через неё
# дважды — фильтром на записи и форматтером на готовой строке (`RedactingFormatter`
# для трассировки обязателен, до неё фильтр не достаёт). Без оговорки ниже
# `\S+` откусывал у уже подставленной маски первое слово, и строка
# `Bearer <токен скрыт>` превращалась в `Bearer <токен скрыт> скрыт>`:
# маска ломала сообщение, в которое её подставили.
_NOT_MASK: Final[str] = f"(?!{re.escape(MASK)})"

# JSON:  "refresh_token" : "значение"
_JSON_FIELD = re.compile(rf'"({_FIELD_NAMES})"\s*:\s*"[^"]*"', re.IGNORECASE)
# form:  refresh_token=значение
_FORM_FIELD = re.compile(rf"\b({_FIELD_NAMES})={_NOT_MASK}[^&\s\"']+", re.IGNORECASE)
# заголовок: Bearer <значение>
_BEARER = re.compile(rf"\bBearer\s+{_NOT_MASK}\S+", re.IGNORECASE)
# «сырой» JWT, попавший в текст сам по себе: три части base64url через точку.
_JWT = re.compile(r"\beyJ[A-Za-z0-9_-]{6,}\.[A-Za-z0-9_-]{6,}\.[A-Za-z0-9_-]{6,}")

# Значения короче этого в реестр не берутся: вырезать из текста двухсимвольную
# подстроку — значит испортить любое сообщение, а защиты это не даёт.
# Настоящий токен БКС — JWT, он на порядок длиннее.
MIN_REGISTERED_LENGTH: Final[int] = 8


class SecretRegistry:
    """Живые значения токенов, которые надо вырезать из любого текста.

    Реестр держит **сильные** ссылки на строки: слабую ссылку на `str` Python
    не даёт. Рост ограничен тем, что `Secret` при сборке мусора зовёт `forget`.

    Учёт — **по числу владельцев, а не по факту наличия**. Двух объектов
    `Secret` с одним значением достаточно, чтобы простой набор сломался:
    один и тот же токен читается из файла и держится сеансом, объекты живут
    порознь, и смерть любого из них выключала бы затирание для живого.
    Отказ при этом молчаливый — токен просто начинает попадать в лог,
    и замечают это по логу, а не по красному тесту. Поймано тестом
    `test_no_token_when_server_echoes_it_back` 30.08.2026: значение уцелело
    в техническом тексте отказа, потому что финализатор мёртвой копии
    сработал после того, как живая копия зарегистрировалась.
    """

    def __init__(self) -> None:
        self._values: dict[str, int] = {}
        #: Опубликованный снимок: то, что читает `scrub`. Кортеж **заменяется
        #: целиком**, а не правится на месте, поэтому читателю ни блокировка,
        #: ни копия не нужны — он берёт ссылку на неизменяемый объект.
        #: Порядок в снимке готовый, от длинного к короткому: сортировать
        #: на каждой записи журнала незачем, состав меняется раз в сутки.
        self._snapshot: tuple[str, ...] = ()
        #: Значения, которые пора забыть. Очередь, а не прямая правка
        #: словаря — см. `forget`. `append` и `popleft` у `deque` атомарны
        #: и никакой блокировки не требуют.
        self._forgotten: deque[str] = deque()
        self._lock = threading.Lock()

    def remember(self, value: str) -> bool:
        """Взять значение под охрану. Отвечает, взято ли оно.

        Единственное место, где блокировка берётся с ожиданием. Зовётся
        только из `Secret.__init__`, то есть из обычного кода, а не из
        финализатора. Остаток риска назван в `known`.
        """
        if not isinstance(value, str) or len(value) < MIN_REGISTERED_LENGTH:
            return False
        with self._lock:
            self._drop_forgotten()
            self._values[value] = self._values.get(value, 0) + 1
            self._publish()
        return True

    def forget(self, value: str) -> None:
        """Забыть значение. Блокировку здесь брать с ожиданием нельзя.

        ⚠️ Это **финализатор** `weakref`, а не обычный вызов: он срабатывает
        в момент сборки мусора, а сборка приходит на любой аллокации —
        в том числе на аллокации под нашей же блокировкой. `threading.Lock`
        не перевходим, и ожидание здесь вешает поток навсегда.

        Поэтому: значение кладётся в очередь атомарным `append`, а разбор
        очереди делается **попыткой** взять блокировку без ожидания. Не вышло
        (её держит этот же поток этажом выше или другой поток) — значение
        просто ждёт следующего раза. Задержка играет в безопасную сторону:
        значение лишний раз затрут, а не лишний раз покажут.
        """
        self._forgotten.append(value)
        if self._lock.acquire(blocking=False):
            try:
                self._drop_forgotten()
                self._publish()
            finally:
                self._lock.release()

    def known(self) -> tuple[str, ...]:
        """Значения под охраной. **Блокировка не берётся вовсе.**

        Это главное свойство реестра, а не оптимизация. `known` зовётся
        из `scrub`, `scrub` — из фильтра журнала, а в фильтр журнала попадает
        всё подряд, включая записи, которые делают чужие финализаторы:
        `__del__` любого объекта, `asyncio.Future.__del__` при отменённой
        задаче. Финализатор приходит внутрь произвольной аллокации — в том
        числе внутрь нашей же критической секции.

        Пока `known` брала блокировку, это была тихая остановка программы:
        `scrub → known` (блокировка взята) `→ аллокация → сборка мусора →
        чужой __del__ → журнал → фильтр → scrub → known` — и поток стоит
        навсегда. Без исключения, без записи в журнал, без нагрузки
        на процессор; робот держит позицию и не отвечает. Воспроизведено
        30.08.2026 при штатных порогах сборщика на 463-й записи журнала.

        Перечислять «безопасные» финализаторы бесполезно: чужой код нам
        не подчиняется. Поэтому повторный вход безопасен **по построению** —
        читатель не берёт ничего. `RLock` не годится: он превратил бы
        зависание в `RuntimeError: dictionary changed size during iteration`
        внутри фильтра журнала.

        Остаток риска ровно один: финализатор, который создаёт `Secret`.
        Тогда `remember` встанет на блокировке. В слое таких нет — `Secret`
        создают `token_store` и `session`, оба из обычного кода.
        """
        return self._snapshot

    def scrub(self, text: str) -> str:
        # Снимок читается один раз: подмена его другим потоком посреди цикла
        # дала бы половину замен от одного состава и половину от другого.
        for value in self._snapshot:
            if value in text:
                text = text.replace(value, MASK)
        return text

    def _drop_forgotten(self) -> None:
        """Учесть отложенные забывания. Зовётся только под блокировкой.

        Аллокации здесь безопасны: финализатор, пришедший в середину, положит
        значение в очередь и вернётся, а читатель не ждёт ничего.
        """
        while True:
            try:
                value = self._forgotten.popleft()
            except IndexError:
                return
            left = self._values.get(value, 0) - 1
            if left > 0:
                self._values[value] = left
            else:
                self._values.pop(value, None)

    def _publish(self) -> None:
        """Собрать новый снимок и опубликовать его. Только под блокировкой.

        Длинные значения идут первыми: короткое значение может оказаться
        подстрокой длинного, и после его замены длинное уже не найдётся
        целиком.
        """
        self._snapshot = tuple(sorted(self._values, key=len, reverse=True))


REGISTRY: Final[SecretRegistry] = SecretRegistry()


def scrub(text: object) -> str:
    """Вернуть текст, из которого вырезано всё похожее на токен."""
    result = text if isinstance(text, str) else str(text)
    result = REGISTRY.scrub(result)
    result = _JSON_FIELD.sub(lambda m: f'"{m.group(1)}": "{MASK}"', result)
    result = _FORM_FIELD.sub(lambda m: f"{m.group(1)}={MASK}", result)
    result = _BEARER.sub(f"Bearer {MASK}", result)
    result = _JWT.sub(MASK, result)
    return result


class RedactingFilter(logging.Filter):
    """Фильтр журналирования: собирает запись в текст и чистит его.

    Запись схлопывается здесь же (`args` очищаются), иначе форматирование
    произойдёт в обработчике — уже после фильтра — и подстановка вернёт
    значение обратно.
    """

    def filter(self, record: logging.LogRecord) -> bool:  # имя метода задано logging
        try:
            message = record.getMessage()
        except Exception:  # noqa: BLE001 — испорченный формат не должен ронять журнал
            message = str(record.msg)
        record.msg = scrub(message)
        record.args = ()
        if record.exc_text:
            record.exc_text = scrub(record.exc_text)
        return True


class RedactingFormatter(logging.Formatter):
    """Форматтер, чистящий готовую строку вместе с трассировкой.

    Трассировку рисует форматтер, а не фильтр: `RedactingFilter` до неё
    не достаёт. Технический лог программы собирается этим форматтером.
    """

    def format(self, record: logging.LogRecord) -> str:  # имя метода задано logging
        return scrub(super().format(record))


