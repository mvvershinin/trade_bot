"""`Secret` — значение, которое нельзя напечатать.

Токен брокера хранится только в этом виде. Наружу он выходит единственным
способом — вызовом `reveal()`, и этот вызов написан в трёх местах слоя:
заголовок запроса, тело запроса авторизации, запись в свой файл.
Любое другое употребление ловится тестом `test_reveal_lives_where_declared`.

Зачем отдельный тип, а не просто дисциплина:

* `repr` объекта попадает в текст исключения при любой ошибке аргументов,
  в вывод отладчика и в дамп переменных кадра у сторонних инструментов;
* f-строка, `%`-подстановка и `format` — три разных пути превратить объект
  в текст, и закрывать надо все три;
* `pickle` и `copy` уносят значение в файлы и в очереди между процессами.
"""

from __future__ import annotations

import hmac
import weakref
from typing import Any, Final

from broker.redaction import MASK, REGISTRY

#: Символы, из которых состоит токен: печатная латиница ASCII без пробелов.
#: Проверка не косметическая. Значение уходит в HTTP-заголовок, а httpx
#: кодирует заголовки в ASCII и на постороннем символе бросает
#: `UnicodeEncodeError` — исключение, которое не является `httpx.HTTPError`
#: и потому мимо разбора отказов проходит насквозь. В кадре этого исключения
#: лежит локальная переменная со строкой `Bearer <значение>`, и инструмент,
#: печатающий переменные кадра, вынесет токен в отчёт об ошибке.
#: Проверено прогоном 30.08.2026 на httpx 0.28.1.
#:
#: Заодно закрывается известная грабля из ранбука подключения к БКС:
#: «токен вставлен с пробелами или переносами» — самая частая причина того,
#: что подключение не встаёт.
_ALLOWED = frozenset(chr(code) for code in range(0x21, 0x7F))


class Secret:
    """Строка, которая не печатается ни одним из способов.

    >>> s = Secret("eyJhbGci.eyJzdWIi.QQQ")
    >>> str(s), repr(s), f"{s}", "%s" % s
    ('<токен скрыт>', '<токен скрыт>', '<токен скрыт>', '<токен скрыт>')
    >>> s.reveal()
    'eyJhbGci.eyJzdWIi.QQQ'
    """

    __slots__ = ("_value", "__weakref__")

    mask: Final[str] = MASK

    def __init__(self, value: str) -> None:
        if not isinstance(value, str):
            # Затирается и здесь — симметрично ветке ниже. Сегодня оба места
            # вызова заранее проверяют тип, то есть сюда с настоящим секретом
            # не попасть. Но `Secret` — тип общего назначения, и следующий
            # вызывающий (этап 2, заявки) может передать сюда байты, прочитанные
            # из файла до декодирования. Дыра одного класса в трёх ветках одной
            # функции — это то, за чем ревью ловило дважды подряд.
            value = None
            del value
            raise TypeError("значение токена — строка")
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("значение токена пустое")
        if not _ALLOWED.issuperset(cleaned):
            # Значение стирается из кадра ДО того, как отсюда полетит отказ.
            # Кадр этой функции попадает в трассировку `ValueError`, а её ловят
            # выше как обычную ошибку разбора ответа — и сырое значение уезжает
            # в отладчик, в `pytest -l` и в будущий сборщик отчётов об ошибках.
            # Тип, который существует ради нераскрытия значения, обязан не
            # раскрывать его и в момент отказа. Аргумент затирается тоже:
            # он живёт в том же кадре.
            value = ""
            cleaned = ""
            del value, cleaned
            # В сообщении нет ни значения, ни его куска, ни позиции символа:
            # позиция вместе с длиной — это уже сведения о токене.
            raise ValueError(
                "в токене есть посторонние символы: пробел, перенос строки "
                "или буква не латинского алфавита. Скорее всего, при копировании "
                "из личного кабинета захватилось лишнее. Скопируйте токен ещё раз"
            )
        object.__setattr__(self, "_value", cleaned)
        # Финализатор ставится только если значение действительно взято под
        # охрану. Короткое значение реестр не берёт, и безусловный финализатор
        # клал бы при его смерти сырую строку в очередь забывания — модуль
        # нарушал бы собственное правило «значение живёт только внутри Secret».
        if REGISTRY.remember(cleaned):
            # Когда объект умрёт, значение перестанет вырезаться из текста.
            # Иначе реестр рос бы на один рабочий токен в сутки бесконечно.
            weakref.finalize(self, REGISTRY.forget, cleaned)

    def reveal(self) -> str:
        """Отдать значение. Имя нарочно громкое: каждый вызов виден в ревью."""
        return self._value

    # --- всё, что превращает объект в текст ---

    def __repr__(self) -> str:
        return MASK

    def __str__(self) -> str:
        return MASK

    def __format__(self, spec: str) -> str:
        return MASK

    # --- сравнение ---

    def __eq__(self, other: object) -> bool:
        if isinstance(other, Secret):
            return hmac.compare_digest(self._value, other._value)
        return NotImplemented

    def __hash__(self) -> int:
        return hash(("broker.Secret", self._value))

    # --- то, чем значение утекает мимо печати ---

    def __len__(self) -> int:
        # Длина токена — тоже сведение о нём, и она нужна ровно ноль раз.
        raise TypeError("длина токена не выдаётся")

    def __reduce__(self) -> Any:
        raise TypeError("токен не сериализуется: pickle унёс бы значение в файл")

    def __getstate__(self) -> Any:
        raise TypeError("токен не сериализуется")

    def __copy__(self) -> "Secret":
        return self

    def __deepcopy__(self, memo: dict[int, Any]) -> "Secret":
        return self

    def __setattr__(self, name: str, value: Any) -> None:
        raise AttributeError("Secret неизменяем")

    def __delattr__(self, name: str) -> None:
        raise AttributeError("Secret неизменяем")
