# --- разбор ответа брокера ---

#: HTTP-код «не найдено». Назван, потому что по нему принимается **решение**,
#: а не только классификация: `session._wrong_address` отличает по нему
#: отсутствующий на шлюзе метод от обычного отказа.
HTTP_NOT_FOUND: Final[int] = 404

#: Текстовые коды из таблиц «Описание исключительных ситуаций» документации БКС.
UNAUTHORIZED: Final[str] = "UNAUTHORIZED"
VALIDATION_ERROR: Final[str] = "VALIDATION_ERROR"
BAD_REQUEST: Final[str] = "BAD_REQUEST"
NOT_FOUND: Final[str] = "NOT_FOUND"
INTERNAL_SERVER_ERROR: Final[str] = "INTERNAL_SERVER_ERROR"


#: Поля, которыми брокер называет код отказа. Порядок — приоритет разбора.
#: Собраны по таблицам «Описание исключительных ситуаций» и по живому отказу
#: подписки 04.09.2026, где вместо `code` пришёл `type` (`broker/stream.py`).
_CODE_FIELDS: Final[tuple[str, ...]] = (
    "errorCode",
    "error_code",
    "code",
    "error",
    "type",
)

#: Как выглядит **код**, а не текст: буква в начале, дальше буквы, цифры,
#: подчёркивание, точка, дефис, и не длиннее 64 символов. Проверка строгая
#: намеренно — это единственное, что переносится из тела ответа в текст,
#: который читает человек, и разметка, фраза или строка в тысячу символов
#: под неё не подходят по построению.
_CODE_SHAPE: Final[re.Pattern[str]] = re.compile(r"[A-Za-z][A-Za-z0-9_.\-]{0,63}")

#: Первый непробельный символ тела → чем это тело является. Таблица, а не
#: цепочка `if`: вид тела — это одно значение одного признака.
_BODY_KINDS: Final[Mapping[str, str]] = {
    "<": "разметка",
    "{": "объект JSON",
    "[": "список JSON",
}


def _json_object(body: str) -> Mapping[str, Any] | None:
    """Тело как объект JSON — или `None`, если это не он."""
    try:
        payload = json.loads(body)
    except (TypeError, ValueError):
        return None
    return payload if isinstance(payload, Mapping) else None


def _code_in(payload: Mapping[str, Any]) -> str | None:
    for field in _CODE_FIELDS:
        value = payload.get(field)
        if isinstance(value, str) and _CODE_SHAPE.fullmatch(value):
            return value
    return None


def code_of(body: str) -> str | None:
    """Код отказа из тела ответа. `None` — тело **не от сервиса брокера**.

    Отвечает на два вопроса сразу, и второй важнее первого. Первый: какой код
    записать в технический лог для разбора. Второй: разговаривал ли с нами
    вообще сервис брокера. Отказ брокера — объект JSON с кодом (`UNAUTHORIZED`,
    `NOT_FOUND`, `BAD_REQUEST`, `VALIDATION_ERROR`, `INTERNAL_SERVER_ERROR`
    по официальному PDF); страница ошибки шлюза, пустое тело и HTML кода
    не содержат, и `None` здесь значит «до сервиса не дошло». На этом различии
    стоит распознавание неверного адреса в `session._wrong_address`.
    """
    payload = _json_object(body)
    if payload is None:
        return None
    found = _code_in(payload)
    if found is not None:
        return found
    # Вложенная форма: `{"errors": [{"code": …, "message": …}]}`. Именно так
    # приходит отказ подписки на поток (проверено живьём 04.09.2026).
    errors = payload.get("errors")
    first = errors[0] if isinstance(errors, list) and errors else None
    return _code_in(first) if isinstance(first, Mapping) else None


def describe_body(body: str) -> str:
    """Чем является тело ответа — **без единого символа из него самого**.

    Это единственное, что о теле попадает в текст, который читает человек:
    вид и длина. «Разметка, 154 симв.» техника до причины доводит («ответил
    шлюз, а не брокер»), а владельцу счёта ничего не показывает.
    """
    head = body.lstrip()[:1]
    return f"{_BODY_KINDS.get(head, 'текст')}, {len(body)} симв."


def from_status(status: int, *, where: str, body: str = "") -> BrokerError:
    """Собрать отказ по HTTP-коду ответа.

    ⚠️ **Тело ответа в `technical` не попадает** — ни целиком, ни куском.
    Из него берутся только код отказа (если тело вообще от брокера) и его
    описание: вид и длина. Само тело кладётся в `details`, у которого один
    адресат — технический лог уровня DEBUG. Причина — в шапке модуля;
    коротко: `technical` читает владелец счёта, и 05.09.2026 он прочитал
    страницу 404 от nginx брокера целиком.
    """
    technical = f"{where}: HTTP {status}"
    code = code_of(body)
    if code:
        technical = f"{technical}, код {code}"
    if body:
        technical = f"{technical}; тело: {describe_body(body)}"

    error = _classify(status, technical)
    error.details = body_details(body)
    return error


def _classify(status: int, technical: str) -> BrokerError:
    """HTTP-код → отказ слоя. Порядок проверок значим: 401/403 и 429 — до 4xx."""
    if status == 401 or status == 403:
        return AuthFailed(technical)
    if status == HTTP_NOT_FOUND:
        return NotFound(technical)
    if status == 429:
        return Throttled(technical)
    if 400 <= status < 500:
        return BadRequest(technical)
    if status >= 500:
        return ServerFailure(technical)
    return UnexpectedAnswer(f"неожиданный код ответа {status}", technical)
