class OutcomeUnknown(BrokerError):
    """Запрос, способный изменить состояние счёта, остался без ответа.

    **Это не «ошибка», а незнание, и разница в том, что делать дальше.**
    `Timeout` означает «ответ не пришёл» и предлагает повторить; для чтения
    это верно, для заявки — нет. Заявка, принятая брокером за миг до обрыва,
    живёт у него независимо от того, дошёл ли до нас ответ. Повтор в этом
    месте даёт **вторую заявку**: удвоенную позицию, удвоенное обеспечение
    и убыток, которого никто не планировал (`B-002`).

    Поэтому исход называется своим именем и **не повторяется автоматически**.
    Выяснять судьбу заявки следует запросом статуса по тому же
    `clientOrderId` (`orderIdType = 1`, `.docs/broker-api/11-get-order-by-id.md`)
    либо списком заявок (`.docs/broker-api/15-orders-search.md`); при отсутствии
    заявки брокер отвечает 404 `NOT_FOUND`.

    ⚠️ **Этот отказ обязан доехать до остановки робота** (`D-086`, закрыт
    основной путь 06.09.2026, **долг целиком не закрыт**: остановка не переживает
    перезапуск программы, а кнопки «возобновить» в окне нет — `D-042`, `D-043`).
    Он — потомок `BrokerError`, а значит его ловит любой
    широкий `except BrokerError`; до правки таких мест было шесть, и все
    шесть превращали его в обычный «брокер не ответил». Правило теперь одно
    и проверяется тестами: ветка `except OutcomeUnknown` стоит **выше**
    широкой и либо останавливает робота, либо пропускает отказ наверх
    к тому, кто остановит. Перевод в остановку живёт в `app/halt.py`:
    движок про этот тип не знает и знать не должен — иначе он начнёт
    различать, откуда пришла свеча (`ARCHITECTURE.md` §1).

    ⚠️ **Сюда попадает всякий неокончательный ответ, а не только таймаут.**
    Отсутствие связи, 5xx и отказ по частоте — про все три документация БКС
    не утверждает, что заявка **не** принята: таблицы «Описание исключительных
    ситуаций» описывают код ответа, а не судьбу заявки. Перестраховка здесь
    стоит одного запроса статуса, недостача — денег на счёте. Окончательный
    отказ (400, 401, 404) сюда не попадает: он говорит, что заявка отвергнута,
    и остаётся собой.
    """

    #: Повторять нельзя ни при каких условиях: повтор — это и есть та самая
    #: вторая заявка. `retryable` здесь означает не «бесполезно», а «опасно».
    retryable: bool = False

    def __init__(self, technical: str = "", *, details: str = "") -> None:
        super().__init__(
            "Брокер не подтвердил и не отклонил команду: ответа нет. "
            "Неизвестно, выполнена она или нет. Программа не повторяет её "
            "сама: повторная заявка удвоила бы позицию и обеспечение. "
            "Проверьте заявки и позицию у брокера, прежде чем продолжать.",
            technical,
            details=details,
        )


