class WrongAddress(BrokerError):
    """Запрос ушёл по адресу, которого у брокера нет: ответил шлюз, не сервис.

    Отдельный отказ, а не `NotFound`, потому что события разные и последствия
    у них разные. «Брокер не нашёл запрошенные данные» — штатный ответ, он
    лечится другим запросом и повторяется в следующий раз. «Такого адреса
    у брокера нет» — **дефект программы**: повторять запрос бессмысленно
    до тех пор, пока адрес не исправят в коде.

    ⚠️ **Найдено 05.09.2026 ценой первого живого запуска.** В `CANDLES_PATH`
    стояло имя сервиса `trade-api-information-service` вместо
    `trade-api-market-data-connector`, и владелец счёта получил на экран
    страницу 404 от nginx брокера вместо графика. Верное имя нашлось
    в официальном PDF; одностраничная документация на сайте таблицу с хостом
    не отдаёт, поэтому перебором адрес не нашёлся.

    Как отличается от штатного 404 — в `session._wrong_address`: коротко,
    у отказа брокера в теле есть его код, у страницы шлюза кода нет.

    Текст владельцу счёта — **две строки**: что перестало работать и что
    из этого следует. Ни кода ответа, ни адреса, ни тела в нём нет; разбор
    причины — в техническом логе. Первая редакция этого текста была на шесть
    предложений, владелец счёта прочитал её и назвал стеной: подробности,
    которые он не может применить, ему не нужны, а нужное в них тонет.
    """

    #: Повторное обращение по тому же неверному адресу в этом сеансе.
    #: Первое говорится вслух, дальнейшие вызывающий вправе не показывать:
    #: догрузка запускается на **каждом** подключении, а обрывы у владельца
    #: счёта частые — иначе он получит одну и ту же строку десятки раз за день.
    repeated: bool = False

    def __init__(
        self,
        what: str,
        consequence: str,
        technical: str = "",
        *,
        details: str = "",
    ) -> None:
        self.what = what
        self.consequence = consequence
        super().__init__(
            f"{what} — ошибка в адресе на нашей стороне. {consequence}",
            technical,
            details=details,
        )


