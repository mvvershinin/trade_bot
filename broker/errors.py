"""Отказы брокера и связи: три текста на каждый отказ.

**Код ошибки брокера — это не сообщение пользователю.** Владелец счёта читает
человеческий текст, техник — код. Поэтому у каждого отказа три поля, и они
различаются не подробностью, а **адресатом**:

* `human` — то, что видит владелец счёта: что случилось, чем это грозит
  и что делать. Без кодов, без английского, без слова «эксепшн»;
* `technical` — короткая строка для технического лога: HTTP-код, текстовый код
  брокера, адрес запроса. Ограничена по длине и по составу **по построению**;
* `details` — сырое тело ответа брокера. Не входит ни в `technical`, ни в
  `human`, ни в `str`, ни в `repr`; пишется отдельной записью уровня DEBUG
  (`session._note_failure`).

⚠️ **Почему тело вынесено в отдельное поле — 05.09.2026.** Прежде оно
дописывалось в `technical` (`technical = f"{technical}; тело: {body[:500]}"`),
а `technical` доезжает до человека сразу двумя дорогами. Первая: слой писал
его в лог, а лог до появления технического (Э1-18) выплёскивался в консоль —
на первом же живом запуске владелец счёта получил там страницу 404 от nginx
брокера в виде разметки вместо сообщения. Вторая жива и сейчас:
`app/backfill` кладёт `failure.technical` в пояснение отчёта о загрузке,
а оно живёт в базе и уходит в выгрузку.

Причина того 404 была своя (неверное имя сервиса в адресе свечей, исправлено),
но защита от неё не зависит: ошибиться адресом можно снова, а тело ответа
из сети показывать владельцу счёта нельзя никогда.

Разделение восстановлено не уговором «сюда не подставлять», а тем, что
**тело физически не попадает в `technical`**: туда идут код отказа (если тело
вообще от брокера) и описание тела — вид и длина, без единого символа из него.

`str(исключение)` возвращает **человеческий** текст. Это сделано нарочно:
где-нибудь обязательно напишут `f"{ошибка}"` и покажут результат в окне.
Все три поля проходят через `scrub`, поэтому даже отказ, в тело которого
брокер вложил токен, наружу его не вынесет.

Классификация — по официальной документации БКС Trade API (таблицы «Описание
исключительных ситуаций» у каждого сервиса): 401 UNAUTHORIZED, 400
VALIDATION_ERROR и BAD_REQUEST, 404 NOT_FOUND, 5xx INTERNAL_SERVER_ERROR.
Отказа по частоте запросов (429) в этих таблицах **нет** — см. `Throttled`.
"""

from __future__ import annotations

import json
import re
from typing import Any, Final, Mapping

from broker.redaction import scrub

#: Сколько символов тела ответа оставляем для технического лога. Тело
#: приходит из сети и по длине ничем не ограничено: страница ошибки шлюза
#: бывает и на десятки килобайт, а запись журнала такой длины технический лог
#: не читает, а забивает.
MAX_DETAILS: Final[int] = 500


def body_details(body: str) -> str:
    """Тело ответа в том виде, в каком его можно положить в технический лог.

    Чистка **до** обрезки, а не после, и это не порядок ради порядка: обрезка
    поперёк значения оставила бы половину токена, которую ни один образец
    `redaction` уже не узнает, — а требование ТЗ §4.1 говорит «ни целиком,
    ни частично».
    """
    return scrub(body)[:MAX_DETAILS]


class BrokerError(Exception):
    """Общий предок отказов слоя `broker/`."""

    #: Можно ли повторить тот же запрос и рассчитывать на другой исход.
    retryable: bool = False

    def __init__(self, human: str, technical: str = "", *, details: str = "") -> None:
        self.human = scrub(human)
        self.technical = scrub(technical)
        #: Сырое тело ответа брокера — единственное поле, содержимое которого
        #: пришло из сети и по составу не ограничено ничем. Наружу само
        #: не выходит: ни `str`, ни `repr`, ни `technical` его не включают.
        self.details = body_details(details)
        super().__init__(self.human)

    def __str__(self) -> str:
        return self.human

    def __repr__(self) -> str:
        return f"{type(self).__name__}({self.human!r})"


