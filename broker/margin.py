"""Гарантийное обеспечение под один контракт: откуда его брать до первого входа.

Замкнутый круг, ради которого модуль заведён
--------------------------------------------
Предохранитель запаса свободных средств делит свободные деньги на ГО одного
контракта — иначе он не знает, сколько контрактов брать. По HTTP у брокера
ГО контракта берётся **только** из открытой позиции: `lockedForFutures`
делённое на количество. Значит перед первым входом за день числа нет,
а без числа предохранитель слеп — и так каждый день.

⚠️ **Прямого поля у брокера нет ни в одном методе.** Проверено 05.09.2026
по оглавлению и по всем схемам официального PDF, а не по памяти:

* `futuresParameters.futuresPortfolio[].futuresCollateral` («Маржинальные
  показатели», вебсокет) — ГО **позиции**; массив, дословно: «при отсутствии
  позиций приходит пустой массив». Круга не разрывает;
* `marginParameters.collateral`, `fortsStability.ownFunds` — по портфелю
  целиком, не по контракту;
* «Лимиты»: `cbplUsedForPositions`, `cbplUsedForOrders` — тоже по портфелю;
* справочник инструментов — поля ГО не содержит вовсе;
* «Получение дисконтов» отдаёт `discountLong` и `discountShort` по тикеру
  и от портфеля не зависит. Это **кандидат**: ставка, умноженная на стоимость
  контракта, даёт ГО. Но документация нигде не говорит, что ставка применима
  к фьючерсу именно так, а стоимость контракта в рублях сама выводится
  (цена × стоимость пункта). Две невыверенные догадки подряд для числа,
  которым считаются деньги, — недопустимо. Проверить живым токеном
  и заменить этот модуль, если подтвердится.

Значит источник — биржа
-----------------------
MOEX ISS отдаёт `INITIALMARGIN` — **биржевое** ГО под контракт, бесплатно
и без токена, тем же путём, которым грузятся свечи (решение 0041, поле уже
читается в `market.iss.InstrumentSpec`). Замер 05.09.2026: у `MXU6` биржа
объявила 23 124,62 ₽, а в окне владельца счёта брокер требовал 38 526 ₽ —
надбавка 1,666.

⚠️ **Биржевое ГО как есть брать нельзя.** Оно ниже брокерского, а ошибка вниз
означает «взяли контрактов больше, чем позволит брокер» и отказ на заявке.
Поэтому наружу отдаётся биржевое ГО, умноженное на надбавку с запасом,
и число **помечено оценочным** везде, где показывается.

Направление ошибки выбрано осознанно
------------------------------------
`floor(свободные / ГО)`: занижение ГО даёт лишние контракты и отказ брокера,
завышение — недобор объёма. На тонком счёте завышение способно дать ноль
контрактов, то есть **пропущенный сигнал**, и это названо вслух, а не спрятано.
Выбрано завышение: пропущенная сделка стоит упущенной прибыли, а отказ заявки
посреди окна — это ещё и неизвестность, в какой позиции робот.

Слой
----
Ни одного запроса отсюда не уходит. Модуль принимает числа и отвечает числом
с пометкой, откуда оно; кто и где их добыл — забота сборки.
"""

from __future__ import annotations

import enum
from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Final

__all__ = [
    "BROKER_MARKUP",
    "BROKER_MEMORY",
    "EXCHANGE_MEMORY",
    "MarginBook",
    "MarginPerContract",
    "MarginSource",
]

#: Во сколько раз брокерское ГО больше биржевого — оценка сверху.
#:
#: ⚠️ **Замер один, и он не наш.** 38 526 ₽ в окне владельца счёта против
#: 23 124,62 ₽ у биржи по `MXU6` 05.09.2026 даёт 1,666. Одно наблюдение,
#: один инструмент, один день; способа спросить надбавку у брокера в API нет.
#:
#: Взято 2,0, а не измеренные 1,666, по одной причине: число обязано быть
#: **верхней** границей. Оценка ниже настоящей даёт лишние контракты и отказ
#: брокера, оценка выше — недобор объёма. Двадцать процентов сверх
#: единственного замера — это запас на другой инструмент и другой день.
#:
#: Цена запаса названа честно: при свободных 120 000 ₽ и настоящем ГО
#: 38 526 ₽ брокер позволил бы три контракта, а по оценке 46 249 ₽ робот
#: возьмёт два. При свободных 40 000 ₽ брокер позволил бы один, а робот
#: не возьмёт ни одного и пропустит сигнал.
#:
#: Число подлежит замене на измеренное при первом же живом подключении:
#: как только у робота была открытая позиция, надбавка вычисляется точно —
#: `lockedForFutures / количество / INITIALMARGIN`.
BROKER_MARKUP: Final[float] = 2.0

#: Сколько живёт брокерское ГО, снятое с закрытой уже позиции.
#:
#: Биржа пересматривает обеспечение на клиринге — промежуточном 14:00–14:05
#: и вечернем 18:45–19:00 МСК, — а внутри клирингового отрезка оно не меняется.
#: Торговое окно 10:05–11:00 лежит внутри одного отрезка целиком и короче часа,
#: поэтому час — верхняя граница, за которой число перестаёт считаться
#: своим для текущего отрезка. Старше — не «примерно верно», а неизвестно.
BROKER_MEMORY: Final[timedelta] = timedelta(hours=1)

#: Сколько живёт биржевое ГО. Тот же довод, что у брокерского, и то же число:
#: `INITIALMARGIN` меняется на клиринге. Держится отдельной величиной, потому
#: что перечитываются они по-разному: брокерское приходит с каждым снимком
#: счёта, биржевое — отдельным запросом к бирже.
EXCHANGE_MEMORY: Final[timedelta] = timedelta(hours=1)


class MarginSource(enum.Enum):
    """Откуда взялось ГО контракта. Порядок объявления — порядок точности."""

    #: Из открытой позиции прямо сейчас: `lockedForFutures / количество`.
    #: Это ответ брокера, а не оценка.
    BROKER_POSITION = "брокер, по открытой позиции"
    #: Брокерское число, снятое раньше в этом сеансе, пока позиция была.
    #: Тот же клиринговый отрезок — значит то же ГО.
    BROKER_RECENT = "брокер, по недавней позиции"
    #: Биржевое ГО с надбавкой. **Оценка**, а не ответ брокера.
    EXCHANGE_ESTIMATE = "оценка по биржевому ГО"


@dataclass(frozen=True, slots=True)
class MarginPerContract:
    """ГО под один контракт с указанием, откуда число и насколько ему верить.

    `told` — фраза для журнала решений и для окна. Она обязана быть, потому
    что число из оценки и число от брокера выглядят одинаково, а стоят
    разного: по оценке робот может взять меньше контрактов, чем позволил бы
    брокер, и владелец счёта имеет право знать, почему объём урезан.
    """

    rubles: float
    source: MarginSource
    told: str
    measured_at: datetime

    @property
    def estimated(self) -> bool:
        """Оценка это или ответ брокера. Ветвление снаружи по `source` не нужно."""
        return self.source is MarginSource.EXCHANGE_ESTIMATE


def _rubles(value: float) -> str:
    """Рубли для человека: разряды неразрывным пробелом, копейки запятой.

    Так же, как в `AccountSnapshot.human_summary`, и по той же причине:
    `f"{x:,.2f}"` даёт «46,249.24» — американскую запись, в которой запятая
    означает не то, что здесь прочтут. Пробел неразрывный, чтобы число
    не разъезжалось по строкам окна.
    """
    return f"{value:,.2f}".replace(",", "\u00a0").replace(".", ",") + " \u20bd"


class MarginBook:
    """Что известно о ГО контракта **одного** инструмента.

    ⚠️ Одна книга — один тикер. ГО у контрактов разное (замер 05.09.2026:
    `MXU6` 23 124,62 ₽, `GZU6` 1 567,22 ₽ — разница в пятнадцать раз), и книга,
    пережившая смену инструмента, посчитала бы деньги по чужому контракту.
    Смена тикера обязана звать `forget`.

    Состояние здесь есть намеренно, и это не кэш ради экономии запросов:
    брокерское ГО существует только в те минуты, когда позиция открыта,
    а нужно оно ровно тогда, когда её нет.
    """

    def __init__(self) -> None:
        self._broker: tuple[float, datetime] | None = None
        self._exchange: tuple[float, datetime] | None = None

    def forget(self) -> None:
        """Забыть всё: инструмент сменился."""
        self._broker = None
        self._exchange = None

    def broker_said(self, per_contract: float | None, at: datetime) -> None:
        """Принять ГО, выведенное из открытой позиции. `None` и ноль — не принимать.

        `None` означает «позиции нет», а не «ГО нулевое», и стирать по нему
        память нельзя: ради этого случая память и заведена.
        """
        if per_contract is not None and per_contract > 0:
            self._broker = (per_contract, at)

    def exchange_said(self, initial_margin: float | None, at: datetime) -> None:
        """Принять биржевое `INITIALMARGIN`. Ноль и отрицательное — не число.

        Ноль здесь означал бы «обеспечения не требуется», то есть разрешение
        взять сколько угодно контрактов, — поэтому он отвергается, а не
        записывается как есть.
        """
        if initial_margin is not None and initial_margin > 0:
            self._exchange = (initial_margin, at)

    def exchange_age(self, now: datetime) -> timedelta | None:
        """Сколько лет биржевому числу. `None` — его нет вовсе.

        Спрашивает **сборка**, чтобы решить, не пора ли сходить на биржу
        заново: как часто ходить — политика источника, а слой брокера
        по собственному почину не опрашивает никого.
        """
        if self._exchange is None:
            return None
        return now - self._exchange[1]

    def markup_seen(self) -> float | None:
        """Настоящая надбавка брокера, если оба числа известны. Иначе `None`.

        Ради неё в отчёт и попадает пара «биржевое / брокерское»:
        `BROKER_MARKUP` взят из одного чужого наблюдения, и первый же день
        с открытой позицией даёт измеренное значение вместо него.
        """
        if self._broker is None or self._exchange is None:
            return None
        exchange = self._exchange[0]
        return self._broker[0] / exchange if exchange > 0 else None

    def best(
        self, now: datetime, *, open_position: float | None = None
    ) -> MarginPerContract | None:
        """Лучшее из известного. `None` — не знаем ничего, и это честный ответ.

        Порядок — по точности, а не по свежести: ответ брокера точнее оценки
        даже будучи получасовой давности, потому что внутри клирингового
        отрезка ГО не меняется. Возраст при этом ограничен (`BROKER_MEMORY`):
        число из вчерашнего клиринга — уже не «примерно верно».

        `open_position` — ГО, выведенное из позиции **на этот момент**
        (`AccountSnapshot.margin_per_contract`). Передаётся сюда, а не берётся
        книгой самой: слой брокера не опрашивает никого по своему почину.
        """
        if open_position is not None and open_position > 0:
            self.broker_said(open_position, now)
            return MarginPerContract(
                rubles=open_position,
                source=MarginSource.BROKER_POSITION,
                told=(
                    f"ГО под контракт {_rubles(open_position)} — брокер, "
                    "по открытой позиции"
                ),
                measured_at=now,
            )
        recent = self._fresh(self._broker, now, BROKER_MEMORY)
        if recent is not None:
            value, at = recent
            return MarginPerContract(
                rubles=value,
                source=MarginSource.BROKER_RECENT,
                told=(
                    f"ГО под контракт {_rubles(value)} — брокер, по позиции "
                    f"от {at.astimezone():%H:%M:%S}; позиции сейчас нет, "
                    "но обеспечение внутри клирингового отрезка не меняется"
                ),
                measured_at=at,
            )
        estimate = self._fresh(self._exchange, now, EXCHANGE_MEMORY)
        if estimate is None:
            return None
        exchange, at = estimate
        value = exchange * BROKER_MARKUP
        return MarginPerContract(
            rubles=value,
            source=MarginSource.EXCHANGE_ESTIMATE,
            told=(
                f"ГО под контракт {_rubles(value)} — ОЦЕНКА, а не ответ "
                f"брокера: биржевое ГО {_rubles(exchange)} с надбавкой "
                f"×{BROKER_MARKUP:g} на требования брокера. Брокер своего ГО "
                "до первой позиции не сообщает; объём может быть занижен"
            ),
            measured_at=at,
        )

    @staticmethod
    def _fresh(
        remembered: tuple[float, datetime] | None, now: datetime, life: timedelta
    ) -> tuple[float, datetime] | None:
        """Запомненное число, если оно ещё живо. Иначе `None`.

        Отрицательный возраст (снимок «из будущего») тоже негоден: он бывает
        при разошедшихся часах, и молча принимать его значит считать деньги
        по числу неизвестного возраста.
        """
        if remembered is None:
            return None
        age = now - remembered[1]
        if age < timedelta(0) or age > life:
            return None
        return remembered
