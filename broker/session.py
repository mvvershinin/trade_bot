def _bare(path: str) -> str:
    """Путь без строки запроса и без хвостового слэша.

    Одна функция на всех, кто приводит адрес к сравнимому виду: пометка
    неверного адреса (`address_is_wrong`), разбор ответа шлюза
    (`_wrong_address`), ключ таблицы повторов в `_with_retries` и разбор
    отказа в `_refused_why`. Два написания одного правила разъехались бы
    молча.

    ⚠️ **В сторож допуска (`_guard`) эта функция больше не входит** (правка
    06.09.2026, находка Н-5). Сторож сверяет строку ровно в том виде, в каком
    она уйдёт в сеть: нормализация перед проверкой означала бы «сверяем одно,
    отправляем другое». Расхождение теперь не приводится к белому списку,
    а называется вслух отказом.
    """
    return path.split("?", 1)[0].rstrip("/")


#: Что слою МОЖНО спросить у брокера на этапе 1: **пара «глагол и адрес»**.
#: Всё остальное — отказ.
#:
#: Здесь стоял чёрный список кусков адреса ("/orders", "/order/", "/cancel",
#: "/transaction"), и он пропускал 9 правдоподобных написаний адреса заявки
#: из 11: единственное число без слэша на конце ("/api/v1/order") не совпадало
#: ни с одним куском. Его собственный тест был параметризован двумя адресами,
#: оба содержали "/orders", то есть проверял список против самого себя.
#:
#: Белый список не требует угадывать, как брокер назовёт адрес заявки:
#: незнакомая пара отвергается по умолчанию. Заявки — этап 2, и появятся
#: они отдельной осознанной строкой здесь, а не по копипасте из документации.
#:
#: ⚠️ **Почему пара, а не адрес** (правка 06.09.2026 по разбору `/risk`).
#: Ни глагол, ни адрес по отдельности чтения от торговли не отделяют.
#: По одному адресу `/trade-api-bff-operations/api/v1/orders` у БКС живут
#: два разных дела: `GET` отдаёт статус заявки, `POST` её создаёт (выписки
#: `.docs/broker-api/11-get-order-by-id.md` и `13-create-order.md`).
#: И наоборот: `POST` бывает чистым чтением — справочник инструментов
#: по тикерам и поиск заявок оба `POST` с телом и оба не меняют ничего
#: (`19-instruments.md`, `15-orders-search.md`).
#:
#: Отсюда же убрана константа `READ_METHODS` («глаголы, которыми слой
#: читает»). Понятие ложное: читающего глагола не существует, читает пара.
#: Именно эта константа делала таблицу повторов декартовым произведением
#: и выдавала каждому адресу белого списка **оба** глагола разом.
#:
#: ⚠️ `scope=TRADE` этот список не открывает и открыть не может: в нём только
#: чтение, и торговый токен ходит по тем же адресам, что читающий.
