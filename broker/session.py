def _bare(path: str) -> str:
    """Путь без строки запроса и без хвостового слэша.

    Одна функция на всех, кто приводит адрес к сравнимому виду: пометка
    неверного адреса (`address_is_wrong`), разбор ответа шлюза
    (`_wrong_address`), ключ таблицы повторов в `_with_retries` и разбор
    отказа в `_refused_why`. Два написания одного правила разъехались бы
    молча.

    ⚠️ **В сторож допуска (`_guard`) эта функция больше не входит** (правка
    06.09.2026, находка Н-5). Сторож сверяет строку ровно в том виде, в каком
    она уйдёт в сеть: нормализация перед проверкой означала бы «сверяем одно,
    отправляем другое». Расхождение теперь не приводится к белому списку,
    а называется вслух отказом.
    """
    return path.split("?", 1)[0].rstrip("/")


