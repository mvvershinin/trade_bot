OUTAGE: Final[tuple[type[BrokerError], ...]] = (NoConnection, Timeout, ServerFailure)


class BrokerSession:
    """Одно подключение к брокеру: токен, транспорт, отказы, состояние связи.

    Заявок не подаёт. Кэша нет намеренно: `DOMAIN.md` §5 требует видеть
    свободные средства **до** заявки, а биржа пересматривает гарантийное
    обеспечение внутри дня — значение получасовой давности здесь негодно.
    """

    def __init__(
        self,
        store: TokenStore,
        *,
        client: httpx.AsyncClient | None = None,
        clock: Callable[[], datetime] = now_utc,
        timeout: float = DEFAULT_TIMEOUT,
        attempts: int = DEFAULT_ATTEMPTS,
        throttle: Throttle | None = None,
        backoff: Backoff | None = None,
        sleep: Callable[[float], Any] = asyncio.sleep,
    ) -> None:
        install_redaction()
        self._store = store
        self._clock = clock
        self._timeout = timeout
        self._attempts = max(1, attempts)
        self._throttle = throttle or Throttle()
        self._backoff = backoff or Backoff()
        self._sleep = sleep
        self._owns_client = client is None
        self._client = client or httpx.AsyncClient(base_url=API_BASE, timeout=timeout)

        self._stored: StoredToken | None = None
        self._access: AccessToken | None = None
        self._auth_lock = asyncio.Lock()
        self.connection = ConnectionState()
        #: Что известно о расхождении часов машины с часами брокера.
        #: Заполняется по заголовку `Date` каждого ответа, ни одного лишнего
        #: запроса не стоит. Говорит об этом `app/`: слой брокера с человеком
        #: не разговаривает (`_note_failure`).
        self.clock = ClockWatch()
        #: Адреса из `ADDRESS_SENSITIVE`, на которые шлюз брокера уже ответил
        #: 404 без кода отказа. Помечаются **на сеанс**: адрес зашит в код
        #: программы и сам собой не исправится, а догрузка пропущенного
        #: запускается на каждом подключении. Без пометки владелец счёта
        #: получал бы одну и ту же строку на каждом переподключении,
        #: а их у него много.
        self._wrong_addresses: set[str] = set()

    # --- жизненный цикл ---

    async def __aenter__(self) -> "BrokerSession":
        return self

    async def __aexit__(self, *exc_info: object) -> None:
        await self.close()

    async def close(self) -> None:
        if self._owns_client:
            await self._client.aclose()

    # --- токен ---

    def stored(self) -> StoredToken:
        """Токен из файла. Читается один раз за сеанс."""
        if self._stored is None:
            self._stored = self._store.load()
        return self._stored

    def cabinet_token(self) -> RefreshToken:
        return self.stored().token

    def token_notice(self) -> TokenNotice:
        """Обратный отсчёт до конца срока токена и предупреждение за 10 дней."""
        return self.cabinet_token().notice(self._clock())

    def can_trade(self) -> bool:
        return self.cabinet_token().scope.can_trade

    def require_trade_rights(self) -> None:
        """Предохранитель боевого режима: на токене для чтения он не включается.

        Пункт приёмки Э1-4 (`/risk`): «тип токена определяется, боевой режим
        на токене „только чтение“ не включается».

        ⚠️ Тип берётся из того, что владелец счёта указал при вводе токена,
        и передаётся брокеру полем `client_id`. Способа **спросить** тип
        у брокера отдельным запросом документация не описывает; ответ сервиса
        авторизации содержит поле `scope`, но состав его значений
        в документации не задан, поэтому решение на нём не строится.
        """
        scope = self.cabinet_token().scope
        if not scope.can_trade:
            raise ReadOnlyToken(f"тип токена в файле настроек: {scope.value}")

    async def access_token(self) -> AccessToken:
        """Действующий рабочий токен. Обменивает и обновляет сам.

        Обмен под замком: без него десять одновременных запросов на старте
        дали бы десять обменов подряд — и это первый способ упереться
        в ограничение частоты на ровном месте.
        """
        current = self._access
        now = self._clock()
        if current is not None and not current.stale(now, ACCESS_REFRESH_MARGIN):
            return current

        async with self._auth_lock:
            current = self._access
            now = self._clock()
            if current is not None and not current.stale(now, ACCESS_REFRESH_MARGIN):
                return current
            return await self._exchange()

    async def _exchange(self) -> AccessToken:
        """Обменять токен личного кабинета на рабочий."""
        stored = self.stored()
        token = stored.token
        now = self._clock()

        if token.expired(now):
            raise TokenExpired(f"срок токена вышел {token.expires_at.isoformat()}")

        # Значение достаётся в отдельную короткую переменную, а не подставляется
        # выражением прямо в словарь: имя поля рядом с длинным выражением —
        # тот самый образец, который ищет детектор секретов в tests/test_layers.py,
        # и продуктовый файл попадал бы в его отчёт наравне с настоящей утечкой.
        raw = token.secret.reveal()
        form = {
            "client_id": token.scope.client_id,
            "grant_type": "refresh_token",
            "refresh_token": raw,
        }
        del raw

        # Очистка обязана быть в `finally`. Если оставить её после `await`,
        # на пути исключения она не выполнится, кадр этой функции попадёт
        # в `__traceback__` поднятого отказа, и сырой 90-дневный токен окажется
        # в переменных кадра. Обычный `format_exception` его не печатает, поэтому
        # проверка ищет его через `capture_locals=True` — иначе дыра невидима.
        # Выстреливает на обрыве связи в момент обмена, то есть на основном
        # сценарии отказа по ТЗ §4.9.
        try:
            payload = await self._auth_post(form)
        finally:
            form.clear()

        # Один `try/finally` на весь разбор ответа, а не на его хвост.
        #
        # Прежде защита стояла только вокруг построения `AccessToken`, и два
        # более ранних отказа — «тело не объект» и «поля токена нет» — улетали
        # мимо неё, оставляя сырое тело ответа в переменных кадра. Утечкой это
        # становится, когда сервис возвращает токен в постороннем поле того же
        # тела: такое его поведение уже наблюдалось — есть отдельная проверка
        # на то, что он присылает наш токен обратно в тексте отказа.
        #
        # `finally` выполняется на всех путях: и на отказе, и на успехе.
        # Затираем значением, а потом `del`: одного `del` мало, если
        # трассировку соберут раньше, чем сборщик мусора дойдёт до строки.
        value: str | None = None
        try:
            if not isinstance(payload, Mapping):
                raise UnexpectedAnswer(
                    "сервис авторизации ответил не объектом",
                    "авторизация: тело ответа не является объектом JSON",
                )

            value = payload.get("access_token")
            if not isinstance(value, str) or not value:
                raise UnexpectedAnswer(
                    "в ответе сервиса авторизации нет рабочего токена",
                    "авторизация: поле рабочего токена отсутствует или пусто",
                )

            lifetime = _seconds(payload.get("expires_in"), ACCESS_LIFETIME)
            try:
                secret = Secret(value)
            except ValueError:
                # `Secret` отвергает значение с посторонним символом. Отказ
                # обязан выйти из слоя как `BrokerError`: голый `ValueError`
                # разбор отказов выше не ловит, и «сервис ответил не тем»
                # читалось бы как дефект программы. Сценарий не выдуманный:
                # шлюз между брокером и клиентом правит тело, а сервис при
                # внутренней ошибке отвечает 200 с текстом вместо токена.
                raise UnexpectedAnswer(
                    "рабочий токен от сервиса авторизации содержит посторонние "
                    "символы",
                    "авторизация: значение рабочего токена не прошло проверку "
                    "состава символов",
                ) from None
            access = AccessToken(
                secret=secret,
                expires_at=self._clock() + lifetime,
                scope=token.scope,
                scope_reported=_text(payload.get("scope")),
            )
        finally:
            value = ""
            payload = {}
            del value, payload

        self._access = access
        log().info(
            "рабочий токен получен, срок до %s, права %s",
            access.expires_at.isoformat(),
            token.scope.value,
        )
        return access

    async def _auth_post(self, form: dict[str, str]) -> object:
        """Запрос к сервису авторизации. **Повторяется: стоит в `REPEATABLE`.**

        Обмен ничего не меняет ни на счёте, ни у брокера: при удаче выдаётся
        ещё один рабочий токен на сутки, и всё. Токен личного кабинета обменом
        не тратится — его срок 90 дней, и живёт он до замены в кабинете (замер
        04.09.2026: `refresh_expires_in` ≈ 90 суток). Без повтора обычный обрыв
        связи на старте валил бы подключение целиком.

        Отдельным методом, а не строкой в `_exchange`: тот и без того длинный,
        и длина его оправдана — там стирается секрет из памяти, а разнос по
        методам удлиняет жизнь секрета в процессе. Здесь наоборот: `form`
        передан **той же** ссылкой, `form.clear()` в `_exchange` опустошает
        его на всех путях, и лишний кадр в трассировке несёт уже пустой
        словарь. Проверяется это `tests/test_broker_no_leak.py`, где кадры
        читаются с `capture_locals=True`.
        """
        return await self._with_retries(
            "POST",
            AUTH_EXCHANGE,
            lambda: self._client.post(AUTH_URL, data=form, timeout=self._timeout),
        )

    # --- запросы ---

    async def read(
        self,
        path: str,
        *,
        method: str = "GET",
        params: Mapping[str, Any] | None = None,
        json: Any = None,
    ) -> Any:
        """Запрос на чтение. Заявки этим методом подать нельзя — и это проверка.

        Сторожится **пара «глагол и адрес»**, а не адрес отдельно (правка
        06.09.2026, находка Н-3). `POST` сам по себе не признак торговли:
        справочник инструментов по тикерам у БКС — это `POST` с телом
        и чистое чтение. И наоборот, `GET` сам по себе не признак чтения:
        разрешить любой глагол по знакомому адресу значит открыть дорогу
        подаче заявки через метод, который называется `read`.

        Глагол приводится к верхнему регистру **до** сторожа, и дальше идёт
        именно приведённый: сверяется и отправляется одна и та же строка.
        По той же причине путь не нормализуется вовсе — расхождение
        отвергается, а не приглаживается (находка Н-5).

        Адрес, признанный неверным (`ADDRESS_SENSITIVE`), отвергается **без
        запроса**: одного ответа шлюза за сеанс достаточно, адрес зашит в код
        и сам собой не исправится. Смысл не в экономии запросов, а в тишине —
        иначе на каждом переподключении в журнал уходила бы новая строка
        про одно и то же.
        """
        verb = method.upper()
        self._guard(verb, path)
        if self.address_is_wrong(path):
            raise self._wrong_address_error(_bare(path), repeated=True)
        # Повтор разрешает не этот вызов, а таблица `REPEATABLE` — отдельная
        # от белого списка и выписанная руками. Повторить чтение можно сколько
        # угодно раз: на счёте от него не меняется ничего. Слова «повторяй»
        # здесь нет нарочно — его написал бы и тот, кто придёт сюда с подачей
        # заявки (`B-002`).
        return await self._with_retries(
            verb,
            path,
            lambda: self._authorized(verb, path, params=params, json=json),
        )

    def address_is_wrong(self, path: str) -> bool:
        """Признан ли адрес неверным в этом сеансе: шлюз брокера его не знает.

        Публичный вопрос, а не внутренняя мелочь: вызывающий (`app/`) вправе
        спросить **до** того, как затеет длинную работу вокруг этого метода,
        и не показывать владельцу счёта отказ во второй раз. Тот же смысл
        несёт поле `WrongAddress.repeated` — на случай, когда спросить
        заранее негде.
        """
        return _bare(path) in self._wrong_addresses

    def _wrong_address_error(
        self,
        bare: str,
        *,
        repeated: bool,
        technical: str = "",
        details: str = "",
    ) -> WrongAddress:
        """Отказ «адреса у брокера нет» по таблице текстов.

        Новый объект на каждый вызов, а не сохранённый: одно и то же
        исключение, поднятое дважды, накапливает `__traceback__` предыдущих
        подъёмов — а в кадрах трассировки этого слоя живут заголовки запросов.

        Оба технических текста идут **через конструктор**, а не присваиванием
        полю: чистка от секретов живёт в `BrokerError.__init__`, и поле,
        заполненное в обход, её не проходит.
        """
        what, consequence = ADDRESS_SENSITIVE[bare]
        error = WrongAddress(
            what,
            consequence,
            technical or f"{bare}: шлюз брокера не знает этого адреса",
            details=details,
        )
        error.repeated = repeated
        return error

    @staticmethod
    def _guard(method: str, path: str) -> None:
        """Пропустить только пару, названную в `READ_ENDPOINTS`. Иначе отказ.

        Две ветки, и обе — про допуск, а не про диагноз. Разбор, **чем
        именно** пара не подошла, живёт в `_refused_why`: он длиннее самого
        сторожа и к решению «пускать или нет» отношения не имеет.
        """
        # Абсолютный URL проверяется первым: httpx игнорирует `base_url`,
        # когда путь абсолютный, поэтому строка с полным адресом уводит
        # запрос на боевой хост брокера мимо всех настроек транспорта —
        # включая подставной хост в тестах.
        if "://" in path or path.startswith("//"):
            raise RuntimeError(
                f"адрес {path} задан целиком. Слой broker/ принимает только "
                "путь: полный адрес уходит мимо настроек транспорта, в том "
                "числе мимо подставного хоста в тестах"
            )
        if (method, path) not in READ_ENDPOINTS:
            raise RuntimeError(_refused_why(method, path))

    async def _authorized(
        self,
        method: str,
        path: str,
        *,
        params: Mapping[str, Any] | None,
        json: Any,
    ) -> httpx.Response:
        access = await self.access_token()
        # Тот же `try/finally`, что вокруг `form` в `_exchange`, и по той же
        # причине. Здесь в словаре лежит строка `Bearer <рабочий токен>` —
        # сутки полного доступа к счёту.
        #
        # `_with_retries` ловит только исключения httpx. Всё остальное проходит
        # этот кадр насквозь и уносит словарь в трассировку: `CancelledError`
        # при закрытии окна или нажатии «Стоп» посреди запроса портфеля,
        # `MemoryError`, `RuntimeError` из чужого кода. Отменённую задачу
        # asyncio штатно печатает через `loop.call_exception_handler`, то есть
        # утечка случается не в редком отказе, а при обычном выходе программы.
        # Проверено прогоном 30.08.2026: до правки все три отказа выносили
        # заголовок целиком, отказ связи — нет.
        headers = {"Authorization": f"Bearer {access.secret.reveal()}"}
        sent_at = self._clock()
        try:
            response = await self._client.request(
                method,
                path,
                params=params,
                json=json,
                headers=headers,
                timeout=self._timeout,
            )
        finally:
            headers.clear()
        # Сверка часов машины с часами брокера — **бесплатно и по пути**:
        # заголовок `Date` есть в каждом ответе, отдельного метода «который
        # час» в API БКС нет вовсе. Замер стоит после `finally`, то есть
        # секрет к этому моменту уже стёрт из кадра; ни одного заголовка
        # запроса в замер не попадает — только время ответа.
        #
        # Зачем это здесь: годность снимка счёта и закрытие свечи по часам
        # считаются как «серверное минус наше», и разошедшиеся часы
        # останавливают торговлю на день (`broker/clock.py`).
        self.clock.observed(
            response.headers.get("Date"), sent_at=sent_at, received_at=self._clock()
        )
        return response

    async def _with_retries(
        self, method: str, where: str, send: Callable[[], Any]
    ) -> Any:
        """Отправить запрос, пережив отказ, которому помогает повтор.

        **Повтор требует двух разных разрешений, и они не одно и то же.**

        1. `error.retryable` — «повтор может помочь»: отказ временный
           (нет связи, таймаут, 5xx, 429), а не «запрос неверен».
        2. `(method, where) in REPEATABLE` — «повтор безопасен»: обращение
           не меняет ничего ни на счёте, ни у брокера. Спрашивается
           **у таблицы**; вызывающий об этом не спрашивается вовсе, и почему —
           сказано у самой таблицы (`B-002`). Глагол входит в ключ потому,
           что подача заявки и чтение её статуса у БКС различаются только им.

        Обращение вне таблицы, оставшееся без окончательного ответа, повтора
        не получает: поднимается `OutcomeUnknown` — «исход неизвестен».
        Окончательный отказ (400, 401, 404) остаётся собой: брокер сказал,
        что запрос отвергнут, гадать не о чем и пугать человека нечем.
        """
        repeatable = (method.upper(), _bare(where)) in REPEATABLE
        last: BrokerError | None = None
        for attempt in range(1, self._attempts + 1):
            await self._throttle.acquire()
            try:
                response = await send()
            except httpx.TimeoutException as error:
                last = Timeout(self._timeout, f"{where}: {type(error).__name__}")
            except httpx.TransportError as error:
                last = NoConnection(f"{where}: {type(error).__name__}")
            except httpx.HTTPError as error:
                # Прочие ошибки httpx: текст исключения библиотеки в человеческий
                # текст не переносится — там бывает и адрес, и заголовки.
                last = NoConnection(f"{where}: {type(error).__name__}")
            else:
                outcome = self._interpret(where, response)
                if isinstance(outcome, BrokerError):
                    last = outcome
                else:
                    self._note_online()
                    return outcome

            self._note_failure(last)
            if not last.retryable:
                raise last
            if not repeatable:
                raise self._outcome_unknown(where, last)
            if attempt == self._attempts:
                raise last
            await self._sleep(self._backoff.delay(attempt))

        raise last if last is not None else ServerFailure(f"{where}: без ответа")

    @staticmethod
    def _outcome_unknown(where: str, cause: BrokerError) -> OutcomeUnknown:
        """Отказ «исход неизвестен» вместо повтора: и вслух, и в лог.

        Молчание здесь — самостоятельный дефект, а не мелочь (правило 13
        `CLAUDE.md`). Программа знает, что состояние операции ей неизвестно,
        и обязана это сказать словами. Обычный `Timeout` сказал бы обратное:
        его текст обещает владельцу счёта «попробуем ещё раз», а повтора
        не будет — и заявка, возможно, уже живёт у брокера.

        Человеческий текст живёт в `OutcomeUnknown`; сюда, в технический лог,
        идут причина и адрес. Тело ответа переносится в `details` — оттуда
        его печатает `_note_technical` уровнем DEBUG, и в текст для человека
        оно не попадает по построению.

        Новый объект на каждый вызов — по той же причине, что
        у `_wrong_address_error`: одно и то же исключение, поднятое дважды,
        накапливает трассировки, а в кадрах этого слоя живут заголовки
        запросов.
        """
        error = OutcomeUnknown(
            f"{cause.technical or f'{where}: {type(cause).__name__}'}"
            "; исход операции неизвестен, повтор запрещён",
            details=cause.details,
        )
        log().warning("исход запроса неизвестен: %s", error.technical)
        return error

    def _interpret(self, where: str, response: httpx.Response) -> Any:
        status = response.status_code
        if status >= 400:
            body = scrub(response.text)
            gone = self._wrong_address(where, body) if status == HTTP_NOT_FOUND else None
            if gone is not None:
                return gone
            error = from_status(status, where=where, body=body)
            if isinstance(error, AuthFailed):
                # Рабочий токен мог протухнуть раньше срока: токен личного
                # кабинета удаляют в кабинете, и все выпущенные по нему
                # рабочие токены умирают вместе с ним.
                self._access = None
            return error
        try:
            return response.json()
        except ValueError:
            return UnexpectedAnswer(
                "ответ пришёл не в формате JSON",
                f"{where}: HTTP {status}, тело длиной {len(response.content)} байт",
            )

    def _wrong_address(self, where: str, body: str) -> WrongAddress | None:
        """404, означающий «такого адреса у брокера нет». Иначе `None`.

        ⚠️ **404 на этом API двузначен**, и в этом вся суть метода. Для свечей
        официальный PDF называет `404 NOT_FOUND` штатным ответом «данные
        не найдены»; тот же 404 приходит и на неверное имя сервиса в адресе.
        Спутать их дорого в обе стороны: принять свою ошибку за «нет данных»
        значит молча остаться без догрузки навсегда, а принять «нет данных»
        за свою ошибку — погасить рабочий метод до перезапуска программы.

        Разводятся два признака сразу, и оба нужны.

        1. **Путь назван в `ADDRESS_SENSITIVE`** — то есть решение гасить
           метод до перезапуска по нему принято вслух.
        2. **В теле нет кода отказа брокера** (`errors.code_of`). Отказ
           сервиса брокера — объект JSON с кодом; ответ шлюза приходит
           страницей его nginx либо пустым телом. Это ровно тот признак,
           по которому 05.09.2026 стало видно, что до сервиса свечей запрос
           не доходил вовсе.

        Пометка ставится **здесь**, а не у вызывающего: это единственное
        место, куда приходит ответ шлюза.
        """
        bare = _bare(where)
        if bare not in ADDRESS_SENSITIVE or code_of(body) is not None:
            return None
        error = self._wrong_address_error(
            bare,
            repeated=bare in self._wrong_addresses,
            technical=(
                f"{where}: HTTP {HTTP_NOT_FOUND} без кода отказа брокера "
                f"(ответил шлюз); тело: {describe_body(body)}"
            ),
            details=body,
        )
        self._wrong_addresses.add(bare)
        return error

    def _note_failure(self, error: BrokerError) -> None:
        """Записать отказ в **технический** лог. Человеку отсюда не говорят.

        Обрывом связи считается не всякий отказ. Отказ по частоте запросов
        (429) в счётчик времени без связи не идёт: связь при нём есть,
        и красная панель с надписью «нет связи» сказала бы владельцу счёта
        неправду. Отказ 5xx — идёт: данных от брокера нет, а значит робот
        всё равно не имеет права принимать решения.

        ⚠️ **`error.human` сюда не попадает, и это правило слоя.** Разговор
        с владельцем счёта — не дело брокера: человеческий текст уезжает
        наверх вместе с отказом, а говорит его окно, через порт и журнал
        решений. Слой брокера пишет в лог только техническое: код, адрес,
        тип отказа, тело ответа.

        Правило записано 05.09.2026 ценой двух показов подряд. Сначала
        владелец счёта получил в консоли тело ответа (`technical` содержал
        разметку страницы шлюза), потом — шесть предложений человеческого
        текста оттуда же. Попадали они на экран через
        `redaction.RedactingSink`, который перекидывал записи слоя
        в `logging.lastResort`, то есть в stderr; перекидывание убрано там же.

        Уровни: отказ — WARNING (техническому логу он важен), тело ответа —
        DEBUG (оно длинное и нужно редко).
        """
        if isinstance(error, OUTAGE):
            # Человеческую строку `went_offline` возвращает для журнала
            # решений — говорит её `app/`, а не слой. Здесь важен сам факт
            # перехода: повторные неудачи подряд второй записи не дают.
            if self.connection.went_offline(self._clock(), error) is not None:
                self._note_technical(error, "связь с брокером пропала")
            return
        if isinstance(error, WrongAddress) and error.repeated:
            return
        self._note_technical(error, "отказ брокера")

    @staticmethod
    def _note_technical(error: BrokerError, headline: str) -> None:
        """Отказ в технический лог: тип, код, адрес, тело. Без текста человеку."""
        log().warning(
            "%s: %s", headline, error.technical or type(error).__name__
        )
        if error.details:
            log().debug("тело ответа брокера: %s", error.details)

    def _note_online(self) -> None:
        # `came_online` возвращает строку для журнала решений — человеческую,
        # с длительностью обрыва. Слой её не печатает по тому же правилу;
        # в технический лог идёт факт.
        if self.connection.came_online(self._clock()) is not None:
            log().info("связь с брокером восстановлена")



def _refused_why(method: str, path: str) -> str:
    """Почему слой не отправил этот запрос — словами и с разбором промаха.

    Три разных промаха и три разных ответа: не тот глагол по знакомому
    адресу; знакомый адрес с лишним хвостом или строкой запроса; вовсе
    незнакомый адрес. Порядок веток — от самого частого промаха к самому
    общему; последняя ветка отвечает всегда.

    Отдельной функцией, а не ветками внутри `_guard`: сторож обязан читаться
    как «пара разрешена — пропускаем, иначе отказ», и разбор промаха туда
    не относится. Ветвление здесь не таблица нарочно — три случая дают три
    непохожих текста и опираются на разные множества, общей формы у них нет.

    Молчаливый отказ здесь стоил бы часа отладки: путь виден только в тексте
    исключения (правило 13 `CLAUDE.md`).
    """
    verbs = sorted(verb for verb, address in READ_ENDPOINTS if address == path)
    if verbs:
        return (
            f"адрес {path} слой читает глаголом {', '.join(verbs)}, а не "
            f"{method}. Глагол — часть допуска: у БКС по одному адресу заявки "
            "GET отдаёт её статус, а POST создаёт новую"
        )
    if (method, _bare(path)) in READ_ENDPOINTS:
        return (
            f"адрес {path} отличается от белого списка строкой запроса или "
            "хвостовым слэшем. Слой сверяет и отправляет одну и ту же строку; "
            "параметры запроса передаются через `params`, а не в пути"
        )
    return (
        f"адрес {path} не входит в список адресов чтения. На этапе 1 слой "
        "broker/ читает портфель, лимиты, справочник инструментов, "
        "исторические свечи и расписание торгов, и больше ничего. Подача, "
        "изменение и снятие заявок — этап 2"
    )


def _seconds(value: object, default: timedelta) -> timedelta:
    """`expires_in` документация объявляет строкой, сервер шлёт число."""
    try:
        return timedelta(seconds=float(str(value)))
    except (TypeError, ValueError):
        return default


def _text(value: object) -> str | None:
    return value if isinstance(value, str) else None
