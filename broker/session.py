#: Методы, у которых **404 двузначен**, и что говорить владельцу счёта, когда
#: этот код означает неверный адрес. Ключ — путь; значение — две короткие
#: строки: что перестало работать и что из этого следует. Оба текста читает
#: владелец счёта, поэтому в них нет ни кодов, ни адресов, ни слова «404»,
#: и они короткие: подробности, которые он не может применить, ему не нужны.
#:
#: Двузначность не выдумана, она в документации. Для свечей официальный PDF
#: называет `404 NOT_FOUND` штатным ответом «данные не найдены» — например,
