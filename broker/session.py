#: Сколько ждём ответа. Больше — робот молча висит и пропускает свечу;
#: меньше — обрываем нормальный ответ на медленном канале.
DEFAULT_TIMEOUT: Final[float] = 10.0

#: Сколько раз повторяем запрос, которому повтор может помочь.
DEFAULT_ATTEMPTS: Final[int] = 3

#: Отказы, которые считаются обрывом связи и запускают счётчик времени
#: без связи. Отказ по частоте запросов сюда не входит: связь при нём есть.
OUTAGE: Final[tuple[type[BrokerError], ...]] = (NoConnection, Timeout, ServerFailure)


class BrokerSession:
    """Одно подключение к брокеру: токен, транспорт, отказы, состояние связи.

    Читает (`read` и обёртки над ним) и подаёт команды (`create_order`,
    `cancel_order`) — двумя разными путями с двумя белыми списками. Кэша нет
    намеренно: `DOMAIN.md` §5 требует видеть свободные средства **до** заявки,
    а биржа пересматривает гарантийное обеспечение внутри дня — значение
    получасовой давности здесь негодно.
    """

    def __init__(
        self,
        store: TokenStore,
        *,
        client: httpx.AsyncClient | None = None,
        clock: Callable[[], datetime] = now_utc,
        timeout: float = DEFAULT_TIMEOUT,
        attempts: int = DEFAULT_ATTEMPTS,
        throttle: Throttle | None = None,
        backoff: Backoff | None = None,
        sleep: Callable[[float], Any] = asyncio.sleep,
        order_throttle: Throttle | None = None,
    ) -> None:
        install_redaction()
        self._store = store
        self._clock = clock
        self._timeout = timeout
        self._attempts = max(1, attempts)
        self._throttle = throttle or Throttle()
        #: Своё ведро для `ORDER_LANE`: заявка не стоит в очереди за догрузкой.
        self._order_throttle = order_throttle or Throttle()
        self._backoff = backoff or Backoff()
        self._sleep = sleep
        self._owns_client = client is None
        self._client = client or httpx.AsyncClient(base_url=API_BASE, timeout=timeout)

        self._stored: StoredToken | None = None
        self._access: AccessToken | None = None
        self._auth_lock = asyncio.Lock()
        self.connection = ConnectionState()
        #: Что известно о расхождении часов машины с часами брокера.
        #: Заполняется по заголовку `Date` каждого ответа, ни одного лишнего
        #: запроса не стоит. Говорит об этом `app/`: слой брокера с человеком
        #: не разговаривает (`_note_failure`).
        self.clock = ClockWatch()
        #: Адреса из `ADDRESS_SENSITIVE`, на которые шлюз брокера уже ответил
        #: 404 без кода отказа. Помечаются **на сеанс**: адрес зашит в код
        #: программы и сам собой не исправится, а догрузка пропущенного
        #: запускается на каждом подключении. Без пометки владелец счёта
        #: получал бы одну и ту же строку на каждом переподключении,
        #: а их у него много.
        self._wrong_addresses: set[str] = set()
        #: Отказ `invalid_grant` на обмене токена: описание и технический текст.
        #: Пока он стоит, обмен к брокеру не идёт — до `allow_token_retry`.
        self._refused: tuple[str, str] | None = None

    # --- жизненный цикл ---

    async def __aenter__(self) -> "BrokerSession":
        return self

    async def __aexit__(self, *exc_info: object) -> None:
        await self.close()

    async def close(self) -> None:
        if self._owns_client:
            await self._client.aclose()

    # --- токен ---

    def stored(self) -> StoredToken:
        """Токен из файла. Читается один раз за сеанс."""
        if self._stored is None:
            self._stored = self._store.load()
        return self._stored

    def cabinet_token(self) -> RefreshToken:
        return self.stored().token

    def token_notice(self) -> TokenNotice:
        """Обратный отсчёт до конца срока токена и предупреждение за 10 дней."""
        return self.cabinet_token().notice(self._clock())

    def can_trade(self) -> bool:
        return self.cabinet_token().scope.can_trade

    def require_trade_rights(self) -> None:
        """Предохранитель боевого режима: на токене для чтения он не включается.

        Пункт приёмки Э1-4 (`/risk`): «тип токена определяется, боевой режим
        на токене „только чтение“ не включается».

        Тип берётся **из самого токена** — поле `azp` полезной нагрузки JWT
        (`tokens.issued_for`, правка 05.10.2026): брокер обменивает токен
        только с этим `client_id`, так что токен для чтения с полем файла
        «торговля» до заявок всё равно не дошёл бы, а предохранитель говорил
        бы «можно». Поле файла решает, только если токен не JWT или клиент
        в нём незнаком. Ответ сервиса авторизации содержит поле `scope`,
        но состав его значений в документации не задан, поэтому решение
        на нём не строится.

        Зовётся **перед каждой командой** пишущего пути (`_command`), а не один
        раз при включении боя: токен заменяют на ходу, и замена на токен для
        чтения не должна оставить робота с разрешением, выданным прежнему.
        """
        stored = self.stored()
        scope = stored.token.scope
        if not scope.can_trade:
            source = "по самому токену" if stored.scope_from_token else "по файлу настроек"
            raise ReadOnlyToken(f"тип токена {source}: {scope.value}")

    def allow_token_retry(self) -> None:
        """Человек нажал «Подключиться»: следующий обмен токена снова идёт к брокеру.

        Единственный способ снять запомненный отказ `invalid_grant`. Зовёт его
        только действие человека (`app/live_feed.LiveLink.switch`), а не цикл
        переподключения: повтор того же токена без изменений даёт тот же отказ.
        """
        self._refused = None

    def forget_access_token(self) -> None:
        """Забыть рабочий токен: следующее обращение обменяет новый.

        Для отказа 401 в рукопожатии сокета (`broker/order_stream.py`): тот
        ответ приходит мимо `_interpret`, который делает то же самое для HTTP.
        Без этого следующее подключение взяло бы тот же отвергнутый токен.
        """
        self._access = None

    async def access_token(self) -> AccessToken:
        """Действующий рабочий токен. Обменивает и обновляет сам.

        Обмен под замком: без него десять одновременных запросов на старте
        дали бы десять обменов подряд — и это первый способ упереться
        в ограничение частоты на ровном месте.
        """
        current = self._access
        now = self._clock()
        if current is not None and not current.stale(now, ACCESS_REFRESH_MARGIN):
            return current

        async with self._auth_lock:
            current = self._access
            now = self._clock()
            if current is not None and not current.stale(now, ACCESS_REFRESH_MARGIN):
                return current
            if self._refused is not None:
                # Новый объект на каждый вызов: поднятое дважды исключение
                # копит трассировки прежних подъёмов (`_wrong_address_error`).
                description, technical = self._refused
                raise TokenRefused(
                    description, f"{technical}; повтор без запроса — обмен уже отклонён"
                )
            try:
                return await self._exchange()
            except TokenRefused as refused:
                # Запоминается до действия человека: повтор того же токена
                # получит тот же отказ, а опрос счёта и расписание спрашивали
                # бы сервис авторизации на каждом круге (`B-062`).
                self._refused = (refused.description, refused.technical)
                raise

    async def _exchange(self) -> AccessToken:
        """Обменять токен личного кабинета на рабочий."""
        stored = self.stored()
        token = stored.token
        now = self._clock()

        if token.expired(now):
            raise TokenExpired(f"срок токена вышел {token.expires_at.isoformat()}")

        # Значение достаётся в отдельную короткую переменную, а не подставляется
        # выражением прямо в словарь: имя поля рядом с длинным выражением —
        # тот самый образец, который ищет детектор секретов в tests/test_layers.py,
        # и продуктовый файл попадал бы в его отчёт наравне с настоящей утечкой.
        raw = token.secret.reveal()
        form = {
            "client_id": token.scope.client_id,
            "grant_type": "refresh_token",
            "refresh_token": raw,
        }
        del raw

        # Очистка обязана быть в `finally`. Если оставить её после `await`,
        # на пути исключения она не выполнится, кадр этой функции попадёт
        # в `__traceback__` поднятого отказа, и сырой 90-дневный токен окажется
        # в переменных кадра. Обычный `format_exception` его не печатает, поэтому
        # проверка ищет его через `capture_locals=True` — иначе дыра невидима.
        # Выстреливает на обрыве связи в момент обмена, то есть на основном
        # сценарии отказа по ТЗ §4.9.
        try:
            payload = await self._auth_post(form)
        finally:
            form.clear()

        # Один `try/finally` на весь разбор ответа, а не на его хвост.
        #
        # Прежде защита стояла только вокруг построения `AccessToken`, и два
        # более ранних отказа — «тело не объект» и «поля токена нет» — улетали
        # мимо неё, оставляя сырое тело ответа в переменных кадра. Утечкой это
        # становится, когда сервис возвращает токен в постороннем поле того же
        # тела: такое его поведение уже наблюдалось — есть отдельная проверка
        # на то, что он присылает наш токен обратно в тексте отказа.
        #
        # `finally` выполняется на всех путях: и на отказе, и на успехе.
        # Затираем значением, а потом `del`: одного `del` мало, если
        # трассировку соберут раньше, чем сборщик мусора дойдёт до строки.
        value: str | None = None
        try:
            if not isinstance(payload, Mapping):
                raise UnexpectedAnswer(
                    "сервис авторизации ответил не объектом",
                    "авторизация: тело ответа не является объектом JSON",
                )

            value = payload.get("access_token")
            if not isinstance(value, str) or not value:
                raise UnexpectedAnswer(
                    "в ответе сервиса авторизации нет рабочего токена",
                    "авторизация: поле рабочего токена отсутствует или пусто",
                )

            lifetime = _seconds(payload.get("expires_in"), ACCESS_LIFETIME)
            try:
                secret = Secret(value)
            except ValueError:
                # `Secret` отвергает значение с посторонним символом. Отказ
                # обязан выйти из слоя как `BrokerError`: голый `ValueError`
                # разбор отказов выше не ловит, и «сервис ответил не тем»
                # читалось бы как дефект программы. Сценарий не выдуманный:
                # шлюз между брокером и клиентом правит тело, а сервис при
                # внутренней ошибке отвечает 200 с текстом вместо токена.
                raise UnexpectedAnswer(
                    "рабочий токен от сервиса авторизации содержит посторонние "
                    "символы",
                    "авторизация: значение рабочего токена не прошло проверку "
                    "состава символов",
                ) from None
            access = AccessToken(
                secret=secret,
                expires_at=self._clock() + lifetime,
                scope=token.scope,
                scope_reported=_text(payload.get("scope")),
            )
        finally:
            value = ""
            payload = {}
            del value, payload

        self._access = access
        log().info(
            "рабочий токен получен, срок до %s, права %s",
            access.expires_at.isoformat(),
            token.scope.value,
        )
        return access

    async def _auth_post(self, form: dict[str, str]) -> object:
        """Запрос к сервису авторизации. **Повторяется: стоит в `REPEATABLE`.**

        Обмен ничего не меняет ни на счёте, ни у брокера: при удаче выдаётся
        ещё один рабочий токен на сутки, и всё. Токен личного кабинета обменом
        не тратится — его срок 90 дней, и живёт он до замены в кабинете (замер
        04.09.2026: `refresh_expires_in` ≈ 90 суток). Без повтора обычный обрыв
        связи на старте валил бы подключение целиком.

        Отдельным методом, а не строкой в `_exchange`: тот и без того длинный,
        и длина его оправдана — там стирается секрет из памяти, а разнос по
        методам удлиняет жизнь секрета в процессе. Здесь наоборот: `form`
        передан **той же** ссылкой, `form.clear()` в `_exchange` опустошает
        его на всех путях, и лишний кадр в трассировке несёт уже пустой
        словарь. Проверяется это `tests/test_broker_no_leak.py`, где кадры
        читаются с `capture_locals=True`.
        """
        return await self._with_retries(
            "POST",
            AUTH_EXCHANGE,
            lambda: self._client.post(AUTH_URL, data=form, timeout=self._timeout),
        )

    # --- запросы ---

    async def read(
        self,
        path: str,
        *,
        method: str = "GET",
        params: Mapping[str, Any] | None = None,
        json: Any = None,
    ) -> Any:
        """Запрос на чтение. Заявки этим методом подать нельзя — и это проверка.

        Сторожится **пара «глагол и адрес»**, а не адрес отдельно (правка
        06.09.2026, находка Н-3). `POST` сам по себе не признак торговли:
        справочник инструментов по тикерам у БКС — это `POST` с телом
        и чистое чтение. И наоборот, `GET` сам по себе не признак чтения:
        разрешить любой глагол по знакомому адресу значит открыть дорогу
        подаче заявки через метод, который называется `read`.

        Глагол приводится к верхнему регистру **до** сторожа, и дальше идёт
        именно приведённый: сверяется и отправляется одна и та же строка.
        По той же причине путь не нормализуется вовсе — расхождение
        отвергается, а не приглаживается (находка Н-5).

        Адрес, признанный неверным (`ADDRESS_SENSITIVE`), отвергается **без
        запроса**: одного ответа шлюза за сеанс достаточно, адрес зашит в код
        и сам собой не исправится. Смысл не в экономии запросов, а в тишине —
        иначе на каждом переподключении в журнал уходила бы новая строка
        про одно и то же.
        """
        verb = method.upper()
        self._guard(verb, path)
        if self.address_is_wrong(path):
            raise self._wrong_address_error(_bare(path), repeated=True)
        # Повтор разрешает не этот вызов, а таблица `REPEATABLE` — отдельная
        # от белого списка и выписанная руками. Повторить чтение можно сколько
        # угодно раз: на счёте от него не меняется ничего. Слова «повторяй»
        # здесь нет нарочно — его написал бы и тот, кто придёт сюда с подачей
        # заявки (`B-002`).
        return await self._with_retries(
            verb,
            path,
            lambda: self._authorized(verb, path, params=params, json=json),
        )

