"""Сверка часов машины с часами брокера. Ничего не чинит — говорит вслух.

Зачем
-----
Две величины программы считаются как «серверное время минус наше», и обе
останавливают торговлю, когда часы машины разошлись с биржей:

* **годность снимка счёта** — две минуты от закрытия свечи
  (`SNAPSHOT_MAX_AGE`, решение 0040). Время снимка ставят наши часы, время
  закрытия свечи приходит от брокера. Часы, **отставшие** на две минуты,
  делают каждый снимок протухшим, и по решению 0037 вход запрещён весь день;
* **закрытие свечи по часам** — запас 30 секунд на молчащем рынке
  (решение 0013) при доставке 3–17 секунд. Часы, **спешащие** на десять
  секунд, съедают запас: минута закрывается раньше срока, и решение
  принимается по обрубленной свече.

Машина у владельца счёта рабочая, а не сервер (решение 0022): службы
синхронизации там никто не проверяет.

⚠️ **Часы не подкручиваются ни здесь, ни где-либо ещё.** Ни системные,
ни «внутреннее время программы». Смещённое время немедленно попало бы
в журнал сделок и в отчёты, то есть ложь стала бы записанной. Модуль
измеряет расхождение и отдаёт наверх фразу; решение принимает человек.

Откуда берётся серверное время
------------------------------
Из заголовка `Date` **обычного ответа** брокера. Отдельного метода «который
час» в API БКС нет (проверено по оглавлению официального PDF), а `Date`
обязателен для ответа с телом по RFC 9110 §6.6.1 и приходит с каждым.
Цена замера — ноль запросов и ноль жетонов ограничителя частоты.

Точность и почему она достаточна
--------------------------------
`Date` — момент **отправки** ответа, с точностью до секунды. Наши часы дают
два момента: перед отправкой запроса и после получения ответа. Серверный
момент лежит между ними, поэтому расхождение считается от **середины**
промежутка, а не от одного из краёв, и рядом хранится погрешность:
половина круга плюс секунда на огрубление заголовка.

На обычном канале круг — десятки миллисекунд, погрешность около секунды.
Порог, с которого мы говорим вслух, — десять секунд, то есть на порядок
больше погрешности. Замер, у которого погрешность перекрывает порог
(очень медленный канал), вердикта не даёт вовсе: сказать «часы врут»,
когда врёт измерение, значит послать владельца счёта чинить исправное.
"""

from __future__ import annotations

import enum
from dataclasses import dataclass
from datetime import datetime, timedelta
from email.utils import parsedate_to_datetime
from typing import Final

__all__ = [
    "SKEW_BLOCKING",
    "SKEW_NOTICE",
    "ClockWatch",
    "Reading",
    "Verdict",
    "reading_of",
    "server_moment",
]

#: С какого расхождения говорим вслух.
#:
#: Число выбрано по **самому тесному** из двух бюджетов, а не на глаз.
#: Закрытие свечи по часам ждёт 30 секунд (решение 0013), а доставка свечи
#: заняла на замере 04.09.2026 от 3 до 17 секунд. Значит настоящий запас —
#: 30 − 17 = 13 секунд, и часы, ушедшие вперёд больше чем на десять,
#: обрубают свечу. Второй бюджет (годность снимка, 120 секунд) шире
#: в двенадцать раз и сторожится порогом ниже.
#:
#: Почему не меньше: погрешность самого замера около секунды, а на машине
#: с работающей синхронизацией времени расхождение — доли секунды. Порог
#: в секунду-две давал бы жалобы на исправных часах.
SKEW_NOTICE: Final[timedelta] = timedelta(seconds=10)

#: С какого расхождения торговля начинает вставать сама.
#:
#: Годность снимка счёта — 120 секунд (`SNAPSHOT_MAX_AGE`,
#: `engine.FUNDS_MAX_AGE`). Половина бюджета взята как порог: при таком
#: расхождении снимок протухает вдвое быстрее срока, а при полном — не бывает
#: годным никогда, и робот перестаёт входить по решению 0037.
#:
#: Разделение на два уровня не косметика: при десяти секундах владелец счёта
#: рискует обрубленной свечой, при шестидесяти он **уже не торгует** — и это
#: разные новости, требующие разной срочности.
SKEW_BLOCKING: Final[timedelta] = timedelta(seconds=60)

#: Огрубление заголовка `Date`: он передаётся с точностью до секунды.
_HEADER_GRANULARITY: Final[timedelta] = timedelta(seconds=1)

#: До скольких секунд длительность показывается с десятыми. На этом масштабе
#: округление до целых превратило бы погрешность 0,4 с в «0 с».
_TENTHS_BELOW: Final[float] = 10.0

#: С какой длительности она показывается минутами и секундами.
_MINUTES_FROM: Final[float] = 60.0


class Verdict(enum.Enum):
    """Что известно о часах машины.

    `UNKNOWN` — **не «часы верны»**, а «не сверяли»: ни одного ответа
    с заголовком времени не приходило либо замер оказался слишком грубым.
    Разница важна: «верны» позволяет молчать, «не сверяли» обязывает
    не выдавать молчание за подтверждение.
    """

    UNKNOWN = "не сверяли"
    MATCHED = "часы совпадают с брокером"
    SKEWED = "часы разошлись с брокером"
    BROKEN = "часы разошлись настолько, что торговля встанет"


@dataclass(frozen=True, slots=True)
class Reading:
    """Один замер расхождения часов.

    `skew` — **серверное минус наше**: положительное значение означает, что
    наши часы **отстают** (сервер уже дальше), отрицательное — что спешат.
    Знак назван здесь один раз, чтобы его не пришлось выводить заново
    на каждом использовании.
    """

    #: Момент, которым брокер пометил ответ.
    server: datetime
    #: Середина промежутка «отправили — получили» по нашим часам.
    local: datetime
    #: Круг: сколько прошло по нашим часам от отправки до получения.
    round_trip: timedelta

    @property
    def skew(self) -> timedelta:
        """Серверное минус наше: плюс — наши отстают, минус — спешат."""
        return self.server - self.local

    @property
    def uncertainty(self) -> timedelta:
        """Насколько замер груб: половина круга плюс огрубление заголовка."""
        return self.round_trip / 2 + _HEADER_GRANULARITY

    @property
    def certain(self) -> bool:
        """Виден ли скос сквозь погрешность замера.

        Ложь означает «замер ничего не доказывает»: расхождение меньше
        собственной погрешности. Такой замер вердикта не даёт.
        """
        return abs(self.skew) > self.uncertainty

    def verdict(self) -> Verdict:
        """Вердикт по одному замеру. Пороги — `SKEW_NOTICE` и `SKEW_BLOCKING`.

        ⚠️ **Замер грубее порога не разрешает ничего — в обе стороны.**
        Круг в сорок секунд даёт погрешность двадцать одну; при таком замере
        «часы совпадают» такое же враньё, как «часы врут»: наблюдаемые восемь
        секунд разницы могут быть и нулём, и тридцатью. Первая редакция
        сторожила только сторону «врут» и на медленном канале объявляла бы
        исправность часов, которой не проверяла. Найдено собственным тестом
        05.09.2026.

        Из этого правила есть одно исключение, и оно осознанное: расхождение,
        **видимое сквозь погрешность** и перешедшее порог остановки, объявляется
        и на медленном канале. Пять минут разницы при погрешности в двадцать
        секунд — это факт, а не шум.
        """
        size = abs(self.skew)
        if size >= SKEW_BLOCKING and self.certain:
            return Verdict.BROKEN
        if self.uncertainty >= SKEW_NOTICE:
            return Verdict.UNKNOWN
        if size >= SKEW_NOTICE:
            return Verdict.SKEWED
        return Verdict.MATCHED


def server_moment(header: str | None) -> datetime | None:
    """Заголовок `Date` → момент с часовым поясом. `None` — разобрать нечем.

    Отсутствие заголовка и мусор в нём — один и тот же ответ «не знаем»:
    оба означают, что сверять не с чем. Исключение здесь было бы вредно —
    сверка часов не повод уронить запрос за котировками.
    """
    if not header:
        return None
    try:
        moment = parsedate_to_datetime(header)
    except (TypeError, ValueError):
        return None
    if moment.tzinfo is None:
        # RFC 9110 разрешает только GMT, но сервер бывает и не таков.
        # Наивный момент дорисовывать поясом нельзя: вычитание из момента
        # с поясом даст `TypeError` посреди торгового дня.
        return None
    return moment


def reading_of(
    header: str | None, *, sent_at: datetime, received_at: datetime
) -> Reading | None:
    """Замер по одному ответу. `None` — заголовка нет либо часы шли назад.

    Круг с отрицательной длиной означает, что наши часы **перевели** между
    отправкой и получением: их только что подкрутила служба синхронизации
    либо владелец счёта руками. Такой замер отбрасывается — середина
    промежутка в нём не значит ничего.
    """
    server = server_moment(header)
    if server is None:
        return None
    round_trip = received_at - sent_at
    if round_trip < timedelta(0):
        return None
    return Reading(
        server=server, local=sent_at + round_trip / 2, round_trip=round_trip
    )


class ClockWatch:
    """Что известно о часах машины и что об этом сказать человеку.

    Хранит **последний** замер, а не среднее: расхождение часов — величина,
    которая либо есть, либо нет, и усреднение по десяти минутам только
    спрятало бы момент, когда службу синхронизации включили.

    Жалоба выдаётся **на смену вердикта**, как у обрыва связи
    (`ConnectionState.went_offline`). Часы, ушедшие на минуту, дают одну
    строку в журнале, а не строку на каждый опрос счёта.
    """

    def __init__(self) -> None:
        self.last: Reading | None = None
        self._told: Verdict = Verdict.UNKNOWN

    def observed(
        self, header: str | None, *, sent_at: datetime, received_at: datetime
    ) -> None:
        """Принять ответ брокера. Негодный замер прежний не стирает.

        Прежний замер сохраняется намеренно: ответ без заголовка времени —
        это отсутствие новых сведений, а не опровержение старых. Стирать
        по нему значило бы терять уже найденное расхождение на первом же
        ответе подставного сервера или прокси.
        """
        fresh = reading_of(header, sent_at=sent_at, received_at=received_at)
        if fresh is not None:
            self.last = fresh

    def verdict(self) -> Verdict:
        """Вердикт по последнему замеру. Без замеров — «не сверяли»."""
        return Verdict.UNKNOWN if self.last is None else self.last.verdict()

    def complaint(self) -> tuple[str, str] | None:
        """Заголовок и текст для журнала решений — либо `None`, если сказать нечего.

        `None` в двух случаях: вердикт не менялся с прошлого раза, либо часы
        совпадают. Возврат «совпадают» отдельной строкой заводил бы в журнале
        запись о том, что всё как обычно.

        Текст называет **число, сторону и последствие**, а не «проверьте
        часы»: владелец счёта должен понимать, что именно сломается, иначе
        строка выглядит придиркой и её пролистывают.
        """
        now = self.verdict()
        if now is self._told or now in (Verdict.UNKNOWN, Verdict.MATCHED):
            return None
        self._told = now
        return _complaint_text(self.last, now)

    def matched_again(self) -> str | None:
        """Строка «часы снова сходятся» — один раз после жалобы.

        Отдельным методом, а не веткой в `complaint`: возвращение к норме —
        хорошая новость, и уровень у неё в журнале другой.
        """
        now = self.verdict()
        if now is not Verdict.MATCHED or self._told is Verdict.MATCHED:
            return None
        was = self._told
        self._told = now
        if was is Verdict.UNKNOWN:
            return None
        return (
            "Часы компьютера снова сходятся с часами брокера: "
            f"{_ru_offset(self.last.skew) if self.last else 'расхождения нет'}."
        )

    def describe(self) -> str:
        """Строка для панели состояния и для отчёта. Всегда непустая."""
        current = self.last
        if current is None:
            return "Часы с брокером не сверялись: он не сказал своего времени"
        return (
            f"Часы компьютера {_ru_offset(current.skew)} "
            f"(точность замера ±{_ru_seconds(current.uncertainty)})"
        )


def _complaint_text(current: Reading | None, verdict: Verdict) -> tuple[str, str]:
    """Заголовок и текст жалобы. Обе стороны расхождения ломают своё."""
    if current is None:  # недостижимо: вердикт без замера — всегда UNKNOWN
        return ("Часы компьютера", "Сверить часы не удалось.")
    behind = current.skew > timedelta(0)
    where = "отстают" if behind else "спешат"
    harm = (
        "Из-за этого состояние счёта выглядит устаревшим сразу, как только "
        "получено, и робот перестаёт открывать позиции: годность снимка "
        "счёта — две минуты, и расхождение съедает её целиком."
        if behind
        else "Из-за этого свеча закрывается раньше срока, и решение "
        "принимается по неполной свече: программа ждёт закрытия ещё "
        "полминуты, а расхождение съедает это ожидание."
    )
    urgency = (
        "Торговля из-за этого уже останавливается."
        if verdict is Verdict.BROKEN
        else "Пока это не остановило торговлю, но запас съеден."
    )
    return (
        f"Часы компьютера {where} от часов брокера",
        f"Часы компьютера {_ru_offset(current.skew)}. {harm} {urgency} "
        "Программа время не подкручивает — ни системное, ни своё: смещённое "
        "время попало бы в журнал сделок. Включите синхронизацию времени "
        "в настройках операционной системы.",
    )


def _ru_offset(skew: timedelta) -> str:
    """«отстают на 12 с» / «спешат на 1 мин 5 с» / «совпадают»."""
    if skew == timedelta(0):
        return "совпадают с брокером"
    where = "отстают" if skew > timedelta(0) else "спешат"
    return f"{where} на {_ru_seconds(abs(skew))}"


def _ru_seconds(span: timedelta) -> str:
    """Длительность словами: секунды, при большой — минуты и секунды."""
    total = span.total_seconds()
    if total < _TENTHS_BELOW:
        return f"{total:.1f} с".replace(".", ",")
    if total < _MINUTES_FROM:
        return f"{total:.0f} с"
    minutes, seconds = divmod(int(total), int(_MINUTES_FROM))
    return f"{minutes} мин {seconds} с" if seconds else f"{minutes} мин"
