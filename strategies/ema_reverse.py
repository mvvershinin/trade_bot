#: Период средней у прототипа. В программу проверки входят ещё 9 и 20 (DOMAIN.md §4).
DEFAULT_PERIOD = 15


class OnPriceEqualsAverage(enum.Enum):
    """Закрытие ровно на средней — что считать.

    Случай редкий и цифрами не подкреплённый (см. шапку модуля), поэтому
    настройка, а не зашитый выбор. Умолчание — поведение прототипа: сигнала нет.
    Значения строк совпадают с `ui.models.OnPriceEqualsAverage`.
    """

    LIKE_PROTOTYPE = "skip"
    TREAT_AS_LONG = "long"
    TREAT_AS_SHORT = "short"

    @property
    def label(self) -> str:
        return {
            OnPriceEqualsAverage.LIKE_PROTOTYPE: "Не входить и не выходить (как сейчас)",
            OnPriceEqualsAverage.TREAT_AS_LONG: "Считать сигналом на лонг",
            OnPriceEqualsAverage.TREAT_AS_SHORT: "Считать сигналом на шорт",
        }[self]


@dataclass(frozen=True, slots=True)
class EmaReverseSettings:
    """Настройки модуля №1. Хранятся отдельно от общих настроек движка.

    ARCHITECTURE.md §3: настройки каждого модуля сохраняются свои —
    переключился на другой модуль и обратно, всё на месте.

    Диапазон периода 5–300 из ТЗ здесь **не** проверяется: это ограничение поля
    ввода, а не правило расчёта. Модуль отвергает только то, на чём расчёт
    теряет смысл — период меньше единицы и нецелый. По этому же правилу
    у порога и подтверждения нет верхней границы: порог в 50% означает
    «робот не торгует», и это безопасный, хотя и бессмысленный ответ, а не
    порча расчёта.

    Два поля против пилы, оба выключены умолчанием
    ----------------------------------------------
    `threshold_percent = 0` и `confirm_bars = 1` дают **в точности** сегодняшнее
    поведение и, значит, сходящуюся сверку с прототипом. Умолчание менять
    нельзя без нового замера и записи решения.
    """

    period: int = DEFAULT_PERIOD
    kind: AverageKind = AverageKind.EMA
    on_equal: OnPriceEqualsAverage = OnPriceEqualsAverage.LIKE_PROTOTYPE
    #: Полоса вокруг средней в процентах: закрытие внутри неё сигналом
    #: не считается. `0` — полосы нет, сравнение как у прототипа.
    threshold_percent: float = 0.0
    #: Сколько свечей подряд закрытие обязано быть по одну сторону, прежде чем
    #: сигнал станет намерением. `1` — подтверждения нет, как у прототипа.
    confirm_bars: int = 1

    def __post_init__(self) -> None:
        if isinstance(self.period, bool) or not isinstance(self.period, int):
            raise TypeError(f"период средней — целое число, получено {self.period!r}")
        if self.period < 1:
            raise ValueError(
                f"период средней должен быть не меньше 1, получено {self.period}"
            )
        if not isinstance(self.kind, AverageKind):
            raise TypeError(f"тип средней — AverageKind, получено {self.kind!r}")
        if not isinstance(self.on_equal, OnPriceEqualsAverage):
            raise TypeError(
                "поведение при закрытии ровно на средней — OnPriceEqualsAverage, "
                f"получено {self.on_equal!r}"
            )
        self._check_threshold()
        self._check_confirm()

    def _check_threshold(self) -> None:
        """Порог — неотрицательное конечное число.

        `nan` отвергается здесь, а не в сравнении: любое сравнение с ним ложно,
        поэтому полоса из `nan` проглотила бы **каждое** закрытие и робот молча
        перестал бы торговать вовсе. Отрицательный порог означал бы полосу
        наизнанку — вход и там, и там; такого правила нет.
        """
        value = self.threshold_percent
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise TypeError(
                f"порог пересечения — число процентов, получено {value!r}"
            )
        if not isfinite(float(value)):
            raise ValueError(
                f"порог пересечения не число: {value!r}. Полоса из nan "
                "проглотила бы каждое закрытие, и робот перестал бы торговать "
                "без единой строки о причине"
            )
        if value < 0:
            raise ValueError(
                f"порог пересечения не может быть отрицательным, получено {value}"
            )

    def _check_confirm(self) -> None:
        """Подтверждение — целое число свечей, не меньше одной.

        Ноль и отрицательное значения означали бы «подтверждать нечем»:
        условие «последние 0 свечей по одну сторону» истинно всегда,
        то есть настройка выглядела бы работающей и не делала бы ничего.
        """
        value = self.confirm_bars
        if isinstance(value, bool) or not isinstance(value, int):
            raise TypeError(
                f"подтверждение сигнала — целое число свечей, получено {value!r}"
            )
        if value < 1:
            raise ValueError(
                "подтверждение сигнала — не меньше одной свечи (1 означает "
                f"«подтверждения нет»), получено {value}"
            )

    @property
    def label(self) -> str:
        """Подпись средней для журнала и графика: `EMA(15)`."""
        return f"{self.kind.short_label}({self.period})"

    def changes_from(self, previous: "EmaReverseSettings") -> list[str]:
        """Что изменилось — строками для журнала решений, с прежним и новым.

        ТЗ §4.4 А требует писать изменение настройки с обоими значениями.
        Составляет строки сам модуль: движок не знает, из чего состоят его
        настройки, и «период средней: 15 → 20» сформулировать не может.
        """
        lines: list[str] = []
        if previous.period != self.period:
            lines.append(f"Период средней: {previous.period} → {self.period}")
        if previous.kind is not self.kind:
            lines.append(
                f"Тип средней: {previous.kind.label} → {self.kind.label}"
            )
        if previous.on_equal is not self.on_equal:
            lines.append(
                "Закрытие ровно на средней: "
                f"{previous.on_equal.label} → {self.on_equal.label}"
            )
        if previous.threshold_percent != self.threshold_percent:
            lines.append(
                "Порог пересечения: "
                f"{_percent(previous.threshold_percent)} → "
                f"{_percent(self.threshold_percent)}"
            )
        if previous.confirm_bars != self.confirm_bars:
            lines.append(
                "Подтверждение сигнала: "
                f"{_bars(previous.confirm_bars)} → {_bars(self.confirm_bars)}"
            )
        return lines

    def replace(self, **changes: object) -> "EmaReverseSettings":
        return replace(self, **changes)  # type: ignore[arg-type]


class EmaReverse:
    """Реверс по средней: закрытие выше средней — лонг, ниже — шорт.

    Модуль накапливает закрытия поданного ряда и на каждой закрытой свече
    отдаёт намерение. Он **stateful** по одной причине: прогрев и значение
    средней зависят от того, сколько свечей подано с начала ряда, а предыстории
    у него нет (PROTOTYPE.md §3).

    Смена настроек на ходу
    ----------------------
    `apply()` **пересчитывает среднюю по всей накопленной истории**, а не только
    вперёд: у экспоненциальной средней прошлое входит в значение, и продолженный
    ряд не совпал бы с посчитанным с нуля. Когда именно применить новые
    настройки — дело движка: по ТЗ они действуют со следующей сделки и открытую
    позицию не трогают.

    История закрытий хранится целиком, ради этого пересчёта: 250 000 свечей —
    это около десяти лет пятиминуток и порядка десяти мегабайт памяти.
    Рядом с ней хранится ряд **значений средней** — по одному на закрытие.
    Он нужен подтверждению сигнала: «N свечей подряд по одну сторону» — это
    вопрос к прошлым свечам, и отвечать на него счётчиком нельзя. Счётчик
    пришлось бы чинить руками после каждой смены периода, а забытая починка
    выглядела бы как «фильтр иногда не срабатывает». Ряд чинится тем же
    пересчётом, что и сама средняя, и ошибиться негде.
    """

    __slots__ = ("_settings", "_closes", "_average", "_averages", "_last_bar_at")

    #: Название для окна и журнала.
    title = "Реверс по скользящей средней"

    def __init__(self, settings: EmaReverseSettings | None = None) -> None:
        self._settings = EmaReverseSettings() if settings is None else settings
        self._closes: list[float] = []
        self._average = MovingAverage(self._settings.period, self._settings.kind)
        self._averages: list[float | None] = []
        self._last_bar_at: object | None = None

    @property
    def settings(self) -> EmaReverseSettings:
        return self._settings

    @property
    def bars(self) -> int:
        """Сколько закрытых свечей подано с начала ряда."""
        return len(self._closes)

    @property
    def average(self) -> float | None:
        """Текущее значение средней или `None`, пока идёт затравка."""
        return self._average.value

    def reset(self) -> None:
        """Забыть ряд: прогрев начнётся заново, как на новом отрезке."""
        self._closes.clear()
        self._averages.clear()
        self._average.reset()
        self._last_bar_at = None

    def apply(self, settings: EmaReverseSettings) -> list[str]:
        """Новые настройки. Возвращает строки для журнала: прежнее → новое.

        Пустой список означает, что ничего не изменилось, — движку не о чем
        писать в журнал.

        ⚠️ Порог и подтверждение пересчёта средней **не требуют**: они читают
        готовые `close` и значение средней, а не участвуют в её арифметике.
        Новый порог поэтому действует с ближайшей свечи, а новое подтверждение
        сразу видит прошлое таким, каким оно было бы с этой настройкой
        с самого начала, — это и есть «действует со следующей сделки»
        при неизменной истории.
        """
        previous = self._settings
        changes = settings.changes_from(previous)
        self._settings = settings
        # Поведение при равенстве в среднюю не входит — пересчитывать нечего.
        if settings.period != previous.period or settings.kind is not previous.kind:
            self._average = MovingAverage(settings.period, settings.kind)
            # Не `replay`: он отдаёт только последнее значение, а подтверждению
            # сигнала нужен весь ряд. Арифметика та же — та же `push` в том же
            # порядке по тем же закрытиям.
            self._averages = [self._average.push(close) for close in self._closes]
        return changes

    def _side(self, close: float, average: float | None) -> Intent:
        """Сторона закрытия относительно средней — с учётом порога.

        Порог задаёт **полосу** вокруг средней: закрытие внутри неё стороны
        не имеет. При нулевом пороге полоса вырождается в саму среднюю, и
        остаются дословные неравенства прототипа `close > EMA` / `close < EMA`:
        `average + average * 0.0` — это в точности `average`, без единого
        младшего разряда разницы.

        ⚠️ Полоса гасит и **выход тоже**, а не только вход. Это не побочный
        эффект, а суть: реверсная система выходит по обратному сигналу, и если
        обратный сигнал слабый, то выходить не на чем. Следствие, о котором
        обязан знать владелец счёта: позиция при включённом пороге живёт
        дольше и в худшем случае доживает до конца торгового окна. При
        выключенном «закрывать в конце окна» и окне на весь день верхней
        границы у этого «дольше» нет вовсе — там порог держит позицию до
        первого сильного движения или до тейка.
        """
        if average is None:
            return Intent.NONE
        edge = average * (self._settings.threshold_percent / 100.0)
        if close > average + edge:
            return Intent.LONG
        if close < average - edge:
            return Intent.SHORT
        return Intent.NONE

    def _confirmed(self, side: Intent) -> int:
        """Сколько свечей подряд (включая последнюю) дали эту сторону.

        Считается по хранимому ряду, а не счётчиком: счётчик пришлось бы
        чинить после каждой смены периода средней, и забытая починка выглядела
        бы как «фильтр иногда не срабатывает». Смотрим не дальше, чем нужно
        настройке, — при `confirm_bars = 1` это ровно одна свеча.
        """
        need = self._settings.confirm_bars
        count = 0
        for index in range(len(self._closes) - 1, -1, -1):
            # Свеча прогрева не считается, даже если средняя на ней уже есть.
            # Затравка появляется на свече №период, а сигнал разрешён только
            # со свечи №(период+1) — и подтверждать сигнал свечой, на которой
            # сам модуль действовать отказался, значит подтверждать его тем,
            # чего не было. Без этой строки первый сигнал ряда выходил бы
            # на свечу раньше остальных.
            if index < self._settings.period:
                break
            if self._side(self._closes[index], self._averages[index]) is not side:
                break
            count += 1
            if count >= need:
                break
        return count

    def _confirm(
        self, side: Intent, close: float, average: float, label: str
    ) -> tuple[Intent, str]:
        """Сторона есть — стала ли она намерением. Плюс строка для журнала.

        Причина написана так, чтобы при выключенных фильтрах совпадать
        с прежней **дословно**: строки журнала читает человек, и «то же самое,
        но другими словами» ломает и сравнение журналов, и привычку.
        Про фильтр в строке появляется ровно то, что включено.
        """
        settings = self._settings
        where = "выше" if side is Intent.LONG else "ниже"
        head = f"Закрытие {_number(close)} {where} {label} {_number(average)}"
        if settings.threshold_percent > 0:
            head += f", порог {_percent(settings.threshold_percent)} пройден"
        if settings.confirm_bars <= 1:
            return side, head
        count = self._confirmed(side)
        if count >= settings.confirm_bars:
            return side, f"{head}, {_bars(count)} подряд по эту сторону"
        return Intent.NONE, (
            f"{head}, но подряд по эту сторону только {_bars(count)}, "
            f"а нужно {_bars(settings.confirm_bars)} — сигнал не подтверждён"
        )

    def _repeat_or_backwards(self, bar: Bar) -> Decision | None:
        """Разбор времени свечи: повтор — штатный, ход назад — порча.

        **Повтор последней свечи — штатное поведение потока**, а не сбой:
        после переподключения брокер присылает её ещё раз. Принятая молча,
        она входит в среднюю дважды и сдвигает прогрев — другой список сделок
        без единого падения по дороге. Но и исключением она быть не может:
        движок, написанный по порту, либо уронил бы на ней цикл обработки
        (робот стоит с открытой позицией и больше не получает сигналов),
        либо обернул бы вызов широким `except`. Поэтому — решение с
        `skip_bar`: свеча в обработку не идёт, движку есть что записать
        в журнал.

        Ход времени назад — другое дело: это порча ряда, и она обязана
        останавливать прогон.

        Это **единственное**, для чего модуль смотрит на время свечи. Торговое
        окно, дни недели и паузы — правила движка, и модуль о них не знает.

        ⚠️ Исправленная поставка свечи (поздние сделки уточнили закрытие)
        этим модулем не поддерживается: он видит ряд как поток и переигрывать
        прошлое не умеет. Если движок захочет учесть исправление — `reset()`
        и подача ряда заново. Политика качества данных принадлежит `market/`
        и `engine/`, а не торговому модулю.

        ⚠️ Наивное время (без пояса) принимается: модулю нужен только порядок,
        смысл момента ему не нужен, а пояс проверяет `market/`. Смесь наивного
        и осознанного времени — отказ, потому что она не сравнивается.
        """
        previous = self._last_bar_at
        if previous is None:
            return None
        try:
            forward = bar.closes_at > previous  # type: ignore[operator]
            repeat = bar.closes_at == previous
        except TypeError as error:
            raise TypeError(
                f"время свечи {bar.closes_at!r} не сравнивается с временем "
                f"предыдущей {previous!r}: скорее всего смешаны свечи с часовым "
                "поясом и без него"
            ) from error
        if forward:
            return None
        if repeat:
            return Decision(
                intent=Intent.NONE,
                reason=(
                    f"Свеча за {_moment(previous)} подана повторно — уже "
                    "учтена, в обработку не идёт"
                ),
                close=float(bar.close),
                average=self._average.value,
                bars=len(self._closes),
                warmed_up=self._is_warm(len(self._closes)),
                skip_bar=True,
            )
        raise ValueError(_sequence_message(previous, bar.closes_at))

    def _is_warm(self, bars: int) -> bool:
        """Прогрев пройден: свечей **больше** периода.

        Дословное условие прототипа наоборот: `свечей <= периода` — сигнала нет.
        Неравенство нестрогое; строгое сдвинуло бы все сделки на свечу.
        Условие живёт в одном месте: два его написания однажды разъедутся.
        """
        return bars > self._settings.period

    def on_closed_bar(self, bar: Bar) -> Decision:
        """Намерение на закрытии свечи.

        Порядок внутри метода значим ровно в одном месте: закрытие попадает
        в среднюю **до** сравнения — сравнивается значение, включающее эту же
        свечу, а не предыдущее (PROTOTYPE.md §3).

        Возвращённое решение с `skip_bar` означает «свеча в обработку не идёт»:
        движок обязан выйти до перестановки тейка и до закрытия по концу окна
        (шаг 2 PROTOTYPE.md §2). Так помечены прогрев и повтор свечи.

        :raises TypeError: свеча не той формы — разбор в `check_bar`.
        :raises ValueError: нечисловое закрытие или ход времени назад.
        """
        check_bar(bar)
        repeated = self._repeat_or_backwards(bar)
        if repeated is not None:
            return repeated
        close = float(bar.close)
        self._closes.append(close)
        self._last_bar_at = bar.closes_at
        average = self._average.push(close)
        self._averages.append(average)

        bars = len(self._closes)
        settings = self._settings
        label = settings.label

        if not self._is_warm(bars):
            return Decision(
                intent=Intent.NONE,
                reason=(
                    f"Прогрев {label}: накоплено свечей {bars} из "
                    f"{settings.period + 1} — сигналов нет"
                ),
                close=close,
                average=average,
                bars=bars,
                warmed_up=False,
                skip_bar=True,      # шаг 2 прототипа: выход из обработки свечи
            )

        if average is None:  # недостижимо: свечей больше периода ⇒ затравка была
            raise RuntimeError(
                f"средней нет при {bars} свечах и периоде {settings.period} — "
                "состояние модуля повреждено"
            )

        side = self._side(close, average)
        if side is Intent.NONE:
            intent, reason = _inside_band(settings, close, average, label)
        else:
            intent, reason = self._confirm(side, close, average, label)

        return Decision(
            intent=intent,
            reason=reason,
            close=close,
            average=average,
            bars=bars,
            warmed_up=True,
        )


def _moment(value: object) -> str:
    """Время свечи для строки журнала: `19.06.2026 10:15`, если это дата."""
    try:
        return f"{value:%d.%m.%Y %H:%M}"
    except (TypeError, ValueError):
        return repr(value)


def _sequence_message(previous: object, current: object) -> str:
    return (
        f"свеча {current!r} подана после {previous!r} — ряд обязан идти вперёд "
        "по времени. Та же свеча дважды тихо испортила бы среднюю и прогрев: "
        "список сделок стал бы другим при зелёных тестах. Новый отрезок "
        "начинается с reset()"
    )


def _inside_band(
    settings: EmaReverseSettings, close: float, average: float, label: str
) -> tuple[Intent, str]:
    """Закрытие не набрало ни одной стороны — почему именно.

    Без порога это единственный возможный случай: закрытие **ровно** на средней,
    шестое исключение прототипа, и решает его настройка `on_equal`.

    ⚠️ С порогом настройка `on_equal` не читается вовсе, и это выбор, а не
    недосмотр: равенство лежит внутри полосы по построению, а полоса — правило
    более сильное. Владелец счёта, включивший порог, просил не входить на
    слабом пересечении; «а вот ровно на средней всё-таки войдём» противоречило
    бы просьбе. Обратный порядок молчаливо возвращал бы вход в самой середине
    мёртвой зоны.
    """
    if settings.threshold_percent <= 0:
        return _on_equal(settings.on_equal, close, label)
    edge = average * (settings.threshold_percent / 100.0)
    return Intent.NONE, (
        f"Закрытие {_number(close)} внутри полосы "
        f"{_number(average - edge)}…{_number(average + edge)} вокруг {label} "
        f"{_number(average)} — пересечение слабее порога "
        f"{_percent(settings.threshold_percent)}, ни входа, ни выхода"
    )


#: Что означает закрытие ровно на средней — намерение и хвост строки журнала.
#:
#: Таблица, а не два `if`, и причина не в длине: то же самое соответствие
#: нужно **описанию правила словами** (`describe`). Написанное дважды, оно
#: разъехалось бы молча — в окне одно, в решениях робота другое, и поймать
#: это можно было бы только сравнением руками.
_ON_EQUAL: Final[dict[OnPriceEqualsAverage, tuple[Intent, str]]] = {
    OnPriceEqualsAverage.LIKE_PROTOTYPE: (
        Intent.NONE, "ни входа, ни выхода, как у прототипа"
    ),
    OnPriceEqualsAverage.TREAT_AS_LONG: (
        Intent.LONG, "по настройке считаем сигналом на лонг"
    ),
    OnPriceEqualsAverage.TREAT_AS_SHORT: (
        Intent.SHORT, "по настройке считаем сигналом на шорт"
    ),
}


def _on_equal(
    setting: OnPriceEqualsAverage, close: float, label: str
) -> tuple[Intent, str]:
    """Закрытие ровно на средней — по настройке, а не по знаку сравнения."""
    intent, tail = _ON_EQUAL[setting]
    return intent, f"Закрытие {_number(close)} ровно на {label} — {tail}"


#: Стороны, о которых модуль вообще умеет говорить: подпись, знак и намерение.
#:
#: Таблица, а не две почти одинаковые ветки. «Выше» и «ниже» отличаются ровно
#: знаком; написанные порознь, они однажды разъедутся — в одной поправят слово,
#: в другой забудут, и описание начнёт врать про одну из двух сторон.
_SIDES: Final[tuple[tuple[str, float, Intent], ...]] = (
    ("выше", 1.0, Intent.LONG),
    ("ниже", -1.0, Intent.SHORT),
)

#: Во сколько раз закрытие-образец отходит от границы полосы и какую долю
#: средней добавляет сверх неё.
#:
#: ⚠️ Числа не «с запасом на всякий случай», а вычислены. Образец подаётся
#: модулю, тот **сперва включает его в среднюю** и только потом сравнивает:
#: средняя успевает шагнуть навстречу образцу. Шаг экспоненциальной средней —
#: доля `k = 2/(период+1)` расстояния, то есть не больше двух третей при
#: периоде ≥ 2; простая средняя за один шаг проходит не больше того же.
#: Условие «образец остался за полосой после шага» сводится к
#: `m·(1 − k) > (средняя + m)·порог`, и оба множителя ниже его закрывают:
#: четырёхкратный отход — для крупных порогов, два процента средней — для
#: нулевого и мелких.
#:
#: ⚠️ Период 1 не покрывается ничем и покрыт быть не может: там средняя
#: **равна** закрытию всегда, ни одно закрытие не бывает выше своей же
#: средней, и утверждения «выше»/«ниже» становятся невыполнимыми — не
#: ложными, а недостижимыми. Поле окна начинается с 5 (`ui/settings_dialog.py`),
#: так что до владельца счёта этот случай не доходит.
_PROBE_REACH: Final[float] = 4.0
_PROBE_LIFT: Final[float] = 0.02


def _probe(settings: EmaReverseSettings, sign: float) -> Callable[[float], float]:
    """Закрытие, которое заведомо по нужную сторону полосы. По значению средней.

    Нужно ровно для одного: чтобы описание правила можно было **исполнить** —
    построить свечу, удовлетворяющую заявленному отношению, подать её модулю
    и сверить намерение с заявленным (`strategies/contracts.py`, `Claim`).
    Арифметику полосы знает только модуль, поэтому образец строит он.
    """

    def probe(average: float) -> float:
        # `average * (порог / 100)` — то же выражение, что в `_side`, и это
        # важно: сравнение идёт по нему, а не по «примерно такому же».
        edge = average * (settings.threshold_percent / 100.0)
        beyond = max(
            _PROBE_REACH * abs(edge), abs(average) * _PROBE_LIFT, _PROBE_LIFT
        )
        return average + sign * (abs(edge) + beyond)

    return probe


def _relation(where: str, *, banded: bool, confirmed: bool) -> str:
    """Отношение **без чисел** — для списка выбора модуля.

    Чисел здесь нет намеренно, включая число подтверждающих свечей: эта
    отрисовка показывается до «Применить», когда настройки ещё не приняты,
    и любое число в ней было бы числом из чужого набора.
    """
    band = "полосы вокруг средней" if banded else "средней"
    head = "несколько закрытий подряд" if confirmed else "закрытие"
    return f"{head} {where} {band}"


def _detail(settings: EmaReverseSettings, where: str) -> str:
    """То же отношение с нынешними числами — для окна, журнала и снимка."""
    label = settings.label
    if settings.threshold_percent > 0:
        place = f"полосы {_percent(settings.threshold_percent)} вокруг {label}"
    else:
        place = label
    if settings.confirm_bars > 1:
        return f"{_bars(settings.confirm_bars)} подряд закрылись {where} {place}"
    return f"закрытие {where} {place}"


def _middle_claim(settings: EmaReverseSettings) -> Claim:
    """Утверждение про середину: полоса при включённом пороге, равенство без него.

    Два случая, а не один, потому что модуль их и различает: при пороге
    настройка «закрытие ровно на средней» не читается вовсе — равенство лежит
    внутри полосы по построению, и полоса сильнее (`_inside_band`). Описание
    обязано повторять это, иначе оно объявит настройку действующей там, где
    она не действует.
    """
    label = settings.label
    if settings.threshold_percent > 0:
        return Claim(
            relation="закрытие внутри полосы вокруг средней",
            detail=(
                f"закрытие внутри полосы {_percent(settings.threshold_percent)} "
                f"вокруг {label}"
            ),
            intent=Intent.NONE,
            probe=lambda average: average,
        )
    return Claim(
        relation="закрытие ровно на средней",
        detail=f"закрытие ровно на {label}",
        # Из той же таблицы, по которой модуль и решает (`_ON_EQUAL`):
        # второе перечисление разъехалось бы с первым молча.
        intent=_ON_EQUAL[settings.on_equal][0],
        probe=lambda average: average,
    )


def _warmup_note(settings: EmaReverseSettings) -> str:
    return (
        f"Пока свечей с начала показанного отрезка не больше {settings.period}, "
        "средняя ещё не набрана и сигналов нет вовсе: первое возможное решение "
        f"— на свече номер {settings.period + 1}."
    )


def _filter_note(settings: EmaReverseSettings) -> str:
    """Состояние фильтра против пилы и его следствие — словами.

    ⚠️ Оба поля выключены умолчанием, и человек, читающий описание, обязан
    понимать, что видит поведение **без них**. Поэтому строка есть всегда,
    в том числе про выключённый фильтр: отсутствие строки читалось бы как
    «фильтра нет вовсе».

    ⚠️ Следствие включённой полосы названо отдельно и не для красоты: «фильтр
    против пилы» читается как «меньше входов», а полоса гасит **и выход тоже**
    (разбор в `_side`). Позиция живёт дольше — это не то, чего ждёт человек,
    поставивший порог.
    """
    band = _percent(settings.threshold_percent)
    confirm = _bars(settings.confirm_bars)
    if settings.threshold_percent <= 0 and settings.confirm_bars <= 1:
        return (
            f"Фильтр против пилы выключен: полоса {band}, подтверждение "
            f"{confirm}. Это в точности поведение вашего нынешнего робота — "
            "сигналом считается любое пересечение средней, каким бы мелким "
            "оно ни было."
        )
    lines = [
        f"Фильтр против пилы включён: полоса {band} вокруг средней, "
        f"подтверждение {confirm} подряд по одну сторону."
    ]
    if settings.threshold_percent > 0:
        lines.append(
            "Полоса гасит и выход тоже: пока обратное закрытие не вышло "
            "за полосу, выходить не на чем — позиция живёт дольше и может "
            "дожить до конца торгового окна."
        )
    if settings.confirm_bars > 1:
        lines.append(
            "Подтверждение задерживает и вход, и выход: пока свечей подряд "
            "по одну сторону меньше нужного, намерения нет."
        )
    return " ".join(lines)


#: Обрамляющие фразы, одинаковые при любых настройках.
#:
#: ⚠️ Они **рукописные и машиной не проверяются** — исполняется только таблица
#: утверждений. Названо вслух, чтобы следующий не принял зелёный прогон
#: за проверку этих двух абзацев.
_REVERSAL_NOTE: Final[str] = (
    "Отдельного сигнала «выйти» у этого алгоритма нет: система реверсная, "
    "выходом служит противоположный сигнал — поэтому робот всё время держит "
    "сторону рынка, а роль стоп-лосса играет переворот."
)
_BOUNDARY_NOTE: Final[str] = (
    "Это всё, что решает алгоритм. Войдёт ли робот на самом деле — решают "
    "общие настройки: торговое окно, режим работы, тейк-профит, объём "
    "и предохранители. Любая из них может отменить любое намерение выше."
)


def describe(settings: EmaReverseSettings) -> Description:
    """Как модуль принимает решение — словами, с нынешними числами.

    Собирается из таблицы утверждений, а не пишется руками: разбор приёма
    и цена отказа от него — в `strategies/contracts.py`, класс `Claim`.

    ⚠️ Результатов на истории здесь нет и не будет. Замер 06.09.2026 (убыток
    на независимом периоде) — отчёт о результатах; описание рассказывает
    правило. Смешать их значит превратить объяснение в обещание.
    """
    banded = settings.threshold_percent > 0
    confirmed = settings.confirm_bars > 1
    claims = tuple(
        Claim(
            relation=_relation(where, banded=banded, confirmed=confirmed),
            detail=_detail(settings, where),
            intent=intent,
            probe=_probe(settings, sign),
            bars=settings.confirm_bars,
        )
        for where, sign, intent in _SIDES
    )
    return Description(
        title=EmaReverse.title,
        lead=(
            "На закрытии каждой свечи робот сравнивает цену закрытия этой же "
            f"свечи со скользящей средней. Средняя: {settings.kind.label}, "
            f"период {settings.period} свечей, считается по ценам закрытия; "
            f"дальше в тексте она обозначена {settings.label}."
        ),
        claims=(*claims, _middle_claim(settings)),
        notes=(
            _REVERSAL_NOTE,
            _warmup_note(settings),
            _filter_note(settings),
            _BOUNDARY_NOTE,
        ),
    )


def _number(value: float) -> str:
    """Цена для строки журнала: `284 812,53`.

    Оформление повторяет `ui.formatting.fmt_number` (пробел между тысячами,
    запятая в дробной части), но своим кодом: `strategies/` не импортирует
    ни один слой проекта. Хвостовые нули отбрасываются, дробная часть — до шести
    знаков: округление до двух знаков сделало бы строку «закрытие 1,23 выше
    EMA(15) 1,23» на инструменте с мелким шагом цены.
    """
    text = f"{value:,.6f}"
    whole, _, fraction = text.partition(".")
    fraction = fraction.rstrip("0")
    whole = whole.replace(",", " ")
    return f"{whole},{fraction}" if fraction else whole


def _percent(value: float) -> str:
    """Процент для строки журнала: `0,04%`. Хвостовые нули отброшены.

    Такая же функция есть в `engine/settings.py`, и это не повод их объединять:
    `strategies/` не импортирует ни один слой проекта (ARCHITECTURE.md §2),
    а общего слоя типов среди семи нет. Ровно то же соображение записано
    у `_number` выше.
    """
    text = f"{float(value):.6f}".rstrip("0").rstrip(".")
    return f"{text.replace('.', ',')}%"


def _bars(count: int) -> str:
    """`1 свеча`, `3 свечи`, `5 свечей` — число со своим окончанием."""
    tail = count % 100
    if 11 <= tail <= 14:  # noqa: PLR2004 — 11–14 это русская грамматика, не порог
        word = "свечей"
    elif count % 10 == 1:
        word = "свеча"
    elif count % 10 in (2, 3, 4):
        word = "свечи"
    else:
        word = "свечей"
    return f"{count} {word}"
