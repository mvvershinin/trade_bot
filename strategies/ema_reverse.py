"""Торговый модуль №1: реверс по скользящей средней. Чистое намерение.

Правило целиком, дословно как у прототипа (PROTOTYPE.md §3):

::

    вход в лонг:    close  >  средняя
    вход в шорт:    close  <  средняя
    выход из лонга: close  <  средняя
    выход из шорта: close  >  средняя

Четыре строки — это два условия: «выше средней» и «ниже средней». Условие входа
в лонг и условие выхода из шорта — одно и то же, поэтому модуль отдаёт одно
намерение на свечу, а движок сам решает, вход это, выход или переворот.
Реверсная система не «ищет вход и ждёт», а всё время держит сторону рынка;
отдельного ценового стоп-лосса в основном контуре нет — стопом работает
переворот (DOMAIN.md §3).

Неравенства строгие. При закрытии **ровно** на средней у прототипа нет ни входа,
ни выхода — это шестое исключение из правила «всегда в позиции», не описанное
в ТЗ. Решением 0004 сделано настройкой с тремя значениями, умолчание — как
у прототипа. На эталонном отрезке случай не встретился ни разу: 0 свечей
из 10 878, ближайший подход 0,017 пункта. Проверить его данными нельзя
в принципе — тем важнее, что поведение здесь объявлено явно, а не получилось
само собой из знака сравнения.

Прогрев: сигналов нет, пока свечей **не больше** периода
--------------------------------------------------------
Неравенство нестрогое, и это дословное условие прототипа: `свечей <= периода`
→ выхода из обработки, сигнала нет. Отсюда

::

    свеча №(период+1) от начала ряда → первая, на которой возможен сигнал
    свеча №(период+2)                → самая ранняя возможная сделка

Проверено на эталонном отрезке: первая свеча начинается в 08:55, период 15,
сигнал возможен на закрытии 16-й свечи (10:10 → 10:15), и первый вход в журнале
прототипа записан на 10:15 — открытие 17-й свечи (PROTOTYPE.md §3).

Обратите внимание на разрыв в одну свечу: средняя существует уже на свече
№период (затравка), а сигнал на ней ещё запрещён. Если поменять `<=` на `<`,
все сделки сдвинутся на одну свечу — и ошибка будет выглядеть как «почти
совпало».

Два фильтра против пилы, оба выключены умолчанием
-------------------------------------------------
Просьба владельца счёта 05.09.2026 после дня 03.09: четыре переворота
за пятнадцать минут, −1 062 ₽. Комиссия там не главная причина — цена уходила
против на девять комиссий, — значит лечить надо не издержки, а **вход
на слабом пересечении**.

::

    threshold_percent   полоса ±X% вокруг средней; закрытие внутри неё
                        стороны не имеет вовсе. 0 — полосы нет
    confirm_bars        сколько свечей подряд закрытие обязано быть
                        по одну сторону, прежде чем сигнал станет
                        намерением. 1 — подтверждения нет

При `threshold_percent = 0` и `confirm_bars = 1` модуль ведёт себя **в точности**
как прежде: `average + average * 0.0` равно `average` без единого младшего
разряда разницы, а условие «подряд не меньше одной свечи» истинно всегда.
На этом стоит сверка с прототипом — 127 сделок из 127 при умолчании.

⚠️ **Фильтр гасит намерение целиком, то есть и выход тоже.** Реверсная система
выходит по обратному сигналу; слабый обратный сигнал — это не повод выйти
куда-то ещё, а повод не считать его сигналом. Позиция при включённом фильтре
живёт дольше. При окне 10:05–11:00 и включённом «закрывать в конце окна»
это ограничено часом; при выключенном закрытии по окну верхней границы нет,
и там фильтр держит позицию до тейка или до сильного движения.

Порядок двух фильтров значим: сперва полоса решает, есть ли сторона, потом
подтверждение считает свечи по этой стороне. Обратный порядок считал бы
подтверждения по сторонам, которых фильтр не признаёт.

⚠️ Замеряны они **порознь**, каждый на своём умолчании второго (замер
05.09.2026 на MXU6, 17.06–04.09, 79 дней, с разделением на подбор и проверку).
Совместная работа не замерена: включать оба сразу — это конфигурация, цифр
по которой нет.

⚠️ И главное про эти цифры: на выборке в сотню сделок итог любого варианта
отличается от нуля меньше чем на две стандартные ошибки. Фильтр на этих данных
**не ухудшил** результат ни в одном месяце и заметно уменьшил просадку —
но «доказано» про него говорить нельзя, и умолчание поэтому «выключено».

Чего в этом модуле нет и не будет
---------------------------------
Объёма, денег, комиссии, ГО, торгового окна, дней недели, тейк-профита,
режима работы, момента переворота, брокера и различения «бой или прогон
по истории». Всё это — `engine/`.
"""

