class UnknownStrategy(LookupError):
    """Запрошен торговый модуль, которого в этой сборке нет.

    Отдельный класс, а не `KeyError`: наверху его переводят в отказ принять
    настройки («Настройки не приняты», прежние в силе), и ловить его широким
    `except KeyError` вместе с любой другой опечаткой в словаре нельзя.
    """


@dataclasses.dataclass(frozen=True, slots=True)
class SettingsField:
    """Одно поле настроек модуля: как зовётся, откуда берётся, как подписано.

    ⚠️ **Одна таблица вместо трёх рукописных списков.** До 09.09.2026 те же
    сведения лежали в трёх местах: пары «поле модуля → поле окна» здесь,
    сборщик значений в `app/convert.py::_STRATEGY_FIELDS` и подписи полей
    в `app/runs.py::_STRATEGY_TITLES`. Правые половины не сверяло ничто
    (`D-100`): список здесь продуктовым кодом не читался вовсе, а настоящий
    перевод делал сборщик. Поле, добавленное в один список и забытое
    в другом, означало настройку, которая молча не доезжает до движка либо
    молча не подписана в снимке прогона.

    Три колонки — три читателя, и все три обязаны говорить об одном поле:
    сборщик настроек, снимок прогона и проверка полноты.
    """

    #: Как поле зовётся у самого модуля — имя в его классе настроек.
    name: str
    #: Из какого поля **общих настроек программы** оно берётся. Внешнее имя,
    #: а не своё: совпадать они не обязаны.
    #:
    #: ⚠️ Не `window`, хотя поле и показывается в окне настроек: слову «окно»
    #: в этом слое занято торговым окном, и сторож
    #: `test_the_module_does_not_speak_about_money_window_or_broker`
    #: справедливо принял бы одно за другое. Понятие торгового окна в слое
    #: стратегий не живёт вовсе (ARCHITECTURE.md §3).
    outer: str
    #: Подпись для человека — снимок настроек прогона и отчёты. Кириллица
    #: здесь законна: это текст, а не имя (`CLAUDE.md` №6).
    title: str


@dataclasses.dataclass(frozen=True, slots=True)
class SettingsDemand:
    """Требование алгоритма к **общей** настройке программы. Имена — строками.

    Есть настройки, при которых алгоритм работает не так, как обещает его
    название, и живут они не у него. «Реверс с постоянной позицией» — тот
    случай: момент переворота принадлежит движку, и при перевороте через
    свечу робот стоит вне рынка целую свечу на каждом перевороте. Название
    в окне становится ложью, а программа считает не то, что показывает.

    ⚠️ **Данные, а не рукописный `if` на границе.** Проверка нужна на **паре**
    и в обоих порядках («выбрали алгоритм при чужом перевороте» и «поменяли
    переворот при выбранном алгоритме»), и не на одном пути: применение
    настроек, запрос прогона, чтение файла настроек. Три рукописных отказа
    по личности алгоритма — это ветвление, которое обязано быть таблицей
    (правило 9 `CLAUDE.md`); `backtest/sweep.py::refuse_foreign_strategy`
    уже второй такой.

    ⚠️ **Строки, а не типы, и это не лень.** Поле типа `engine.Reversal`
    здесь означало бы, что слой стратегий импортирует движок, — прямое
    нарушение `ARCHITECTURE.md` §2, красное сторожем
    `tests/test_layers.py::test_dependency_direction`. Прецедент уже принят
    и работает: `SettingsField.outer` тоже называет строкой поле
    `ui.models.Settings`, а мост по **имени элемента** перечисления уже
    наводит `app/convert.py::_module_value`.

    ⚠️ Чего эта запись сама проверить не может: что названное поле у общих
    настроек есть, а названный элемент есть у его перечисления. Обе стороны
    сверки видит только `app/` — проверка живёт в `app/convert.py::_demand_gap`
    и роняет сборку настроек алгоритма. Без неё опечатка **молча** выключила
    бы требование целиком.
    """

    #: Поле **общих настроек программы** (`ui.models.Settings`), которое
    #: алгоритму важно. Строка, а не поле: см. разбор выше.
    outer: str
    #: Имя элемента перечисления, которого алгоритм требует, — `"SAME_BAR"`.
    #: Сверяется с `Enum.name`, а не со значением: значения перечислений
    #: окна и движка совпадать не обязаны.
    value: str
    #: Почему без этого нельзя — человеческим языком, без названия алгоритма
    #: (его подставляет тот, кто показывает фразу) и без «настройки не
    #: приняты»: та же причина читается и при отказе, и при подмене значения
    #: из файла настроек.
    reason: str


@dataclasses.dataclass(frozen=True, slots=True)
class StrategyEntry:
    """Одна строка реестра: всё, что программа знает о торговом модуле.

    Поля — данные, а не поведение: по ним собирается модуль, подписывается
    список в окне и переводятся настройки. Запись неизменяема целиком,
    включая таблицу полей (кортеж записей, а не словарь): общая таблица,
    которую можно поправить из любого места, однажды будет поправлена
    из теста и достанется соседям.
    """

    #: Имя в настройках, в журнале и в базе прогонов. Только латиница: оно
    #: уезжает в файл настроек, в командную строку и в имена шаблонов, а
    #: кириллическое имя там показывается escape-последовательностями.
    id: str
    #: Название для окна и журнала. Обязано совпадать с тем, что говорит о себе
    #: сам модуль, — иначе в списке одно, а в журнале другое.
    title: str
    #: Класс настроек модуля. По нему же отвергаются чужие настройки.
    settings_type: type[Any]
    #: Сборка модуля из его настроек.
    factory: Callable[[Any], Strategy]
    #: Поля настроек модуля: имя у модуля, имя в окне, подпись для человека.
    #: Кортеж, а не словарь: запись неизменяема целиком.
    #:
    #: ⚠️ Читается продуктовым кодом, а не только проверками: по нему
    #: `app/convert.py` собирает настройки модуля из полей окна, а
    #: `app/runs.py` подписывает их в снимке прогона. Второго такого списка
    #: в программе быть не должно — именно расхождение двух списков и было
    #: `D-100`.
    fields: tuple[SettingsField, ...]
    #: Требования алгоритма к **общим** настройкам программы: без чего его
    #: название становится ложью (`SettingsDemand`). Пустой кортеж — требований
    #: нет, и это законный ответ.
    #:
    #: ⚠️ **Без умолчания, и это условие, а не придирка.** Умолчание `()`
    #: означало бы, что алгоритм, заведённый завтра и забывший про свои
    #: требования, молча получает поведение первого — то есть работает при
    #: настройках, при которых работать не должен, и никто об этом не узнает.
    #: Пустой кортеж пишется руками: это утверждение «требований нет»,
    #: а не пропуск.
    demands: tuple[SettingsDemand, ...]
    #: Как модуль принимает решение — **сборка описания словами** по его
    #: настройкам, а не готовая строка.
    #:
    #: Строка здесь была бы рукописной, а рукописное описание расходится
    #: с кодом при первой правке модуля и расходится молча: текст не падает.
    #: Собранное же из таблицы утверждений можно **исполнить** — построить
    #: свечу под заявленное отношение и сверить намерение
    #: (`strategies/contracts.py`, `Claim`).
    describe: Callable[[Any], Description]

    def summary(self, settings: object) -> str:
        """Правило словами и без чисел — для списка выбора модуля.

        ⚠️ Настройки обязательны, и это правка дефекта, а не украшение.
        Здесь стояло свойство без аргумента, считавшее правило **по умолчаниям
        модуля**, с доводом: «отрисовка `brief()` чисел не содержит вовсе,
        поэтому от настроек не зависит». Довод неверен. Чисел в ней
        действительно нет, но **формулировки** зависят от настроек без единой
        цифры: при включённом пороге «закрытие выше средней» становится
        «закрытие выше полосы вокруг средней», при подтверждении сигнала —
        «несколько закрытий подряд выше…», а при `on_equal` меняется намерение
        в третьем утверждении. Владелец счёта, включивший фильтр против пилы —
        ровно тот параметр, по которому есть замер, — читал правило **без
        фильтра** и на вкладке, и в окне выбора (`B-039`).

        Отсюда и подпись: настройки называет тот, кто вызывает. У выбранного
        модуля это применённые настройки, у остальных — их собственные
        умолчания, и окно обязано сказать это вслух (`app/convert.py`).
        Молчаливое умолчание внутри свойства как раз и прятало развилку.

        Чужие настройки — тот же отказ, что у `build()` и `description()`.
        """
        return self.description(settings).brief()

    def description(self, settings: object) -> Description:
        """Описание с нынешними числами. Чужие настройки — отказ вслух.

        Тот же отказ, что у `build()`, и по той же причине: описание,
        собранное по чужим настройкам, рассказывало бы человеку про правило,
        по которому робот не торгует.
        """
        self._own(settings)
        return self.describe(settings)

    def titles(self) -> dict[str, str]:
        """«Поле модуля» → «подпись для человека». Снимок прогона читает это.

        Словарь, а не кортеж: читатель ищет подпись по имени поля. Собирается
        на каждый вызов из неизменяемой таблицы — общий словарь, который можно
        поправить из любого места, однажды поправили бы из теста.
        """
        return {one.name: one.title for one in self.fields}

    def defaults(self) -> StrategySettings:
        """Настройки модуля по умолчанию — его собственные, а не чужие.

        Тип ответа — `object`, а не `Any`: реестр не знает, какой класс
        настроек у модуля, и `Any` здесь означал бы «проверок больше нет»
        у **всех** вызывающих. Кому нужен конкретный тип, тот называет его
        у себя, а `build()` всё равно проверит принадлежность.

        Тип ответа — **порт настроек**: сборке от них нужны подпись линии
        и строки журнала, и больше ничего (`strategies/contracts.py`).
        """
        made: StrategySettings = self.settings_type()
        return made

    def build(self, settings: object) -> Strategy:
        """Собрать модуль. Настройки чужого модуля — отказ вслух.

        Молчаливое согласие здесь означало бы торговлю с параметрами, которых
        владелец счёта не выбирал: настройки одного модуля, поданные другому,
        либо не подошли бы по именам полей, либо — что хуже — подошли бы
        частично.
        """
        self._own(settings)
        return self.factory(settings)

    def _own(self, settings: object) -> None:
        """Настройки принадлежат этому модулю — или отказ вслух.

        Одна проверка на сборку и на описание: две написанные порознь
        разъехались бы, и одна из дорог однажды приняла бы чужое молча.
        """
        if not isinstance(settings, self.settings_type):
            raise TypeError(
                f"торговому модулю «{self.title}» ({self.id}) поданы настройки "
                f"{type(settings).__name__}, а он работает с "
                f"{self.settings_type.__name__}. Настройки одного модуля, "
                "попавшие в другой, — это торговля с параметрами, которых "
                "никто не выбирал"
            )

    def settings_gap(self) -> tuple[str, ...]:
        """Настройки модуля, которых нет в таблице полей. Пусто — таблица полна.

        Тот же приём, что у `app/convert.py::_strategy_gap()`: поле, заведённое
        завтра и забытое в таблице, молча получило бы умолчание вместо того,
        что выбрано в окне.
        """
        named = {one.name for one in self.fields}
        known = {field.name for field in dataclasses.fields(self.settings_type)}
        return tuple(sorted(known - named))

    def stray_fields(self) -> tuple[str, ...]:
        """Имена в таблице, которых у настроек модуля нет. Пусто — согласовано.

        Обратная сторона `settings_gap`: опечатка в таблице не отняла бы
        настройку, а завела бы несуществующую — и сборщик настроек упал бы
        не там, где причина.
        """
        known = {field.name for field in dataclasses.fields(self.settings_type)}
        return tuple(sorted({one.name for one in self.fields} - known))


