"""Реестр сменных торговых модулей: таблица, а не ветвление.

Программе нужно уметь менять **правило принятия решения** из настроек, а не
переписыванием кода (ТЗ §4.8). Замер 06.09.2026 объяснил, зачем: на годе данных
умолчания дали убыток на проверке, а чистую прибыль на независимой половине
года дали 112 сочетаний из 9 744 — то есть дело не в подборе цифр, а в самом
правиле (`.docs/quality/FINDINGS.md`). Значит правило обязано быть сменным.

Здесь лежит **вся** осведомлённость программы о том, какие модули существуют:
одна таблица `_ENTRIES`. Всё остальное — движок, прогон по истории, сборка
настроек — работает через порт `Strategy` и про имена модулей не знает.

Почему таблица, а не `if id == ...`
-----------------------------------
Правило 9 `CLAUDE.md`, и оно куплено замером 03.09.2026: шесть из десяти самых
длинных функций проекта оказались одним и тем же ветвлением, которое должно
было быть таблицей, и цена была не в длине — добавление настройки требовало
вспомнить три места. Здесь то же самое в чистом виде: ветвление по имени
модуля пришлось бы повторить в сборке модуля, в подписи для окна, в таблице
полей и в снимке прогона. Одна запись на модуль — одно место, где можно забыть.

⛔ Динамический импорт здесь запрещён
-------------------------------------
Реестры модулей принято собирать обходом пакета (`pkgutil`), загрузкой по имени
(`importlib.import_module`) или точками входа. **Ни одного из этих приёмов
здесь быть не должно.** Nuitka линкует то, что видит статически: собранная
программа получила бы пустой список модулей при полностью зелёном прогоне
тестов из исходников — то есть дефект, невидимый до запуска на машине
владельца счёта. Импорты в этом файле явные и только явные, и это стережёт
`tests/test_strategies_registry.py`.

Что запись знает и чего не знает
--------------------------------
Запись описывает модуль **данными**: `id` для настроек и журнала, название для
окна, класс настроек, сборку, таблицу соответствия полей общих настроек
и короткое описание правила словами. Ни одна запись не знает про окно, деньги,
комиссию и брокера — это по-прежнему `engine/` (ARCHITECTURE.md §3).

⚠️ Таблица полей — это **имена**, а не перевод значений. Реестр говорит
«поле `period` модуля берётся из поля `average_period` общих настроек»; чем
именно `average_kind` окна превращается в `AverageKind` модуля, знает `app/`,
и знать это здесь нельзя: слой стратегий не импортирует ни один слой проекта.
"""

