#: Модуль по умолчанию. ТЗ §4.8: «по умолчанию всегда выбрана скользящая
#: средняя»; подтверждено владельцем счёта 08.09.2026. Уехавшее умолчание —
#: это сборка, которая торгует не тем правилом, о котором договаривались,
#: и заметить это по экрану нельзя.
DEFAULT_ID: Final[str] = "ema_reverse"


def entries() -> tuple[StrategyEntry, ...]:
    """Все торговые модули сборки, в порядке показа в списке выбора."""
    return _ENTRIES


def known_ids() -> tuple[str, ...]:
    """Имена модулей этой сборки — для сообщений об отказе и для проверок."""
    return tuple(entry.id for entry in _ENTRIES)


def find(strategy_id: str) -> StrategyEntry:
    """Запись по имени модуля. Незнакомое имя — отказ вслух, а не умолчание.

    ⚠️ Подстановка умолчания вместо отказа была бы худшим из возможных
    ответов: программа торговала бы **другим правилом**, чем записано
    в настройках, и на экране всё выглядело бы исправно. Правило 13
    `CLAUDE.md` — молчание дороже поломки.
    """
    for entry in _ENTRIES:
        if entry.id == strategy_id:
            return entry
    raise UnknownStrategy(
        f"торгового модуля «{strategy_id}» в этой сборке нет. "
        f"Есть: {', '.join(known_ids())}. "
        "Скорее всего настройки или шаблон сделаны более новой сборкой "
        "программы: обновите программу целиком либо выберите модуль "
        "из списка в настройках"
    )


def default_entry() -> StrategyEntry:
    """Запись модуля по умолчанию. Отсутствие `DEFAULT_ID` в таблице — отказ."""
    return find(DEFAULT_ID)
