#: Требования «Реверса с постоянной позицией» к настройкам программы:
#: переворот в одной свече и выход по концу окна с предельной ценой.
#:
#: ⚠️ Замерено, а не предположено: в эталонном журнале прототипа **79
#: переворотов из 79** идут с разрывом ровно в одну пятиминутку
#: (`engine/settings.py:131`). При перевороте через свечу робот покидает
#: рынок на каждом перевороте — при названии, которое обещает обратное.
#:
#: ⚠️ Режим работы («Только лонг», «Только закрытие» и прочие) в требования
#: **не входит**, хотя тоже способен оставить робота вне рынка. Он приходит
#: другой командой и не лежит в общих настройках, а главное — отказ на смене
#: режима держал бы «Только закрытие», средство свернуть позицию, заложником
#: названия алгоритма. Человеку, которому надо выйти из рынка, программа
#: отвечала бы «настройки не приняты». Записано исключением в спецификации.
_ALWAYS_DEMANDS: Final[tuple[SettingsDemand, ...]] = (
    SettingsDemand(
        outer="reversal_moment",
        value="SAME_BAR",
        reason=(
            "требует переворота в одной свече: при перевороте через свечу "
            "робот стоит вне рынка целую свечу на каждом перевороте, а его "
            "название обещает обратное"
        ),
    ),
    # Жёсткое закрытие по концу окна (решение 0060 §3, Э5 Ф3 задачи З8):
    # заявка с предельной ценой. Она же значит «закрывать по концу окна
    # всегда» — галочка «Закрывать позицию в конце окна» её не выключает
    # (`engine.TimeExitOrder`), поэтому отдельного требования к галочке нет.
    SettingsDemand(
        outer="time_exit_order",
        value="LIMIT",
        reason=(
            "требует закрывать позицию по концу окна заявкой с предельной "
            "ценой: так велит заказчик, и выключить это закрытие нельзя"
        ),
    ),
)

#: Таблица модулей. Явные импорты, ни одного `importlib` — см. шапку файла.
