"""Торговый модуль №2: «Реверс с постоянной позицией».

Правило принятия решения у этого алгоритма **то же самое**, что у модуля №1,
и здесь оно не написано второй раз. Модуль — тонкий наследник `EmaReverse`
с собственным названием и собственным, узким классом настроек.

Почему копии правила нет — это главное в файле
----------------------------------------------
Заказанное отличие «в торговое время всегда есть позиция» слой стратегий
выговорить не может и не должен: сторона рынка, момент переворота и защита
прибыли живут в `engine/` (ARCHITECTURE.md §3). Модуль отдаёт **намерение**
на свечу, и намерение у обоих алгоритмов одно и то же:

::

    close  >  средняя   → лонг
    close  <  средняя   → шорт
    close ==  средняя   → ни входа, ни выхода: сторона не создаётся
                          и не отменяется, и открытое остаётся открытым

Отличие целиком в настройках движка — переворот подаётся в одной свече,
а не через свечу.

⚠️ **Вторая реализация того же правила была бы дефектом, а не осторожностью.**
Сверкой с прототипом — 127 сделок из 127, единственный машинный пункт приёмки
проекта — покрыт **один** расчёт: `EmaReverse`. Копия рядом расходится с ним
на мелочи, которую сверка не увидит по построению: строгость сравнения,
свеча прогрева, засев средней. Разные сделки под названием, обещающим одно
правило. Ровно по этой причине 14.09.2026 удалён проверочный `ma_crossing` —
«повторял правило первого».

Что этот модуль добавляет к первому
-----------------------------------
**Название.** `StrategyEntry.title` обязан совпадать с тем, что модуль
говорит о себе сам, иначе в списке окна одно, а в журнале другое. Голое
`factory=EmaReverse` писало бы в журнал «Реверс по скользящей средней».

**Узкие настройки.** `MaReverseAlwaysSettings` — период и тип средней,
и всё. Ни порога пересечения, ни подтверждения сигнала, ни поведения
на равенстве: документ заказчика этих настроек не знает, а класс настроек,
полный полями, которых алгоритм не читает, уже дал долг `D-107`.
Три недостающих поля **прибиты** значениями прототипа при расширении
(`MaReverseAlwaysSettings.widened`), а не берутся из окна: владелец счёта,
выбравший этот алгоритм, не должен получить фильтр против пилы, которого
он не включал.

Чего в этом модуле нет и не будет
---------------------------------
Того же, чего нет у первого: объёма, денег, комиссии, ГО, торгового окна,
дней недели, тейк-профита, режима работы, момента переворота, брокера
и различения «бой или прогон по истории».
"""

from __future__ import annotations

import dataclasses
from collections.abc import Callable
from dataclasses import dataclass
from typing import Final

from strategies.average import AverageKind
from strategies.contracts import Description, Fact, FactKind
from strategies.ema_reverse import (
    DEFAULT_PERIOD,
    EmaReverse,
    EmaReverseSettings,
    OnPriceEqualsAverage,
)
from strategies.ema_reverse import describe as describe_ema_reverse

__all__ = [
    "MaReverseAlwaysSettings",
    "MaReverseAlways",
    "PINNED_ON_EQUAL",
    "PINNED_THRESHOLD_PERCENT",
    "PINNED_CONFIRM_BARS",
    "describe",
]

#: Закрытие **ровно** на средней: ни входа, ни выхода — как у прототипа.
#:
#: ⚠️ Это и есть «равенство держит прежнюю сторону» из спецификации: `NONE`
#: движок читает как «ни входа, ни выхода», то есть открытое не закрывается
#: и не переворачивается, а если открытого не было — оно и не открывается
#: (PROTOTYPE.md §3, шестое исключение). Настройкой это у нового алгоритма
#: не сделано намеренно: документ заказчика такой настройки не знает,
#: а «всегда есть сторона» требует однозначного ответа.
PINNED_ON_EQUAL: Final[OnPriceEqualsAverage] = OnPriceEqualsAverage.LIKE_PROTOTYPE

#: Полосы вокруг средней у этого алгоритма нет: ноль процентов — это
#: дословные неравенства прототипа `close > средняя` / `close < средняя`.
PINNED_THRESHOLD_PERCENT: Final[float] = 0.0

#: Подтверждения сигнала нет: одна свеча означает «подтверждать нечем».
PINNED_CONFIRM_BARS: Final[int] = 1


@dataclass(frozen=True, slots=True)
class MaReverseAlwaysSettings:
    """Настройки алгоритма №2: период и тип средней, и больше ничего.

    ⚠️ **Три поля первого алгоритма сюда не попали намеренно.** Порог
    пересечения, подтверждение сигнала и поведение на равенстве документ
    заказчика не называет, и показывать их владельцу счёта на этом алгоритме
    значило бы предлагать ему крутить то, чего в его правиле нет. При
    расширении они прибиты значениями прототипа — `PINNED_*` выше.

    Своей проверки значений у класса нет, и это не пропуск: она была бы
    вторым написанием той же проверки. Расширенные настройки проверяют себя
    сами (`EmaReverseSettings.__post_init__`), и `__post_init__` здесь ровно
    их и строит. Диапазон периода 5–300 из ТЗ — ограничение поля ввода,
    а не правила расчёта, и здесь его нет по той же причине, что у первого.

    Своей таблицы полей взамен перечисления руками тут тоже нет: полей два,
    и таблица из двух строк с циклом по ней была бы паттерном ради паттерна
    (`CLAUDE.md` №9, обратная половина правила). Таблица полей, которую
    сверяет `settings_gap()`, живёт там, где ей место, — в реестре.
    """

    period: int = DEFAULT_PERIOD
    kind: AverageKind = AverageKind.EMA

    def __post_init__(self) -> None:
        """Проверка одна на два алгоритма: её делают расширенные настройки."""
        self.widened()

    def widened(self) -> EmaReverseSettings:
        """Настройки расчёта: свои два поля плюс три прибитых.

        Единственное место, где прибиваются три недостающих значения. Второе
        такое место означало бы алгоритм, который считает по одним настройкам,
        а рассказывает про другие.
        """
        return EmaReverseSettings(
            period=self.period,
            kind=self.kind,
            on_equal=PINNED_ON_EQUAL,
            threshold_percent=PINNED_THRESHOLD_PERCENT,
            confirm_bars=PINNED_CONFIRM_BARS,
        )

    @property
    def label(self) -> str:
        """Подпись средней для журнала и графика: `EMA(15)`."""
        return self.widened().label

    def changes_from(self, previous: "MaReverseAlwaysSettings") -> list[str]:
        """Что изменилось — строками для журнала, с прежним и новым значением.

        Считает расширенная пара, а не этот класс: строки журнала про период
        и тип средней у двух алгоритмов обязаны читаться одинаково, а
        написанные порознь они разъедутся при первой правке формулировки.
        Прибитые поля в ответ не попадают никогда — они у обеих сторон равны.
        """
        return self.widened().changes_from(previous.widened())


class MaReverseAlways(EmaReverse):
    """Реверс с постоянной позицией: то же правило, своё название и настройки.

    Наследник, а не `factory=EmaReverse`, по одной причине: название.
    `StrategyEntry.title` берётся у модуля, и голое переиспользование первого
    писало бы в журнал и в снимок прогона «Реверс по скользящей средней» —
    при том, что владелец счёта выбрал в окне другую строку.

    Переопределено ровно три вещи: название, приём **узких** настроек при
    сборке и приём их же на ходу. Расчёт, прогрев, разбор повторной свечи
    и описание правила — родительские, и это главное свойство этого класса,
    а не экономия строк: считает оба алгоритма один код, сверенный
    с прототипом сделка в сделку.
    """

    __slots__ = ()

    #: Название для окна и журнала. Названо по главному отличию, видимому
    #: человеку: этот алгоритм рынка не покидает, а первый стоит свечу
    #: на перевороте. Решение владельца счёта 14.09.2026.
    title = "Реверс с постоянной позицией"

    def __init__(self, settings: MaReverseAlwaysSettings | None = None) -> None:
        chosen = MaReverseAlwaysSettings() if settings is None else settings
        super().__init__(chosen.widened())

    def apply(self, settings: object) -> list[str]:
        """Новые настройки на ходу. Чужие — отказ вслух, а не тихое расширение.

        Довод тот же, что у `StrategyEntry._own`: настройки первого алгоритма,
        принятые здесь молча, включили бы фильтр против пилы, которого
        владелец счёта на этом алгоритме не выбирал и в окне не видел.

        Тип довода — `object`, а не свой класс: сужать тип довода
        у наследника нельзя, и проверка поэтому идёт значением, а не подписью.
        """
        if not isinstance(settings, MaReverseAlwaysSettings):
            raise TypeError(
                f"торговому модулю «{self.title}» поданы настройки "
                f"{type(settings).__name__}, а он работает с "
                f"{MaReverseAlwaysSettings.__name__}. Настройки одного "
                "алгоритма, попавшие в другой, — это торговля с параметрами, "
                "которых никто не выбирал"
            )
        return super().apply(settings.widened())


#: Текст факта про фильтр против пилы. У первого алгоритма он называет числа
#: двух полей, которых у этого нет вовсе, — и человек, прочитавший «полоса 0%,
#: подтверждение 1 свеча», пошёл бы искать их в окне.
#:
#: ⚠️ Ответ факта (`выключен`) в текст подставляется, а не пишется рядом:
#: проверка требует, чтобы ответ стоял в тексте целым словом, и второе
#: написание однажды разъехалось бы с первым (`FactKind.SAW_FILTER`).
_FILTER_TEXT: Final[str] = (
    "Фильтр против пилы {answer}, и включить его здесь нечем: ни полосы "
    "вокруг средней, ни подтверждения сигнала у этого алгоритма нет вовсе. "
    "Сигналом считается любое пересечение средней, каким бы мелким оно "
    "ни было."
)

#: Чем дописывается факт про общие настройки программы. Момент переворота
#: назван отдельно: именно он, а не правило, отвечает за то, чем этот
#: алгоритм отличается от первого, — и без этой фразы название в окне
#: осталось бы необъяснённым.
_OVERRIDE_TAIL: Final[str] = (
    " Момент переворота — тоже общая настройка, и она здесь главная: именно "
    "она решает, подаются ли выход и обратный вход подряд или робот ждёт "
    "следующую свечу."
)


def _filter_text(fact: Fact) -> str:
    """Про фильтр — своими словами: полей, о которых говорит первый, здесь нет."""
    return _FILTER_TEXT.format(answer=fact.answer)


def _override_text(fact: Fact) -> str:
    """Про общие настройки — родительский текст плюс оговорка про переворот."""
    return fact.text + _OVERRIDE_TAIL


#: Кто как пересказывается: вид факта → сборка текста по родительскому факту.
#:
#: Таблица, а не два `if`: видов факта шесть, пересказанных два, и разбор
#: ветвлением завёл бы место, где седьмой вид молча потеряется.
_RETOLD: Final[dict[FactKind, Callable[[Fact], str]]] = {
    FactKind.SAW_FILTER: _filter_text,
    FactKind.ENGINE_MAY_OVERRIDE: _override_text,
}


def _retold(fact: Fact) -> Fact:
    """Факт первого алгоритма, пересказанный для второго. Ответ не трогаем.

    ⚠️ Ответ (`Fact.answer`) остаётся родительским всегда: проверка получает
    его **исполнением модуля**, а модуль — тот же самый расчёт. Пересказ
    касается только абзаца, который читает человек.
    """
    retell = _RETOLD.get(fact.kind)
    if retell is None:
        return fact
    return dataclasses.replace(fact, text=retell(fact))


#: Как средняя называется словами — для отрисовки **без чисел**.
#:
#: ⚠️ Не украшение, а следствие узких настроек. Отрисовка без чисел видна
#: в списке выбора алгоритма, до всякого «Применить». У первого алгоритма
#: она меняется от порога, подтверждения и поведения на равенстве; у этого
#: таких полей нет, а период — число, и в отрисовку без чисел не попадает
#: по определению. Останься здесь родительское «средней», подпись не зависела
#: бы от настроек **вовсе**: `summary(settings)` был бы честным по подписи
#: и умолчанием по сути — ровно тем, чем был `B-039`.
#:
#: Тип средней при этом не число, а формулировка, и место ей именно здесь.
_KIND_IN_WORDS: Final[dict[AverageKind, str]] = {
    AverageKind.EMA: "экспоненциальной средней",
    AverageKind.SMA: "простой средней",
}

#: Как о средней говорит первый алгоритм в отрисовке без чисел. Подстановка
#: идёт по этому слову; исчезни оно из родительских формулировок — подпись
#: снова перестанет зависеть от настроек, и проверка `B-039` упадёт. Молча
#: это не пройдёт.
_PLAIN_AVERAGE: Final[str] = "средней"


def _with_kind(relation: str, kind: AverageKind) -> str:
    """«закрытие выше средней» → «закрытие выше экспоненциальной средней»."""
    return relation.replace(_PLAIN_AVERAGE, _KIND_IN_WORDS[kind])


def describe(settings: MaReverseAlwaysSettings) -> Description:
    """Как модуль принимает решение — словами, с нынешними числами.

    Описание берётся у первого алгоритма по **расширенным** настройкам
    и не пишется заново: правило одно, и два описания одного правила
    разъехались бы молча. Своего здесь четыре вещи — название, тип средней
    в отрисовке без чисел, факт про фильтр (у первого он называет числа полей,
    которых здесь нет) и оговорка про момент переворота в факте про общие
    настройки программы.

    ⚠️ Всё остальное — родительское, и потому исполняется теми же проверками:
    утверждения подаются настоящему модулю свечой-образцом, факты получают
    свой ответ исполнением (`tests/test_strategies_description.py`).
    """
    base = describe_ema_reverse(settings.widened())
    return dataclasses.replace(
        base,
        title=MaReverseAlways.title,
        claims=tuple(
            dataclasses.replace(
                claim, relation=_with_kind(claim.relation, settings.kind)
            )
            for claim in base.claims
        ),
        facts=tuple(_retold(fact) for fact in base.facts),
    )
