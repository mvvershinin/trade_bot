"""Оформление чисел для строк журнала и описаний. Общее на все торговые модули.

Вынесено из `strategies/ema_reverse.py` 14.09.2026, долг `D-106`. Пока модуль
был один, три закрытые функции у него внутри были на своём месте. Со вторым
модулем у них ровно три возможных дома, и два из них плохи:

* импортировать закрытое имя чужого модуля — значит объявить `_number`
  частью договора между модулями, ничего об этом не написав;
* копия рядом — два оформления одного и того же числа. Разъезжаются они
  молча: человек видит «284 812,53» в одной строке журнала и «284812.53»
  в другой, и понять, какая из них правда, нельзя ниоткуда;
* общий дом с открытыми именами — этот файл.

⚠️ Оформление повторяет `ui.formatting.fmt_number` (пробел между тысячами,
запятая в дробной части), но **своим кодом**: `strategies/` не импортирует
ни один слой проекта (ARCHITECTURE.md §2), а общего слоя типов среди семи нет.
Такая же функция есть и в `engine/settings.py` — и это не повод их объединять
по той же самой причине.

Здесь нет и не будет ничего, кроме превращения числа в текст для человека:
ни правила, ни настроек, ни состояния. Функция, которой понадобилось знать,
какой алгоритм её позвал, в этот файл не годится.
"""

from __future__ import annotations

__all__ = ["number", "percent", "bars"]


def number(value: float) -> str:
    """Цена для строки журнала: `284 812,53`.

    Хвостовые нули отбрасываются, дробная часть — до шести знаков: округление
    до двух знаков сделало бы строку «закрытие 1,23 выше EMA(15) 1,23»
    на инструменте с мелким шагом цены.
    """
    text = f"{value:,.6f}"
    whole, _, fraction = text.partition(".")
    fraction = fraction.rstrip("0")
    whole = whole.replace(",", " ")
    return f"{whole},{fraction}" if fraction else whole


def percent(value: float) -> str:
    """Процент для строки журнала: `0,04%`. Хвостовые нули отброшены."""
    text = f"{float(value):.6f}".rstrip("0").rstrip(".")
    return f"{text.replace('.', ',')}%"


def bars(count: int) -> str:
    """`1 свеча`, `3 свечи`, `5 свечей` — число со своим окончанием."""
    tail = count % 100
    if 11 <= tail <= 14:  # noqa: PLR2004 — 11–14 это русская грамматика, не порог
        word = "свечей"
    elif count % 10 == 1:
        word = "свеча"
    elif count % 10 in (2, 3, 4):
        word = "свечи"
    else:
        word = "свечей"
    return f"{count} {word}"
