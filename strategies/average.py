"""Скользящая средняя по ценам закрытия: EMA и SMA, затравка как у прототипа.

Тип средней — переключатель с умолчанием EMA (решение 0004). Считается **только
по ценам закрытия** и **только по закрытым свечам**: средняя, дотянутая до
незакрытой свечи, меняется внутри бара и даёт сигнал, которого в бою не будет.

Четыре правила, каждое из которых при нарушении даёт другой список сделок
--------------------------------------------------------------------------
**1. Затравка — простое среднее первых `period` закрытий, а не первое закрытие.**

::

    i <  период−1 :  средней ещё нет
    i == период−1 :  среднее арифметическое закрытий с 0 по период−1
    i >  период−1 :  E(i) = E(i−1) + 2/(период+1) * (close(i) − E(i−1))

Затравка первым закрытием даёт на эталонном отрезке **128 сделок вместо 127**
и другое время выхода уже на первой сделке (PROTOTYPE.md §3). Коварство в том,
что дальше оба ряда сходятся: ошибка выглядит как «разъехались первые сделки,
дальше всё хорошо» и легко списывается на прогрев.

**2. Средняя считается по всем свечам поданного ряда** — вечерняя сессия, ночь,
выходные. Торговое окно и запрет торговли в выходные гасят торговлю, а не
расчёт, и на границе дня средняя не сбрасывается. На эталонном отрезке
1 520 выходных свечей из 10 878 участвуют в расчёте даже при выключенных
выходных. Здесь это соблюдается само собой: модуль получает ряд и не знает
ни про окно, ни про дни недели, — а движок обязан подавать ему **весь** ряд,
а не только свечи внутри окна.

**3. Предыстории нет: счёт идёт от первой поданной свечи.** Тот же датасет,
поданный с более ранней границы, даёт на общем участке другой список сделок
целиком: к общей дате средняя приходит уже прогретой. Отрезок при сверке должен
совпадать до свечи, а не «примерно тот же период».

**4. Сравнивается закрытие со значением средней, включающим эту же свечу.**
Не с предыдущим значением. Поэтому `push()` возвращает значение уже с учётом
поданного закрытия.

Про SMA: у прототипа её нет, сверять не с чем. Затравка у неё та же по смыслу —
первое значение появляется на `period`-й свече и равно среднему тех же
`period` закрытий, дальше окно едет.
"""

from __future__ import annotations

import enum
from collections import deque
from collections.abc import Iterable
from math import fsum, isfinite

__all__ = ["AverageKind", "MovingAverage", "average_series"]


class AverageKind(enum.Enum):
    """Тип скользящей средней.

    Значения строк совпадают с `ui.models.AverageKind` намеренно: `app/`
    перекладывает выбор из окна в модуль по значению, без таблицы перевода,
    которую пришлось бы держать в двух местах синхронной.
    """

    EMA = "ema"
    SMA = "sma"

    @property
    def label(self) -> str:
        return {
            AverageKind.EMA: "Экспоненциальная (EMA)",
            AverageKind.SMA: "Простая (SMA)",
        }[self]

    @property
    def short_label(self) -> str:
        """Короткое имя для журнала и подписи на графике: `EMA`, `SMA`."""
        return {AverageKind.EMA: "EMA", AverageKind.SMA: "SMA"}[self]


class MovingAverage:
    """Средняя, которую кормят закрытиями по одному.

    Состояние — накопленные закрытия и текущее значение. Значения `None`
    до `period`-й свечи включительно означают «средней ещё нет»: это не ошибка
    и не ноль, ноль здесь был бы ценой.

    Пересчёт при смене периода делается **заново по всей истории**
    (`replay`), а не «вперёд с текущего значения»: у экспоненциальной средней
    прошлое входит в значение, и продолженный ряд не совпал бы с посчитанным
    с нуля.
    """

    __slots__ = ("_period", "_kind", "_recent_closes", "_count", "_value", "_factor")

    def __init__(self, period: int, kind: AverageKind = AverageKind.EMA) -> None:
        if isinstance(period, bool) or not isinstance(period, int):
            raise TypeError(f"период средней — целое число, получено {period!r}")
        if period < 1:
            raise ValueError(f"период средней должен быть не меньше 1, получено {period}")
        if not isinstance(kind, AverageKind):
            # Ветка выбора — сравнение по идентичности, поэтому чужое
            # перечисление с теми же строками («ema», «sma» есть и в слое окна)
            # молча провалилось бы в экспоненциальную. Владелец счёта выбрал бы
            # простую среднюю, а робот считал бы экспоненциальную — и увидеть
            # это можно было бы только сравнением графика с журналом решений.
            raise TypeError(
                f"тип средней — strategies.AverageKind, получено {kind!r}. "
                "Одноимённое перечисление другого слоя не подходит: сравнение "
                "идёт по идентичности, и выбор молча стал бы экспоненциальным"
            )
        self._period = period
        self._kind = kind
        self._factor = 2.0 / (period + 1)
        self._recent_closes: deque[float] = deque(maxlen=period)
        self._count = 0
        self._value: float | None = None

    @property
    def period(self) -> int:
        return self._period

    @property
    def kind(self) -> AverageKind:
        return self._kind

    @property
    def count(self) -> int:
        """Сколько закрытий подано с последнего сброса."""
        return self._count

    @property
    def value(self) -> float | None:
        """Текущее значение или `None`, пока свечей меньше периода."""
        return self._value

    def reset(self) -> None:
        self._recent_closes.clear()
        self._count = 0
        self._value = None

    def push(self, close: float) -> float | None:
        """Добавить закрытие и вернуть значение средней **с его учётом**.

        `nan` и бесконечность отвергаются здесь, а не только на торговом пути:
        второй публичный вход в ту же арифметику без той же защиты означал бы,
        что робот на порченых данных останавливается вслух, а отчёт по тем же
        данным печатает пустую колонку.
        """
        close = float(close)
        if not isfinite(close):
            raise ValueError(
                f"закрытие не число: {close!r}. Одного такого значения хватит, "
                "чтобы средняя стала nan до конца ряда, а все сравнения с ней — "
                "ложными"
            )
        self._count += 1
        self._recent_closes.append(close)

        if self._count < self._period:
            self._value = None
        elif self._count == self._period or self._kind is AverageKind.SMA:
            # Затравка EMA и каждое значение SMA — одна и та же формула:
            # среднее арифметическое `period` последних закрытий.
            # `fsum` вместо накопительной суммы: вычитание уходящего значения
            # копит ошибку округления на длинном ряде, а расхождение в младшем
            # знаке при строгом сравнении с ценой — это другой сигнал.
            self._value = _mean(self._recent_closes, self._period)
        else:
            previous = self._value
            assert previous is not None  # count > period ⇒ затравка уже была
            self._value = previous + self._factor * (close - previous)
        return self._value

    def replay(self, closes: Iterable[float]) -> float | None:
        """Пересчитать всё с нуля по поданной истории закрытий."""
        self.reset()
        value = None
        for close in closes:
            value = self.push(close)
        return value


def _mean(values: deque[float], period: int) -> float:
    """Среднее по окну. На ровной цене — ровно эта цена, без ошибки округления.

    Зачем отдельная ветка на флэт. Если все `period` закрытий затравки равны,
    а сама цена в двоичной плавающей точке непредставима (0,03, 0,11 — то есть
    обычная цена акции), то `сумма / period` промахивается мимо неё на 1 ULP.
    Дальше цена стоит, поправка `α·(close − E)` округляется в ноль — и средняя
    **застревает мимо цены навсегда**.

    Последствие не косметическое: прототип считает в десятичном типе, где
    0,03 представима точно, и на таком флэте отдаёт «ни входа, ни выхода».
    Мы бы отдавали лонг (или шорт) на каждой свече. Замерено: цена 0,03,
    период 15 — 25 расхождений из 40 свечей; то же на 0,11/5, 0,03/9,
    0,11/20, 0,03/30. Для целых котировок (весь диапазон срочного рынка)
    случай недостижим, для сеток 0,01 и мельче — 5–15 % цен.

    Мёртвое начало ряда — не выдумка: ночная сессия, остановленная бумага,
    первые свечи набора с одной ценой.

    ⚠️ Это лечит только флэт **в затравке**. Если ровная цена начинается
    позже, средняя подходит к ней геометрически и застревает в одном ULP
    от неё — но с той же стороны, что и в десятичной арифметике, поэтому
    знак сравнения совпадает и расхождения не даёт.
    """
    lowest = min(values)
    if lowest == max(values):
        return lowest
    return fsum(values) / period


def average_series(
    closes: Iterable[float],
    period: int,
    kind: AverageKind = AverageKind.EMA,
) -> list[float | None]:
    """Ряд значений средней: по одному на каждое закрытие, `None` до затравки.

    Чистая функция того же правила. Нужна там, где ряд считается разом, а не
    свеча за свечой: линия средней поверх истории на графике и в отчёте прогона.
    Считать её вторым способом нельзя — на экране оказалась бы одна средняя,
    а в решениях робота другая.
    """
    average = MovingAverage(period, kind)
    return [average.push(close) for close in closes]
