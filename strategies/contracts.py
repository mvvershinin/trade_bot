class Intent(enum.Enum):
    """Намерение торгового модуля на закрытой свече.

    Три значения, и третье — не «ошибка» и не «нет данных», а полноценный ответ
    «ни входа, ни выхода». Именно так ведёт себя прототип при закрытии ровно
    на средней (PROTOTYPE.md §3) и во время прогрева.
    """

    LONG = "long"
    SHORT = "short"
    NONE = "none"

    @property
    def label(self) -> str:
        return {Intent.LONG: "Лонг", Intent.SHORT: "Шорт", Intent.NONE: "Ничего"}[self]

    @property
    def in_words(self) -> str:
        """Намерение фразой — для описания правила словами (`Claim`).

        Второе оформление рядом с `label`, а не вместо него, и это не вкус.
        `label` — подпись в таблице и в столбце журнала, там нужно
        существительное. Описание правила читается предложением, и
        «Закрытие выше EMA(15) — Лонг» в нём звучит как заголовок графы,
        а не как объяснение.

        ⚠️ Формулировка намеренно говорит «хочет», а не «покупает»: намерение
        не приказ (см. шапку модуля). Войдёт ли робот на самом деле, решает
        движок по окну, режиму, тейку, объёму и предохранителям.
        """
        return {
            Intent.LONG: "робот хочет быть в лонге",
            Intent.SHORT: "робот хочет быть в шорте",
            Intent.NONE: "ни входа, ни выхода",
        }[self]


@dataclass(frozen=True, slots=True)
class Bar:
    """Закрытая свеча, как её видит торговый модуль.

    `closes_at` — время **закрытия**, а не начала. Про имя поля — в шапке модуля;
    коротко: у свечи слоя данных поле `time` означает начало, и совпадение имён
    сделало бы подмену слоёв молчаливой.

    `volume` со значением по умолчанию: модулю №1 объём не нужен, а модуль,
    которому он нужен, обязан сам проверить, что его заполнили, — ноль здесь
    означает «не задан», а не «сделок не было».
    """

    closes_at: datetime
    open: float
    high: float
    low: float
    close: float
    volume: float = 0.0


@dataclass(frozen=True, slots=True)
class Decision:
    """Ответ модуля на закрытую свечу.

    `reason` — причина человеческим языком, для журнала решений (ТЗ §4.6).
    Формулирует её модуль, а не движок: движок не знает, что у модуля внутри
    (ARCHITECTURE.md §1), и «закрытие выше EMA(15)» составить не может. Готовую
    строку журнала движок собирает из этой причины и своей части — объёма,
    режима, номера контракта.

    `average` — значение средней на этой же свече, то самое, с которым сравнивалось
    закрытие. Отдаётся наружу не для красоты: линию средней на графике рисуют
    по этим числам, а не пересчитывают заново. Пересчёт на стороне окна означал бы,
    что на экране одна средняя, а в решениях робота другая. `None` — средней
    ещё нет (прогрев).

    `warmed_up` — прогрев пройден. Отличает «сигнала нет, потому что данных мало»
    от «сигнала нет, потому что закрытие ровно на средней»: намерение в обоих
    случаях `NONE`, а смысл разный.

    `skip_bar` — **свеча в обработку не идёт вовсе**. Читать движку обязательно,
    см. отдельный разбор ниже.

    Два поля, а не одно: они совпадают везде, кроме повторно поданной свечи.
    Там прогрев давно позади (`warmed_up` истинно), а обрабатывать её второй раз
    нельзя (`skip_bar` тоже истинно).

    Почему `skip_bar` — не то же самое, что «намерение NONE»
    -------------------------------------------------------
    `NONE` означает «ни входа, ни выхода» — движок продолжает обработку свечи:
    переставляет тейк, закрывает по концу окна. Прогрев — другое: шаг 2
    `PROTOTYPE.md` §2 выходит из обработки свечи **целиком**, то есть **до**
    шага 5 (переставить тейк) и **до** шага 6 (закрытие в конце окна).

    Разница невидима на эталонном прогоне: прогрев 19.06 приходится на
    08:55–10:10, позиции ещё нет, шаги 5 и 6 пустые. Сверка с прототипом этой
    ошибки **не поймает**. Вылезет она на прогоне, начатом внутри открытой
    позиции, и при выключенном «закрывать в конце окна» — там, где сверять
    уже не с чем.
    """

    intent: Intent
    reason: str
    close: float
    average: float | None = None
    bars: int = 0
    warmed_up: bool = False
    skip_bar: bool = False


# ---------------------------------------------------------------------------
# Описание правила словами: таблица утверждений, а не написанный текст
# ---------------------------------------------------------------------------
#
# Владелец счёта, глядя в окно настроек, видит поля «Период средней» и «Порог
# пересечения» — и нигде не написано, что робот с ними делает. Узнать правило
# можно только прочитав исходник; он не программист и принимает по этим полям
# решения о деньгах.
#
# Соблазн — написать абзац руками в окне. Он разойдётся с кодом при первой
# правке модуля, и разойдётся молча: текст не падает. Поэтому описание
# приходит **от самого модуля** (тот же приём, что у `Decision.reason`
# и `EmaReverseSettings.changes_from`: текст принадлежит тому, кто его
# посчитал), а внутри модуля оно не пишется, а **собирается из таблицы
# утверждений**.
#
# Смысл именно в этом переносе. Пока направление живёт в тексте, соврать
# может текст, и поймать это нечем. Как только направление живёт в таблице,
# а текст собирается из неё общей функцией, соврать может только таблица —
# а таблицу можно **исполнить**: построить свечу, удовлетворяющую заявленному
# отношению, подать её модулю и сверить полученное намерение с заявленным.
# Мутация `close > average` → `close < average` в модуле роняет такую проверку
# (`tests/test_strategies_description.py`).
#
# ⚠️ Насколько описание «проверяется машиной» — замер, а не самоощущение
# ---------------------------------------------------------------------
# 09.09.2026 механизм замерили мутациями, и название оказалось сильнее сути:
# из 1562 знаков полного описания при умолчаниях исполнялось **67 (4,3 %)**.
# Шесть правдоподобных подмен прошли молча — «средняя считается по максимумам»,
# «система не реверсная», «первое решение на свече 22», выключенный фильтр
# назван включённым. Хуже того, беззащитными были **подписи самих утверждений**:
# поменять местами слова «выше» и «ниже», не трогая знак сравнения, — и
# проверка оставалась зелёной, потому что модуль на той же свече отвечал
# тем же намерением.
#
# Отсюда нынешнее устройство и его честные границы. Описание делится на три
# части, и они **разного веса**:
#
# * `claims` — исполняются: слово отношения сверяется с образцом, образец
#   подаётся модулю, намерение сверяется с заявленным, причина решения обязана
#   назвать сторону тем же словом;
# * `facts` — исполняются: у каждого факта есть ответ, который проверка
#   получает **от модуля** (по каким ценам считается средняя, на какой свече
#   возможно первое решение, включён ли фильтр), и текст обязан этот ответ
#   содержать;
# * `lead` и `notes` — **проза**. Объяснение «что такое скользящая средняя»
#   утверждением о поведении не является и исполняться не может. Проза
#   названа прозой и в долю проверяемого не засчитывается.
#
# Замер после правки — в отчёте `.docs/strategy/`; доля считается по знакам,
# тем же способом, что и до неё.


@dataclass(frozen=True, slots=True)
class Claim:
    """Одно утверждение описания: отношение закрытия к правилу → намерение.

    Два оформления отношения, потому что описание показывается дважды:

    * `relation` — **без чисел**: «закрытие выше средней». Видно в списке
      выбора модуля, до всякого «Применить», когда настроек ещё нет;
    * `detail` — **с числами** нынешних настроек: «закрытие выше EMA(15)».
      Пересчитывается на каждом применении настроек и уходит в окно, в журнал
      решений и в снимок настроек прогона.

    Развилки «статическое или зависящее от настроек» здесь нет намеренно:
    статическое ничего не говорит про сегодняшний период, а зависящее
    от настроек становится ложью при их смене, если его не пересчитывать.
    Берётся одна таблица и две отрисовки из неё.

    ⚠️ `relation` обязано быть свободно от цифр — это подпись **правила**,
    а не настроек. Стережёт `tests/test_strategies_description.py`.

    Исполняемая часть
    -----------------
    `probe` по текущему значению средней возвращает закрытие, которое
    заявленному отношению удовлетворяет, а `bars` говорит, сколько таких
    свечей подряд нужно, чтобы отношение стало намерением (при включённом
    подтверждении сигнала одной мало). Этих двух полей достаточно, чтобы
    проверка **исполнила** описание, ничего не зная про устройство модуля.

    ⚠️ `probe` получает среднюю **до** подачи свечи, а модуль сравнивает
    закрытие со средней, уже включающей эту свечу. Значит запас, который
    `probe` берёт от границы, обязан пережить сдвиг средней в свою сторону.
    Это забота модуля: он один знает свою арифметику.
    """

    #: Отношение без чисел — для списка выбора модуля.
    relation: str
    #: То же отношение с нынешними числами — для окна, журнала и снимка.
    detail: str
    #: Что модуль решает, когда отношение выполнено.
    intent: Intent
    #: Закрытие, удовлетворяющее отношению, по значению средней.
    probe: Callable[[float], float]
    #: Сколько таких свечей подряд нужно, чтобы намерение появилось.
    bars: int = 1


class FactKind(enum.Enum):
    """О чём факт — и, значит, чем проверка его исполняет.

    Перечисление закрытое и полное намеренно: проверка ходит по нему,
    а не по тому, что модуль решил объявить. Вид, заведённый здесь и никем
    не исполняемый, роняет прогон — иначе появилась бы графа «факт», которую
    никто не проверяет, и мы вернулись бы туда, откуда пришли.

    Каждый вид описан вместе с **процедурой исполнения**: сама процедура
    живёт в проверке (`tests/test_strategies_description.py`), а здесь
    записано, что именно она делает, — чтобы модуль №2 знал, что от него
    потребуют, до того как напишет первую фразу.
    """

    #: По каким ценам свечи считается правило. Ответ — слово из словаря
    #: проверки («закрытия», «максимумам», …).
    #:
    #: Исполнение: прогретому модулю подаётся свеча, у которой изменена
    #: **только** названная цена — среднее обязано сдвинуться; и свеча,
    #: у которой изменены все остальные, а названная нет, — среднее обязано
    #: остаться прежним. Мутация «считается по максимумам» падает на первой же.
    PRICE_SOURCE = "price_source"

    #: Номер свечи ряда (считая с единицы), на которой возможно первое
    #: решение. Ответ — число текстом.
    #:
    #: Исполнение: свежему модулю подаётся ряд с начала, ищется первая свеча,
    #: которая **пошла в обработку** (`skip_bar` ложно). Мутация «первое
    #: решение на свече `период + 7`» падает здесь.
    FIRST_DECISION_BAR = "first_decision_bar"

    #: Отсчёт начинается заново после `reset()` — то есть при смене отрезка,
    #: который робот разбирает. Ответ — фраза из словаря проверки.
    #:
    #: Исполнение: модуль прогревается, получает `reset()` и одну свечу —
    #: она обязана снова оказаться свечой прогрева.
    RESTART = "restart"

    #: Включён ли фильтр против пилы. Ответ — «включён» или «выключен».
    #:
    #: Исполнение — по тому, что фраза и обещает: прогретому модулю подаётся
    #: **сколь угодно мелкое** пересечение средней. Ответило стороной —
    #: фильтр выключен; ответило «ни входа, ни выхода» — включён.
    SAW_FILTER = "saw_filter"

    #: Есть ли у модуля отдельный сигнал «выйти». Ответ — фраза из словаря
    #: проверки.
    #:
    #: Исполнение: в таблице утверждений достижимы оба направления, и каждое
    #: из них исполнено проверкой А — значит выходом служит противоположный
    #: сигнал, а не отдельное решение.
    REVERSAL = "reversal"

    #: Общие настройки программы способны отменить любое намерение модуля.
    #:
    #: ⚠️ Единственный вид, который модуль исполнить **не может**: это
    #: утверждение про `engine/`, а слой стратегий про движок не знает
    #: (ARCHITECTURE.md §2). Умолчать о нём тоже нельзя — иначе описание
    #: модуля прочтут как полное правило поведения робота. Поэтому факт
    #: объявляется здесь, а исполняется в проверке движка, и передача
    #: сверяется списком: вид, никем не исполняемый, роняет прогон.
    ENGINE_MAY_OVERRIDE = "engine_may_override"


@dataclass(frozen=True, slots=True)
class Fact:
    """Утверждение о самом модуле: фраза для человека и её проверка машиной.

    `Claim` отвечает на вопрос «где закрытие → что решает модуль». Факт
    отвечает на другой: **какой это модуль** — по каким ценам он считает
    правило, на какой свече ряда возможно первое решение, включён ли у него
    фильтр против пилы. Такие фразы человек читает как обещание о поведении,
    и до 09.09.2026 они были обычной прозой: подмена «по ценам закрытия»
    на «по максимумам» не роняла ничего.

    Два поля, а не одно, и в этом весь приём:

    * `answer` — то же самое **машинным ответом**: слово из закрытого словаря
      проверки или число текстом. Проверка получает свой ответ, **исполнив
      модуль**, и сверяет с этим;
    * `text` — абзац, который читает человек, собранный вокруг `answer`.
      Проверка требует, чтобы `answer` в нём стоял целым словом.

    Соврать теперь можно только двумя способами сразу. Подменили текст —
    в нём не осталось ответа, проверка падает. Подменили и ответ — он разошёлся
    с исполнением, проверка падает. Согласованно поменять и то и другое —
    значит поменять поведение модуля, а это уже другая работа.

    ⚠️ Проверяется **ответ, а не абзац**. Объяснение вокруг ответа остаётся
    прозой, и в доле проверяемого оно не считается: обещать обратное значило бы
    вернуть ровно ту ошибку, ради которой этот класс заведён.
    """

    #: О чём факт — по нему проверка выбирает процедуру исполнения.
    kind: FactKind
    #: Машинный ответ: слово из словаря проверки или число текстом.
    answer: str
    #: Абзац для человека. Обязан содержать `answer` целым словом.
    text: str


@dataclass(frozen=True, slots=True)
class Description:
    """Как модуль принимает решение — словами. Три отрисовки одной таблицы.

    Что здесь есть и чего нет
    -------------------------
    Описание рассказывает **как принимается решение**, и ничего не обещает.
    «Ищет разворот тренда», «работает лучше на волатильном рынке», «надёжный
    сигнал» — неправда: модуль сравнивает закрытие со средней, и всё. Список
    запрещённых слов-обещаний стоит в проверке, но это дымовой извещатель,
    а не доказательство: он ловит слова, которые мы придумали, а не обещание,
    которого не придумали.

    Результатов на истории здесь тоже нет. Замер 06.09.2026 (убыток
    на независимом периоде) — это отчёт о результатах, а описание — правило;
    смешивать их значит превращать объяснение в рекламу или в приговор.

    Границы модуля названы вслух
    ----------------------------
    Торговое окно, тейк-профит, объём, комиссия, режим и момент переворота
    в описании числами **не упоминаются**: они общие, живут в `engine/`
    и в каждом модуле не дублируются (ARCHITECTURE.md §3) — продублированные,
    они разошлись бы молча. Но умолчать о них нельзя, иначе описание модуля
    прочтут как полное правило поведения робота. Отсюда факт
    `ENGINE_MAY_OVERRIDE` про то, что любое намерение могут отменить общие
    настройки; исполняет его проверка движка, а не сам модуль.

    Что здесь исполняется, а что проза
    ----------------------------------
    Исполняются `claims` и `facts` — и только они. `lead` и `notes` —
    **проза**: объяснение для человека, машиной не проверяемое ничем.

    ⚠️ Проза названа прозой не для порядка в словах. До 09.09.2026 весь текст
    описания числился «собранным из таблицы», и это читалось как «проверено»;
    замер показал 4,3 % исполняемых знаков и шесть правдоподобных подмен,
    прошедших молча. Прикидка покрытия рассуждением здесь не годится:
    её обязана делать мутация.
    """

    #: Название модуля — то же, что в списке выбора и в журнале.
    title: str
    #: Вступление с нынешними числами: что вообще считает модуль.
    #:
    #: ⚠️ **Проза.** Проверка требует от него ровно одного: назвать все
    #: направляющие слова таблицы утверждений («выше», «ниже»). Всё
    #: остальное — объяснение, и машиной оно не проверяется.
    lead: str
    #: Таблица утверждений: отношение закрытия к правилу → намерение.
    #: Исполняется целиком — слово, образец, намерение, причина решения.
    claims: tuple[Claim, ...]
    #: Факты о самом модуле: ответ, полученный исполнением, и абзац вокруг
    #: него. Исполняется **ответ**, а не абзац (`Fact`).
    facts: tuple[Fact, ...] = ()
    #: Обрамляющие абзацы. ⚠️ **Проза**, машиной не проверяется. Всё, что
    #: утверждает факт о поведении, обязано жить в `facts`, а не здесь.
    notes: tuple[str, ...] = ()

    def brief(self) -> str:
        """Без чисел — для списка выбора модуля, до всякого «Применить».

        Настроек в этой отрисовке нет вовсе: она обязана читаться одинаково
        при любых числах в полях, потому что показывается тогда, когда числа
        ещё не применены.
        """
        return f"{self.title}: " + _claims_in_a_row(self.claims, numbers=False)

    def headline(self) -> str:
        """Одной строкой с нынешними числами — для журнала решений.

        Журнал решений — таблица; многострочный абзац в ней не читается.
        Но и промолчать нельзя: без этой строки разобрать потом, **почему
        в тот день робот повёл себя иначе**, нечем — настройки в журнале
        есть, а правило, которое из них получилось, нет.
        """
        return f"{self.title}: " + _claims_in_a_row(self.claims, numbers=True)

    def full(self) -> str:
        """Абзацами с нынешними числами — для окна настроек и снимка прогона.

        Порядок частей: что считаем → таблица утверждений → факты о модуле →
        оговорки. Оговорки идут последними намеренно: человек, прочитавший
        только первые три части, уже знает правило, а не половину правила.
        """
        blocks = [self.lead, "\n".join(
            f"• {_capitalized(claim.detail)} — {claim.intent.in_words}."
            for claim in self.claims
        )]
        blocks.extend(fact.text for fact in self.facts)
        blocks.extend(self.notes)
        return "\n\n".join(block for block in blocks if block)

    def fact(self, kind: FactKind) -> Fact | None:
        """Факт этого вида или `None`, если модуль его не объявил.

        Нужен проверке и отчёту о покрытии: искать факт перебором `facts`
        в трёх местах значило бы завести три почти одинаковых цикла.
        """
        for item in self.facts:
            if item.kind is kind:
                return item
        return None


def _claims_in_a_row(claims: tuple[Claim, ...], *, numbers: bool) -> str:
    """Утверждения одной строкой. Общая сборка для обеих коротких отрисовок.

    Одна функция на все модули и все отрисовки: текст утверждения нигде
    не пишется руками, иначе смысл переноса правила в таблицу теряется.
    """
    parts = [
        f"{claim.detail if numbers else claim.relation} — {claim.intent.in_words}"
        for claim in claims
    ]
    return "; ".join(parts) + "."


def _capitalized(text: str) -> str:
    """Первая буква прописная. `str.capitalize()` не годится: он гасит остальные."""
    return text[:1].upper() + text[1:]


@runtime_checkable
class StrategySettings(Protocol):
    """Порт «настройки модуля»: то, на что вправе рассчитывать сборка.

    Настройки каждого модуля — его собственные (ARCHITECTURE.md §3), и
    сборка (`app/`) их не толкует: она собирает их по таблице полей реестра
    и перекладывает готовое. Но две вещи ей от них нужны, и обе — **текст,
    посчитанный самим модулем**:

    * `label` — короткая подпись линии, которую модуль рисует на графике;
    * `changes_from` — строки журнала «было → стало» на каждое изменение.

    Почему порт, а не класс модуля №1. До 09.09.2026 `app/runs.py`,
    `app/port.py` и `app/leaders.py` называли `EmaReverseSettings` по имени —
    то есть сборка знала, каким алгоритмом торгует. Второй алгоритм при этом
    не падал бы: он **молча** не доехал бы до движка, а окно показывало бы
    его название (миниплан `strategy-modules-switchable.md`, З2).

    ⚠️ Обе строки собирает модуль, а не сборка, и это то же правило, что
    у `Decision.reason` и `backtest.headline`: текст принадлежит тому, кто
    его посчитал. Написанный в `app/` или в `ui/`, он разошёлся бы с кодом
    при первой правке модуля — и разошёлся бы молча, потому что текст
    не падает.
    """

    @property
    def label(self) -> str:
        """Короткая подпись линии модуля на графике: `EMA(15)`.

        Пустая строка — законный ответ: у модуля, который линии не рисует,
        подписывать нечего, и окно тогда её не показывает.
        """

    def changes_from(
        self,
        previous: Any,  # noqa: ANN401 — контравариантность доводов, разбор ниже
    ) -> list[str]:
        """Что изменилось против прежних настроек — строками для журнала.

        ТЗ §4.4 А: изменение настройки пишется **с прежним и новым**
        значением. Пустой список означает «ничего не поменялось».

        ⚠️ `previous` — настройки **того же** модуля. Сборка обязана
        сравнивать только однородное: при смене самого алгоритма прежние
        настройки принадлежат другому классу, и строка «было → стало»
        по ним не составляется (`app/convert.py::rule_changes`).

        ⚠️ Почему здесь `Any`, а не порт и не `object`. Реализация принимает
        **свой** класс настроек (`EmaReverseSettings.changes_from`), то есть
        более узкий тип, чем порт. Объявить здесь `object` или сам порт
        значило бы требовать от реализации принимать чужие настройки —
        по правилу контравариантности доводов протокол с более широким
        доводом реализацией не удовлетворяется. `Any` — единственная
        запись, при которой порт описывает то, что есть на самом деле:
        однородность доводов держит не система типов, а `StrategyEntry._own`
        и `app/convert.py::rule_changes`.
        """


@runtime_checkable
class Strategy(Protocol):
    """Порт «стратегия» со стороны модуля: то, на что вправе рассчитывать движок.

    Движок не знает, какая стратегия внутри, и не знает её настроек: он подаёт
    закрытые свечи и получает намерения. Всё, что специфично для модуля —
    период, тип средней, поведение на равенстве, — живёт в самом модуле и
    сохраняется отдельно от общих настроек (ARCHITECTURE.md §3).
    """

    @property
    def title(self) -> str:
        """Название модуля для окна и журнала."""

    def reset(self) -> None:
        """Забыть накопленные свечи: прогрев начнётся заново.

        Прогрев отсчитывается от начала поданного ряда, предыстории у модуля нет
        (PROTOTYPE.md §3). Поэтому сброс — это не «очистка кэша», а смена ряда:
        тот же файл, поданный с другой начальной даты, даёт другой список сделок
        целиком.
        """

    def on_closed_bar(self, bar: Bar) -> Decision:
        """Намерение на закрытии свечи.

        ⚠️ **При `Decision.skip_bar` движок обязан выйти из обработки свечи
        целиком** — до перестановки тейка (шаг 5 `PROTOTYPE.md` §2) и до
        закрытия по концу окна (шаг 6). Это шаг 2 прототипа. Прочитать
        `skip_bar` как обычное «сигнала нет» — значит на прогреве и на
        повторно поданной свече делать то, чего прототип не делает.

        Что бросает — и это часть порта, а не деталь реализации:

        :raises TypeError:
            подан объект не той формы: свеча другого слоя (поле `time`),
            не свеча вовсе, нечисловое закрытие, несравнимое время.
            Это дефект связки слоёв, а не рыночное событие: движку следует
            падать, а не продолжать.
        :raises ValueError:
            закрытие `nan` или бесконечность; свеча из прошлого — время
            закрытия **раньше** предыдущего. Обе — порча входных данных.

        Штатный повтор последней свечи (переподключение к потоку) исключением
        **не** является: возвращается решение с `skip_bar`. Оборачивать вызов
        широким `except` не нужно и нельзя.
        """


def check_bar(bar: object) -> None:
    """Свеча пригодна для решения — или отказ вслух. Молчание дороже.

    Проверяется то, что нельзя доверить утиной типизации:

    * поле `time` — признак свечи слоя данных, где оно означает **начало**;
    * отсутствие `closes_at` и `close` — объект вообще не свеча модуля;
    * закрытие не число, `nan` или бесконечность.

    Про `nan` отдельно. Он не падает, а расползается: любое сравнение с ним
    ложно, поэтому закрытие-`nan` попало бы в ветку «ровно на средней», а сама
    средняя стала бы `nan` навсегда — и дальше каждая свеча уходила бы в ту же
    ветку. При настройке «считать сигналом на лонг» это сигнал на покупку
    на каждой свече до перезапуска. Такое обязано останавливаться на входе.

    Стоимость — несколько проверок на свечу: раз в пять минут в бою и десять
    тысяч раз за прогон по истории. Цена молчаливой подмены — другой список
    сделок при зелёных тестах.
    """
    if hasattr(bar, "time"):
        raise TypeError(
            "у свечи есть поле `time` — это объект другого слоя, где `time` "
            "означает НАЧАЛО свечи. Торговому модулю подаётся свеча со временем "
            "ЗАКРЫТИЯ в поле `closes_at`. Преобразование — обязанность engine/, "
            "и оно обязано быть явным, иначе всё уедет на один бар"
        )
    missing = [name for name in ("closes_at", "close") if not hasattr(bar, name)]
    if missing:
        raise TypeError(
            f"это не свеча торгового модуля: нет полей {', '.join(missing)}. "
            "Ожидается объект формы strategies.Bar"
        )
    close = getattr(bar, "close")
    try:
        value = float(close)
    except (TypeError, ValueError) as error:
        raise TypeError(f"закрытие свечи не число: {close!r}") from error
    if not isfinite(value):
        raise ValueError(
            f"закрытие свечи не число: {value!r}. Средняя стала бы nan навсегда, "
            "а сравнения с ней — ложными: робот молча ушёл бы в ветку "
            "«закрытие ровно на средней» на каждой свече"
        )
