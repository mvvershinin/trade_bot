"""Сменные торговые модули; первый — реверс по скользящей средней.

Модуль получает **закрытые** свечи и отдаёт **намерение**: лонг, шорт или ничего.
Больше он не делает ничего и больше ничего не знает: ни объёма, ни денег,
ни комиссии, ни ГО, ни торгового окна, ни тейк-профита, ни режима работы,
ни момента переворота, ни брокера — и уж точно не знает, пришла свеча из потока
реального времени или из базы при прогоне на истории. Всё это живёт в `engine/`
и в каждом модуле не дублируется (ARCHITECTURE.md §3).

Слой не импортирует ни один слой проекта. Типы свечи и намерения объявлены
здесь же, соответствие им структурное: движок подаёт объект нужной формы.
У свечи модуля время — **закрытия**, и поле называется `closes_at`, а не `time`;
почему именно так — в `strategies/contracts.py`.

Одно правило для движка, которое нельзя вывести из намерения
-----------------------------------------------------------
`Decision.skip_bar` означает «свеча в обработку не идёт **целиком**»: движок
обязан выйти до перестановки тейка и до закрытия по концу окна — это шаг 2
`PROTOTYPE.md` §2. Так помечены прогрев и повторно поданная свеча. Намерение
`NONE` при этом означает другое — «ни входа, ни выхода», обработка свечи
продолжается. Разница невидима на эталонном прогоне и сверкой не ловится.

Что здесь считается дефектом, даже если ничего не упало:

* любое `if режим == тестер` или иное различение боевого и тестового пути;
* решение по незакрытой свече;
* появление объёма, комиссии, окна, тейка или брокера в любом виде;
* средняя, посчитанная не по закрытиям или не по всему поданному ряду.

Какие модули существуют — знает `strategies/registry.py`
--------------------------------------------------------
Модуль сменный, и выбор живёт в настройках (ТЗ §4.8). Список того, из чего
выбирают, лежит **одной таблицей** в `strategies/registry.py`: запись на модуль,
в ней `id`, название, класс настроек, сборка, соответствие полей общим
настройкам программы и описание правила словами. Больше нигде в программе
имён торговых модулей быть не должно — движок работает через порт `Strategy`.

⛔ Реестр собирается **явными импортами**. `importlib`, обход пакета `pkgutil`
и точки входа здесь запрещены: Nuitka линкует то, что видит статически,
и собранная программа получила бы пустой список модулей при полностью зелёном
прогоне тестов из исходников.
"""

