"""Стоимость пункта цены: сколько рублей приносит движение на один пункт.

Свойство инструмента, а не торговое правило: биржа объявляет его сама
(`MINSTEP` и `STEPPRICE` в карточке), и слой данных только читает
(`market.iss.InstrumentSpec`). Движок получает готовое число и не знает,
откуда оно взялось (ARCHITECTURE.md §1).

Зачем модуль нужен отдельно от `market.iss`
-------------------------------------------
`IssClient.security` спрашивает карточку **на названном рынке**. Порт
инструмента знает только тикер: в настройках окна стоит строка `MXU6`,
и кода класса рядом с ней нет. Поэтому рынок здесь **подбирается**:
сперва срочный, затем акции. Порядок не случаен — программа торгует
фьючерсами, и для них ответ приходит с первого запроса.

Ошибки не выбрасываются наружу, а превращаются в слова
------------------------------------------------------
У вызывающего один вопрос — «сколько рублей в пункте» — и два законных
ответа: число либо причина, по которой числа нет. Причина обязана быть
фразой: **молчаливая единица хуже отказа**. Умолчание 1,0 верно для одного
контракта из шести (замер 05.09.2026: `MXU6` — 1,00, `SiU6` — 1,00,
`GZU6` — 1,00, `SRU6` — 1,00, `RIU6` — 1,73774, `BRV6` — 868,872),
и ошибка при нём тихая: сделки те же, деньги другие.

⚠️ **Величина плавает.** У РТС и Брента стоимость шага считается через курс
доллара и пересчитывается на клиринге. Снять её однажды и запомнить навсегда —
это вторая тихая ошибка вместо первой; когда перечитывать, решает вызывающий
(`app/port.py`, `POINT_VALUE_GAP`).
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from market.iss import (
    FUTURES,
    SHARES,
    InstrumentSpec,
    IssClient,
    IssError,
    IssUnknownInstrument,
    Market,
)

__all__ = ["MARKETS_PROBED", "PointValue", "ask_point_value"]

#: Рынки, на которых ищется тикер, и порядок поиска. Срочный первым:
#: программа торгует фьючерсами, и для них ответ приходит с первого запроса.
#: Второй запрос уходит только тогда, когда первый ответил «такого не знаю», —
#: то есть за акцию платится один лишний запрос, а за фьючерс ни одного.
MARKETS_PROBED: tuple[Market, ...] = (FUTURES, SHARES)


@dataclass(frozen=True, slots=True)
class PointValue:
    """Что удалось узнать о стоимости пункта. Молчаливого ответа здесь нет.

    `rubles` — число либо `None`. `None` **не повод подставить единицу**:
    единица подставленная и единица подтверждённая выглядят одинаково,
    а стоят разного — по `BRV6` разница в 869 раз.

    `told` заполнен **всегда**, и в обоих случаях это фраза для человека:
    при числе — откуда оно взялось (уходит в поле «Стоимость пункта
    подсказана: …» окна настроек), без числа — почему его нет. Пустым
    не бывает: молчание здесь означало бы, что владелец счёта видит
    в отчёте деньги и не знает, на чём они посчитаны.
    """

    symbol: str
    rubles: float | None
    told: str
    spec: InstrumentSpec | None = None

    @property
    def confirmed(self) -> bool:
        """Биржа назвала величину. Ложь — в поле осталось прежнее число."""
        return self.rubles is not None


def ask_point_value(
    client: IssClient,
    secid: str,
    *,
    markets: Sequence[Market] = MARKETS_PROBED,
) -> PointValue:
    """Спросить у биржи стоимость пункта. Синхронно, без токена и бесплатно.

    Идёт по рынкам, пока инструмент не найдётся. «Не знаю такого» — не отказ,
    а повод спросить на следующем рынке: у фьючерса и акции один и тот же
    вид тикера, и различить их по строке нельзя.

    ⚠️ Найденный инструмент **останавливает поиск**, даже если стоимости шага
    у него нет. У акций колонки `STEPPRICE` нет вовсе, и идти за ней на
    срочный рынок значило бы взять чужой контракт с похожим именем.

    :param client: чем ходить на биржу. Повторы и разбор — его забота.
    :param secid: тикер как он стоит в настройках окна.
    :param markets: где искать и в каком порядке. Пустая
        последовательность — ответ «искать было негде», а не исключение:
        отвечать здесь надо словами, как и на всё остальное.
    """
    for market in markets:
        try:
            spec = client.security(secid, market=market)
        except IssUnknownInstrument:
            continue
        except IssError as trouble:
            return PointValue(secid, None, _silent(market, trouble))
        return _answer(secid, spec)
    return PointValue(secid, None, _nowhere(secid, markets))


def _answer(secid: str, spec: InstrumentSpec) -> PointValue:
    """Карточка найдена: число либо причина, по которой числа в ней нет."""
    rubles = spec.ruble_per_point
    if rubles is None or rubles <= 0:
        return PointValue(secid, None, _no_step_price(spec, rubles), spec)
    return PointValue(secid, rubles, _source(spec), spec)


def _source(spec: InstrumentSpec) -> str:
    """Откуда взялось число — фразой, которую окно показывает как есть.

    В строке стоит **отметка биржи** (`IMTIME`), а не момент нашего запроса,
    и это выбор со следствием. Отметка меняется примерно раз в торговый день
    (замер 05.09.2026: у всех шести контрактов `2026-09-04 07:00:01`), значит
    строка не дрожит на каждом запросе — а от неё зависит, будет ли пересчитан
    прогон: порт применяет ответ только при изменении числа **или** строки.
    Момент нашего запроса менял бы её каждые десять минут, то есть гнал бы
    прогон по всей истории впустую.

    Заодно она честна к сохранённой настройке: величина, записанная в файл
    вчера, показывает вчерашнюю отметку и видна как вчерашняя.
    """
    step = _number(spec.price_step)
    price = _number(spec.step_price) if spec.step_price is not None else "?"
    told = (
        f"биржей — карточка {spec.secid} ({spec.board}): шаг цены {step}, "
        f"стоимость шага {price} ₽"
    )
    if spec.quoted_at:
        # Пояс в ответе не указан, и дорисовывать его нельзя (`InstrumentSpec`).
        told += f", помечена {spec.quoted_at}"
    return told


def _no_step_price(spec: InstrumentSpec, rubles: float | None) -> str:
    """Инструмент найден, а стоимости шага у него нет либо она не годится."""
    if rubles is None:
        return (
            f"биржа знает {spec.secid} на режиме {spec.board}, но стоимости "
            "шага (STEPPRICE) у него не объявляет — у акций такой колонки нет "
            "вовсе. Подставить за биржу единицу нельзя: она выглядела бы "
            "подтверждённой величиной"
        )
    return (
        f"биржа объявила у {spec.secid} стоимость шага {_number(rubles)} "
        "рублей за пункт — это не положительное число, и считать по нему "
        "деньги нельзя"
    )


def _silent(market: Market, trouble: IssError) -> str:
    """Биржа не ответила. Сказать это вслух, а не оставить прежнее число молча."""
    return (
        f"биржа не ответила про {market.title}: {trouble}. Стоимость пункта "
        "осталась той, что стояла в настройках, и биржей она не подтверждена"
    )


def _nowhere(secid: str, markets: Sequence[Market]) -> str:
    """Тикера нет ни на одном из рынков — либо рынков не назвали вовсе.

    Ответы биржи сюда **не пересказываются**: они одинаковы для всех рынков
    («такого инструмента не знаю») и складываются в строку, где одна и та же
    подсказка про экспирацию повторена столько раз, сколько было рынков.
    Владельцу счёта нужна одна фраза и один совет.
    """
    if not markets:
        return (
            f"стоимость пункта {secid} не спрошена: не назван ни один рынок, "
            "на котором её искать"
        )
    where = ", ".join(market.title for market in markets)
    return (
        f"биржа не знает инструмента {secid} ни на одном из рынков ({where}). "
        "У фьючерса тикер меняется с каждой экспирацией — проверьте его "
        "в настройках"
    )


def _number(value: float) -> str:
    """Число для человека: без хвостовых нулей и с запятой, как в окне."""
    text = f"{value:.5f}".rstrip("0").rstrip(".")
    return (text or "0").replace(".", ",")
