"""Синтетический ряд: чем он отличается от инструмента биржи и где ему нельзя быть.

Зачем это существует
--------------------
Сшитый ряд ближних контрактов (`market.chain`) — **наш**, а не биржевой.
Заявку по нему подать нельзя: кода `@MX` на бирже нет, и не будет. Но в базе
он лежит рядом с настоящими минутками, в той же таблице и с тем же видом
ключа, и единственное, что отличает его от `MXU6`, — имя.

Имени поэтому мало. Отличать надо там, где ошибка стоит денег:

* **список инструментов окна.** Владелец счёта выбирает код мышью. Ряд,
  попавший в этот список, рано или поздно будет выбран;
* **поток свечей движка.** Движок не знает, откуда пришла свеча, и это его
  главное свойство (ARCHITECTURE.md §1). Значит, он не может и отказаться
  от синтетического ряда сам — отказать обязан слой данных;
* **запись в рабочую базу.** Файл `candles.sqlite3` — тот, что открывает
  программа. Всё, что туда попало, видно окну.

Правило
-------
**Синтетический код начинается с `@`.** Символ выбран потому, что в кодах
МосБиржи его нет ни на срочном рынке (`MXU6`, `RIZ5`), ни на акциях
(`SBER`, `GAZP`): секции ISS отдают коды из букв, цифр, дефиса и точки.
То есть столкновение с настоящим инструментом невозможно по построению,
а не «маловероятно».

Два сторожа, оба в слое данных:

============================  =============================================
где                           что запрещено
============================  =============================================
`CandleStore.put_minutes`     писать синтетический ряд в рабочую базу
                              программы (`candles.sqlite3`). Он живёт
                              в отдельном файле и только там
`MarketWorker.bars/minutes`   отдавать синтетические свечи окну и движку.
                              `MarketWorker` — единственная дверь, через
                              которую свечи попадают в боевой путь
                              (решение 0005); перебор настроек ходит
                              в `CandleStore` напрямую и потому работает
============================  =============================================

⚠️ **Чего это НЕ даёт.** Защиты от того, кто откроет отдельный файл
`CandleStore` вручную и перепишет символ. Сторож закрывает путь, которым
ошибка приходит сама: выбор из списка и подстановку кода в настройки.
"""

from __future__ import annotations

import pathlib

from market.paths import DB_FILE_NAME

__all__ = [
    "SYNTHETIC_PREFIX",
    "is_synthetic",
    "refuse_synthetic_in_working_base",
    "refuse_synthetic_for_trading",
]

#: С чего начинается имя ряда, которого на бирже нет. Разбор — в шапке модуля.
SYNTHETIC_PREFIX = "@"


def is_synthetic(symbol: str) -> bool:
    """Это наш собранный ряд, а не инструмент биржи."""
    return symbol.startswith(SYNTHETIC_PREFIX)


def refuse_synthetic_in_working_base(symbol: str, path: pathlib.Path) -> None:
    """Отказать, если синтетический ряд кладут в рабочую базу программы.

    :raises ValueError: имя файла совпадает с рабочей базой (`candles.sqlite3`).
    """
    if not is_synthetic(symbol) or path.name != DB_FILE_NAME:
        return
    raise ValueError(
        f"«{symbol}» — собранный нами ряд, а не инструмент биржи, и в рабочую "
        f"базу {path.name} он не пишется. Оттуда его увидит список "
        "инструментов окна, и по коду, которого на бирже нет, будет отправлена "
        "заявка. Сшитый ряд живёт в отдельном файле — см. market.chain"
    )


def refuse_synthetic_for_trading(symbol: str) -> None:
    """Отказать, если синтетический ряд просят для окна или движка.

    :raises ValueError: код начинается с `@`.
    """
    if not is_synthetic(symbol):
        return
    raise ValueError(
        f"«{symbol}» — собранный нами ряд ближних контрактов, а не инструмент "
        "биржи: у него нет ни стакана, ни гарантийного обеспечения, ни срока "
        "жизни, и заявка по нему невозможна. Он существует только для проверки "
        "на истории: python -m backtest --symbol " + symbol
    )
