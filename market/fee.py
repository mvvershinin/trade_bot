"""Биржевой сбор за контракт: биржа объявляет его сама, как и стоимость пункта.

[Решение 0047](../.docs/decisions/0047-the-exchange-fee-comes-from-the-exchange.md).

Свойство инструмента, а не торговое правило, — и берётся оттуда же, откуда
стоимость пункта: из карточки инструмента на ISS, бесплатно и без токена
(решение 0041). Второго запроса это не стоит: `BUYSELLFEE` и `SCALPERFEE`
лежат в **той же строке**, что `MINSTEP` и `STEPPRICE`, — одна карточка,
два ответа.

Почему умолчание 14 ₽ неверно, и не в ту сторону, в какую кажется
------------------------------------------------------------------
`DOMAIN.md` §5: «биржевой сбор из карточки инструмента плюс 1 ₽ брокеру»,
в замерах — 14 ₽ за контракт на сторону. Замер 05.09.2026 по `MXU6`:

=====================  ==========  ==========
                       04.09.2026  05.09.2026
=====================  ==========  ==========
`BUYSELLFEE`, ₽            14,68       14,92
`SCALPERFEE`, ₽             7,34        7,46
=====================  ==========  ==========

Отсюда следуют три вещи, и все три меняют деньги отчёта.

**1. Сбор плавает.** За сутки он вырос на 24 копейки, потому что это
не число, а **доля стоимости контракта**: 14,92 ₽ ÷ 226 200 ₽ = 0,0066 %,
и накануне было ровно столько же от другой цены. Проверено по шести
контрактам сразу (замер 05.09.2026): у `MXU6` и `RIU6` — 0,0066 %,
у `SiU6` — 0,0046 %, у `BRV6` — 0,0132 %, у `GZU6` и `SRU6` — 0,0198 %.
Записать сбор в настройки один раз — завести тихую ошибку, которая растёт
вместе с ценой; поэтому его спрашивают заново, как и стоимость пункта.

**2. Скальперский сбор — ровно половина.** У всех шести контрактов
`SCALPERFEE` = `BUYSELLFEE` ÷ 2 с точностью до копейки. Он применяется
к сделке, закрытой внутри той же сессии, — а реверсная система
на пятиминутках закрывается внутри сессии почти всегда.

**3. Направление ошибки зависит от тарифа, а не от арифметики.** Если
считать по обычному сбору, умолчание 14 ₽ **занижено**: 14,92 + тариф
брокера. Если применим скальперский — умолчание **завышено** почти вдвое:
7,46 + тариф. Разница на переворот больше семи рублей, а переворотов
за день десятки. Какой тариф действует у владельца счёта — вопрос
к владельцу счёта (`OPEN-QUESTIONS.md`), и до его ответа умолчание
не меняется: за 14 ₽ стоит его же решение.

⚠️ **Тариф брокера биржа не знает и знать не может.** Это условие договора,
а не свойство инструмента: у тарифа «Трейдер» это 1,2 ₽ за контракт. Поэтому
здесь считается только биржевая часть, а тариф брокера приходит числом
снаружи — из настроек (`per_side`).

⚠️ **Ни одного торгового решения тут нет.** Комиссия на список сделок
не влияет вовсе (`PROTOTYPE.md` §6): она вычитается из денег после того,
как сделка состоялась. Ошибка в ней тихая — сделки те же, прибыль другая.
"""

from __future__ import annotations

from dataclasses import dataclass

from market.iss import InstrumentSpec

__all__ = ["Commission", "read_commission"]


@dataclass(frozen=True, slots=True)
class Commission:
    """Что биржа объявила о сборе — и чего она не объявляла.

    `exchange_rub` — `BUYSELLFEE`, сбор биржи за контракт **на сторону**.
    `scalper_rub` — `SCALPERFEE`, он же для сделки, закрытой внутри сессии.
    Оба `None`, когда биржа промолчала: ноль здесь выглядел бы посчитанным,
    а бесплатных сделок на срочном рынке не бывает.

    `told` заполнен **всегда** и всегда фразой для человека: при числах —
    откуда они и на какой момент, без чисел — почему их нет. Молчание
    означало бы, что владелец счёта видит в отчёте деньги и не знает,
    на каком сборе они посчитаны.
    """

    symbol: str
    exchange_rub: float | None
    scalper_rub: float | None
    told: str

    @property
    def confirmed(self) -> bool:
        """Биржа назвала сбор. Ложь — в настройках осталось прежнее число."""
        return self.exchange_rub is not None

    def per_side(self, broker_rub: float, *, scalper: bool = False) -> float | None:
        """Сколько стоит контракт на сторону: сбор биржи плюс тариф брокера.

        Одно место сложения на всю программу. Складывать эти два числа
        в окне, в отчёте и в журнале порознь — верный способ получить
        три разные комиссии в одном прогоне.

        `None` — биржа нужного сбора не назвала. Подставлять вместо него
        обычный сбор при `scalper=True` нельзя: скальперский вдвое меньше,
        и подстановка удвоила бы комиссию молча.

        :param broker_rub: тариф брокера за контракт на сторону. Биржа его
            не знает — это условие договора, и приходит оно из настроек.
        :param scalper: считать по скальперскому сбору, то есть для сделки,
            закрытой внутри той же торговой сессии.
        """
        exchange = self.scalper_rub if scalper else self.exchange_rub
        if exchange is None or broker_rub < 0:
            return None
        return exchange + broker_rub


def read_commission(spec: InstrumentSpec | None, *, secid: str) -> Commission:
    """Прочитать сбор из карточки инструмента. Ни сети, ни исключений.

    Карточку добывает вызывающий — той же дорогой, которой добывает
    стоимость пункта (`market.point.ask_point_value`, поле `spec`), потому
    что это **одна и та же строка ответа**. Второй запрос за теми же полями
    был бы вторым источником правды о величине, которая меняется каждый
    клиринг.

    :param spec: карточка либо `None`, если биржа её не дала. `None` —
        не ошибка: биржа, которая не ответила, такой же законный ответ,
        как число, и сказать о нём надо словами.
    :param secid: тикер как он стоит в настройках окна. Нужен для фразы
        в том случае, когда карточки нет и имени взять неоткуда.
    """
    if spec is None:
        return Commission(secid, None, None, _no_card(secid))
    fee, scalper = spec.exchange_fee, spec.scalper_fee
    if fee is None or fee <= 0:
        return Commission(spec.secid, None, _positive(scalper), _no_fee(spec, fee))
    return Commission(spec.secid, fee, _positive(scalper), _source(spec, fee, scalper))


def _positive(value: float | None) -> float | None:
    """Число, которым можно считать деньги, — или `None`.

    Ноль и минус отсеиваются там же, где `None`: биржа их не присылает,
    а если пришлют, считать по ним комиссию нельзя.
    """
    return value if value is not None and value > 0 else None


def _source(spec: InstrumentSpec, fee: float, scalper: float | None) -> str:
    """Откуда взялись числа — фразой, которую окно показывает как есть.

    В строке стоит **отметка биржи** (`IMTIME`), а не момент нашего запроса,
    по той же причине, что и у стоимости пункта: отметка меняется примерно
    раз в торговый день, и строка не дрожит на каждом запросе.
    """
    told = f"биржей — карточка {spec.secid} ({spec.board}): сбор {_rubles(fee)}"
    if scalper is not None and scalper > 0:
        told += f", скальперский {_rubles(scalper)}"
    told += " за контракт на сторону"
    if spec.quoted_at:
        # Пояс в ответе не указан, и дорисовывать его нельзя (`InstrumentSpec`).
        told += f", помечена {spec.quoted_at}"
    return told


def _no_fee(spec: InstrumentSpec, fee: float | None) -> str:
    """Инструмент найден, а сбора у него нет либо он не годится."""
    if fee is None:
        return (
            f"биржа знает {spec.secid} на режиме {spec.board}, но сбора "
            "(BUYSELLFEE) у него не объявляет — у акций такой колонки нет "
            "вовсе, там комиссию целиком назначает брокер. Комиссия осталась "
            "той, что стоит в настройках"
        )
    return (
        f"биржа объявила у {spec.secid} сбор {_rubles(fee)} — это не "
        "положительное число, и считать по нему деньги нельзя"
    )


def _no_card(secid: str) -> str:
    """Карточки нет вовсе: биржа не ответила либо тикера она не знает."""
    return (
        f"карточку {secid} биржа не дала, и сбор с неё не прочитан. Комиссия "
        "осталась той, что стоит в настройках, и биржей она не подтверждена"
    )


def _rubles(value: float) -> str:
    """Деньги для человека: копейки и запятая, как в окне."""
    return f"{value:.2f} ₽".replace(".", ",")
