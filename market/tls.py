@functools.cache
def exchange_ssl_context() -> ssl.SSLContext:
    """Проверка сервера биржи: обычный набор `certifi` плюс корень Минцифры.

    Собирается один раз: чтение набора `certifi` — десятки миллисекунд, а страниц
    истории за загрузку — сотни.
    """
    context = ssl.create_default_context(cafile=certifi.where())
    context.load_verify_locations(cadata=RUSSIAN_TRUSTED_ROOT_CA)
    return context
