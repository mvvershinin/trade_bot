"""Единица объёма свечи: контракты. Где источник даёт деньги — там пересчёт.

[Решение 0046](../.docs/decisions/0046-the-volume-column-holds-contracts.md).

Правило одно, и оно записано здесь, потому что нарушить его можно из любого
места: **в `minute_candle.volume` лежат контракты, всегда и у любого
источника**. Оборот в рублях в эту колонку не кладётся ни при каких условиях —
даже «временно», даже с рангом ноль.

Почему это не придирка
----------------------
Замер 05.09.2026 на базе владельца счёта, запись в журнале загрузки: объём
брокера ÷ наш = **2,199 × 10⁵** на 3858 общих минутах. У биржи на тех же
минутах ровно 1. Порядок совпал с ценой контракта (≈ 226 000 ₽), и это не
догадка: словарь полей брокера говорит про свои `volume` прямым текстом —
«объём сделки **в валюте инструмента**» (`.docs/broker-api/08-last-trades.md`),
«объём торгов **в валюте**» (`20-ws-last-candle.md`). У ISS в тех же свечах
контракты, сверено с эталоном построчно.

Две несопоставимые величины под одним именем — это не «неточность в показе».
Первый, кто их сложит (дневной объём, средний объём минуты, любая будущая
статистика), получит число, отличающееся в двести тысяч раз, и никакая
проверка его не поймает: колонка называется одинаково.

Как считается
-------------
Контрактов = оборот ÷ цена. Цена — **середина разброса минуты**,
`(high + low) / 2`, и это выбор по замеру, а не по вкусу.

Настоящая средневзвешенная нам недоступна: брокер её не отдаёт, у свечи есть
только `volume`, поля `quantity` в ней нет вовсе. Значит делить приходится
на оценку — и оценки можно сравнить там, где истина известна. У акций ISS
отдаёт в свече **и** оборот, **и** число бумаг; замер 05.09.2026 на 1000
настоящих минут (`SBER` и `GAZP`, 04.09.2026, по 500 баров):

==============  ==================  ==================
делим на        ошибка, медиана     она же, максимум
==============  ==================  ==================
`close`         0,0089 % / 0,019 %  0,144 % / 0,507 %
`(high+low)/2`  0,0038 % / 0,0088 % 0,049 % / 0,232 %
`(h+l+c)/3`     0,0043 % / 0,0089 % 0,060 % / 0,213 %
==============  ==================  ==================

Середина разброса точнее закрытия в 2,2 раза по медиане и втрое по худшему
бару, на обоих инструментах. Причина простая: средняя цена минуты лежит
внутри разброса, а закрытие — на его краю.

⚠️ Живой поток того же брокера делит **на закрытие** (`app/live_feed.py`),
и это не разнобой: там делится приращение оборота между двумя снимками,
то есть интервал в секунды, у которого `high` и `low` — не разброс минуты,
а шум. Одни и те же минуты этими двумя путями не считаются никогда: поток
пишет строго правее границы, догрузка строго левее (`market.backfill`).

Насколько неточная оценка вообще может быть — измерено. Ошибка не может
превысить разброс цены внутри бара: истинная средняя лежит между `low` и
`high`. Замер на 81 914 настоящих минутах `MXU6` (база владельца счёта,
источник `iss`):

======================================  =========
разброс `(high − low) / close`          доля
======================================  =========
медиана                                 0,048 %
90-я доля                               0,157 %
99-я доля                               0,339 %
максимум                                5,32 %
======================================  =========

В контрактах это медианные 0,05 контракта, и **в 81,7 % минут округление
до целого даёт заведомо точное число** — граница ошибки там меньше половины
контракта. Худший бар за год — 1227 контрактов из 43 146, то есть 2,8 %.

⚠️ **Множитель «рублей за пункт» здесь сознательно НЕ применяется.**
У фьючерса на индекс МосБиржи он равен единице (замер 05.09.2026: `MINSTEP`
25, `STEPPRICE` 25), и для торгуемого инструмента формула точна. У РТС он
1,73, у Брента 869 — и там ответ зависит от того, что брокер называет
«валютой инструмента»: настоящий рублёвый оборот `количество × цена × рублей
за пункт` или наивное произведение `цена × количество`. Пример из документации
самого брокера (`23-ws-trades.md`: `volume` 612 = `price` 305,89 × `quantity`
2) — наивное произведение; живым запросом по контракту с множителем, отличным
от единицы, это не проверял никто, а токен в разработке не участвует.
Подставить множитель «на всякий случай» — такая же догадка, как не подставить
его, только дороже: живой поток того же брокера уже делит на цену без
множителя (`app/live_feed.py`), и две формулы для одной величины разошлись бы
молча. Поэтому формула одна, а несовпадение ловится замером на нахлёсте
(`market.backfill.volume_ratio`, полоса `MATCH_BAND`): у инструмента, где
множитель важен, отношение выйдет из полосы и скажет об этом вслух.
"""

from __future__ import annotations

from typing import Final

__all__ = ["CONTRACT_HALF", "PRICE_OF", "bar_price", "contracts_from_turnover"]

#: Ниже этого пересчёт объявляет отказ: минута, в которой были сделки,
#: не может дать меньше половины контракта. Один контракт даёт оборот
#: ровно в одну цену, то есть отношение около единицы; чтобы округление
#: увело его в ноль, цена внутри минуты должна была вырасти вдвое.
#:
#: Отсюда сторож против **обратной** ошибки: если брокер однажды начнёт
#: слать контракты вместо оборота, деление даст 0,0009 — и это будет видно
#: сразу, а не через месяц в статистике.
CONTRACT_HALF: Final[float] = 0.5

#: Какой ценой делим — одной строкой для журнала и окна. Текст здесь,
#: а не у вызывающего: правило пересчёта и его описание расходиться
#: не должны.
PRICE_OF: Final[str] = "середине разброса минуты"


def bar_price(high: float, low: float) -> float:
    """Цена, на которую делится оборот: середина разброса минуты.

    Отдельной функцией, а не выражением у вызывающего: это **правило слоя
    данных**, и оно обязано лежать рядом с делением и рядом с замером,
    который его выбрал (шапка модуля). Выражение `(bar.high + bar.low) / 2`,
    написанное в `app/`, разошлось бы со строкой `PRICE_OF` при первой же
    правке — и владелец счёта прочитал бы в журнале одно, а получил другое.
    """
    return (high + low) / 2


def contracts_from_turnover(turnover: float, *, price: float) -> float | None:
    """Оборот в рублях → контракты. `None` — это не оборот, считать нечего.

    Ноль остаётся нулём: минута без сделок даёт нулевой оборот, и нулевой
    объём для неё — правда, а не подстановка.

    `None` возвращается там, где деление дало бы **ложное** число:

    * цена не положительная — делить не на что;
    * оборот отрицательный — такого не бывает;
    * оборот положительный, а контрактов вышло меньше половины
      (`CONTRACT_HALF`). Это не «мало торговали», это «пришло не то»:
      контракты вместо оборота либо чужая валюта. Записать здесь ноль
      значило бы объявить минуту без сделок.

    Округление до целого — не украшение: контракт неделим, а дробное число
    в колонке объёма выглядело бы измеренным. Точность округления измерена
    и названа в шапке модуля (81,7 % минут — заведомо точно).
    """
    if turnover == 0:
        return 0.0
    if turnover < 0 or price <= 0:
        return None
    counted = turnover / price
    if counted < CONTRACT_HALF:
        return None
    return float(round(counted))
