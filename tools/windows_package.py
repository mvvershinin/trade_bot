r"""Собрать из результата Nuitka то, что отдаётся владельцу счёта.

Запуск после `tools/build.py` из корня рабочей копии:

    .venv\Scripts\python.exe tools\windows_package.py

Что делает
----------
1. Копирует `build/main.dist` в `dist/Terminal` — имя папки закреплено.
   `main.dist` названо по имени файла точки входа и владельцу счёта
   ничего не говорит.
2. **Снимает `userdata/`**, если она осталась от прогонов на машине сборки.
   Это папка с настройками и, возможно, с файлом токена: попасть в артефакт
   поставки она не имеет права ни при каких условиях.
3. Кладёт рядом `README.txt` и `Запустить.bat` — чек-лист DESKTOP-2026 §3.

Про кодировки, потому что на них тут всё и ломается
---------------------------------------------------
* `README.txt` — UTF-8 **с BOM** и переводами строк CRLF. Без BOM «Блокнот»
  старых сборок Windows читает файл как CP1251 и показывает кракозябры;
  без CRLF он же показывает текст одной строкой.
* `Запустить.bat` — UTF-8 без BOM, но первой строкой `chcp 65001`: BOM
  в начале `.bat` командный процессор пытается выполнить как команду
  и печатает `'я╗┐' is not recognized`.

⚠️ Имя `Запустить.bat` кириллическое, и это расходится с правилом 6
`CLAUDE.md` («имена файлов — латиницей»). Причины правила — пути в git,
в консоли и в сборке Nuitka; этот файл не проходит ни через одно из трёх:
он создаётся после сборки, в артефакте, который в git не попадает. Имя взято
из чек-листа DESKTOP-2026 §3, где оно названо буквально. Расхождение
вынесено в отчёт, а не решено молча.
"""

from __future__ import annotations

import pathlib
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "build" / "main.dist"
TARGET = ROOT / "dist" / "Terminal"

README = """\
«Терминал» — программа автоматической торговли на Московской бирже
==================================================================

Версия 0.1.0. Ничего устанавливать не нужно.


Как запустить
-------------

1. Скопируйте папку «Terminal» целиком куда вам удобно: на рабочий стол,
   в «Документы», на флешку. Работает с любого места.

   ВАЖНО: копировать надо папку целиком, а не один файл Terminal.exe.
   Отдельно от своей папки он не запустится.

2. Откройте папку и запустите Terminal.exe (или «Запустить.bat» — это одно
   и то же).


Что покажет Windows при первом запуске и почему
-----------------------------------------------

Скорее всего вы увидите синее окно:

    «Система Windows защитила ваш компьютер»
    Фильтр SmartScreen Защитника Windows предотвратил запуск
    неопознанного приложения.

Программа не заражена. Windows говорит не «это вирус», а «я вижу эту
программу впервые и не знаю, кто её выпустил».

Чтобы Windows знала автора, программу подписывают цифровой подписью.
Подпись выдают удостоверяющие центры и только юридическим лицам, за
абонентскую плату. Юридического лица под эту программу нет, поэтому
подписи нет — и не будет. Это осознанное решение, а не недоделка.

Как пройти:

    Нажмите «Подробнее» — под текстом появится кнопка
    «Выполнить в любом случае». Нажмите её.

Второй раз Windows об этом не спросит.

Если антивирус (не Windows, а сторонний) удалил файл или не даёт запустить —
сообщите нам. Так бывает, это называется ложным срабатыванием; мы отправляем
такие случаи производителю антивируса, разбор занимает несколько дней.


Куда программа пишет свои данные
---------------------------------

В папку «userdata» рядом с собой — внутри той же папки «Terminal».
Она создаётся при первом запуске. В ней:

    candles.sqlite3   база свечей, журнал сделок и журнал решений
    settings.json     ваши настройки
    broker-token.json ключ доступа к счёту у брокера
    instance.lock     служебный файл, см. ниже
    logs\\             технический журнал

В системные папки, в реестр и в «Мои документы» программа не пишет ничего.

Чтобы перенести программу на другой компьютер вместе со всей историей —
скопируйте папку «Terminal» целиком.

Чтобы удалить программу — удалите папку. Больше ничего делать не нужно.


Почему нельзя запустить две копии сразу
----------------------------------------

Если запустить программу второй раз, она скажет:

    «Терминал» уже запущен на этом компьютере.

Так и задумано. Две копии работали бы с одной базой и одними настройками
и затирали бы записи друг друга, а в бою подали бы две заявки на один
сигнал — двойной объём вместо нужного.

Окно уже открытой программы ищите в панели задач.

Если программа была закрыта аварийно (выключили питание, сняли через
диспетчер задач) — следующий запуск пройдёт как обычно. Ничего чистить
вручную не нужно, файл instance.lock удалять не надо.


Если программа не запускается
------------------------------

Напишите нам и приложите файл userdata\\logs\\terminal.log — в нём записано,
что произошло. Ключ доступа к счёту в этот файл не попадает никогда.
"""

LAUNCHER = """\
@echo off
chcp 65001 >nul
rem Запуск «Терминала» из папки, в которой лежит этот файл, — а не из той,
rem откуда его позвали. Без cd /d программа искала бы userdata\\ не там.
cd /d "%~dp0"
start "" "%~dp0Terminal.exe"
"""


def _speak_utf8() -> None:
    """Вывод в utf-8: консоль Windows иначе роняет скрипт на русском тексте.

    ⚠️ Замер 06.09.2026: сборка под Windows упала на **последней строке
    отчёта** с `UnicodeEncodeError: 'charmap' codec` — консоль отдавала
    cp1252, а весь текст скрипта русский. Собранная программа при этом
    была готова: упал не сборщик, а печать о нём. Тот же класс, что
    падение самой программы без `LANG` под Linux.
    """
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            try:
                reconfigure(encoding="utf-8", errors="replace")
            except (ValueError, OSError):
                pass


def package() -> int:
    if not SOURCE.is_dir():
        print(f"нет {SOURCE} — сначала tools/build.py", file=sys.stderr)
        return 2

    if TARGET.exists():
        shutil.rmtree(TARGET)
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(SOURCE, TARGET)

    # Следы прогонов на машине сборки. Там настройки и, возможно, токен.
    leftovers = TARGET / "userdata"
    if leftovers.exists():
        shutil.rmtree(leftovers)
        print("снята userdata/ от прогонов на машине сборки")

    (TARGET / "README.txt").write_bytes(
        b"\xef\xbb\xbf" + README.replace("\n", "\r\n").encode("utf-8")
    )
    (TARGET / "Запустить.bat").write_bytes(LAUNCHER.replace("\n", "\r\n").encode("utf-8"))

    files = [p for p in TARGET.rglob("*") if p.is_file()]
    total = sum(p.stat().st_size for p in files)
    print(f"{TARGET}: {len(files)} файлов, {total} Б = {total / 1024 / 1024:.0f} МБ")
    return 0


if __name__ == "__main__":
    _speak_utf8()
    raise SystemExit(package())
