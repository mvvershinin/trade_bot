"""Что нарисовано на графике — таблицей, по строке на каждое обозначение.

Зачем это отдельная таблица
---------------------------
Просьба владельца счёта 05.09.2026 со снимком экрана, дословно: «это сейчас
максимально запутано и непонятно мне, или легенду расширь что ли». На графике
одновременно шесть видов меток, два вида пунктира, две сплошные линии
и затенение, а легенда объясняла пять из них одной строкой мелким текстом.

Таблица, а не разметка руками, по той же причине, по которой таблицей стали
поля свечи (`ui/formatting.py::PRICE_FIELDS`): по ней идут все обходы —
и сборка легенды, и проверка полноты. Вид метки, забытый в перечислении,
иначе не объяснён нигде, и заметить это некому.

Полноту стережёт `tests/test_ui_legend.py`: у каждого `MarkerKind` обязана
быть своя строка. Пять случаев «прогноз против факта» (`DOMAIN.md` §8) —
это и есть виды меток, поэтому проверка полноты таблицы и есть проверка
того, что все пять названы человеческим языком.

Текстов для человека здесь много, и это единственное содержимое модуля:
ни одного правила торговли, ни одного числа, которое где-то считается.
"""

from __future__ import annotations

from dataclasses import dataclass

from ui.models import Layer, MarkerKind


@dataclass(frozen=True, slots=True)
class MarkerSample:
    """Значок легенды — метка сделки того же вида, что на графике."""

    kind: MarkerKind
    layer: Layer = Layer.FACT


@dataclass(frozen=True, slots=True)
class LineSample:
    """Значок легенды — отрезок линии. `colour` — имя поля темы."""

    colour: str
    dashed: bool = False


@dataclass(frozen=True, slots=True)
class AreaSample:
    """Значок легенды — прямоугольник. `colour` — имя поля темы.

    `filled=False` — только пунктирная рамка, без заливки. Так на графике
    нарисован пропуск данных: заливкой там показано затенение «робот молчал»,
    и вторая заливка рядом читалась бы как то же самое
    (`painter_surface._draw_gaps`).
    """

    colour: str
    filled: bool = True


Sample = MarkerSample | LineSample | AreaSample


@dataclass(frozen=True, slots=True)
class LegendItem:
    """Строка легенды: значок, название и что это значит человеческим языком.

    `meaning` видно на экране всегда и потому коротко; `detail` — подсказка
    при наведении, туда уходит длинное объяснение. Разделение не косметика:
    легенда стоит поверх графика и отнимает у него высоту, а объяснять надо
    подробно.

    `needs_plan` — строка показывается, только когда включён слой «Прогноз».
    Легенда обязана объяснять то, что **может появиться** на экране; со снятой
    галочкой полая метка появиться не может, и место она занимать не должна.
    """

    sample: Sample
    title: str
    meaning: str
    detail: str = ""
    needs_plan: bool = False

    @property
    def hint(self) -> str:
        """Текст подсказки: подробное объяснение, а если его нет — короткое."""
        return self.detail or self.meaning


