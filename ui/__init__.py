"""PySide6: график, настройки, журналы.

Слой окна. **Торговой логики здесь нет ни одной строки** — окно показывает
состояние и отправляет команды (ARCHITECTURE.md §3). Проверка на себе: заменить
весь `ui/` на вывод в консоль можно, не тронув поведение робота.

Что где:

| Модуль | Зачем |
|---|---|
| `models` | формы данных для показа — свеча, метка, строка журнала, настройки |
| `ports` | единственная граница с движком: сигналы внутрь, команды наружу |
| `main_window` | окно целиком: панель состояния, график, журналы, предупреждения |
| `chart/` | график за собственным интерфейсом; чем он нарисован, снаружи не видно |
| `settings_dialog` | настройки с подсказками простым языком |
| `notices` | тексты предупреждений про деньги — в одном месте, а не в трёх |
| `journals` | вкладки «Сделки» и «Решения робота» |
| `export` | выгрузка обеих вкладок в CSV |
| `theme`, `formatting` | цвета для светлой и тёмной темы, числа и время по-русски |
| `background` | длинные операции вне потока интерфейса |

Импорт пакета намеренно не тянет PySide6: `tests/test_layers.py` импортирует все
слои, и тянуть за собой Qt ради строки документации незачем. Имена ниже
подгружаются при первом обращении.
"""

from __future__ import annotations

from typing import Any

__all__ = ["MainWindow", "TerminalPort", "DetachedPort"]


def __getattr__(name: str) -> Any:
    if name == "MainWindow":
        from ui.main_window import MainWindow

        return MainWindow
    if name in {"TerminalPort", "DetachedPort"}:
        import ui.ports as ports

        return getattr(ports, name)
    raise AttributeError(f"в пакете ui нет имени {name!r}")
