"""Интерфейс графика. Единственное, что об отрисовке знает остальная программа.

ТЗ §6 предусматривает запасной вариант: если встроенный веб-график не пойдёт
на Linux заказчика, отрисовка меняется на другую библиотеку. Чтобы такая замена
стоила один файл, а не переписывание окна, между окном и библиотекой стоит этот
интерфейс.

Правило, которое делает интерфейс осмысленным: **имя библиотеки отрисовки
не встречается нигде, кроме `ui/chart/`.** Вызов из окна настроек, из журнала
или из главного окна напрямую — нарушение, ради предотвращения которого
интерфейс и заведён. Проверяется тестом `tests/test_ui_no_trading_logic.py`.

Чего в интерфейсе нет и не будет
--------------------------------
Методов вида «нарисуй тейк по цене входа и проценту» или «посчитай среднюю».
Отрисовщик получает готовые точки, уровни и метки. Как только он начнёт что-то
выводить сам, на экране появится вторая версия стратегии — та, которая ничем
не подтверждена.
"""

from __future__ import annotations

from collections.abc import Callable, Sequence

from PySide6.QtCore import QPointF
from PySide6.QtGui import QPainter
from PySide6.QtWidgets import QWidget

from ui.chart.glyphs import GlyphStyle, draw_marker
from ui.models import (
    Candle,
    CandleInfo,
    ChartData,
    ChartSpan,
    Layer,
    LinePoint,
    Marker,
    MarkerKind,
    PriceLevel,
    Shade,
    TradePath,
)
from ui.theme import Theme

#: Кому отрисовщик сообщает, над какой свечой стоит курсор.
#: `None` — курсор ушёл с графика или встал мимо свечи (пустое место
#: пропуска, поле за областью построения). Подставлять вместо `None`
#: соседнюю свечу запрещено: см. `set_hover_handler`.
HoverHandler = Callable[[CandleInfo | None], None]

#: Кому отрисовщик сообщает про отрезок, выделенный правой кнопкой мыши.
#: `None` — выделение снято. Правый щелчок без протяжки — тот же отрезок
#: шириной в одно место оси: отдельного случая для щелчка нет, чтобы отбор
#: сделок был один на оба действия.
SpanHandler = Callable[[ChartSpan | None], None]


class ChartSurface:
    """Поверхность, на которой нарисован график.

    Базовый класс намеренно не `abc.ABC`: реализации наследуют его вместе
    с `QWidget`, а метакласс Shiboken с `ABCMeta` не совмещается без обёрток,
    которые ломаются при обновлении PySide6.
    """

    #: Человеческое имя отрисовщика. Показывается в «О программе» и пишется
    #: в журнал при старте: при разборе жалобы «график пустой» это первое,
    #: что нужно знать.
    name: str = "неизвестный отрисовщик"

    @classmethod
    def is_available(cls) -> tuple[bool, str]:
        """Можно ли использовать эту реализацию здесь и сейчас.

        Возвращает признак и причину отказа человеческим языком — причина попадёт
        в журнал и в окно, если пришлось перейти на запасной вариант.
        """
        return True, ""

    def widget(self) -> QWidget:
        """Виджет для вставки в окно."""
        raise NotImplementedError

    # --- данные -------------------------------------------------------------

    def show_chart(self, data: ChartData) -> None:
        """Полная замена содержимого: история, средняя, метки, уровни, затенение."""
        raise NotImplementedError

    def append_candle(self, candle: Candle) -> None:
        """Добавить закрытую свечу справа."""
        raise NotImplementedError

    def update_last_candle(self, candle: Candle) -> None:
        """Уточнить последнюю свечу (она ещё формируется).

        ⚠️ Незакрытая свеча — это только картинка. Решения робот принимает
        на закрытии (ARCHITECTURE.md §6); метки по незакрытой свече не приходят,
        и отрисовщик их не придумывает.
        """
        raise NotImplementedError

    def set_average(self, points: Sequence[LinePoint], label: str = "") -> None:
        """Заменить линию скользящей средней. Значения посчитаны стратегией."""
        raise NotImplementedError

    def set_markers(self, layer: Layer, markers: Sequence[Marker]) -> None:
        """Заменить метки одного слоя — «прогноз» или «факт»."""
        raise NotImplementedError

    def set_paths(self, layer: Layer, paths: Sequence[TradePath]) -> None:
        """Заменить линии «вход → выход» одного слоя."""
        raise NotImplementedError

    def set_levels(self, levels: Sequence[PriceLevel]) -> None:
        """Заменить горизонтальные линии уровней открытой позиции."""
        raise NotImplementedError

    def set_shades(self, shades: Sequence[Shade]) -> None:
        """Заменить затенённые отрезки — время, когда робот молчал."""
        raise NotImplementedError

    # --- вид ----------------------------------------------------------------

    def set_layer_visible(self, layer: Layer, visible: bool) -> None:
        """Показать или скрыть слой меток."""
        raise NotImplementedError

    def set_theme(self, theme: Theme) -> None:
        """Сменить цвета — например, когда система переключилась на тёмную тему."""
        raise NotImplementedError

    def set_hover_handler(self, handler: HoverHandler | None) -> None:
        """Кому сообщать, над какой свечой курсор. `None` — никому.

        Единственный, кто может ответить на вопрос «над какой свечой стоит
        мышь», — отрисовщик: только он знает, где на экране какая свеча.
        Панель со строкой сведений (`ui/chart_panel.py`) подписывается сюда
        и показывает то, что ей сказали; выбирать свечу по координатам она
        не умеет и уметь не должна.

        Обязанности того, кто зовёт обработчик:

        * курсор **над пустым местом** пропуска — это `None`, а не соседняя
          свеча. Пустое место подписано «Данных нет: 13:08–14:03», и сведения
          о свече рядом с такой подписью — неправда (`B-005`);
        * курсор ушёл с виджета — тоже `None`, иначе строка навсегда
          останется на случайной свече;
        * сведения собираются из свечи под курсором и **предыдущей свечи**
          ряда: `CandleInfo.from_pair`.

        Расчёта здесь нет: `CandleInfo` — это две цены и вычитание, то же
        самое, что человек делает глазами по двум числам на экране.
        """
        raise NotImplementedError

    def set_span_handler(self, handler: SpanHandler | None) -> None:
        """Кому сообщать про отрезок, выделенный правой кнопкой. `None` — никому.

        Разведение кнопок мыши — часть договора, а не подробность отрисовки:

        * **просто движение** — перекрестье за курсором, без единого нажатия;
        * **левая зажата и ведём** — панорама графика (принято владельцем счёта,
          ломать нельзя);
        * **правая** — выделение отрезка. Щелчок без протяжки — тот же отрезок
          шириной в одно место оси, отдельного случая для него нет.

        Обязанности того, кто зовёт обработчик, ровно те же, что у наведения:
        границы отрезка берутся у **мест оси**, а не у свечей, и место, в котором
        свечи нет, остаётся пропуском — он приезжает отдельным полем
        `ChartSpan.holes`, а не растворяется в «сделок не было» (`B-005`).
        """
        raise NotImplementedError

    def draw_marker_glyph(
        self,
        painter: QPainter,
        point: QPointF,
        kind: MarkerKind,
        layer: Layer,
        style: GlyphStyle,
    ) -> None:
        """Нарисовать значок метки для легенды — тот же самый, что на графике.

        Легенда спрашивает значок у отрисовщика, а не рисует свой: иначе
        правка формы метки оставляет в легенде старую картинку, и молча.
        Умолчание — общие формы (`ui/chart/glyphs.py`); отрисовщик, у которого
        формы задаёт чужая библиотека, переопределяет этот метод под свои.
        """
        draw_marker(painter, point, kind, layer, style)

    def scroll_to_last(self) -> None:
        """Перейти к последней свече и дальше следовать за ней."""
        raise NotImplementedError

    def is_following(self) -> bool:
        """Следует ли график за последней свечой.

        Кнопка «к последней свече» по этому признаку гасится: если пользователь
        отмотал историю, график не должен прыгать назад на каждой новой свече.
        """
        raise NotImplementedError
