"""Ось времени графика: место под каждую свечу и под каждую пропущенную.

Зачем это отдельный модуль
--------------------------
До 04.09.2026 обе отрисовки клали свечи подряд, по порядковому номеру
(`B-005`). Час, которого нет в данных, исчезал при этом не только из данных,
но и с картинки: 13:08 и 14:04 стояли встык, и по графику нельзя было узнать,
что между ними пропущено 56 минут. Решение, принятое глазами по такой
картинке, ошибочно, а заподозрить неладное владельцу счёта не по чему —
ряд выглядит непрерывным.

Здесь ряд свечей превращается в **ряд мест**. У каждого места своя отметка
времени, и место есть не только у свечи, но и у каждого бара, которого
в данных нет. Пустое место рисуется пустым — пропуск виден как пропуск.

Модуль общий для обеих отрисовок (`painter_surface`, `web_surface`)
намеренно: правка одной из них молча оставила бы другую со старым
поведением, и на машине владельца счёта чинилось бы не то, что он видит.
Так уже было с `B-008`.

Ночь и выходные: разрыв внутри дня показываем, разрыв между днями схлопываем
----------------------------------------------------------------------------
Честное расстояние во времени **всегда** — не работает. Между вечерним
закрытием и утренним открытием проходит девять часов, между пятницей
и понедельником — двое с лишним суток; дневной график при этом превращается
в две узкие полоски по краям пустоты, и смотреть на него нельзя.

Биржевые терминалы поступают так же: разрывы внутри сессии показывают,
межсессионные схлопывают. Граница здесь проведена **по календарному дню
МСК**, а не по расписанию биржи, и это осознанный выбор:

* расписание торгов — торговое знание, а его в `ui/` быть не должно
  (ARCHITECTURE.md, главное правило);
* календарь праздников пришлось бы вести и обновлять, и в день, когда он
  устареет, график соврёт молча — ровно тем способом, от которого уходим;
* сутки ограничивают пропуск сверху сами: внутри дня мест не больше,
  чем в нём минут.

Следствие названо вслух: клиринговый перерыв (14:00–14:05) и вечерний
(18:45–19:05) лежат внутри дня и потому рисуются пустыми местами, хотя
в терминале брокера их не видно. Цена ошибки несимметрична — показать
настоящий перерыв стоит одного-четырёх пустых мест на экране, спрятать
потерянный час стоит решения, принятого по картинке, которой нет
соответствия в действительности. Вопрос вынесен владельцу счёта
(`.docs/OPEN-QUESTIONS.md`), решение — `.docs/decisions/0026`.

⚠️ Правило ломается на инструменте, чья сессия переходит через полночь:
разрыв «23:59 → 00:01» окажется межсессионным и схлопнется. На срочном
рынке Московской биржи такого нет — торги заканчиваются в 23:50, — поэтому
правило принято как есть.

Часовой пояс
------------
Все отметки считаются от `to_msk`: время без пояса считается московским
(`ui.formatting`), время с поясом переводится в МСК. Так и отметка эпохи,
и признак «тот же день» берутся из одной и той же величины.

⚠️ Звать `datetime.timestamp()` напрямую здесь нельзя. У наивного времени
Python подставит **системный** пояс машины, а `to_msk` — московский; машина
владельца счёта может стоять не в Москве, и тогда отметка и граница дня
разъехались бы на разницу поясов. Перехода на летнее время в России нет
(отменён в 2014), сдвиг МСК постоянный +03:00, поэтому час 07.09 не наступает
и удвоенных отметок не бывает.
"""

from __future__ import annotations

import bisect
from collections import Counter
from collections.abc import Sequence
from datetime import datetime, timedelta

from ui.formatting import to_msk
from ui.models import Candle

#: Шаг сетки, который не из чего вывести: свеча одна или ни одной.
#: Пропуски при неизвестном шаге не достраиваются — достраивать нечем.
UNKNOWN_STEP = 0.0

#: Потолок числа пустых мест на один пропуск. Правило «в пределах суток»
#: ограничивает пропуск и без него (минут в сутках 1440), потолок стоит
#: на случай испорченной отметки времени: одна свеча, приехавшая из 1970 года,
#: иначе развернулась бы в миллионы пустых мест и подвесила бы окно.
MAX_GAP_SLOTS = 1500


class Timeline:
    """Ряд мест на оси: у каждого своя отметка, у части — свеча.

    Списки `stamps`, `moments` и `slots` одной длины и всегда меняются вместе;
    `filled` — номера мест, в которых свеча есть. Последнее место — всегда
    свеча: пустые достраиваются только **между** свечами, справа их не бывает.
    """

    __slots__ = ("candles", "filled", "moments", "slots", "stamps", "step")

    def __init__(self, candles: Sequence[Candle] = ()) -> None:
        self.stamps: list[float] = []
        self.moments: list[datetime] = []
        self.slots: list[Candle | None] = []
        self.candles: list[Candle] = []
        self.filled: list[int] = []
        self.step: float = grid_step(candles)
        for candle in candles:
            self._put(candle)

    def __len__(self) -> int:
        """Сколько мест на оси — вместе с пустыми."""
        return len(self.slots)

    @property
    def empty(self) -> bool:
        """Нет ни одного места: график ещё ничего не показывает."""
        return not self.slots

    # ------------------------------------------------------------------ приход

    def append(self, candle: Candle) -> list[float]:
        """Добавить свечу справа. Возвращает отметки достроенных пустых мест.

        Отметки возвращаются, потому что веб-графику их надо отправить
        отдельно: библиотека рисования держит свой ряд, и пустое место
        в нём появляется только тем же способом, что и свеча.
        """
        if self.step <= UNKNOWN_STEP:
            # Шаг был неизвестен: график начали с пустого ряда и наполняют
            # живыми свечами. Со второй свечи выводить его уже есть из чего.
            self.step = grid_step([*self.candles, candle])
        before = len(self.slots)
        self._put(candle)
        return self.stamps[before:-1]

    def replace_last(self, candle: Candle) -> None:
        """Уточнить последнюю свечу — ту, что ещё формируется."""
        if self.empty:
            self.append(candle)
            return
        moment = to_msk(candle.opens_at)
        self.stamps[-1] = moment.timestamp()
        self.moments[-1] = moment
        self.slots[-1] = candle
        self.candles[-1] = candle

    def _put(self, candle: Candle) -> None:
        moment = to_msk(candle.opens_at)
        stamp = moment.timestamp()
        if self.slots:
            self._open_gap(moment, stamp)
        self.stamps.append(stamp)
        self.moments.append(moment)
        self.slots.append(candle)
        self.filled.append(len(self.slots) - 1)
        self.candles.append(candle)

    def _open_gap(self, moment: datetime, stamp: float) -> None:
        """Достроить пустые места между последней свечой и приходящей."""
        previous_stamp = self.stamps[-1]
        previous_moment = self.moments[-1]
        if self.step <= UNKNOWN_STEP:
            return
        if moment.date() != previous_moment.date():
            return  # ночь и выходные схлопываются, см. заголовок модуля
        missing = int(round((stamp - previous_stamp) / self.step)) - 1
        if missing < 1 or missing > MAX_GAP_SLOTS:
            return
        for number in range(1, missing + 1):
            self.stamps.append(previous_stamp + self.step * number)
            self.moments.append(previous_moment + timedelta(seconds=self.step * number))
            self.slots.append(None)

    # ------------------------------------------------------------------ чтение

    def neighbours(self, first: int, last: int) -> list[Candle]:
        """Ближайшие свечи слева и справа от промежутка мест `first…last`.

        Нужны, когда человек отмотал в середину пропуска: свечей на экране
        нет, и шкале цены не от чего оттолкнуться. Без них ось цены показала бы
        диапазон 0…1 — числа, которых на рынке не было ни разу.
        """
        found: list[Candle | None] = []
        left = bisect.bisect_left(self.filled, first) - 1
        if left >= 0:
            found.append(self.slots[self.filled[left]])
        right = bisect.bisect_left(self.filled, last)
        if right < len(self.filled):
            found.append(self.slots[self.filled[right]])
        return [candle for candle in found if candle is not None]

    def pair_at(self, index: int) -> tuple[Candle, Candle | None] | None:
        """Свеча в этом месте оси и ближайшая свеча слева от неё.

        Нужна строке сведений о свече: при наведении она показывает цены
        свечи под курсором и изменение против **предыдущей свечи**.

        Возвращается пара, а не две отдельные величины, намеренно: свеча
        и то, с чем её сравнивают, взятые двумя вызовами по двум разным
        номерам мест, дали бы изменение против чужой свечи — и молча.

        ⚠️ `None` означает «свечи здесь нет»: место пустое (пропуск) или
        его нет вовсе. Соседняя свеча вместо неё **не подставляется**.
        Пустое место подписано «Данных нет: 13:08–14:03», и строка сведений
        о свече рядом с этой подписью — прямая неправда о том, что в данных
        есть. Пропуск и есть содержание `B-005`.

        «Ближайшая слева» — это предыдущая **свеча ряда**, а не предыдущее
        место: у свечи сразу за часовым пропуском предыдущей считается та,
        что стояла до пропуска. Так же считает и хвост ряда
        (`ui.chart_panel.tail_info`), иначе одна и та же свеча меняла бы
        своё изменение в зависимости от того, навели на неё или нет.
        """
        if not 0 <= index < len(self.slots):
            return None
        candle = self.slots[index]
        if candle is None:
            return None
        place = bisect.bisect_left(self.filled, index) - 1
        previous = self.slots[self.filled[place]] if place >= 0 else None
        return candle, previous

    def gaps(self, first: int, last: int) -> list[tuple[int, int]]:
        """Полосы пустых мест, задевающие `first…last`. Границы полуоткрытые.

        Нужны отрисовке: пустое место само по себе ничем не отличается
        от края выборки, и полосу надо подписать.

        ⚠️ Полоса возвращается **целиком**, даже если в запрошенный кусок
        попала только её часть. Обрезанная по краю экрана, она дала бы подпись
        «Данных нет: 13:13–14:03» на пропуске, который начался в 13:08, —
        то есть новую неправду вместо старой (замечено глазами на снимке
        04.09.2026 при закрытии `B-005`). Куда рисовать, решает отрисовка;
        сколько времени потеряно на самом деле — знает только ось.
        """
        size = len(self.slots)
        begin = min(max(first, 0), size)
        end = min(max(last, 0), size)
        while begin > 0 and self.slots[begin - 1] is None:
            begin -= 1
        while end < size and self.slots[end] is None:
            end += 1

        runs: list[tuple[int, int]] = []
        start: int | None = None
        for index in range(begin, end):
            if self.slots[index] is None:
                if start is None:
                    start = index
            elif start is not None:
                runs.append((start, index))
                start = None
        if start is not None:
            runs.append((start, end))
        return runs


def grid_step(candles: Sequence[Candle]) -> float:
    """Шаг сетки в секундах — самая частая разница между соседними свечами.

    Не разбор подписи размера свечи («5 минут»): таблица подписей живёт
    в `app/convert.py`, и второй её экземпляр здесь означал бы два места,
    которые надо помнить, — тот самый паттерн, за который заплачено
    в `EngineSettings` (`.docs/quality/code-size-2026-09-03.md` §8).
    Данные о своём шаге говорят сами.

    Именно **самая частая**, а не средняя и не наименьшая: среднее растянет
    как раз тот пропуск, ради которого всё затевалось, а наименьшая примет
    за шаг случайную сдвоенную отметку. При равной частоте берётся меньшая:
    ошибка в меньшую сторону даёт лишние пустые места (видно и разбирается),
    в большую — снова склеенные свечи (не видно вовсе).
    """
    steps = Counter(
        round((to_msk(later.opens_at) - to_msk(earlier.opens_at)).total_seconds())
        for earlier, later in zip(candles, candles[1:], strict=False)
        if later.opens_at > earlier.opens_at
    )
    if not steps:
        return UNKNOWN_STEP
    best, _ = min(steps.items(), key=lambda item: (-item[1], item[0]))
    return float(best)
