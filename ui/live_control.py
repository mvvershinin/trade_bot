"""Кнопка «Бой» и строка рядом с ней: что сказать по снимку боя.

Э4, шаг 2в (план `.docs/plans/E4-live-orders.md` §12, решение 0066). Бой —
заявки «факта» уходят брокеру на настоящий счёт. Включает его человек
кнопкой, и **только** после вопроса; выключает тоже он, и при открытой
позиции — тоже после вопроса.

Логики здесь нет. Доступен ли бой, почему нет, включён ли он, прогрет ли,
почему отложена пересборка и почему отказано — всё приходит готовым в снимке
порта (`ui.models.LiveView`, `TerminalPort.live_changed`). Модуль переводит
снимок в подпись, подсказку и цвет — тем же приёмом, что кнопка связи
по `RobotState.connection` (`ui/main_window.py::STREAM_BUTTON`): кнопка
зеркалит снимок, а не помнит нажатие.
"""

