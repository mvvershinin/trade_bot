from collections.abc import Callable
from dataclasses import dataclass

from ui.formatting import fmt_price
from ui.models import LiveView
from ui.status_panel import position_head

__all__ = [
    "LIVE_NO_PORT",
    "LIVE_OFF_LEAD",
    "LIVE_OFF_TAIL",
    "LIVE_OFF_LABEL",
    "LIVE_ON_LABEL",
    "LIVE_UNGUARDED",
    "NO_EMERGENCY_STOP",
    "POSITION_UNREAD",
    "TAKE_MAY_STAY",
    "TAKE_NONE",
    "LIVE_UNMANAGED",
    "LiveLook",
    "live_look",
    "live_mode_off_question",
    "live_off_question",
    "live_on_question",
    "take_words",
    "unguarded_question",
]

#: Подпись кнопки, когда бой выключен. Многоточие — обещание вопроса.
LIVE_ON_LABEL = "Включить бой…"
#: Подпись кнопки, когда бой просили включить или он включён.
LIVE_OFF_LABEL = "Выключить бой"

#: Что сказать до первого снимка: порт ещё не ответил или его нет вовсе.
LIVE_NO_PORT = (
    "Бой: программа ещё не сказала, можно ли его включить. Если окно открыто "
    "без торговой части, включить бой нельзя вовсе."
)

#: Что остаётся без присмотра, когда позиция «факта» открыта, а программы
#: при ней нет: окно закрыли или бой выключили. Одно утверждение на два
#: вопроса — закрытие окна и выключение боя (план §12, С8).
#:
#: ⚠️ Утверждение держится на решении 0066: скользящий уровень сторожит
#: программа (Р2), неподвижный тейк — лимитная заявка у брокера (Р1),
#: аварийного стопа у брокера нет (Р10).
LIVE_UNGUARDED = (
    "Позиция останется без стопа: скользящий уровень (трейлинг) сторожит "
    "сама программа, а не брокер, и без неё его не сторожит никто."
)

#: Что сказать о тейке, когда у позиции есть уровень. Условно: какой это
#: уровень — неподвижный тейк у брокера или скользящий у программы, — окно
#: не знает, и утверждать первое безусловно не вправе.
TAKE_MAY_STAY = (
    "Если уровень {level} — неподвижный тейк, он стоит лимитной заявкой "
    "у брокера: она остаётся и может сработать сама, без программы."
)
#: Что сказать о тейке, когда уровня у позиции нет: живой заявки тейка
#: программа за ней не знает (у запомненной позиции уровень стоит, только
#: если тейк жив по журналу команд). Обещать тейк здесь нельзя.
TAKE_NONE = (
    "Живой заявки тейка у брокера за этой позицией программа не знает — "
    "рассчитывать на тейк нельзя."
)
#: Хвост каждого вопроса о позиции без присмотра (решение 0066, Р10).
NO_EMERGENCY_STOP = "Аварийного стопа у брокера робот не ставит."


@dataclass(frozen=True, slots=True)
class LiveLook:
    """Строка рядом с кнопкой: текст, подсказка и цвет — имя поля темы.

    Пустой `text` — строки нет вовсе: бой доступен и выключен, сказать нечего.
    """

    text: str
    tooltip: str
    colour: str = "text_dim"


def _reasons(view: LiveView) -> str:
    """Все причины недоступности — списком, по строке на причину."""
    return "\n".join(f"• {reason}" for reason in view.why_not)


def _halted(view: LiveView) -> LiveLook:
    return LiveLook(
        f"Бой остановлен: {view.halted}",
        f"Бой остановлен: {view.halted}\n\nЗаявки брокеру не подаются. Позиция "
        "у брокера, если есть, осталась как была — она показана в шапке, "
        "в ячейке «Позиция у брокера».",
        "danger",
    )


def _held(view: LiveView) -> LiveLook:
    return LiveLook(
        f"Бой включён · пересборка отложена: {view.held}",
        "Настройки поменялись так, что робота надо собрать заново, но сейчас "
        f"это нельзя: {view.held} Робот работает со старыми настройками, "
        "пока причина не уйдёт.",
        "warning",
    )


def _armed(_view: LiveView) -> LiveLook:
    return LiveLook(
        "БОЙ: заявки уходят брокеру",
        "Бой включён: робот сам подаёт заявки брокеру на ваш счёт. Сделки "
        "настоящие. Выключение боя позицию не закрывает.",
        "danger",
    )


def _warming(_view: LiveView) -> LiveLook:
    return LiveLook(
        "Бой включён · прогрев, заявок ещё нет",
        "Боевая часть собрана; робот досчитывает среднюю по прошлым свечам. "
        "Заявки пойдут брокеру со свечи включения — об этом строка в журнале "
        "решений.",
        "warning",
    )


def _asked(_view: LiveView) -> LiveLook:
    return LiveLook(
        "Бой включается…",
        "Программа сверяется с брокером (позиция, незакрытые заявки) "
        "и собирает боевую часть. Итог — следующей строкой в журнале решений.",
        "warning",
    )


def _refused(view: LiveView) -> LiveLook:
    return LiveLook(
        f"Бой не включён: {view.refused}",
        f"Бой не включён: {view.refused}"
        + (f"\n\nСейчас мешает:\n{_reasons(view)}" if view.why_not else ""),
        "danger",
    )


def _unavailable(view: LiveView) -> LiveLook:
    first = view.why_not[0] if view.why_not else "причина не названа"
    # Число причин — **до** первой: строка в панели обрезается справа,
    # и счёт в хвосте пропадал бы первым (проверено на ширине 720).
    count = len(view.why_not)
    return LiveLook(
        (f"Бой недоступен, причин {count}: " if count > 1 else "Бой недоступен: ") + first,
        f"Включить бой сейчас нельзя:\n{_reasons(view)}",
    )


#: Что сказать по снимку — цепочкой «условие → строка», первое совпавшее.
#:
#: Цепочка, а не ветвление, и **порядок здесь — данные**: остановка боя
#: важнее всего — после неё `wanted` ещё стоит, и строка «Бой включается…»
#: врала бы (аудит /risk 01.11.2026, R4); отложенная пересборка важнее
#: «бой включён», включённый бой важнее давнего отказа, а отказ, случившийся
#: после нажатия, важнее общей недоступности — человек жал кнопку и ждёт
#: ответа именно на это.
_LOOKS: tuple[tuple[Callable[[LiveView], bool], Callable[[LiveView], LiveLook]], ...] = (
    (lambda view: bool(view.halted), _halted),
    (lambda view: view.on and bool(view.held), _held),
    (lambda view: view.on and view.armed, _armed),
    (lambda view: view.on, _warming),
    (lambda view: view.wanted, _asked),
    (lambda view: bool(view.refused), _refused),
    (lambda view: not view.available, _unavailable),
)


def live_look(view: LiveView | None) -> LiveLook:
    """Строка рядом с кнопкой боя по снимку. `None` — снимка ещё нет."""
    if view is None:
        return LiveLook("Бой: ждём ответа программы", LIVE_NO_PORT)
    for applies, look in _LOOKS:
        if applies(view):
            return look(view)
    return LiveLook(
        "",
        "Бой доступен: нажмите «Включить бой…» — программа спросит подтверждение.",
    )


def live_on_question(volume: str, instrument: str) -> str:
    """Вопрос перед включением боя. Первая строка — главное, остальное — цена."""
    return (
        "Бой: заявки уйдут брокеру на реальный счёт.\n\n"
        f"Робот будет сам подавать заявки по своим сигналам по {instrument} — "
        f"настоящие сделки на ваши деньги, по {volume} за раз.\n\n"
        "Предохранителей по деньгам нет: ни дневного лимита убытка, ни потолка "
        "объёма. Скользящий уровень сторожит программа: пока она закрыта или "
        "без связи, позиция без защиты.\n\n"
        "Перед включением программа сверится с брокером; итог — строкой "
        "в журнале решений.\n\nВключить бой?"
    )


#: Первая строка вопроса, когда позиция у брокера не прочитана (порт отдал
#: `position = None` с оговоркой): позиции может и не быть, но проверить надо.
POSITION_UNREAD = (
    "Позиция робота у брокера не прочитана — проверьте её в приложении брокера."
)


def take_words(view: LiveView) -> str:
    """Что сказать о тейке позиции в вопросе.

    Слова порта (`take_note`) — первыми и как есть: «неизвестно» не имеет
    права стать «нет» (Н7). Без них — по уровню живой позиции: условно при
    уровне, «рассчитывать нельзя» без него.
    """
    if view.take_note:
        return f"О тейке: {view.take_note}."
    position = view.position
    if position is None or position.take_level is None:
        return TAKE_NONE
    return TAKE_MAY_STAY.format(level=fmt_price(position.take_level))


def unguarded_question(
    view: LiveView, lead: str, question: str, *, tail: str = LIVE_UNGUARDED
) -> str:
    """Вопрос, после которого позиция «факта» остаётся без программы или без робота.

    `tail` — что станет со скользящим уровнем: без программы
    (`LIVE_UNGUARDED`), без боя (`LIVE_OFF_TAIL`) или в режиме «Выключен»
    (`LIVE_UNMANAGED`). О тейке — `take_words`. Оговорка порта о позиции
    (`position_note`) — сразу за ней: позиция может быть не текущей. Позиции
    нет, а оговорка есть — позиция у брокера не прочитана, и первая строка
    говорит это (`POSITION_UNREAD`).
    """
    note = view.position_note
    said = f" Сведения о позиции: {note}." if note else ""
    position = view.position
    head = (
        POSITION_UNREAD if position is None
        else f"У брокера открыта позиция робота: {position_head(position)}."
    )
    return (
        f"{head}{said}\n\n"
        f"{lead}\n\n{tail} {take_words(view)} {NO_EMERGENCY_STOP}\n\n{question}"
    )


#: Что сказать о выключении боя: новых заявок нет, позиция остаётся.
LIVE_OFF_LEAD = (
    "Выключение боя позицию не закрывает: новых заявок к брокеру робот "
    "не подаёт и позицией больше не управляет. Новый бой включится только "
    "при нулевой позиции."
)

#: Что станет с уровнями позиции, когда бой выключен, а программа открыта.
#: С выключением боя уходит боевая часть программы, а с ней сторож
#: скользящего уровня (решение 0066, Р2); неподвижный тейк — заявка у брокера
#: (Р1) — остаётся.
LIVE_OFF_TAIL = (
    "Позиция останется без стопа: скользящий уровень (трейлинг) сторожит "
    "только боевая часть программы, и с выключением боя его не сторожит никто."
)


def live_off_question(view: LiveView, *, by_stop: bool = False) -> str:
    """Вопрос перед выключением боя при открытой позиции.

    `by_stop` — выключение просят «Стопом»: в бою «Стоп» выключает бой
    (решение владельца 01.11.2026, 0066), и вопрос говорит это первым.
    """
    lead = ("«Стоп» в бою выключает бой. " if by_stop else "") + LIVE_OFF_LEAD
    return unguarded_question(view, lead, "Выключить бой?", tail=LIVE_OFF_TAIL)


#: Что с уровнями позиции «факта» в режиме «Выключен» при включённом бое.
#:
#: Решение владельца 01.11.2026 (0066) по коду: в «Выключен» движок свечу
#: не разбирает и вооружённый уровень не снимает и не переставляет
#: (`engine/pipeline.py`, шаг 1), а сторож исполнителя от режима движка
#: не зависит (`app/live_executor.py::_sweep`) — застывший скользящий уровень
#: сторожится, пока живы окно и связь. Неподвижный тейк — заявка у брокера (Р1).
LIVE_UNMANAGED = (
    "Робот новых входов не делает и уровень не двигает. Застывший скользящий "
    "уровень программа продолжает сторожить и на касании выходит по рынку — "
    "пока окно открыто и есть связь; закроете окно или пропадёт связь — "
    "сторожить его некому."
)


def live_mode_off_question(view: LiveView) -> str:
    """Вопрос перед режимом «Выключен» в бою при позиции «факта»."""
    return unguarded_question(
        view,
        "Режим «Выключен» позицию не закрывает — выключение само по себе "
        "не приводит к сделке; переворота по средней не будет.",
        "Выключить робота?",
        tail=LIVE_UNMANAGED,
    )
