"""Предупреждения про деньги — в одном месте, а не в трёх.

Здесь живут тексты, неверность которых стоит владельцу счёта денег. Логики
торговли в них нет ни строки: это оформление того, что пришло в `RobotState`
и `Position`. Ни одно поле здесь не вычисляется — все приходят от `engine/`
через порт.

Почему отдельный модуль
-----------------------
Одно и то же утверждение про открытую позицию делалось **в трёх местах**
`ui/main_window.py`: в плашке над графиком, в окне подтверждения при
переключении режима в «Выключен» и в окне подтверждения при закрытии
программы. Три копии разошлись с движком одинаково и одновременно, и это
не совпадение: копия текста живёт своей жизнью ровно до первого изменения
поведения.

Что именно разошлось (найдено гейтом `/risk` 30.08.2026): все три места
обещали, что после выключения робота «ни тейк, ни переворот к ней больше
не применяются». Половина этого обещания неверна. Тейк-профит — **заявка
у брокера**, а не расчёт внутри программы (решение 0008, пункт 2): движок
её при выключении не снимает, и уровень остаётся жить на стороне брокера.
Цена ошибки названа в решении 0008: поверив окну, владелец счёта поставит
свой стоп и получит два. Сработает наш — позиция закрыта; его стоп остаётся
и при следующем касании открывает позицию в обратную сторону на полный объём.

Правило, ради которого модуль заведён: **утверждение о том, что происходит
с позицией без робота, делается ровно один раз**. Появилось четвёртое место —
оно зовёт функцию отсюда, а не пишет свой текст.

⚠️ Обстановка — часть утверждения, а не украшение (31.08.2026)
---------------------------------------------------------------
Одного места оказалось мало: текст переехал туда, где он ложен. `guard_note`
писался для обстановки «робот перестал управлять», а панель состояния звала
его **безусловно** — на работающем роботе тоже. Рабочая конфигурация
с выключенным тейком (ею сделаны обе конфигурации-сторожа сверки,
PROTOTYPE.md §1) давала на экране: «сторожить у брокера нечего, и робот её
не закроет» — при работающем роботе в режиме переворота, где переворот
по средней позицию как раз закрывает, на ближайшем обратном сигнале.
Владелец счёта, поверивший этому, закрывает позицию руками у брокера; сверки
позиции с брокером в движке ещё нет, и на следующем сигнале рыночный выход
**открывает позицию в обратную сторону на полный объём**.

Вторая половина той же ошибки — симуляция. Модуль про неё не знал вовсе
и звал «снять заявку в приложении брокера» там, где ни позиции, ни заявки
у брокера нет: разработка и первые недели идут на симуляции. Два похода
к брокеру впустую обесценивают красную плашку к тому дню, когда она станет
правдой.

Отсюда `Context`: **утверждение делится на безусловную часть** (что за
уровень и чей он) **и контекстную** (что будет без робота, куда идти
проверять). Контекстная выдаётся только там, где она верна.
"""

from __future__ import annotations

from dataclasses import dataclass, replace

from ui.formatting import fmt_datetime, fmt_level, fmt_price, fmt_volume
from ui.models import HaltCause, Mode, Position, RobotState, TakeGuard

#: Куда идти человеку в боевом режиме. Повторяется в нескольких текстах,
#: поэтому вынесено: расхождение в этой фразе означало бы, что в одном месте
#: зовут проверить позицию, а в другом — список заявок, хотя проверять надо
#: и то и другое.
CHECK_WITH_BROKER = "Проверьте позицию и список заявок в приложении брокера"

#: То же место в симуляции. Не «ничего не делайте», а прямая речь о том,
#: почему идти к брокеру незачем: иначе следующая мысль владельца счёта —
#: «а раньше звали, значит и сейчас надо».
NOTHING_AT_BROKER = (
    "Идёт симуляция: на счёте у брокера ни этой позиции, ни этих заявок нет"
)


@dataclass(frozen=True, slots=True)
class Context:
    """Обстановка, в которой читается текст. Не состояние робота — обстановка.

    Два признака, и каждый переворачивает смысл одних и тех же слов.

    `managed` — робот сейчас управляет позицией. При нём **не выдаётся**
    ни «и робот её не закроет», ни «снять её можно в приложении брокера»:
    первое ложно (в режиме переворота позицию закрывает как раз робот),
    второе опасно (снятую руками заявку движок не заметит — срабатывание
    тейка приходит ему только сделкой, решение 0008 — и будет считать
    сторожа живым, пока позиция идёт без уровня).

    `simulation` — заявки на биржу не отправляются. При нём не выдаётся
    ничего про счёт у брокера: там пусто.

    ⚠️ Умолчания намеренно «громкие» и намеренно **не** совпадают
    с умолчаниями `RobotState` (у того `simulation=True`). Забытый аргумент
    обязан давать текст боевого режима без управления: лишний совет проверить
    счёт стоит человеку минуты, пропущенный — денег.
    """

    managed: bool = False
    simulation: bool = False

    @classmethod
    def of(cls, state: RobotState) -> Context:
        """Обстановка по снимку состояния.

        Единственное место, где записано, что значит «робот управляет».
        Это не торговое правило: оно ничего не решает про вход, выход
        и уровни, а только выбирает, какой из двух верных текстов показать.
        Все три признака приходят готовыми из `engine/` через порт.
        """
        return cls(
            managed=state.running and state.mode is not Mode.OFF and not state.halted,
            simulation=state.simulation,
        )


def position_line(position: Position) -> str:
    """Позиция одной строкой: «Шорт 1 по 284 812,53»."""
    return (
        f"{position.side.label} {fmt_volume(position.volume)} "
        f"по {fmt_price(position.entry_price)}"
    )


def where_to_look(context: Context) -> str:
    """Куда идти проверять — и куда не надо, потому что там пусто."""
    return NOTHING_AT_BROKER if context.simulation else CHECK_WITH_BROKER


def guard_note(position: Position, context: Context = Context()) -> str:
    """Что за уровень выхода у этой позиции и чей он.

    Самое важное предложение во всём слое окна. Оно отвечает на вопрос,
    который владелец счёта задаёт сразу после «робот выключен»: закроется
    ли позиция сама.

    Четыре ответа вместо прежнего одного, и каждый отличается от остальных
    последствием:

    * уровень выставлен — он сработает без нас, и ставить второй стоп нельзя;
    * уровня нет — сторожить у брокера нечего;
      хвост «и робот её не закроет» добавляется только без робота;
    * заявка на выход подана — она может исполниться сама;
    * **неизвестно** — умолчание, и оно обязано существовать. Пока `app/`
      не заполнил поле, окно не вправе утверждать ни того, ни другого:
      молчаливое «стопа нет» — это ровно та неправда, из-за которой модуль
      написан.

    ⚠️ Всё, что сказано выше, — безусловно. Что будет с позицией **без
    робота** и куда идти её проверять, добавляется по `context`: на
    работающем роботе оба этих утверждения ложны (см. заголовок модуля).
    """
    parts: list[str] = []
    simulated = context.simulation

    if position.closing:
        if simulated:
            # ⚠️ Слова «идёт симуляция» здесь нет намеренно: их говорит
            # `where_to_look` один раз в конце. Три «идёт симуляция» подряд
            # в одном абзаце — это шум, а абзац читают ради денег.
            parts.append(
                "По ней уже подана заявка на выход, а сделки по ней ещё "
                "не было: заявка живёт внутри программы"
            )
        else:
            parts.append(
                "⚠️ По ней уже подана заявка на выход, а сделки по ней ещё не было: "
                "заявка живёт у брокера и может исполниться сама, без участия "
                "«Терминала»"
            )

    # `None` — движок не сказал, какой это уровень. Тогда и окно не называет:
    # «выставленный уровень выхода» верно для обоих, а «тейк» про скользящий
    # уровень — уже неправда, он мог уехать далеко от цены входа.
    #
    # `.get`, а не индексация: значение вне трёх известных роняло бы
    # `KeyError` внутри слота показа состояния — то есть окно переставало бы
    # показывать позицию из-за одного неверного поля.
    what = {
        True: "скользящий тейк",
        False: "тейк",
        None: "уровень выхода",
    }.get(position.take_trailing, "уровень выхода")
    if position.take is TakeGuard.ARMED:
        level = (
            f" {fmt_level(position.take_level)}" if position.take_level is not None else ""
        )
        if simulated:
            # Про то, что у брокера пусто, говорит `where_to_look` — один раз
            # и в конце. Здесь сказано другое и достаточное: где уровень живёт.
            parts.append(
                f"Выставленный {what}{level} существует только внутри программы"
            )
        else:
            # Хвост «снять её можно» — только когда робот позицией не управляет.
            # Снятую руками заявку движок не заметит и будет считать сторожа
            # живым: срабатывание тейка приходит ему только сделкой (0008).
            tail = "" if context.managed else ". Снять её можно в приложении брокера"
            parts.append(
                f"⚠️ Выставленный {what}{level} остаётся у брокера и может "
                "сработать: это заявка на его стороне, а не расчёт внутри "
                "программы" + tail
            )
    elif position.take is TakeGuard.NONE:
        # ⚠️ «Робот её не закроет», а НЕ «сама она не закроется». Второе —
        # обещание, которого не может дать никто: биржа пересматривает
        # обеспечение внутри дня, и при нехватке свободных средств позицию
        # закрывает брокер, по своей цене и в свой момент (DOMAIN.md §5).
        # Владелец счёта, прочитавший «сама не закроется» в пятницу вечером,
        # уходит на выходные и за обеспечением не следит.
        #
        # ⚠️ И это тоже неверно на работающем роботе: в режиме переворота
        # позицию закрывает как раз он, на ближайшем обратном сигнале.
        head = "Выставленного уровня выхода у этой позиции нет"
        # «Сторожить у брокера нечего» опускается в двух случаях: в симуляции
        # у брокера нечего сторожить в принципе, а при поданной заявке
        # на выход предложение выше только что сказало, что у брокера живёт
        # заявка, — и рядом с ней это читается как противоречие.
        if not simulated and not position.closing:
            head += " — сторожить у брокера нечего"
        tail = (
            ", и робот её не закроет"
            if not context.managed and not position.closing
            else ""
        )
        parts.append(head + tail)
    else:
        # ⚠️ Оборот «поэтому не считайте, что её нет» одинаков в обеих ветках
        # намеренно: это то самое место, где окно обязано не утверждать
        # отсутствие стопа, и проверка на него не должна зависеть от режима.
        if simulated:
            parts.append(
                "⚠️ Есть ли у этой позиции выставленный тейк, программа сказать "
                "не может — движок этого не сообщил, поэтому не считайте, "
                "что её нет"
            )
        else:
            parts.append(
                "⚠️ Есть ли у этой позиции выставленный тейк, программа сказать "
                "не может — движок этого не сообщил. Заявка на стороне брокера "
                "срабатывает без участия «Терминала», поэтому не считайте, "
                "что её нет"
            )

    if context.managed:
        # Безусловная часть без контекстной читается тревожнее, чем есть
        # на самом деле: «сторожить нечего» — и точка.
        #
        # ⚠️ Что именно робот делает в этом режиме, здесь НЕ пересказывается:
        # описание режима живёт ровно в одном месте (`Mode.hint`), и вторая
        # копия разошлась бы с первой при первой же правке — ровно так этот
        # слой уже ломался.
        #
        # ⚠️ И ссылка не на «ячейку рядом»: текст обязан быть верен везде,
        # куда его позовут, а «рядом» верно только в панели состояния.
        parts.append(
            "Робот сейчас работает и управляет этой позицией. Что он делает "
            "в текущем режиме — в подсказке к названию режима"
        )

    return ". ".join(parts) + "."


def unmanaged_note(position: Position, context: Context = Context()) -> str:
    """Что перестаёт работать, когда робот больше не управляет позицией.

    Ровно одно утверждение на весь слой окна. Первая половина — про то, чего
    точно не будет: переворот и закрытие по концу окна делает движок, а он
    не работает. Вторая половина — `guard_note`: про то, что всё-таки может
    произойти без него.

    ⚠️ `managed` здесь принудительно снимается. Функция и есть текст про
    обстановку «робота больше нет», и вызывают её из подтверждений, где робот
    ещё работает: `Context.of(state)` в этот момент говорит «управляет».
    Разбираться в этом на каждом вызове — способ получить четвёртую копию
    утверждения.
    """
    context = replace(context, managed=False)
    return (
        "Переворот по сигналу средней и закрытие по концу торгового окна "
        f"к ней больше не применяются. {guard_note(position, context)} "
        f"{where_to_look(context)}."
    )


def cause_line(cause: HaltCause) -> str:
    """Одна причина остановки строкой: с каких пор, какого вида и что сказано.

    Время — московское и помечено как московское: машина владельца счёта
    может стоять в другом поясе, и «11:20» без пометки читается как местное.
    Вид не назван — про вид молчим, а не подставляем «неизвестно»: строка
    и без него полная.
    """
    marks = []
    if cause.at is not None:
        marks.append(f"с {fmt_datetime(cause.at)} МСК")
    if cause.kind:
        marks.append(cause.kind)
    head = f" ({', '.join(marks)})" if marks else ""
    return f"{cause.reason}{head}"


def resume_question(state: RobotState) -> str:
    """Вопрос перед снятием одной причины остановки. Пусто — снимать нечего.

    ⚠️ **Текст обязан сказать, что снимается одна причина, а не остановка.**
    Нажатие снимает самую раннюю; если причин больше одной, робот остаётся
    остановленным. Кнопка, про которую человек думает «сейчас всё заработает»,
    и кнопка, которая снимает один запрет из двух, — это разные кнопки,
    и различие целиком в этом тексте (`D-086`, аудит `/risk` 06.09.2026).

    ⚠️ **Про поход к брокеру говорится тогда, когда он нужен.** Признак
    приходит готовым полем (`HaltCause.broker_check`): решать, надо ли идти
    к брокеру, окно не имеет права. Совет, выданный не по делу, обесценивает
    его к тому дню, когда он станет правдой (см. шапку модуля).
    """
    causes = state.halt_causes
    if not causes:
        return ""
    first, rest = causes[0], causes[1:]
    lines = [
        "Робот остановлен." if len(causes) == 1
        else f"Робот остановлен, причин {len(causes)}.",
        "",
        "Сейчас снимается только одна — самая ранняя:",
        cause_line(first),
    ]
    if rest:
        listed = "\n".join(
            f"{number}) {cause_line(cause)}"
            for number, cause in enumerate(rest, 2)
        )
        lines += [
            "",
            "После этого робот останется остановленным. Не снято будет:",
            listed,
            "",
            "Причины снимаются по одной намеренно: они про разные беды, "
            "и согласиться с одной, не прочитав остальные, нельзя.",
        ]
    else:
        lines += [
            "",
            "Это последняя причина. После снятия робот заработает заново: "
            "живой ход движка начнётся с прогрева на ближайшем закрытом баре.",
        ]
    if first.broker_check:
        lines += [
            "",
            f"{CHECK_WITH_BROKER} — прежде чем снимать эту причину. Программа "
            "не знает, что на счёте: команда ушла, ответа на неё не было.",
        ]
    lines += ["", "Снять эту причину?"]
    return "\n".join(lines)


def halt_note(state: RobotState) -> str:
    """Крупный текст про остановленного робота.

    Остановка — не «робот вне рынка». Это «робот перестал понимать, что
    происходит на счёте, и ждёт человека»: он встаёт на сделке, которую
    не смог сопоставить со своей заявкой, на застрявшем выходе, на отказе
    исполнителя принять заявку и на отказе журнала принять строку.
    В последнем случае причину не найти больше нигде — приёмник журнала
    и есть то, что отказало, — и показать её обязано окно.

    Причина приходит готовой строкой из `engine/`. Окно её не сочиняет
    и не сокращает: она уже написана человеческим языком и уже названа
    целиком.
    """
    if not state.halted:
        return ""
    context = Context.of(state)
    # Причина может прийти пустой — например, если `app/` заполнил флаг,
    # а строку потерял. Молча спрятать остановку в этом случае нельзя:
    # неназванная причина это плохо, а невидимая остановка — хуже.
    reason = state.halted.strip().rstrip(".")
    head = (
        f"Робот остановлен: {reason}."
        if reason
        else "Робот остановлен, но причина не названа — ищите её в журнале решений."
    )
    text = (
        f"{head} Он не подаёт заявок "
        "и не следит за рынком, пока человек не разберётся, что произошло."
    )
    if state.position is not None:
        # ⚠️ Указание, что делать, — часть текста, а не любезность. Плашка
        # остановки закрывает собой плашку режима, а вместе с ней исчезала
        # единственная строка «закройте вручную». Совет при этом другой:
        # остановленному роботу переключение режима не поможет, помогут
        # только руки в приложении брокера.
        text += (
            f" Позиция при этом осталась открыта: {position_line(state.position)}. "
            f"{unmanaged_note(state.position, context)} "
        )
        text += (
            "Разберитесь с причиной и запустите робота заново: "
            "закрывать у брокера нечего."
            if context.simulation
            else "Закрыть её и снять оставшиеся заявки можно только вручную, "
                 "у брокера: переключение режима остановленным роботом "
                 "не исполняется."
        )
    else:
        text += (
            " Идёт симуляция: заявок «Терминала» на счёте у брокера нет."
            if context.simulation
            else f" {CHECK_WITH_BROKER}."
        )
    return text
