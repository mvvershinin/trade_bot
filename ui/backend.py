"""Три ответа, которые окно получить само не может, и кто их даёт.

Зачем это существует
--------------------
Окну шаблонов настроек нужны три вещи, и ни одну оно не имеет права посчитать:

1. **«было → стало»** — перечень изменений человеческим языком. Считает его
   `app/convert.py` вместе с `EngineSettings.changes_from` и
   `EmaReverseSettings.changes_from`: это те же строки, что уходят в журнал
   решений. Второе описание тех же изменений разошлось бы с первым молча.
2. **Прогоны, сделанные этим набором настроек** — статистика шаблона. Берётся
   из записанных прогонов (`journal_session`), а не считается заново: считать
   отдельно значило бы завести вторую правду о деньгах.
3. **Снимок настроек словами** — тот же текст, что записывается в журнал
   прогона (`app/runs.py::settings_text`). Человек видит в окне ровно то, что
   потом найдёт в записи.

Почему через реестр, а не импортом
----------------------------------
`ui/` не имеет права импортировать `app/` (ARCHITECTURE.md §2), а всё
перечисленное живёт в `app/`: перевод настроек окна в настройки движка —
это торговое правило, и его копия в окне была бы вторым источником правды
ровно там, где цена ошибки — деньги.

Поэтому здесь объявлена **дверь**, а створку в неё вставляет слой сборки:
`app/runs.py` при импорте зовёт `use(...)`. Направление зависимостей от этого
не страдает — `app/` знает про `ui/`, `ui/` про `app/` не знает.

⚠️ Створки может не быть вовсе: окно, открытое без торговой части (тесты
интерфейса, снимок экрана), получает `None`. Это **не повод молча продолжить**:
подтверждение изменений без перечня изменений превращается в кнопку «Да»,
а шаблон без статистики — в список имён. Каждое место, спрашивающее backend,
обязано сказать вслух, что ответа нет.

Торговых правил здесь нет ни одного: это объявление границы, как `ui/ports.py`.
"""

from __future__ import annotations

from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from ui.models import Settings

__all__ = [
    "Backend",
    "RunStats",
    "SettingsDiff",
    "TemplateRun",
    "current",
    "use",
]


@dataclass(frozen=True, slots=True)
class SettingsDiff:
    """Что меняется при применении настроек — строками «было → стало».

    Два списка, а не один. `money` — то, за чем стоят деньги на счёте: объём,
    потолок объёма, дневной лимит убытка, запас свободных средств, комиссия.
    Смена периода средней и смена объёма сделки читаются по-разному, и окно
    показывает их отдельно, крупнее и цветом.

    `trouble` — настройки не удалось разобрать вовсе (например, выбран режим,
    которого движок не умеет). Пустая строка означает, что разбор удался.
    ⚠️ Пустой перечень при непустом `trouble` **не означает «ничего
    не меняется»**: он означает «перечислить не удалось».
    """

    money: tuple[str, ...] = ()
    other: tuple[str, ...] = ()
    trouble: str = ""

    @property
    def empty(self) -> bool:
        """Совсем нечего показывать: ни изменений, ни причины отказа."""
        return not self.money and not self.other and not self.trouble

    @property
    def count(self) -> int:
        """Сколько всего изменений насчитано."""
        return len(self.money) + len(self.other)


@dataclass(frozen=True, slots=True)
class TemplateRun:
    """Один записанный прогон, сделанный этим набором настроек.

    ⚠️ Числа берутся **из записи прогона**, а не считаются заново. `None`
    у `trades` и `profit` означает «в записи этого нет» — прогон прерван,
    не удался или закрыт без итога. Ноль здесь стоять не имеет права: ноль
    читается как «дало ноль рублей», а это другое утверждение.
    """

    started_at: datetime
    #: Что это был за прогон: «проверка на истории», «симуляция», «бой».
    origin: str
    symbol: str = ""
    timeframe: str = ""
    #: Отрезок, на котором гнали, — как он записан в прогоне. Пусто — не назван.
    period: str = ""
    trades: int | None = None
    profit: float | None = None
    #: Итог прогона целиком, как записан. Уходит в подсказку при наведении.
    note: str = ""


@dataclass(frozen=True, slots=True)
class RunStats:
    """Прогоны для каждого поданного набора настроек, в том же порядке.

    `trouble` — базу прочитать не удалось. Пустой список прогонов при этом
    означает «неизвестно», а не «прогонов не было», и окно обязано сказать
    именно так.
    """

    runs: tuple[tuple[TemplateRun, ...], ...] = ()
    trouble: str = ""


@dataclass(frozen=True, slots=True)
class Backend:
    """Створка двери: что умеет слой сборки.

    :param changes: перечень «было → стало» для пары наборов настроек.
    :param runs: прогоны, сделанные каждым из поданных наборов.
    :param snapshot: снимок настроек человеческим текстом — тот же, что
        записывается в журнал прогона.
    :param userdata: где лежит папка данных программы. Библиотека шаблонов
        кладётся туда же, где настройки и база: папка переносится целиком.
    """

    changes: Callable[[Settings, Settings], SettingsDiff]
    runs: Callable[[Sequence[Settings]], RunStats]
    snapshot: Callable[[Settings], str]
    userdata: Callable[[], Path]


@dataclass(slots=True)
class _Door:
    """Единственная створка на всю программу. Пусто — торговой части нет."""

    backend: Backend | None = field(default=None)


_DOOR = _Door()


def use(backend: Backend | None) -> None:
    """Вставить створку. Зовётся слоем сборки, из окна — никогда.

    Повторный вызов заменяет прежнюю: тесты ставят свою и возвращают старую.
    """
    _DOOR.backend = backend


def current() -> Backend | None:
    """Что вставлено. `None` — окно работает без торговой части."""
    return _DOOR.backend
