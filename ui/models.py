@dataclass(frozen=True, slots=True)
class BacktestRequest:
    """Что владелец счёта просит прогнать.

    ⚠️ `settings` — набор целиком, **уже** с выбранным инструментом и размером
    свечи внутри. Второго места, где инструмент задаётся отдельно от настроек,
    не заводится: разъехались бы молча, и прогон пошёл бы не по тому ряду,
    что показан в настройках.

    `since` и `until` — границы отрезка, оба момента включительно и оба
    московские. Диалог берёт их из покрытия базы, поэтому «до» не бывает
    раньше «от».

    `settings_source` — откуда взяты настройки, человеческими словами:
    «текущие настройки» либо имя шаблона. Уходит в отчёт и в журнал, чтобы
    через неделю было видно, чем гнали.
    """

    settings: Settings
    since: datetime
    until: datetime
    settings_source: str = ""


@dataclass(frozen=True, slots=True)
class RunAssumption:
    """Одно допущение прогона: чем показанный итог отличается от выписки.

    Приходит готовым из `backtest/assumptions.py`; окно не сочиняет ни одного
    слова и не решает, какое допущение показать. `short` — одна фраза рядом
    с числом, `text` — абзац целиком, `beside_number` — обязано ли оно стоять
    вплотную к деньгам.
    """

    name: str
    short: str
    text: str
    beside_number: bool = False


@dataclass(frozen=True, slots=True)
class BacktestReport:
    """Итог прогона на истории — всё, что показывает окно отчёта.

    Ни одно число здесь окном не считается: и деньги, и число торговых дней,
    и допущения приходят готовыми из слоя сборки (`app/convert.py`).

    ⚠️ `assumptions` едет **в этом же объекте**, что и `summary`. Показать
    деньги и не иметь под рукой оговорку к ним нельзя даже по невнимательности
    — ровно то же правило, ради которого `headline` лежит полем `TradesSummary`
    (решение 0030).

    `trading_days` — сколько **торговых** дней в отрезке, то есть сколько
    разных дат встретилось у свечей прогона. Календарных дней между границами
    больше: выходные, праздники и дни без торгов свечей не дают.
    """

    instrument: str = ""
    timeframe: str = ""
    #: Границы отрезка, которые просили. Могут быть шире того, что нашлось.
    asked_since: datetime | None = None
    asked_until: datetime | None = None
    #: Границы того, что нашлось: закрытие первой и последней свечи прогона.
    first_bar: datetime | None = None
    last_bar: datetime | None = None
    bars: int = 0
    trading_days: int = 0
    settings_source: str = ""
    #: Снимок настроек словами — тот же текст, что уходит в запись прогона.
    settings_text: str = ""
    trades: tuple[TradeRow, ...] = ()
    summary: TradesSummary | None = None
    assumptions: tuple[RunAssumption, ...] = ()
    #: Робота остановил предохранитель — причина словами. Пусто — не останавливали.
    halted: str = ""
