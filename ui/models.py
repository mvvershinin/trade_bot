    #: или перевороту.
    #:
    #: ⚠️ Умолчание «включено» менять нельзя без нового замера: на нём стоит
    #: сверка с прототипом, 127 сделок из 127. Выключенный режим замерами
    #: не подкреплён ничем, и у позиции в нём **нет верхней границы времени
    #: жизни** — она переживает конец окна, ночь и выходные, пока не придёт
    #: обратный сигнал.
    close_on_time_end: bool = True
    volume: int = 1
    # Три предохранителя по деньгам. Проверки живут в движке
    # (`engine/guards.py`), числа доезжают до них из этих полей — но **только
    # через галочку**, и все три галочки сняты умолчанием (`D-030`).
    #
    # ⚠️ Умолчание «выключено» здесь не осторожность, а условие. Проводка,
    # включившая потолок 5 контрактов и дневной лимит 2 % сама по себе,
    # означала бы остановку торговли, которой владелец счёта не просил;
    # `CLAUDE.md` прямо говорит, что цифры предохранителей называет он.
    # Пока галочка снята, движок получает своё умолчание — то есть проверки
    # нет вовсе, и поведение робота ровно такое же, как до проводки.
    #
    # ⚠️ Числа — **предложение**, а не значение. 5 контрактов и 2 % ничем
    # не подкреплены: замеров под них у проекта нет.
    volume_cap_enabled: bool = False
    volume_cap: int = 5
    #: Дневной лимит убытка и запас средств считаются **от размера счёта**,
    #: а его программе сегодня никто не сообщает: портфель у брокера ещё
    #: не читается. Включённая галочка при неизвестном счёте не срабатывает
    #: и не молчит: движок пишет «НЕ ПРОВЕРЕНО» в строку входа
    #: (`engine/pipeline.py::_blind_note`), а окно говорит это заранее.
    daily_loss_limit_enabled: bool = False
    daily_loss_limit_pct: float = 2.0
    free_funds_reserve_enabled: bool = False
    free_funds_reserve_pct: float = 30.0
    # Тариф комиссии: рублей за контракт на ОДНУ сторону. `None` — не задан,
    # и это не то же самое, что ноль. Без тарифа движок не может проверить
    # требование ТЗ §4.4 В «цель должна окупать комиссию обеих сторон» и пишет
    # об этом предупреждением на каждой позиции. Подставленный за владельца
    # счёта ноль превратил бы проверку в вечное «окупается».
    #
    # ⚠️ Умолчание 14 ₽ поставлено 31.08.2026 и является **предварительным**.
    # Это не выдуманное число: `DOMAIN.md` §5 записывает его как биржевой сбор
    # из карточки инструмента плюс 1 ₽ брокеру, и на нём сделаны все замеры
    # проекта, включая таблицу вариантов тейка. Ноль здесь по-прежнему запрещён
    # по причине выше, а `None` оставлен достижимым: очистка поля в окне
    # возвращает честное «не задана».
    #
    # Заменяется на тариф владельца счёта перед боем. Сбор берётся из карточки
    # **того инструмента**, которым торгуют: у другого фьючерса он другой,
    # и 14 ₽ станут неверными молча — цифры сойдутся, а рубли нет.
    commission_per_side_rub: float | None = 14.0
    # Проскальзывание: насколько цена сделки на счёте хуже расчётной. Задаётся
    # в ШАГАХ цены (ТЗ §4.4 Ж), потому что шаг — свойство инструмента: полшага
    # на фьючерсе на индекс и на акции это разные деньги. Отсюда два поля,
    # и шаг цены обязателен, как только шагов проскальзывания больше нуля, —
    # иначе настройка выглядела бы заданной и работала бы как ноль
    # (`backtest.Costs.__post_init__`, то же условие).
    #
    # ⚠️ Умолчание — ноль шагов, и за ним стоит сверка с прототипом: ровно так
    # считал он, и на любом другом значении сверка не сойдётся по построению.
    # Ноль при этом не «пока не сделали»: замер 05.09.2026 на MXU6
    # (шаг 25 ₽, 19.06–26.08.2026) — 0 шагов дают +9 908 ₽, 1 шаг +4 394 ₽,
    # 2 шага −153 ₽. Один шаг съедает половину, два уводят в минус.
    price_step: float = 0.0
    slippage_steps: float = 0.0
    #: Сколько рублей приносит движение цены на один пункт. Свойство
    #: инструмента, а не торговое правило: у фьючерса на индекс МосБиржи
    #: это ровно 1 ₽, у РТС 1,74, у Брента 869 (замер 05.09.2026).
    #:
    #: ⚠️ Умолчание 1,0 верно **для одного контракта из шести** и молча врёт
    #: для остальных: сделки те же, деньги другие. Поэтому программа
    #: спрашивает величину у биржи и подставляет сама, а поле остаётся
    #: подсказанным — владелец счёта вправе перебить (`B-021`).
    #:
    #: ⚠️ Величина **плавающая**: у РТС и Брента считается через курс доллара
    #: и меняется каждый день. Снятая однажды и запомненная навсегда — это
    #: вторая тихая ошибка вместо первой.
    #:
    #: Менять умолчание нельзя: у `MXU6` величина ровно 1,0, и на ней стоит
    #: сверка с прототипом, 127 сделок из 127.
    ruble_per_point: float = 1.0
    #: Откуда взялось число выше — словами, для показа в окне. Пусто значит
    #: **не подтверждено биржей**, и окно об этом говорит красным: молчаливая
    #: единица хуже отказа. Заполняется тем, кто ходил на биржу.
    ruble_per_point_source: str = ""
    #: Дни, про которые владелец счёта решил сам: «не торгуем» (выборы,
    #: отпуск, дурное предчувствие) и «торгуем» (рабочая суббота при переносе).
    #: Пусто — обычное правило: будни торговые, суббота и воскресенье нет.
    #:
    #: ⚠️ Отметки действуют **и на истории**: иначе проверка на истории
    #: перестала бы отвечать на вопрос «что было бы».
    #:
    #: ⚠️ Дни, объявленные нерабочими **биржей**, сюда не попадают никогда.
    #: Это факт про мир, а не настройка: он приходит из расписания брокера,
    #: не сохраняется в файл настроек и не снимается мышкой (решение 0038).
    calendar: tuple[CalendarDay, ...] = ()
    #: Куда писать технический лог. Пусто — умолчание программы (`userdata/logs`).
    #: Это настройка программы, а не торговли: в `EngineSettings` ей места нет
    #: по той же причине, что и глубине показа (`D-021`).
    log_directory: str = ""

    def replace(self, **changes: object) -> Settings:
        """Копия с изменёнными полями. Тонкая обёртка над `dataclasses.replace`."""
        return replace(self, **changes)  # type: ignore[arg-type]


