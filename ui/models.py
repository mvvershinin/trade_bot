    trailing_enabled: bool = False
    trailing_start_pct: float = 0.5
    trailing_offset_pct: float = 0.2
    trailing_step_pct: float = 0.05
    window_start: time = time(10, 5)
    window_end: time = time(11, 0)
    #: Закрывать ли позицию по концу торгового окна. Включено — позиция
