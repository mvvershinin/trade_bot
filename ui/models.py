@dataclass(frozen=True, slots=True)
class Candle:
    """Одна свеча. `opens_at` — время **открытия** интервала, aware.

    Почему открытия, а не закрытия: свеча на бирже подписывается временем
    **начала** своего интервала, и терминал брокера рисует её именно так.
    Пятиминутка 12:55–13:00 стоит на отметке 12:55. Владелец счёта держит
    наше окно и терминал брокера рядом и сверяет их глазами — расхождение
    в одну свечу делает такую сверку невозможной.

    ⚠️ Это **не** то же время, по которому движок принимает решения.
    Граница торгового окна считается по времени **закрытия** свечи
    (ARCHITECTURE.md §6, `engine/bars.py`) — там это копия эталонного
    прототипа, и трогать её нельзя. Разделение жёсткое: движок считает
    по закрытию, ось графика размечена открытиями. Перевод одного
    в другое — обязанность `app/convert.py`, и он единственный на программу.
    Раньше в график уходило закрытие, и весь график вместе с метками сделок
    стоял на бар правее, чем у брокера (B-008).

    ⚠️ Поле называется `opens_at`, а не `time` и не `open_time`, намеренно.
    В слое данных (`market/candles.py`) у свечи поле `time` — это тоже начало
    свечи, и значения совпали бы. Формы двух классов совпадают, соответствие
    в проекте структурное (ARCHITECTURE.md §2), проверок типа нет: под именем
    `time` свеча слоя данных прошла бы сюда молча — вместе с полями
    `timeframe` и `filled_minutes`, о которых окно ничего не знает, и вместе
    с незакрытой свечой, которую движок ещё не принял. Имя `opens_at`
    у свечи слоя данных отсутствует, поэтому неверное соединение слоёв
    даёт `AttributeError` сразу, а не тихо неправильную картинку.
    """

    opens_at: datetime
    open: float
    high: float
    low: float
    close: float
    volume: float = 0.0


@dataclass(frozen=True, slots=True)
class CandleInfo:
    """Свеча и закрытие предыдущей — всё, из чего состоит строка сведений.

    Заведено ради одной надписи над графиком, поэтому полей ровно два: сама
    свеча и число, с которым сравнивается её закрытие. Предыдущая свеча целиком
    здесь не хранится намеренно — в надпись из неё попадает только `close`,
    а лишнее поле рано или поздно выводят на экран.

    `previous_close is None` означает **«сравнивать не с чем»**: свеча первая
    в ряду либо предыдущая не пришла. Это не ноль. Ноль — утверждение «цена
    не изменилась», и такого утверждения у нас в этом случае нет.

    Вычитание ниже — не торговое правило, а то же самое действие, которое
    человек делает глазами по двум числам на экране. Ни объёма, ни стороны,
    ни комиссии в нём нет, и прибылью оно не является: прибыль по сделке
    считает `engine/` и приносит готовой в `TradeRow.profit_rub`.
    """

    candle: Candle
    previous_close: float | None = None

    @classmethod
    def from_pair(cls, candle: Candle, previous: Candle | None = None) -> CandleInfo:
        """Сведения по двум соседним свечам. `previous is None` — сравнивать не с чем."""
        return cls(candle, None if previous is None else previous.close)

    @property
    def change(self) -> float | None:
        """Изменение закрытия против предыдущей свечи, в пунктах цены.

        Пункты, а не рубли: во сколько денег это обошлось, зависит от объёма,
        стороны и комиссии, а их здесь нет и быть не должно.
        """
        if self.previous_close is None:
            return None
        return self.candle.close - self.previous_close

    @property
    def change_pct(self) -> float | None:
        """То же в процентах от предыдущего закрытия.

        `None` ещё и при нулевом предыдущем закрытии: делить не на что.
        Нулевой цены у фьючерса не бывает, но деление на неё уронило бы
        не расчёт, а окно — в момент отрисовки, у владельца счёта.
        """
        if self.previous_close is None or self.previous_close == 0:
            return None
        return (self.candle.close - self.previous_close) / self.previous_close * 100


