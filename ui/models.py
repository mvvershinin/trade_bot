    #: сделок не меняет — она меняет, сколько их видно.
    #:
    #: Девяносто, а не тридцать: владелец счёта 05.09.2026 увидел данные только
    #: с 6 августа и решил, что истории нет. Тридцать дней от 4 сентября —
    #: это ровно 6 августа, данные были на месте (`D-026`).
    #:
    #: ⚠️ Первые свечи показанного отрезка уходят на прогрев средней, и решений
    #: на них нет вовсе. Сколько именно — считает `market.warmup_bars`; окно
    #: об этом говорит подсказкой, а не молчит.
