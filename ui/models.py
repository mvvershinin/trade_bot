@dataclass(frozen=True, slots=True)
class HistoryFacts:
    """Что уже лежит в базе по инструменту — числами, до нажатия кнопки.

    Заведено против слепого «вы уверены?». Вопрос без чисел приучает жать
    «да» не читая, и первый же раз, когда вопрос будет важным, его пролистают.
    Диалог загрузки показывает не страшилку, а опись: сколько дней, с какого
    по какой и сколько из них плотные.

    `dense` и `sparse` — дни, где свечей много, и дни, где сделки были, но их
    единицы. Разделение не косметическое: ровно оно отвечает на вопрос «почему
    я вижу данные только с августа, а контракт с июня» — до августа данные
    есть, но их по десятку минут в день (`market.inventory`).

    ⚠️ Ни одно число здесь окном не считается. Опись приходит готовой из слоя
    данных; окно её показывает.

    `trouble` — базу прочитать не удалось. Пустые числа при этом означают
    «неизвестно», а не «в базе пусто»: это разные утверждения, и диалог
    обязан сказать именно то, которое верно.
    """

    symbol: str = ""
    first: date | None = None
    last: date | None = None
    #: Дни, в которых есть хотя бы одна минутка.
    trading_days: int = 0
    dense_days: int = 0
    sparse_days: int = 0
    minutes: int = 0
    trouble: str = ""

    @property
    def known(self) -> bool:
        """Есть ли в базе хоть что-нибудь по этому инструменту."""
        return not self.trouble and self.minutes > 0


@dataclass(frozen=True, slots=True)
class HistoryLoadRequest:
    """Что владелец счёта просит загрузить с биржи.

    Два способа задать левую границу, и они не равнозначны.

    * `days` — «последние N календарных дней», умолчание и обычный путь.
      Число берётся из настроек (`Settings.history_depth_days`), а не
      придумывается диалогом.
    * `since` — конкретная дата. Задаётся, когда выбрано «загрузить заново
      с даты…», и тогда `days` не используется вовсе.

    `replace` — снять отметки «за этот день у биржи уже спрашивали» и
    запросить отрезок целиком. **Умолчание — `False`**, и это правило,
    а не осторожность: кнопка, по умолчанию перезапрашивающая всё, однажды
    будет нажата случайно.
    """

    symbol: str
    days: int = 90
    since: date | None = None
    replace: bool = False


@dataclass(frozen=True, slots=True)
class HistoryLoadOutcome:
    """Чем кончилась загрузка — готовыми фразами для окна.

    Ни одной оценки окно не выносит само: «хватает ли данных для прогрева
    средней», «опечатка это или выходные» решает слой данных, сюда приходит
    ответ словами (`market.history.HistoryOutcome.problem`).

    `ok` — загрузка дошла до конца и данных хватает. `cancelled` — её сняли
    кнопкой; это не сбой, и говорить о ней надо иначе, чем об отказе биржи.
    """

    symbol: str = ""
    ok: bool = False
    cancelled: bool = False
    #: Одна фраза: что произошло. Показывается заголовком.
    headline: str = ""
    #: Числа: сколько минуток, за какой отрезок, сколько заняло.
    detail: str = ""
    #: Что не так — человеческой фразой. Пусто — всё в порядке.
    trouble: str = ""


