@dataclass(frozen=True, slots=True)
class HaltCause:
    """Одна причина остановки робота: что сказано, какого вида и с каких пор.

    ⚠️ **Список, а не склеенная строка**, и разница здесь денежная. Причин
    бывает несколько, они не отменяют друг друга и снимаются по одной, самой
    ранней. Склеенные в одну строку, они превращаются в один абзац, из
    которого нельзя ни назвать снимаемую, ни пересчитать оставшиеся, — и
    владелец счёта соглашается с убытком, заодно, не читая, снимая требование
    сходить к брокеру (`D-086`, аудит 06.09.2026).

    `reason` — причина человеческим языком, целиком. Окно её не сочиняет,
    не сокращает и не переносит по словам: она приходит готовой.

    `kind` — вид остановки **словами**, а не кодом: «предохранитель робота»
    либо «состояние счёта неизвестно». Требование решения 0014 — видно,
    какая остановка случилась. Пусто — вид не назван, и окно говорит так же.

    `broker_check` — эта причина требует сходить **к брокеру** и посмотреть
    заявки и позицию своими глазами. Признак приходит готовым: решать, надо
    ли идти к брокеру, окно не имеет права.

    `at` — с какого момента причина стоит, по московскому времени.
    `None` — момент неизвестен.

    `restored` — причина поднята **в прошлом сеансе** и восстановлена из базы
    при запуске. Отдельное поле, а не вывод из `at`: «остановка со вчера»
    и «остановка минуту назад в этом же запуске» — разные вещи для того,
    кто только что открыл программу.
    """

    reason: str
    kind: str = ""
    broker_check: bool = False
    at: datetime | None = None
    restored: bool = False


@dataclass(frozen=True, slots=True)
class RobotState:
    """Снимок состояния для панели сверху.

    Ни одно поле окно не вычисляет. `simulation`, `token_read_only`,
    `token_days_left` приходят от `app/` и `engine/`; окно превращает их
    в предупреждения и в блокировку кнопок.

    `halted` — причина остановки движка, пустая строка значит «не остановлен».
    Это **не** то же самое, что `running=False`. «Робот стоит» — обычное
    состояние: его не запускали, или окно торгового дня закрылось. Остановка —
    другое: робот перестал понимать, что происходит на счёте, и ждёт человека
    (`engine/runner.py`, свойство `halted`). Она наступает на несопоставленной
    сделке, на застрявшем выходе, на отказе исполнителя принять заявку и на
    отказе журнала принять строку — и в последнем случае причину не найти
    больше нигде: приёмник журнала и есть то, что отказало. Показать её
    обязано окно, другого места нет.
    """

    instrument: str = "—"
    timeframe: str = "5 минут"
    connection: Connection = Connection.UNKNOWN
    mode: Mode = Mode.OFF
    running: bool = False
    simulation: bool = True
    position: Position | None = None
    day_profit_rub: float | None = None
    day_profit_pct: float | None = None
    day_commission_rub: float | None = None
    day_trades: int | None = None
    token_read_only: bool = False
    token_days_left: int | None = None
    halted: str = ""
    #: Причины остановки поштучно, в порядке появления. Пусто — не остановлен.
    #:
    #: ⚠️ **Пара к `halted`, а не замена ему.** `halted` — тот же набор одной
    #: строкой, и он остаётся тем, что читает красная плашка: она говорит
    #: человеку, что случилось, и заворачивать единственную причину
    #: в перечисление ради редкого случая нельзя. Список нужен другому —
    #: кнопке возобновления: снимается **одна** причина, самая ранняя,
    #: и назвать её отдельно от остальных по склеенной строке невозможно.
    #:
    #: ⚠️ Список может быть пуст при непустом `halted`: остановку показывает
    #: и прогон по истории (`HistoryRun.halted`), а у него причина одна
    #: и поштучного разбора нет. Кнопка возобновления в этом случае молчит —
    #: снимать в порту нечего.
    halt_causes: tuple[HaltCause, ...] = ()
    #: Закреплённый отрезок истории, человеческими словами. Пусто — обычный
    #: показ последних дней.
    #:
    #: ⚠️ Поле заведено ради **предупреждения**, а не ради подписи. Пока
    #: отрезок закреплён, живые свечи на график не приходят вовсе
    #: (`app/port.py::_Span`): график, застывший в июне при живом потоке
    #: котировок, выглядит ровно как потерянная связь, и разбираться в этом
    #: владелец счёта будет с секундомером в руках. Окно поэтому показывает
    #: плашку всё время, пока строка непуста.
    history_span: str = ""
    note: str = ""


