"""Данные для показа: то, что окно рисует, и то, что оно отправляет наружу.

Здесь нет ни одного правила торговли. Ни «войдём ли», ни «где тейк», ни «в окне ли
сейчас время» — всё это решает `engine/`, а сюда приходит готовым. Классы ниже —
описания того, *как выглядит* состояние, а не того, как оно получилось.

Проверка, которую стоит применять к каждой правке этого файла: если поле нельзя
вывести на экран, ему здесь не место.

Почему свои типы, а не типы `market/` и `engine/`
--------------------------------------------------
`ui/` разрешено читать `engine/`, `backtest/` и `market/` (ARCHITECTURE.md §2),
но привязка окна к их структурам означает, что перерисовка графика ждёт готовности
движка, а изменение внутреннего типа свечи ломает окно. Поэтому окно объявляет
свои формы и принимает всё, что структурно им соответствует: `app/` при сведении
программы перекладывает данные движка в эти классы.

Время
-----
Все `datetime` — с часовым поясом (aware). Хранится момент времени, показывается
он всегда в МСК: машина владельца счёта может стоять в другом поясе, а торговое
время в этом проекте только московское. Перевод — `ui.formatting.to_msk`.
"""

