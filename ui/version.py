"""Версия программы — видна в окне и пишется в журнал при каждом старте.

Без версии в окне разбор жалобы начинается с вопроса «а какая у вас сборка»,
на который у владельца счёта нет ответа: программа портативная, установщика нет,
папку он мог скопировать откуда угодно.
"""

from __future__ import annotations

from importlib import metadata

FALLBACK = "0.0.0-из-исходников"


def version() -> str:
    """Версия дистрибутива или явная пометка «запущено из исходников»."""
    try:
        return metadata.version("terminal")
    except metadata.PackageNotFoundError:
        # Собранный бинарь метаданных дистрибутива не несёт. Это не ошибка —
        # но и молчать нельзя: версия обязана быть видна.
        return FALLBACK
