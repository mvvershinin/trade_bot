"""Граница окна с остальной программой. Всё, что окно знает о роботе, — здесь.

Окно ничего не решает. Оно принимает события (сигналы Qt) и отправляет команды
(методы). Между ним и движком стоит `TerminalPort`: `app/` наследует его при
сведении программы и связывает с `engine/`.

Почему наследование, а не `Protocol`
------------------------------------
Сигналы Qt объявляются только в наследнике `QObject`. Протокол дал бы структурную
совместимость без импорта, но лишил бы окно единственного безопасного способа
получать события из другого потока — очередь Qt. Направление зависимостей при этом
не нарушено: порт объявлен в `ui/`, а наследует его `app/`, которому разрешено всё
(ARCHITECTURE.md §2).

Про потоки
----------
Порт живёт в потоке интерфейса. Движок и сеть — нет. Событие из другого потока
доставляется `QMetaObject.invokeMethod` или `signal.emit` через соединение типа
`QueuedConnection`; прямой вызов методов окна из потока брокера — гонка, которая
проявляется случайной перерисовкой и падением на пустом месте.

Что запрещено здесь появиться
-----------------------------
Реализация. Ни HTTP, ни WebSocket, ни расчёта: `TerminalPort` — объявление границы.
Первый же `httpx` в этом файле означает, что сеть уехала в поток интерфейса
и окно замрёт на обрыве связи (ARCHITECTURE.md §5).
"""

from __future__ import annotations

from collections.abc import Callable

from PySide6.QtCore import QObject, Signal

from ui.models import (
    BacktestRequest,
    ChartData,
    HistoryLoadRequest,
    Mode,
    Settings,
)

#: Чистка секретов: текст на входе, текст без токена на выходе.
#:
#: Объявлена здесь, потому что это часть границы, а не часть окна. Реализацию
#: слой окна не пишет и не импортирует: единственная полная чистка —
#: `broker.redaction.scrub`, у неё есть реестр живых значений токена,
#: а `broker/` окну по ARCHITECTURE.md §2 не положен (`ui/` → `engine/`,
#: `backtest/`, `market/`). Поэтому функция приходит **параметром**
#: с границы `app/` — тем же вызовом, каким `app/main.py` отдаёт её слою данных.
#:
#: Тот же вид, что у `sanitize` в `CandleStore` и `MarketWorker`: чистка обязана
#: быть **одна** на запись в базу, на отправку в окно и на выгрузку в файл.
#: Две разных разошлись бы, и разошлись бы молча.
Sanitize = Callable[[str], str]


class TerminalPort(QObject):
    """Единственная дверь окна наружу.

    События — сигналы, команды — методы. Базовая реализация команд ничего не делает
    и сообщает об этом: окно, открытое без движка (тесты, снимок экрана, разбор
    журнала), обязано открываться, а не падать.
    """

    # --- события: снаружи внутрь -------------------------------------------
    # Все несут готовые объекты из `ui.models`. Разбор «что это значит» произошёл
    # до отправки; окно только показывает.

    state_changed = Signal(object)        # RobotState
    chart_replaced = Signal(object)       # ChartData — полный снимок
    candle_appended = Signal(object)      # Candle — новая закрытая свеча
    candle_updated = Signal(object)       # Candle — уточнение последней свечи
    average_changed = Signal(object)      # tuple[LinePoint, ...]
    markers_changed = Signal(object, object)   # Layer, tuple[Marker, ...]
    paths_changed = Signal(object, object)     # Layer, tuple[TradePath, ...]
    levels_changed = Signal(object)       # tuple[PriceLevel, ...]
    shades_changed = Signal(object)       # tuple[Shade, ...]
    trades_replaced = Signal(object, object)   # tuple[TradeRow, ...], TradesSummary | None
    trade_appended = Signal(object)       # TradeRow
    decisions_replaced = Signal(object)   # tuple[DecisionRow, ...]
    decision_appended = Signal(object)    # DecisionRow
    settings_applied = Signal(object)     # Settings — эхо движка, а не наше
    strategy_rule_changed = Signal(str)   # правило робота словами, с числами
    busy_changed = Signal(bool, str)      # идёт длинная операция, что именно
    progress_changed = Signal(int, str)   # 0…100, подпись
    failed = Signal(str)                  # человеческая фраза, не код ошибки
    stuck_changed = Signal(str)           # работа не отвечает; «» — снять сообщение
    backtest_options_ready = Signal(object)  # BacktestOptions — из чего выбирать
    backtest_finished = Signal(object)    # BacktestReport — что вышло из прогона
    history_facts_ready = Signal(object)  # HistoryFacts — что уже есть в базе
    history_progress = Signal(int, str)   # 0…100, подпись — ход загрузки истории
    history_finished = Signal(object)     # HistoryLoadOutcome — чем кончилась

    # ⚠️ `stuck_changed` — не отказ и не ошибка, поэтому сигнал свой, а не
    # `failed`. Отказ отвечает на нажатие и живёт в строке состояния секунды;
    # это — состояние, которое **длится**, и висеть оно обязано, пока длится
    # (`B-025`: владелец счёта полчаса смотрел на окно, которое молчало,
    # потому что порт был занят навсегда застрявшей задачей). Пустая строка
    # означает «работа отозвалась или кончилась» — сообщение снять.

    # ⚠️ Ход загрузки истории идёт **своими** сигналами, а не общими
    # `busy_changed` и `progress_changed`. Причина не в чистоте: общие сигналы
    # испускает и обычная перерисовка графика, которая во время долгой загрузки
    # случается от каждой живой свечи. Её «работа кончилась» закрыло бы полоску
    # идущей загрузки, и владелец счёта увидел бы, что окно само отменило то,
    # что он запустил минуту назад.

    # --- команды: изнутри наружу -------------------------------------------

    def start(self) -> None:
        """Запустить робота. Что при этом произойдёт — дело движка."""
        self._not_connected("Запуск")

    def stop(self) -> None:
        """Остановить робота. Позицию это само по себе не закрывает."""
        self._not_connected("Остановка")

    def resume(self) -> None:
        """Снять **одну** причину остановки — самую раннюю. Жмёт человек.

        ⚠️ Одну, а не все. Причин остановки бывает несколько, и они про разные
        беды: дневной лимит убытка — про деньги, «исход команды брокеру
        неизвестен» — про позицию, которой программа не знает. Кнопка,
        снимающая всё разом, позволила бы согласиться с убытком и **заодно**,
        не читая, снять требование сходить к брокеру (`D-086`, аудит `/risk`
        06.09.2026).

        Какая именно причина снимется и что останется — решает не окно.
        Окно **называет** это человеку до нажатия и отправляет команду;
        порядок снятия задан портом (`app/port.py::HistoryPort.resume`).

        Это единственный способ снять остановку. Ни перезапуск программы,
        ни смена настройки, ни переподключение её не снимают (решения
        [0014](../.docs/decisions/0014-daily-loss-limit-and-margin-shortfall.md)
        и [0045](../.docs/decisions/0045-a-halt-outlives-the-live-run.md)).
        """
        self._not_connected("Возобновление работы робота")

    def set_mode(self, mode: Mode) -> None:
        """Сменить режим. Последствия для открытой позиции считает движок."""
        self._not_connected(f"Смена режима на «{mode.label}»")

    def stream(self, on: bool) -> None:
        """Подключиться к потоку котировок брокера или отключиться.

        ⚠️ Это **не** запуск робота, и путать их нельзя. Подписка на котировки
        и торговля — разные права и разные последствия: смотреть на живой рынок
        можно и на токене, выданном только для чтения, а подать заявку по нему
        брокер не даст. Поэтому в окне это отдельная кнопка, а не часть «Старта».

        Что происходит при подключении, решает не окно: оно просит связь,
        а чем её дать — забота сборки программы (`app/main.py`).
        """
        self._not_connected("Подключение к брокеру" if on else "Отключение от брокера")

    def apply_settings(self, settings: Settings) -> None:
        """Отдать новые настройки.

        Окно не решает, с какого момента они действуют, и не пишет строку в журнал
        решений: и то и другое — работа движка (SPEC §4.4 А). Окно узнает результат
        из `settings_applied` и из очередной строки журнала.
        """
        self._not_connected("Применение настроек")

    def request_settings(self) -> None:
        """Попросить текущие настройки.

        Ответ приходит **двумя** сигналами: `settings_applied` — значения
        полей, `strategy_rule_changed` — правило робота словами, с этими же
        числами. Второй нужен потому, что правило считает торговый модуль,
        а окно торговых слоёв не импортирует (ARCHITECTURE.md §2): текст
        принадлежит тому, кто его посчитал, окно его только показывает.
        """
        self._not_connected("Чтение настроек")

    def request_chart(self, instrument: str, timeframe: str) -> None:
        """Попросить историю для графика. Ответ — `chart_replaced`."""
        self._not_connected("Загрузка графика")

    def request_journals(self) -> None:
        """Попросить журналы за текущий период. Ответ — `*_replaced`."""
        self._not_connected("Чтение журналов")

    def close_position(self) -> None:
        """Закрыть позицию вручную. Заявку подаёт движок, не окно."""
        self._not_connected("Закрытие позиции")

    def request_backtest_options(self) -> None:
        """Попросить, из чего выбирать в диалоге прогона.

        Ответ придёт сигналом `backtest_options_ready`, а не возвратом: список
        инструментов и границы их истории лежат в базе, а чтение базы — работа
        потока данных. Синхронный ответ здесь означал бы чтение диска в слоте
        Qt, то есть замершее окно на файле в тридцать мегабайт.
        """
        self._not_connected("Чтение списка инструментов")

    def run_backtest(self, request: BacktestRequest) -> None:
        """Прогнать робота по истории на выбранном отрезке.

        ⚠️ Прогон **применяет** настройки из просьбы обычным путём, как
        «Применить» в окне настроек, и меняет то, что показано на графике.
        Иначе на экране оказались бы сделки одних настроек рядом с полями
        других — кадр, против которого написан докстринг `app/port._Frame`.

        Отчёт придёт сигналом `backtest_finished`. Отказ — сигналом `failed`
        и строкой в журнале решений; отчёта в этом случае не будет вовсе.

        :param request: что и на каком отрезке прогнать.
        """
        self._not_connected("Прогон на истории")

    def cancel_backtest(self) -> None:
        """Снять идущий прогон. Что уже нарисовано, остаётся на экране."""
        self._not_connected("Отмена прогона")

    def request_history_facts(self, symbol: str) -> None:
        """Попросить опись того, что по инструменту уже лежит в базе.

        Ответ придёт сигналом `history_facts_ready`, а не возвратом: опись
        считается по всем минуткам инструмента, а это чтение базы. Синхронный
        ответ означал бы окно, замершее на открытии меню, и тем дольше, чем
        больше накоплено истории.
        """
        self._not_connected(f"Чтение описи базы по «{symbol}»")

    def load_history(self, request: HistoryLoadRequest) -> None:
        """Скачать историю с биржи и положить в базу.

        Единственный путь к свечам для того, у кого нет консоли, — а это
        и есть владелец счёта: на его машине нет питона, программа приходит
        одним файлом. До появления этой команды свежепоставленная программа
        показывала пустой график и совет набрать команду, которой у него нет.

        Ход работы идёт сигналом `history_progress`, конец — `history_finished`,
        и **конец приходит всегда**: и на успехе, и на отказе, и на отмене.
        Иначе полоска хода осталась бы на экране навсегда.

        Токена брокера загрузка не требует: свечи берутся у биржи, а не у него.
        """
        self._not_connected(f"Загрузка истории «{request.symbol}»")

    def cancel_history_load(self) -> None:
        """Остановить идущую загрузку. Скачанное к этому моменту остаётся в базе."""
        self._not_connected("Отмена загрузки истории")

    def show_recent(self) -> None:
        """Вернуться к обычному показу последних дней вместо закреплённого отрезка.

        Пара к `run_backtest`. Без неё выбранный однажды отрезок снять было бы
        нечем, и график остался бы в прошлом навсегда — при живом потоке это
        читается как «программа перестала получать данные».
        """
        self._not_connected("Возврат к текущим данным")

    # --- вспомогательное ----------------------------------------------------

    def _not_connected(self, action: str) -> None:
        self.failed.emit(
            f"{action}: движок не подключён. Окно открыто без торговой части — "
            "команда не выполнена."
        )


class DetachedPort(TerminalPort):
    """Порт, ни к чему не подключённый.

    Нужен ровно для трёх случаев: тесты интерфейса, снимок экрана и разбор
    сохранённых журналов без запуска торговой части. Команды молча игнорируются,
    но каждая отражается в `failed` — чтобы «ничего не произошло» было видно.
    """

    def request_chart(self, instrument: str, timeframe: str) -> None:
        self.chart_replaced.emit(ChartData(instrument=instrument, timeframe=timeframe))
