"""Разделение истории на подбор и проверку. Ни один день не попадает в обе части.

Зачем этот модуль
-----------------
Умолчания проекта — тейк 0,5 %, окно 10:05–11:00 — подобраны перебором на том
же отрезке, на котором проверялись (DOMAIN.md §4). Независимой проверки не было
ни одной. Любая таблица результатов, показывающая одно число за один период,
повторяет ту же ошибку и не может её обнаружить.

Замер 05.09.2026 назвал цену вопроса в рублях: порог фильтра пилы 0,20 % был
**лучшим на подборе** (+7 048 ₽) и дал на проверке **−3 497 ₽**. Одно число
за один период соврало бы на десять тысяч.

Поэтому разделение живёт отдельным модулем, а не строчкой внутри перебора:
у него свои сторожа, свои тесты и своё правило, которое нельзя обойти
параметром. `Fold` **невозможно построить** так, чтобы подбор залезал
на проверку: конструктор отвергает такое сочетание.

Что здесь есть
--------------
* `Period` — отрезок дней, обе границы включительно;
* `Fold` — пара «подбор → проверка», где проверка строго позже подбора;
* `trading_days` — какие дни считаются торговыми и почему именно эти;
* `walk_forward` — скользящее окно вперёд: подбираем на первых днях, гоняем
  следующие, ничего не переподбирая (слова владельца счёта 05.09.2026);
* `single_split` — одно деление пополам, тот же рубеж, что у первого окна.

⚠️ **Разделение не зависит ни от одной перебираемой настройки.** Оно считается
один раз из календаря данных и одинаково для всех сочетаний. Иначе разные
строки таблицы считались бы на разных отрезках, и колонка «проверка»
складывала бы несравнимое.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from datetime import date, time

__all__ = [
    "CHECKING_DAYS",
    "DENSE_ENOUGH",
    "SATURDAY",
    "SWEEP_SPAN",
    "TUNING_DAYS",
    "Fold",
    "Period",
    "single_split",
    "trading_days",
    "walk_forward",
]

#: Часы, которые обязана покрывать история дня, чтобы день считался торговым.
#: Границы взяты **из программы перебора**, а не на глаз: начало торгового окна
#: перебирается до 11:00, длительность — до четырёх часов (ТЗ §8), то есть
#: самое позднее окно кончается в 15:00, а самое раннее начинается в 09:30.
#: День, у которого этих часов нет, дал бы одним сочетаниям сделки, а другим
#: пустоту — и строки таблицы считались бы на разной истории.
SWEEP_SPAN = (time(9, 30), time(15, 0))

#: Сколько пятиминуток из 66 возможных внутри `SWEEP_SPAN` обязано найтись.
#: Замер 05.09.2026 по MXU6: у 71 буднего дня их 60 и больше, у следующих
#: по величине — 59 и меньше, причём между 59 и 60 в данных пусто. Порог
#: попал в разрыв распределения, а не выбран круглым числом.
DENSE_ENOUGH = 60

#: Первый день недели, который биржа не считает рабочим. `datetime.weekday()`
#: нумерует с понедельника, поэтому суббота — это 5. Названо числом с именем:
#: голая пятёрка рядом с днями недели читается как «пять дней».
SATURDAY = 5

#: Длина подбора и длина проверки одного окна, в торговых днях.
#: Обоснование чисел — в докстринге `walk_forward`.
TUNING_DAYS = 36
CHECKING_DAYS = 5


@dataclass(frozen=True, slots=True)
class Period:
    """Отрезок дней, **обе границы включительно**.

    Границы включительные, а не полуоткрытые, ровно потому, что этот отрезок
    читает человек: «проверка 20.07–04.09» и «проверка 20.07–05.09, последний
    день не считается» — разные тексты, и второй в отчёте не напишешь.
    Стыковка отрезков без пересечения обеспечивается не формой границы,
    а `Fold` и `walk_forward`, у которых это проверяется явно.
    """

    since: date
    until: date

    def __post_init__(self) -> None:
        if self.until < self.since:
            raise ValueError(
                f"отрезок кончается раньше, чем начинается: {self.since} … {self.until}"
            )

    def contains(self, day: date) -> bool:
        """День внутри отрезка."""
        return self.since <= day <= self.until

    def holds(self, entry: date, exit_day: date) -> bool:
        """Сделка целиком внутри отрезка: и вход, и выход.

        ⚠️ Сделка, вошедшая внутри отрезка и вышедшая за его пределами,
        отрезку **не принадлежит**. Это не педантизм: отнести её к подбору
        значило бы посчитать в подборе деньги, полученные уже на проверочных
        днях, то есть заглянуть вперёд ровно в той колонке, которая заведена
        против заглядывания вперёд. Такие сделки не идут никуда и считаются
        отдельной строкой отчёта.
        """
        return self.contains(entry) and self.contains(exit_day)

    def overlaps(self, other: "Period") -> bool:
        """Отрезки имеют хотя бы один общий день."""
        return self.since <= other.until and other.since <= self.until

    def __str__(self) -> str:
        return f"{self.since:%d.%m.%Y}–{self.until:%d.%m.%Y}"


@dataclass(frozen=True, slots=True)
class Fold:
    """Одно окно: на чём подбирали и на чём проверяли.

    ⚠️ **Конструктор отвергает пересечение.** Это главное, что делает модуль:
    протечка настроек из подбора в проверку выражается ровно одним способом —
    общим днём у двух отрезков, — и построить такой объект нельзя. Проверка
    стоит здесь, а не в вызывающем коде, потому что вызывающих будет много,
    а забыть проверку достаточно в одном.
    """

    number: int
    tuning: Period
    checking: Period

    def __post_init__(self) -> None:
        if self.tuning.until >= self.checking.since:
            raise ValueError(
                f"окно {self.number}: подбор {self.tuning} заходит на проверку "
                f"{self.checking}. Настройки, выбранные на дне, который потом "
                "объявлен проверочным, проверены не были: колонка «проверка» "
                "показала бы тот же подбор под другим заголовком"
            )

    def __str__(self) -> str:
        return f"окно {self.number}: подбор {self.tuning} → проверка {self.checking}"


def trading_days(bar_days: Sequence[tuple[date, int]]) -> tuple[date, ...]:
    """Дни, на которых считается перебор: будние и с полной историей часов перебора.

    :param bar_days: пары «день → сколько пятиминуток нашлось внутри
        `SWEEP_SPAN`». Считает их вызывающий, потому что здесь нет ни свечей,
        ни таймфрейма: модуль знает про календарь, а не про рынок.

    Отбрасываются два вида дней, и оба — по названной причине, а не «для
    чистоты»:

    * **выходные.** Умолчание движка — не торговать в выходные
      (`EngineSettings.trade_in_weekend`), а данные по MXU6 выходные содержат:
      биржа их отдаёт. День, в который робот не торгует, не должен занимать
      место в окне подбора;
    * **день с неполной историей** (меньше `DENSE_ENOUGH` пятиминуток внутри
      `SWEEP_SPAN`). Такой день даёт сделки одним границам окна и пустоту
      другим, и строки таблицы окажутся посчитанными на разной истории.

    Возвращает дни по возрастанию. Дыры в середине ряда не заполняются
    и не сшиваются: они видны как расстояние между соседними днями,
    и вызывающий вправе на них посмотреть.
    """
    return tuple(sorted(
        day for day, bars in bar_days
        if day.weekday() < SATURDAY and bars >= DENSE_ENOUGH
    ))


def walk_forward(
    days: Sequence[date],
    *,
    tuning: int = TUNING_DAYS,
    checking: int = CHECKING_DAYS,
) -> tuple[Fold, ...]:
    """Скользящее окно вперёд: подобрали на прошлом, прогнали будущее, не переподбирая.

    Схему назвал владелец счёта 05.09.2026 своими словами: «подбираем на первых
    днях, потом прогоняем следующие, ничего не переподбирая». Окно подбора
    едет вперёд шагом ровно в длину проверки, поэтому **проверочные отрезки
    не пересекаются ни одним днём** и их деньги можно складывать. Отрезки
    подбора пересекаются — это природа скользящего окна, и складывать их
    нельзя; таблица этого и не делает.

    Откуда числа умолчаний (замер по MXU6, 05.09.2026, 71 торговый день):

    * **проверка 5 дней** — торговая неделя. При таком шаге каждый проверочный
      отрезок содержит понедельник, вторник, среду, четверг и пятницу ровно
      по разу, и наблюдение заказчика про понедельник–вторник не превращается
      в артефакт нарезки. Проверено на данных: все семь отрезков вышли Пн–Пт;
    * **подбор 36 дней** — остаток. 36 + 7 × 5 = 71, то есть используется
      каждый торговый день и ни один не используется дважды в проверке.
      Деление вышло 36 против 35: половины настолько равны, насколько
      позволяет нечётное число дней, и ни одна половина не привилегирована;
    * **семь окон** — сколько помещается.

    ⚠️ Цену этих чисел надо называть вслух: 5 проверочных дней — это около
    восьми сделок на умолчаниях. Отдельное окно не доказывает **ничего**;
    читается только сумма семи, то есть 35 дней и порядка 66 сделок.

    :raises ValueError: длины неположительны либо дней меньше, чем нужно
        хотя бы на одно окно.
    """
    if tuning <= 0 or checking <= 0:
        raise ValueError(
            f"длины окна должны быть положительными: подбор {tuning}, проверка {checking}"
        )
    if len(days) < tuning + checking:
        raise ValueError(
            f"торговых дней {len(days)}, а на одно окно нужно {tuning + checking} "
            f"(подбор {tuning} + проверка {checking}). Делить нечего: "
            "проверка на таком объёме была бы названием, а не проверкой"
        )
    order = sorted(days)
    count = (len(order) - tuning) // checking
    return tuple(
        Fold(
            number=number + 1,
            tuning=Period(order[number * checking], order[number * checking + tuning - 1]),
            checking=Period(
                order[number * checking + tuning],
                order[number * checking + tuning + checking - 1],
            ),
        )
        for number in range(count)
    )


def single_split(
    days: Sequence[date], *, tuning: int = TUNING_DAYS
) -> Fold:
    """Одно деление на две части: подбор — первые `tuning` дней, проверка — весь остаток.

    Рубеж здесь **тот же самый**, что у первого окна `walk_forward` с теми же
    умолчаниями, и это не совпадение, а условие: во всём отчёте одна граница
    между «подбирали» и «проверяли». Две разные границы в одном отчёте дали бы
    две разные правды, и выбрать между ними было бы нечем.

    Зачем нужны обе схемы. Скользящее окно отвечает на вопрос «сколько дал бы
    робот, если его настройки пересматривать каждую неделю»; одно деление —
    на вопрос «сколько дал бы робот, настроенный один раз и оставленный
    в покое». Это разные роботы, и владелец счёта выбирает между ними.

    :raises ValueError: дней не хватает даже на один проверочный день.
    """
    if tuning <= 0:
        raise ValueError(f"длина подбора должна быть положительной: {tuning}")
    if len(days) <= tuning:
        raise ValueError(
            f"торговых дней {len(days)}, на подбор просят {tuning} — "
            "на проверку не остаётся ни одного дня"
        )
    order = sorted(days)
    return Fold(
        number=0,
        tuning=Period(order[0], order[tuning - 1]),
        checking=Period(order[tuning], order[-1]),
    )
