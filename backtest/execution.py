"""Модель исполнения для прогона по истории: цена сделки, издержки, сторож уровня.

Это **реализация порта «исполнитель заявок»** (`engine/ports.py`) — одна из двух,
и единственная, которую можно прогнать по записанным свечам. Движок про этот
модуль не знает и знать не может: у порта нет ни признака «это прогон», ни
метода, которого не было бы у боевой реализации (ARCHITECTURE.md §1).

Почему сторож уровня живёт именно здесь
---------------------------------------
До Э1-9 правила исполнения были написаны **дважды**: в `backtest/history.py`
и в тестовой оснастке движка `tests/engine_helpers.py`. Два куска кода,
сторожащих один уровень, — ровно та болезнь, о которой предупреждает
[решение 0008](../.docs/decisions/0008-take-profit-port-contract.md):
первая же правка процента, округления или порядка кругов разводит их молча,
и сверка с прототипом продолжает сходиться на той копии, которую она зовёт.
Здесь они схлопнуты в один класс; оснастка движка его наследует и своих правил
не имеет ни одного.

Правила исполнения — прототипа, а не наши
------------------------------------------
1. **Рыночная заявка, поданная на закрытии свечи, исполняется по `open`
   следующей свечи**; временем сделки записывается **начало** свечи исполнения
   (PROTOTYPE.md §2).
2. **Сторожимый уровень проверяется внутри бара** — по `high` для лонга и `low`
   для шорта, достижение считается по касанию. Это **единственное событие
   прототипа, происходящее не на закрытии свечи** (PROTOTYPE.md §5); без него
   сделки разойдутся по причине, не связанной с торговой логикой.
3. **Заявка не участвует в свече, интервал которой начался раньше момента
   её подачи.** Один интервал показывается исполнителю несколько раз — круг
   обмена внутри свечи, повтор после переподключения, незакрытый бар на каждом
   тике потока, — и без этой проверки повтор исполнил бы заявку по открытию
   той самой свечи, на закрытии которой она подана. Родственная гипотеза
   «вход по цене сигнальной свечи» даёт 73 расхождения из 127.
4. **Внутри круга сначала отдаются исполнения по открытию, и только следующим
   кругом — внутрибарные события.** Иначе уровень, вооружённый сделкой
   открытия, проверялся бы раньше, чем движок успел его назвать, и три сделки
   из 127, открывшиеся и закрывшиеся внутри одной свечи, не воспроизвелись бы.
   ⚠️ Это **не местное решение**: правило записано в контракте порта
   (`engine/ports.py`, `OrderExecutor.fills_at`) как единственное исключение
   из «за один вызов отдаётся всё накопленное», и относится оно к обеим
   реализациям. Читать его только здесь нельзя — боевой адаптер пишут
   по тексту порта.

Уровень **движущийся**, а не только неподвижный
------------------------------------------------
Скользящий тейк перенесён в первый этап
([решение 0009](../.docs/decisions/0009-trailing-take-in-stage-one.md)),
и сторож обязан уметь едущий уровень. Механика этого умения — не отдельная
ветка, а следствие двух правил, уже записанных выше:

* имя заявки вооружения **устойчиво между свечами** (`engine.take_order_id`),
  поэтому повторное вооружение с новым уровнем **заменяет** прежний, а не
  добавляет вторую заявку. Сторож всегда сторожит последний названный уровень;
* новый уровень назван на закрытии свечи *i*, значит сторожится он с свечи
  *i+1*: правило 3 отсекает свечу, в которой он ещё не был известен. Уровень,
  вооружённый **сделкой** открытия, помечен временем сделки — то есть началом
  свечи, — и потому сторожится уже на ней самой.

Ни одной проверки «скользящий это или нет» здесь нет и быть не должно: модель
исполнения знает про уровень ровно то, что ей назвал движок.

Издержки: комиссия и проскальзывание
-------------------------------------
Комиссия **всегда отдельной величиной** и никогда не подставляется нулём.
Неизвестный тариф — это `None`, а не ноль: подставленный ноль объявил бы любую
сделку окупившей комиссию, а реверсная система на пятиминутках делает много
переворотов (DOMAIN.md §5).

Проскальзывание по умолчанию **ноль**, и это не «пока не сделали»: ровно так
считал прототип, и на любом другом значении сверка с ним не сойдётся
по построению. Значение больше нуля — это уже не воспроизведение прототипа,
а оценка того, во что исполнение обойдётся на настоящем счёте.

⚠️ **Этого абзаца владелец счёта не прочитает.** Ноль здесь означает, что
показанная прибыль систематически лучше той, что была бы на счёте: замер
05.09.2026 на боевых умолчаниях — один шаг цены забирает 5 514 ₽ из 9 908 ₽,
два шага сводят итог в ноль. Чтобы это доехало до человека вместе с числом,
а не осталось докстрингом, оговорка считается из самого прогона
(`backtest/assumptions.py`, `HistoryRun.headline`) и показывается рядом
с деньгами. Разбор и таблица замера — [решение 0030][0030].

.. [0030] ../.docs/decisions/0030-run-assumptions-travel-with-the-number.md
"""

