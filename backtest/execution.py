#: Тариф брокера БКС на срочном рынке: 1 ₽ за один фьючерсный контракт
#: (ТЗ §4.4 Е, правка заказчика и п. 10). Вторая половина комиссии — биржевой
#: сбор за регистрацию сделки, и он **не константа**: биржа считает его
#: от стоимости контракта и пересматривает, поэтому берётся из карточки
#: инструмента, а не отсюда.
BROKER_FEE_PER_CONTRACT = 1.0


def selling(action: OrderAction, side: Side) -> bool:
    """Эта операция — продажа?

    Сторона заявки — это сторона **позиции**, а не направление сделки: заявка
    на выход из лонга несёт `LONG`, но исполняется продажей. Перевод одного
    в другое нужен в двух местах сразу — при расчёте проскальзывания и при
    сведении расчёта с фактом (`backtest.pairs`), — и написан поэтому один раз:
    две копии этой таблицы разошлись бы знаком, а знак здесь означает «в пользу
    позиции» или «против неё».

    ======================  ==========
    Операция                Что делаем
    ======================  ==========
    вход в лонг             покупаем
    вход в шорт             продаём
    выход из лонга          продаём
    выход из шорта          покупаем
    ======================  ==========
    """
    if action is OrderAction.OPEN:
        return side is Side.SHORT
    return side is Side.LONG


def commissions_disagree(one: float | None, other: float | None) -> bool:
    """Обе цифры комиссии названы и **не совпадают**?

    Один вопрос, который задаётся в проекте трижды: разбивка против общей
    цифры внутри `Costs`, издержки против отдельного параметра
    в `backtest.HistoryExecutor`, цифра движка против цифры отчёта в `replay`.
    Три написанных руками сравнения разошлись бы на округлении, а расхождение
    здесь означает **две разные комиссии в одном отчёте**: 254 ₽ вместо
    3 556 ₽ на эталонных 127 сделках — при непустой колонке, то есть
    неотличимо от правды.

    ⚠️ `None` — это «не названа», а не ноль, и разногласием само по себе
    не считается: незаполненную половину можно дозаполнить, а вот заменить
    названную цифру другой молча нельзя никогда. Прогон целиком судит строже
    (`backtest.history._one_commission`): там `None` у движка против числа
    у отчёта — уже расхождение, потому что движок по своей цифре решает,
    окупает ли цель комиссию обеих сторон, и «не названа» у него значит
    «не проверено».
    """
    return one is not None and other is not None and not math.isclose(one, other)


@dataclass(frozen=True, slots=True)
class Tariff:
    """Комиссия одной стороны за один контракт, разложенная по ТЗ §4.4 Е.

    Две составляющие, и обе названы отдельно, потому что берутся из разных
    источников и меняются независимо:

    * `exchange_fee` — **биржевой сбор за регистрацию сделки**. Берётся
      из карточки инструмента на сайте МосБиржи. На срочном рынке он
      не фиксирован: биржа считает его от стоимости контракта и пересматривает,
      поэтому подставлять сюда «известное число» из памяти нельзя;
    * `broker_fee` — тариф брокера, 1 ₽ за фьючерсный контракт.

    Процентная часть тарифа (ТЗ §4.4 Е, «комиссия брокера, % от оборота»)
    и минимум за поручение здесь **не выражены**: на фьючерсах они нулевые,
    а минимум за поручение в ТЗ помечен «к обсуждению». Молчаливого нуля
    вместо них тут нет — их нет вовсе, и это видно по подписи.

    ⚠️ **Ноль запрещён обеим составляющим.** Карточку инструмента МосБиржи
    сегодня не читает никто, и поле `exchange_fee` осталось бы нулём само
    собой. `Tariff(exchange_fee=0.0)` даёт 1 ₽ за контракт: на эталонных
    127 сделках отчёт показал бы комиссию 254 ₽ вместо 3 556 ₽ и «чистую
    прибыль» 6 225 ₽ вместо 2 923 ₽ — завышение на 3 302 ₽ **при непустой
    колонке комиссии**, то есть неотличимое от правды. `Tariff(0.0, 0.0)`
    дал бы комиссию 0 ₽ и чистую, равную валовой. Это путь, на котором
    сливаются «тариф не задан» и «комиссия нулевая»: `Costs` их различает,
    и `Tariff` внутри себя обязан различать тоже. **«Тарифа нет» выражается
    отсутствием `Costs`, а не нулём внутри него** (DOMAIN.md §5).

    ⚠️ Сумма `per_contract` — то же самое число, которым сегодня задаётся
    комиссия в настройках движка (`EngineSettings.commission_per_side`).
    Опорная цифра замеров — 14 ₽ за контракт на сторону (PROTOTYPE.md §6).
    """

    exchange_fee: float
    broker_fee: float = BROKER_FEE_PER_CONTRACT

    def __post_init__(self) -> None:
        _check_money(self.exchange_fee, "биржевой сбор за контракт", allow_zero=False)
        _check_money(self.broker_fee, "комиссия брокера за контракт", allow_zero=False)

    @property
    def per_contract(self) -> float:
        """Комиссия одной стороны за один контракт — сумма обеих составляющих."""
        return self.exchange_fee + self.broker_fee


@dataclass(frozen=True, slots=True)
class Costs:
    """Издержки исполнения: комиссия и проскальзывание.

    Комиссия задаётся **одним из двух способов**, и оба означают одно число:

    * `tariff` — разбивка по ТЗ §4.4 Е: биржевой сбор плюс тариф брокера.
      Так задаёт программа, когда справочник инструмента доступен;
    * `commission_per_side` — «столько-то рублей за контракт на сторону»,
      одним числом. Так задан тариф в настройках движка сегодня, и так же
      считались все замеры прототипа.

    Оба сразу задавать можно, но только если они сходятся: расхождение —
    это не «какое-нибудь из двух», это две разные цифры комиссии в одном
    отчёте, и выбор любой из них молча был бы неправдой.

    Не задан ни один — комиссия **неизвестна**. Это `None`, а не ноль
    (DOMAIN.md §5).

    ⚠️ **Явный ноль здесь разрешён, а внутри `Tariff` — запрещён. Это
    не недосмотр**, вопрос задан ревью 03.09.2026 и разобран. Разница в том,
    что именно зануляется:

    * `Tariff.exchange_fee` — **слагаемое**. Карточку инструмента МосБиржи
      сегодня не читает никто, поле осталось бы нулём само собой, а сумма
      вышла бы ненулевой: 1 ₽ за контракт, то есть 254 ₽ комиссии
      на эталонных 127 сделках вместо 3 556 ₽. Ноль внутри суммы **прячется**
      и выходит наружу правдоподобным числом;
    * `commission_per_side` — комиссия **целиком**, и умолчания у неё нет:
      не названа — это `None`. Ноль сюда попадает только от того, кто его
      написал, и в отчёте он виден насквозь: колонка «комиссия 0 ₽» и чистая
      прибыль, равная валовой. Спрятаться ему негде.

    Запрет вдобавок был бы не строже, а противоречивее.
    `EngineSettings.commission_per_side` явный ноль разрешает намеренно
    (разбор — у поля в `engine/settings.py`), а `replay` требует, чтобы цифра
    движка и цифра отчёта совпадали. Запретить ноль здесь значило бы: настройки,
    которые движок считает законными, нельзя прогнать по истории. Ни одной
    подстановки нуля вместо неизвестной величины это не закрыло бы — их
    закрывает `None`.

    Проскальзывание
    ---------------
    Задаётся в **шагах цены** (ТЗ §4.4 Ж), а не в рублях: шаг — свойство
    инструмента, и «полшага» на фьючерсе на индекс и на акции это разные
    деньги. Отсюда два поля вместо одного, и `price_step` обязателен,
    как только `slippage_steps` больше нуля: иначе настройка выглядела бы
    заданной, а работала бы как ноль.

    Умолчание — **ноль шагов**. Ровно так считал прототип, и на любом другом
    значении сверка с ним не сойдётся по построению.

    ⚠️ **Зависимость проскальзывания от объёма здесь не выражена, и это
    сказано вслух, а не спрятано.** ТЗ §4.4 Ж прямо говорит, что с ростом
    объёма заявка забирает несколько уровней стакана, — но глубина стакана
    внутри торгового окна не измерена, порог перехода на лимитные заявки
    в ТЗ помечен «к обсуждению», и оракула нет ни одного. Модель с выдуманной
    зависимостью от объёма выдавала бы числа, за которыми не стоит ни одного
    замера. Поэтому здесь плоская величина, одинаковая на любом объёме,
    и на больших объёмах она издержки **занижает**.
    """

    tariff: Tariff | None = None
    commission_per_side: float | None = None
    price_step: float = 0.0
    slippage_steps: float = 0.0

    def __post_init__(self) -> None:
        if self.commission_per_side is not None:
            # `allow_zero` назван вслух: явный ноль тут разрешён намеренно,
            # разбор — в докстринге класса. Умолчанием он выглядел бы как
            # недосмотр, а `Tariff` рядом ноль отвергает.
            _check_money(
                self.commission_per_side,
                "комиссия за контракт на сторону",
                allow_zero=True,
            )
        _check_money(self.price_step, "шаг цены", allow_zero=True)
        _check_money(self.slippage_steps, "проскальзывание в шагах цены", allow_zero=True)
        if self.tariff is not None and commissions_disagree(
            self.tariff.per_contract, self.commission_per_side
        ):
            raise ValueError(
                "комиссия задана дважды и по-разному: разбивка даёт "
                f"{self.tariff.per_contract} ₽ за контракт, а одним числом "
                f"указано {self.commission_per_side} ₽. Это две разные цифры "
                "комиссии в одном отчёте, и выбрать любую из них молча нельзя"
            )
        if self.slippage_steps > 0 and self.price_step <= 0:
            raise ValueError(
                f"проскальзывание {self.slippage_steps} шагов задано, а шаг цены "
                "не назван: настройка выглядела бы заданной, а работала бы как "
                "ноль. Шаг цены берётся из карточки инструмента"
            )

    @property
    def per_side(self) -> float | None:
        """Комиссия одной стороны за один контракт. `None` — тариф не задан."""
        if self.tariff is not None:
            return self.tariff.per_contract
        return self.commission_per_side

    @property
    def slippage(self) -> float:
        """Проскальзывание в пунктах цены: шаги, умноженные на шаг."""
        return self.slippage_steps * self.price_step

    def commission(self, volume: float) -> float | None:
        """Комиссия одной стороны за этот объём. `None` — тариф не задан, а не ноль."""
        per_side = self.per_side
        return None if per_side is None else per_side * volume

    def fill_price(self, price: float, action: OrderAction, side: Side) -> float:
        """Цена сделки с учётом проскальзывания — всегда **против** позиции.

        Покупке невыгодна цена повыше, продаже — пониже, и модель двигает цену
        именно в невыгодную сторону. Обратный знак превратил бы издержку
        в подарок и завысил бы результат прогона ровно там, где он и так
        завышен.

        ⚠️ Проскальзывание применяется и к **сработавшему уровню тейка**,
        а не только к рыночным заявкам. Причина не в вкусе: у брокера
        сработавший стоп это рыночная заявка, и исполняется она так же,
        как любая другая. Освободить от проскальзывания именно тейк значило бы
        занизить издержки ровно там, где их больше всего, — 42 выхода из 127
        эталонного прогона идут по уровню.
        """
        shift = self.slippage
        if shift == 0.0:
            return price
        moved = price - shift if selling(action, side) else price + shift
        if moved <= 0:
            raise ValueError(
                f"проскальзывание {shift} пунктов увело цену {price} в ноль "
                "или в минус: такой цены не бывает, а дальше она разошлась бы "
                "по результату в пунктах и по уровню тейка"
            )
        return moved


