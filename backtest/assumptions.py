"""Допущения прогона: чем показанный итог отличается от настоящего счёта.

Зачем этот модуль
-----------------
Прогон по истории показывает деньги. Деньги эти получены при допущениях,
и **все главные из них смещают результат в одну сторону** — в пользу отчёта.
Владелец счёта увидит «+9 908 ₽» и примет это за то, что было бы на счёте,
если рядом не написать, чего в этой цифре нет.

Раньше оговорка жила в докстринге `backtest/execution.py` («проскальзывание
по умолчанию ноль, и это не „пока не сделали“») и в `ROADMAP.md` строкой
«говорить об этом вслух, а не полагаться на докстринг». Докстрингов владелец
счёта не читает, а устная оговорка не переживает ни выгрузки в файл,
ни следующего показа.

Поэтому оговорка здесь **считается из самого прогона** и едет вместе с числом:
`HistoryRun.assumptions` и `HistoryRun.headline` — свойства того же объекта,
который несёт прибыль. Разъехаться с числом они не могут по построению:
хранимого поля нет, подставить пустой список неоткуда, отдельного объекта,
который можно забыть передать, тоже нет.

Что здесь считается, а что нет
------------------------------
**Считается** ровно то, что видно из самого прогона: задан ли тариф, задано ли
проскальзывание, сколько было исполнений, сколько выходов по уровню, какой
объём, осталась ли позиция открытой, попадает ли отрезок сделок в тот, на
котором подбирались умолчания.

**Не считается** цена допущения — «сколько было бы при проскальзывании в один
шаг». Её нельзя получить арифметикой, и это замерено, а не предположено
(разбор — [решение 0030](../.docs/decisions/0030-run-assumptions-travel-with-the-number.md)):
проскальзывание сдвигает цену входа, вместе с ней уровень тейка, вместе
с уровнем — какие свечи его задевают, и список сделок меняется целиком
(127 сделок против 130). Наивное «сделки × 2 × шаг» разошлось с настоящим
вторым прогоном на −18…+30 % и не является границей ни сверху, ни снизу.
Настоящая цена берётся вторым прогоном с ненулевым `Costs.slippage_steps`,
и для этого нужен шаг цены инструмента, которого в программе сегодня нет
нигде: карточки инструмента не читает никто, `price_step` за пределы
`backtest/` не выходит.

Поэтому в тексте оговорки стоит **замеренная** цифра с датой и названием
инструмента, а не выведенная на ходу оценка: соврать замером нельзя,
а оценкой — можно, и она соврала бы в пользу отчёта.

Длина: одна строка рядом с числом, абзац в выгрузке
----------------------------------------------------
Оговорка, повторённая пять раз одними и теми же словами, перестаёт читаться;
оговорка в одном месте пропускается. Отсюда два размера у каждой записи —
`short` (одна фраза, рядом с итогом) и `text` (абзац, в выгрузку), и признак
`beside_number`: рядом с числом стоят не все, а только те, без которых число
читается неправдой. Их не больше трёх, и это стережёт тест.
"""

