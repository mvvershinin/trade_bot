#: Порядок оговорок — данные, а не последовательность `if`. Первой идёт та,
#: без которой число читается неправдой сильнее всего: происхождение самих
#: настроек. Дальше — издержки, потом полнота итога, потом идеальность
#: обстановки. Перестановка строк меняет то, что владелец счёта прочитает
#: первым, и делается осознанно.
_TABLE: tuple[Callable[[_Facts], Assumption | None], ...] = (
    _tuning_and_check_are_the_same_slice,
    _commission_is_not_named,
    _slippage_is_not_counted,
    _slippage_is_counted,
    _position_is_left_open,
    _level_fills_on_a_touch,
    _volume_does_not_move_the_price,
    _nothing_refused_and_nothing_stopped,
    _the_data_are_perfect,
)


def assumptions(run: HistoryRun) -> tuple[Assumption, ...]:
    """Чем этот итог отличается от настоящего счёта. Пустым не бывает.

    Пустой список означал бы «отчёт равен выписке со счёта», а это неправда
    при любых настройках: происхождение умолчаний и отсутствие предохранителей
    от настроек не зависят. Поэтому в таблице есть записи без условия,
    и что список непуст, стережёт тест.
    """
    facts = _facts_of(run)
    found = (builder(facts) for builder in _TABLE)
    return tuple(item for item in found if item is not None)


def headline(run: HistoryRun) -> str:
    """Оговорка рядом с итогом: не больше трёх строк плюс отсылка к остальным.

    Рядом с числом стоят только записи с `beside_number`. Остальные названы
    счётом — «ещё 5 допущений», — чтобы человек знал, что список длиннее,
    и не принял три строки за весь перечень.
    """
    everything = assumptions(run)
    beside = [item for item in everything if item.beside_number]
    lines = ["⚠️ Это расчёт, а не выписка со счёта."]
    lines.extend(f"• {item.short}" for item in beside)
    rest = len(everything) - len(beside)
    if rest > 0:
        lines.append(
            f"Ещё {_plural(rest, 'допущение', 'допущения', 'допущений')} "
            "прогона — в выгрузке отчёта."
        )
    return "\n".join(lines)
