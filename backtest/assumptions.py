#: Отрезок, на котором подбирались умолчания ТЗ, — и на нём же они проверялись
#: (DOMAIN.md §4, `reference/stand/ЗАМЕРЫ-ПРОТОТИПА.md`). Независимой проверки
#: не было ни одной. Даты здесь для того, чтобы прогон **сам** сказал, повторяет
#: он подбор или идёт по другому отрезку: на глаз владелец счёта этого
#: не различит, а разница между «проверил» и «повторил подбор» — вся разница
#: между результатом и его иллюзией.
TUNED_FROM = date(2026, 6, 19)
TUNED_UNTIL = date(2026, 8, 26)

#: Сколько оговорок разрешено ставить рядом с числом. Больше — и их перестают
#: читать; ноль — и число читается как выписка со счёта. Три разных факта,
#: у каждого своё число, — не то же самое, что одна оговорка, повторённая
#: трижды в трёх местах.
BESIDE_THE_NUMBER_LIMIT = 3


@dataclass(frozen=True, slots=True)
class Assumption:
    """Одно допущение прогона в двух размерах.

    `name` — короткое имя, по нему запись узнают и в тесте, и в заголовке
    строки выгрузки. `short` — одна фраза с числом, для места рядом с итогом.
    `text` — абзац целиком: что именно допущено, в какую сторону это смещает
    результат и что с этим делать.

    `beside_number` — стоять ли рядом с числом. Признак у записи, а не
    у того, кто её показывает: решение «что человек обязан увидеть вместе
    с прибылью» принимается один раз и здесь, иначе каждое окно и каждая
    выгрузка решали бы его заново и по-разному.
    """

    name: str
    short: str
    text: str
    beside_number: bool = False


@dataclass(frozen=True, slots=True)
class _Facts:
    """Всё, что оговорки берут у прогона. Считается один раз и не пересчитывается."""

    trades: int
    #: Исполнений: у каждой закрытой сделки ровно два — вход и выход. Число
    #: сверено с комиссией эталона: 127 сделок × 2 × 14 ₽ = 3 556 ₽ архива.
    fills: int
    #: Деньги той же базы, что и весь итог: чистые при заданном тарифе,
    #: валовые при незаданном. Смешивать базы в одном отчёте нельзя.
    money: float
    commission_known: bool
    slippage: float
    #: Сколько рублей в одном пункте цены — свойство инструмента. Нужно,
    #: чтобы назвать проскальзывание в деньгах, а не только в пунктах.
    ruble_per_point: float
    take_exits: int
    volume: float
    position_left_open: bool
    #: Первый и последний день сделок по Москве. Пусто — сделок не было.
    period: tuple[date, date] | None


#: Ниже этой величины число печатается с десятой долей. Округление 46,7 ₽
#: до 47 ₽ ничего не портит, а округление 0,4 ₽ до нуля превращает издержку
#: в её отсутствие — и ровно на таких величинах живёт прибыль на одно
#: исполнение, ради которой этот формат и заведён.
ROUND_TO_WHOLE_ABOVE = 100.0


#: Неразрывный пробел записан escape-последовательностью намеренно: сам символ
#: в исходнике неотличим от обычного пробела глазом, а разница в том, перенесёт
#: ли окно «9 908 ₽» на другую строку посреди числа.
NBSP = "\u00a0"


def _number(value: float) -> str:
    """Число для человека: разряды пробелом, дробная часть запятой."""
    if abs(value) >= ROUND_TO_WHOLE_ABOVE:
        return f"{value:,.0f}".replace(",", NBSP)
    return f"{value:.1f}".replace(".", ",")


def _money(value: float) -> str:
    """Рубли для человека."""
    return f"{_number(value)}{NBSP}₽"


#: Остатки, на которых кончается «одна вещь» и «две вещи». Записаны числами,
#: а не выведены на месте: правило русского счёта не выводится из значения,
#: его надо знать, и знать его должно одно место, а не каждая фраза.
_ONE_REMAINDERS = (1,)
_FEW_REMAINDERS = (2, 3, 4)
_TEEN_REMAINDERS = range(11, 15)


def _plural(count: int, one: str, few: str, many: str) -> str:
    """Число и слово в согласованной форме: «1 сделка», «2 сделки», «5 сделок».

    Написано здесь, а не в каждой фразе, потому что «31 выходов» и «3 допущений»
    в отчёте о деньгах читаются как небрежность, а небрежности в отчёте
    не верят целиком — вместе с числами.
    """
    tail_hundred = abs(count) % 100
    tail_ten = abs(count) % 10
    if tail_hundred in _TEEN_REMAINDERS:
        word = many
    elif tail_ten in _ONE_REMAINDERS:
        word = one
    elif tail_ten in _FEW_REMAINDERS:
        word = few
    else:
        word = many
    return f"{count}{NBSP}{word}"


def _contracts(volume: float) -> str:
    """Объём словами. Дробный объём остаётся числом: склонять его нечем."""
    if volume.is_integer():
        return _plural(int(volume), "контракт", "контракта", "контрактов")
    return f"{_number(volume)}{NBSP}контракта"


def _facts_of(run: HistoryRun) -> _Facts:
    """Факты прогона. Ни одного числа заново: всё уже посчитано в `Summary`."""
    summary = run.summary
    known = summary.commission is not None
    days = sorted(in_moscow(deal.entry_time).date() for deal in run.deals)
    return _Facts(
        trades=summary.trades,
        fills=summary.trades * 2,
        money=summary.net_profit if known and summary.net_profit is not None
        else summary.gross_profit,
        commission_known=known,
        slippage=run.costs.slippage,
        ruble_per_point=next(
            (deal.ruble_per_point for deal in run.deals), 1.0
        ),
        take_exits=sum(
            1 for deal in run.deals if deal.exit_reason is ExitReason.TAKE_PROFIT
        ),
        volume=max((deal.volume for deal in run.deals), default=0.0),
        position_left_open=run.position is not None,
        period=(days[0], days[-1]) if days else None,
    )


