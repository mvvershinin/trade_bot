# решения, а не строка в списке.
#
# Побочно снята вторая беда: разрешённый тест пропускал и выходную проверку,
# поэтому `_poisoned_by` оставался пустым, и каждый следующий тест воркера
# падал с текстом «кто поганил — не записано». Тот самый режим, который
# комментарий ниже объявляет отвергнутым.


class OpenedAWindow(BaseException):
    """Тест добрался до настоящего экрана.

    ⚠️ Наследник `BaseException` по той же причине, что и `WentOutside`
    (см. выше): разбираемый код ловит `Exception` широко и по делу —
    `HistoryPort._pass`, `LiveObserver._ride`, а на этом самом пути ещё
    и `app.main._say_already_running`, который глушит **любой** отказ Qt
    намеренно. Отказ-наследник `Exception` был бы проглочен всеми тремя,
    и сторож промолчал бы ровно там, где он нужен.
    """


def _screen_in(environment) -> str:
    """Чем это окружение способно дотянуться до экрана. Пусто — ничем.

    Смотрится наличие `DISPLAY`/`WAYLAND_DISPLAY`, а не имя платформы,
    и это осознанно. Окно появляется не от того, что переменная платформы
    названа как-то не так, а от того, что процессу есть куда рисовать:
    без этих двух переменных ни `xcb`, ни `wayland` подняться не могут
    ни на столе, ни в контейнере. Обратное неверно — платформа может быть
    вовсе не выставлена, и тогда Qt выберет экранную сам.

    Отсюда следствие, на котором стоят проверки `B-028` и ключа `--runs`:
    заведомо негодное имя плагина проходит — но проходит потому, что
    окружение прогона уже без экрана, а не потому, что имя чем-то особенное.
    Тот же негодный плагин вместе с живым `DISPLAY` будет отвергнут, и это
    осознанно: живой экран ребёнку не отдают ни под каким предлогом.
    """
    if (environment.get("QT_QPA_PLATFORM") or "") in SCREENLESS_PLATFORMS:
        return ""
    found = [
        f"{name}={environment[name]!r}"
        for name in ("DISPLAY", "WAYLAND_DISPLAY")
        if environment.get(name)
    ]
    return ", ".join(found)


