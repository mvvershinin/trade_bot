#: Платформы Qt, на которых окно на экране появиться не может.
#: `offscreen` рисует в память, `minimal` не рисует вовсе.
SCREENLESS_PLATFORMS: Final[frozenset[str]] = frozenset({"offscreen", "minimal"})

# ⚠️ **Присвоение, а не `setdefault`, и это `B-033`.** `setdefault` молчит,
# когда переменная уже выставлена: человек с `QT_QPA_PLATFORM=xcb` в своём
# окружении получал прогон на настоящем экране и не знал об этом.
os.environ["QT_QPA_PLATFORM"] = "offscreen"

# ⚠️ Экран убирается **из окружения целиком**, а не заменяется платформой.
# Довод — второй вопрос владельца счёта 06.09.2026: «как я при CI/CD буду
# запускать, там будет докерхост и там не будет монитора». Пока `DISPLAY`
# на месте, машина разработчика и докерхост — две разные машины: место,
# втихую понадеявшееся на экран, здесь зеленеет, а там падает. Без `DISPLAY`
# стол ведёт себя как контейнер, и такое место падает **у нас**.
#
# Это не украшение. Замер 06.09.2026: полный прогон без `DISPLAY` ронял
# воркер целиком (`Fatal Python error: Aborted`) на тесте, который с экраном
# проходил, — на `test_the_refusal_is_shown_by_a_window_not_only_by_the_console`.
# Расхождение двух машин было ровно в одном тесте, и найти его иначе было
# нечем.
#
# Убирается до первого касания Qt: плагин платформы читает эти переменные
# один раз, при создании `QApplication`, и после уже поздно.
for _screen in ("DISPLAY", "WAYLAND_DISPLAY"):
    os.environ.pop(_screen, None)

# Снимок экрана и разметка не должны зависеть от масштаба системы, иначе один
# и тот же тест даёт разные размеры виджетов на разных машинах.
os.environ.setdefault("QT_SCALE_FACTOR", "1")


#: Подстроки в имени файла, по которым тест считается сверкой с эталоном.
#: Пропуск такого теста — не мелочь: без него зелёный прогон ничего
#: не говорит о совпадении с прототипом.
PARITY_MARKERS = ("reference_parity", "parity")


# `exitstatus` и `config` не нужны, но подпись хука задана pytest целиком.
def pytest_terminal_summary(terminalreporter, exitstatus, config) -> None:
    """Отдельная строка о пропущенном — в каждой сводке, без ключей.

    Пропуск обязан быть виден: «прогон зелёный» и «всё проверено» — разные
    утверждения, и различает их только эта строка.
    """
    skipped = terminalreporter.stats.get("skipped", [])
    if not skipped:
        return

    parity_skips = [
        report for report in skipped
        if any(marker in str(getattr(report, "nodeid", "")) for marker in PARITY_MARKERS)
    ]
    terminalreporter.write_sep("=", "ПРОПУЩЕНО", yellow=True)
    for report in skipped:
        reason = report.longrepr[2] if isinstance(report.longrepr, tuple) else ""
        terminalreporter.write_line(f"  {report.nodeid}: {reason}")
    if parity_skips:
        terminalreporter.write_line(
            f"  ⚠️ из них сверок с эталоном: {len(parity_skips)}. Совпадение с прототипом "
            "в этом прогоне НЕ проверено — зелёный цвет о нём ничего не говорит",
            yellow=True,
        )


