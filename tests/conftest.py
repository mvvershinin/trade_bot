#: Наполнение базы минутками с биржи для сверки с эталоном включается
#: **руками** и только на время наполнения:
#: `TERMINAL_ISS_NETWORK=1 .venv/bin/pytest tests/test_market_reference_parity.py`.
#: Признак заведён не здесь, а в самом файле сверки, и живёт там с начала:
#: обычный прогон в сеть не ходит и без всякого сторожа.
FILLING_THE_CACHE: Final[bool] = os.environ.get("TERMINAL_ISS_NETWORK") == "1"

#: Кому в прогоне тестов можно в настоящую сеть — **поимённо и с причиной**.
#: Ключ — начало `nodeid`: либо файл целиком (`tests/x.py`), либо один тест
#: (`tests/x.py::test_y`). Значение — зачем, словами для человека.
#:
#: ⚠️ При обычном запуске список **пуст**, и это проверяемое утверждение,
#: а не умолчание: сегодня в интернет не ходит ни один тест проекта. Строка
#: сюда добавляется осознанно и видна в обзоре правки — в отличие от пометки
#: внутри файла, которую ставит себе сам автор теста. Так уже было: `D-020`
#: начался с теста, про который никто не знал, что он ходит на биржу.
#:
#: Единственное исключение открывается переменной окружения, то есть
#: не открыто никогда, пока его не открыли руками, — и открывается ровно
#: на один файл, а не на прогон.
#:
#: Протухшую строку ловит `tests/test_conftest_guards.py`: имя, которого
#: в дереве нет, — это разрешение, выданное неизвестно кому.
INTERNET_ALLOWED: Final[dict[str, str]] = {
    "tests/test_market_reference_parity.py": (
        "наполнение базы минутками с биржи под сверку с эталоном; "
        "включается руками через TERMINAL_ISS_NETWORK=1"
    ),
} if FILLING_THE_CACHE else {}

#: Адреса, до которых пускают всегда: та же машина.
#: Локальный сервер поднимают проверки потока котировок
#: (`tests/test_broker_stream.py`, `tests/test_app_live_feed.py`) — это
#: не интернет, а способ проверить разбор кадров на настоящем сокете.
#:
#: Пустая строка и `0.0.0.0` — это привязка к порту, а не соединение;
#: собственное имя машины нужно чужим библиотекам (Qt, D-Bus) при опросе
#: окружения, и разрешено оно только для **разбора имени**: соединение
#: по адресу, в который оно разрешится, сторож проверит отдельно.
LOOPBACK: Final[frozenset[str]] = frozenset({
    "",
    "0.0.0.0",
    "::",
    "::1",
    "127.0.0.1",
    "localhost",
    "localhost.localdomain",
    socket.gethostname(),
})


def named_in(nodeid: str, allowed: Iterable[str]) -> bool:
    """Тест назван в списке разрешений — целиком, а не по началу строки.

    ⚠️ Сравнение по границе, а не `startswith`, и это находка ревью
    06.09.2026. Ключ списка — либо файл (`tests/x.py`), либо один тест
    (`tests/x.py::test_y`); голое `nodeid.startswith(name)` выдавало
    разрешение, выписанное `tests/test_app_main.py`, ещё и
    `tests/test_app_main_extra.py`, а разрешение на `::test_load` —
    заодно `::test_load_twice`. Молча и в ту сторону, в которую ошибаться
    нельзя: список открывает доступ, а не закрывает.

    Разделителей два, и оба обязательны. `::` отделяет тест от файла;
    `[` — набор параметров у параметризованного теста, без него разрешение
    на `test_y` не покрыло бы `test_y[случай]`, ради которого и выдавалось.
    """
    for name in allowed:
        if nodeid == name or nodeid.startswith((f"{name}::", f"{name}[")):
            return True
    return False


class WentOutside(BaseException):
    """Тест попытался выйти в настоящую сеть.

    ⚠️ Наследник `BaseException`, а не `Exception`, и это не педантизм.
    Разбираемый код ловит широко и по делу: `HistoryPort._pass` держит
    `except Exception`, чтобы окно не падало вместе с прогоном,
    `LiveObserver._ride` — чтобы беда в роботе не уносила весь проход.
    Отказ-наследник `Exception` они оба проглотили бы и превратили
    в строку «прогон не удался»; тест при этом остался бы зелёным или
    покраснел бы **не по той причине**, а сторож молчал бы ровно там,
    где он нужен. Тем же приёмом пользуется сам pytest: его собственные
    `Failed` и `Skipped` — тоже `BaseException`.
    """


def _local(host: object) -> bool:
    """Адрес указывает на эту же машину и наружу не идёт."""
    if host is None:
        return True
    if isinstance(host, bytes):
        host = host.decode("utf-8", "replace")
    if not isinstance(host, str):
        return False
    return host in LOOPBACK or host.startswith("127.")


def _host_of(address: object) -> object:
    """Хост из того, что дают `connect` и `connect_ex`.

    Адрес приходит тремя видами: пара `(host, port)` для IPv4, четвёрка
    для IPv6 и строка либо `bytes` для сокета файловой системы (AF_UNIX).
    Последний — это Qt, D-Bus и прочая местная машинерия: наружу он
    не ведёт по устройству, поэтому и считается своим (`None`).
    """
    if isinstance(address, (str, bytes)):
        return None  # AF_UNIX: путь в файловой системе, а не сеть
    if isinstance(address, Sequence) and address:
        return address[0]
    return address


@pytest.fixture(autouse=True)
def no_internet(request: pytest.FixtureRequest, monkeypatch) -> None:
    """Настоящая сеть закрыта на весь прогон, кроме названных поимённо.

    ⚠️ Ставится на `socket`, а не на `httpx`. Библиотек, умеющих в сеть,
    в проекте три (`httpx` синхронный, `httpx` асинхронный, `websockets`),
    и все три в конце концов зовут `socket.socket.connect`: асинхронный
    цикл событий делает это внутри `sock_connect`, а `socket.create_connection`
    и `http.client` — напрямую. Сторож на одной библиотеке пропустил бы
    две другие, и первый же тест на потоке котировок ушёл бы наружу молча.

    Разрешение имён закрыто отдельно (`getaddrinfo`): без него отказ приходил
    бы не отсюда, а из чужого кода — сообщением «сервер не отвечает», по
    которому не догадаться, что тест вообще куда-то шёл.

    **Чего сторож не закрывает, сказано вслух.** Первое — отдельный процесс:
    тесты, запускающие программу через `subprocess`, живут в своём
    интерпретаторе, и подмена сюда не доезжает; корень этого не в обвязке,
    а в том, что ключ `--db` переносит базу, а лог оставляет в умолчании
    (`BACKLOG.md`, `D-041`). Второе — датаграммы: `sendto` без соединения
    сторож не смотрит. Ни один слой проекта UDP не пользуется, и заводить
    сторожа впрок значит стеречь то, чего нет.
    """
    nodeid = request.node.nodeid
    if named_in(nodeid, INTERNET_ALLOWED):
        return

    # Подписи снятого берутся как есть: пересказывать их значит спорить
    # с typeshed о видах адреса (пара, четвёрка, путь) там, где сторож
    # смотрит только на хост, а всё прочее передаёт дальше нетронутым.
    connect: Any = socket.socket.connect
    connect_ex: Any = socket.socket.connect_ex
    getaddrinfo: Any = socket.getaddrinfo

    def refuse(where: str, address: object) -> WentOutside:
        return WentOutside(
            f"{nodeid} пошёл в настоящую сеть: {where} на {address!r}. "
            "Тест, ходящий в интернет, проверяет заодно связь, биржу "
            "и ограничение частоты — и краснеет не по своей причине. "
            "Нужен настоящий обмен — впишите тест поимённо в "
            "INTERNET_ALLOWED (tests/conftest.py) и скажите зачем; "
            "во всех прочих случаях подменяйте транспорт."
        )

    def guarded_connect(self: socket.socket, address: object) -> None:
        if not _local(_host_of(address)):
            raise refuse("socket.connect", address)
        connect(self, address)

    def guarded_connect_ex(self: socket.socket, address: object) -> object:
        if not _local(_host_of(address)):
            raise refuse("socket.connect_ex", address)
        return connect_ex(self, address)

    def guarded_getaddrinfo(host: object, *rest: object, **named: object) -> object:
        if not _local(host):
            raise refuse("socket.getaddrinfo", host)
        return getaddrinfo(host, *rest, **named)

    monkeypatch.setattr(socket.socket, "connect", guarded_connect)
    monkeypatch.setattr(socket.socket, "connect_ex", guarded_connect_ex)
    monkeypatch.setattr(socket, "getaddrinfo", guarded_getaddrinfo)


