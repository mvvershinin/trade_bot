"""Имена в коде — только латиницей. Кириллица — в текстах для человека.

Правило проекта, слова владельца счёта: **кириллица допустима в комментариях,
докстрингах, строках окна, сообщениях журнала и документации — и нигде больше.**
Имя переменной, аргумента, функции, класса, модуля и импорта пишется латиницей.

Основание — [PEP 672](https://peps.python.org/pep-0672/): Python принимает
идентификаторы в любом письме, а глаз их не различает. `с` кириллическая
и `c` латинская — разные имена с одинаковым начертанием; `ѕtore` и `store`
тоже. Такая опечатка не падает на разборе, она даёт `NameError` в другом
месте или, хуже, второе имя рядом с первым.

Цена уже заплачена: на 31.08.2026 разбором дерева нашлось 1476 кириллических
идентификаторов, и ключи командной строки `--снимок`, `--дней`, `--база`
дожили до владельца счёта. Линтера в проекте не было ни одного.

Почему это тест, а не только правило линтера
--------------------------------------------

`ruff` ловит то же самое правилами `PLC2401` (`non-ascii-name`) и `PLC2403`
(`non-ascii-import-name`), и настройка под них лежит в `pyproject.toml`.
Но на 31.08.2026 `ruff` в окружении **не установлен** (машина без сети),
а CI не существует вовсе. Правило, за которым не стоит запускаемого
механизма, — это соглашение; в этом проекте таким словом описывают дефект.
Здесь механизм есть, и он работает в том же прогоне, что все остальные тесты.

Когда `ruff` встанет, этот файл не становится лишним: `pytest` и `ruff`
запускаются разными людьми в разное время, а правило одно.

Чего этот сторож НЕ видит
-------------------------

⚠️ **Питоновский исходник, лежащий строковым литералом.** Сторож читает токены
файла, и для него такая строка — литерал, а не код. `ruff` эту дыру не
закрывает тоже: `PLC2401` работает по AST файла, а не по содержимому строк.

Дыра не теоретическая. На 31.08.2026 в дереве было два таких исходника,
и оба **исполняются**: `CLOSING_DRIVER` в `tests/test_app_main.py` (пишется
в файл и запускается отдельным процессом) и `IMPORT_PROBE`
в `tests/test_broker_no_leak.py` (уезжает дочернему Python через `-c`).
Шесть имён внутри них были кириллическими; переведены руками, а не сторожем.
У второго был и свой отказ: CPython декодирует `argv` файловой кодировкой
процесса, а не `PYTHONIOENCODING`, и на машине с `LC_ALL=C` имена приехали бы
мусором — проба упала бы `SyntaxError`, и тест про утечку токена покраснел бы
по причине, к утечке отношения не имеющей.

Оставшиеся строки-исходники в дереве **инертны** — они пишутся в файл
и разбираются `ast.parse`, но не исполняются: подсадки в этом файле
(им кириллица нужна по построению), фикстуры детектора секретов
в `tests/test_layers.py` и поддельные «слои» в `tests/test_market_candles.py`.
Проверено разбором каждого строкового литерала дерева, который парсится
как Python.

Расширять сторож на разбор литералов не стали намеренно: он начал бы падать
на собственных подсадках, а отличить «исходник для запуска» от «текста,
похожего на код» надёжно нельзя.

Проверка проверки
-----------------

Сторож, который не падает после удаления того, что он сторожит, хуже
отсутствующего: он единственный довод в пользу своего утверждения.
Поэтому здесь три подсадки — на имя, на импорт и на обратный случай
(кириллица в тексте для человека обязана проходить), — и отдельная
проверка, что обход вообще дошёл до файлов.
"""

from __future__ import annotations

import io
import pathlib
import tokenize
from typing import Final

import pytest

REPO_ROOT: Final = pathlib.Path(__file__).resolve().parent.parent

#: Каталоги, в которые обход не заходит: чужое, порождённое или вне git.
#: Список **похож** на `tests/test_layers.py`, но не равен ему, и сводить их
#: в один нельзя. Там `node_modules` намеренно НЕ пропускается: тот тест ищет
#: файлы, похожие на секрет, а чужие npm-пакеты кладут внутрь свои `.npmrc`
#: и токены. Здесь `node_modules` пропускается, потому что искать имена
#: в чужом коде незачем. Списки повторены, а не разделены, ещё и потому,
#: что тесты не импортируют друг друга: падение одного не уносит второй.
SKIP_DIRS: Final = frozenset({
    ".git", ".venv", "venv", "env", "reference", "userdata",
    "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache",
    "terminal.egg-info", "dist", "build", "AppDir", "node_modules",
})

#: Сколько файлов обход обязан увидеть. Число нужно не само по себе:
#: `rglob` по несуществующему каталогу возвращает пустоту **без ошибки**,
#: и после перестройки раскладки сторож прошёл бы вхолостую, ничего
#: не проверив, — зелёный прогон вместо проверки.
SOURCES_AT_LEAST: Final = 80


def python_files() -> list[pathlib.Path]:
    """Все файлы `*.py` рабочей копии, кроме заведомо чужих."""
    return sorted(
        path
        for path in REPO_ROOT.rglob("*.py")
        if not SKIP_DIRS.intersection(path.relative_to(REPO_ROOT).parts)
    )


def non_ascii_names(source: str) -> list[tuple[int, str]]:
    """Идентификаторы не из ASCII: строка и само имя.

    Читаются **токены**, а не текст. Это и есть разница между «нет кириллицы
    в файле» и «нет кириллицы в именах»: строковые литералы, комментарии
    и докстринги — токены других типов, и сюда они не попадают ни при каком
    их содержимом.

    Точки имени `import market.storage` разбиваются лексером на отдельные
    токены `NAME`, поэтому `PLC2403` (имя импортируемого модуля) закрывается
    тем же проходом, что `PLC2401`.
    """
    found: list[tuple[int, str]] = []
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        if token.type == tokenize.NAME and not token.string.isascii():
            found.append((token.start[0], token.string))
    return found


def test_no_identifier_in_the_tree_is_written_in_another_script() -> None:
    """Ни одного имени не из ASCII во всей рабочей копии."""
    culprits: list[str] = []
    seen = 0
    for path in python_files():
        seen += 1
        source = path.read_text(encoding="utf-8")
        culprits += [
            f"{path.relative_to(REPO_ROOT)}:{line}: {name}"
            for line, name in non_ascii_names(source)
        ]

    assert seen >= SOURCES_AT_LEAST, (
        f"обход увидел {seen} файлов вместо {SOURCES_AT_LEAST} и более. "
        "Сторож ничего не проверил — скорее всего, раскладку дерева "
        "перестроили, а путь остался прежним"
    )
    assert not culprits, (
        "имена в коде пишутся латиницей (PEP 672). Кириллица остаётся "
        "в комментариях, докстрингах и текстах для человека:\n  "
        + "\n  ".join(culprits)
    )


def test_the_guard_catches_a_planted_name() -> None:
    """Подсадка имени: без неё тест выше зеленел бы и на сломанном сторже."""
    assert non_ascii_names("свеча = 1\n") == [(1, "свеча")]
    assert non_ascii_names("def прогнать(): pass\n") == [(1, "прогнать")]
    assert non_ascii_names("class Свеча: pass\n") == [(1, "Свеча")]
    assert non_ascii_names("def f(*, поле=1): pass\n") == [(1, "поле")]


def test_the_guard_catches_a_planted_import() -> None:
    """`PLC2403`: имя импортируемого модуля — тоже имя."""
    assert non_ascii_names("import модуль\n") == [(1, "модуль")]
    assert non_ascii_names("from пакет.часть import x\n") == [(1, "пакет"), (1, "часть")]
    assert non_ascii_names("import market as база\n") == [(1, "база")]


def test_the_guard_leaves_human_text_alone() -> None:
    """Обратная подсадка: кириллица в тексте для человека — не нарушение.

    Без этой проверки правило можно было бы «выполнить», выгнав русский язык
    из сообщений и докстрингов. Владелец счёта — не программист, и читает он
    именно их.
    """
    assert non_ascii_names('"""Докстринг по-русски."""\n') == []
    assert non_ascii_names("x = 1  # комментарий по-русски\n") == []
    assert non_ascii_names('raise ValueError("нельзя писать")\n') == []
    assert non_ascii_names('print(f"свечей: {count}")\n') == []


def test_the_guard_reads_tokens_not_text() -> None:
    """Имя внутри строки не считается именем, а рядом с ней — считается.

    Разделение проверено на одной строке: так видно, что дело в типе токена,
    а не в том, что в файле «где-то есть кириллица».
    """
    assert non_ascii_names('поле = "поле"\n') == [(1, "поле")]


@pytest.mark.parametrize("source", ["def f(: pass", "x = (", "'''"])
def test_a_file_that_does_not_tokenize_is_a_loud_failure(source: str) -> None:
    """Нечитаемый файл роняет сторожа, а не проходит мимо него.

    `tokenize` на обрывке кидает `TokenError`. Проглотить его значило бы
    пропускать ровно те файлы, которые сломаны, — и молчать об этом.
    """
    with pytest.raises((tokenize.TokenError, IndentationError, SyntaxError)):
        non_ascii_names(source)
